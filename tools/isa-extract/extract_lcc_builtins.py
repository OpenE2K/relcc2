"""Write spec/abi/lcc-builtins.yaml: the MCST builtins lcc documents in
its manual (doc/lcc/builtin_mcst.html, shipped with every lcc; lcc-doc),
as data: name, return and argument types, group, and for the builtins
that build one machine operation, the operation and the first ISA
version the manual lists it under.

Only names and signatures are taken (interface facts); the manual's
descriptions are not copied.  lcc's headers (e2kintrin.h, e2kbuiltin.h)
are not read: the manual lists every __builtin_e2k_* name e2kintrin.h
declares.  tools/abi/probes/gen_builtins.py checks the data against lcc.

  python3 tools/isa-extract/extract_lcc_builtins.py

The manual is lcc 1.31.05's (in /opt/mcst, or where
tools/setup/fetch-lcc.sh 1.31.05 e2k-v3 puts it).
tools/abi/probes/find_builtins.py checks that it lists every name lcc
knows.
"""

import html
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
VERSION = "1.31.05"
LCC = next((d for d in (
    Path(f"/opt/mcst/lcc-{VERSION}.e2k-v3.linux-6.1"),
    ROOT / "toolchains" / f"lcc-{VERSION}-e2k-v3" / "opt" / "mcst"
    / f"lcc-{VERSION}.e2k-v3.linux-6.1") if d.exists()), None)
if LCC is None:
    raise SystemExit(f"no lcc {VERSION} (tools/setup/fetch-lcc.sh {VERSION} e2k-v3)")
DOC = LCC / "doc" / "lcc" / "builtin_mcst.html"
OUT = ROOT / "spec" / "abi" / "lcc-builtins.yaml"

# Section headings of the manual (Russian) -> group names.
GROUPS = [
    ("Машинно-независимые", "barrier"),
    ("Обращения в память с MAS", "mas"),
    ("Вычисление типа процессора", "cpu"),
    ("Работа с системными регистрами", "sysreg"),
    ("Работа с дескрипторами и тэгами", "protected"),
    ("Программно-аппаратные барьеры", "barrier"),
    ("Система команд v", "op"),
    ("Обращения в память с ASI", "e90"),
]
SIG = re.compile(r"^(?P<ret>[A-Za-z_][\w\s\*\(\)]*?)\s+(?P<name>__builtin_\w+)"
                 r"\s*\((?P<args>[^)]*)\)\s*$")


def text_lines(path):
    s = path.read_text()
    s = re.sub(r"<(script|style)[^>]*>.*?</\1>", "", s, flags=re.S)
    s = re.sub(r"</?(p|div|h\d|li|dt|dd|br|tr|td|pre|table|ul|section)\b[^>]*>",
               "\n", s)
    s = re.sub(r"<[^>]+>", "", s)
    for line in html.unescape(s).splitlines():
        line = line.replace("\xa0", " ").strip()
        if line:
            yield line


def parse_args(text):
    text = text.strip()
    if text in ("", "void"):
        return []
    out = []
    for a in text.split(","):
        a = " ".join(a.split())
        m = re.match(r"(.*?)\s*\b(\w+)$", a)
        typ, name = (m.group(1), m.group(2)) if m and m.group(1) else (a, "")
        out.append({"type": typ.replace(" *", "*"), "name": name})
    return out


def main():
    group, iset, seen, rows = None, None, set(), []
    for line in text_lines(DOC):
        if line.endswith("¶"):
            head = line[:-1]
            for prefix, g in GROUPS:
                if head.startswith(prefix):
                    group = g
                    m = re.search(r"v(\d+)", head)
                    iset = int(m.group(1)) if g == "op" and m else None
            continue
        m = SIG.match(line)
        if not m or group is None:
            continue
        name = m.group("name")
        if name in seen:
            # A second signature (lcc overloads a few builtins).
            prev = next(r for r in rows if r["name"] == name)
            args = parse_args(m.group("args"))
            if [x["type"] for x in args] != [x["type"] for x in prev["args"]]:
                prev.setdefault("overloads", []).append(args)
            continue
        seen.add(name)
        ret = " ".join(m.group("ret").split())
        # "uint64 (или uint32)": either, by the operand's format.
        ret = re.sub(r"\s*\(или\s+(\w+)\)", r" | \1", ret)
        row = {"name": name, "returns": ret, "args": parse_args(m.group("args")),
               "group": group}
        if group == "op":
            row["iset"] = iset
            row["op"] = name[len("__builtin_e2k_"):]
        rows.append(row)

    def yq(s):
        return "'" + s.replace("'", "''") + "'"
    lines = ["# SPDX-License-Identifier: CC-BY-SA-4.0",
             "# Generated by tools/isa-extract/extract_lcc_builtins.py from",
             f"# lcc {VERSION}'s manual ({DOC.relative_to(LCC)}, lcc-doc): names",
             "# and signatures only. Groups: barrier (compiler and wait barriers),",
             "# mas (memory access with a MAS), cpu (run-time CPU detection),",
             "# sysreg (system registers), protected (descriptors and tags),",
             "# op (one machine operation; iset = the first version the manual",
             "# lists it under), e90 (SPARC E90, not E2K). overloads: further",
             "# argument lists the manual gives for the same name.",
             "builtins:"]
    for r in rows:
        args = ", ".join("{type: %s, name: %s}" % (yq(a["type"]), yq(a["name"]))
                         for a in r["args"])
        extra = (f", op: {r['op']}, iset: {r['iset']}" if r["group"] == "op"
                 else "")
        for o in r.get("overloads", []):
            extra += ", overloads: [[" + ", ".join(
                "{type: %s, name: %s}" % (yq(a["type"]), yq(a["name"]))
                for a in o) + "]]"
        lines.append(f"  - {{name: {r['name']}, group: {r['group']}{extra}, "
                     f"returns: {yq(r['returns'])}, args: [{args}]}}")
    OUT.write_text("\n".join(lines) + "\n")
    by = {}
    for r in rows:
        k = r["group"] + (f" v{r['iset']}" if r["group"] == "op" else "")
        by[k] = by.get(k, 0) + 1
    print(len(rows), "builtins:", ", ".join(f"{k} {n}" for k, n in by.items()))


if __name__ == "__main__":
    main()
