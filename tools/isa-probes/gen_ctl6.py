"""Write ctl6.s and ctl6-cases.h: the v6 control operations on hardware
(the register branch and call ibranchd / icalld, a prepare and a
transfer through one CTPR in one instruction, fillr / fillc, abgc / rbgc
and the %bgr helpers modbgv / vfbgv) for ctl6.c (spec/isa/
control-transfer.md, operations-v6.md).

  python3 tools/isa-probes/gen_ctl6.py

Every case is  long c6_NAME(long *mem, long a, long b, long c).  Semantic cases
return a value that says what happened; timing cases (t_*) return the
%clkr cycles of K blocks, for K = 16 and 32, so ctl6.c prints the cost
of one block as (T32 - T16) / 16.
"""

from pathlib import Path

HERE = Path(__file__).resolve().parent

HEADER = """! SPDX-License-Identifier: GPL-3.0-or-later
! Generated by tools/isa-probes/gen_ctl6.py; see ctl6.c.
	.ignore	ld_st_style
	.ignore	strict_delay
	.text
"""

cases = []      # (name, kind)
text = []


def wi(*ops):
    return "\t{\n" + "".join(f"\t  {o}\n" for o in ops) + "\t}\n"


def nops(n):
    """N cycles of nothing (N >= 1)."""
    out = ""
    while n > 0:
        k = min(n, 8)
        out += wi(f"nop {k - 1}" if k > 1 else "nop")
        n -= k
    return out


def func(name, body, kind="value"):
    fn = f"c6_{name}"
    cases.append((name, kind))
    text.append(
        f"\n\t.global\t{fn}\n\t.type\t{fn}, #function\n\t.align\t8\n{fn}:\n"
        + wi("setwd\twsz = 0x20, nfx = 0x1, dbl = 0x0")
        + body
        + wi("return\t%ctpr3") + nops(6) + wi("ct\t%ctpr3")
        + f"\t.size\t{fn}, .-{fn}\n")


# The leaf every call case calls: returns its first argument + 1.
text.append("""
	.global	c6_leaf
	.type	c6_leaf, #function
	.align	8
c6_leaf:
""" + wi("setwd\twsz = 0x4, nfx = 0x1, dbl = 0x0", "return\t%ctpr3")
            + wi("addd,0\t%dr0, 0x1, %dr0") + nops(4) + wi("ct\t%ctpr3")
            + "\t.size\tc6_leaf, .-c6_leaf\n")

# --- What the operations do -------------------------------------------

# ibranchd to a label: 1 if it went there, 2 if it fell through.
func("ibranchd", wi("addd,0\t0x0, .Lib_t, %dr2") + nops(8)
     + wi("ibranchd,0\t%dr2, %empty")
     + wi("addd,0\t0x0, 0x2, %dr0") + wi("ibranch\t.Lib_end")
     + ".Lib_t:\n" + wi("addd,0\t0x0, 0x1, %dr0") + ".Lib_end:\n")
# Conditional: a != 0 sets %pred0; taken (1) only when it is true.
for nm, cond in (("ibranchd_p", "%pred0"), ("ibranchd_np", "~%pred0")):
    func(nm, wi("addd,0\t0x0, .L%s_t, %%dr2" % nm,
                "cmpedb,1\t%dr1, 0x0, %pred1") + nops(3)
         + wi("pass\t%pred1, @p0", "landp\t~@p0, ~@p0, @p4",
              "pass\t@p4, %pred0") + nops(8)
         + wi(f"ibranchd,0\t%dr2, %empty ? {cond}")
         + wi("addd,0\t0x0, 0x2, %dr0") + wi(f"ibranch\t.L{nm}_end")
         + f".L{nm}_t:\n" + wi("addd,0\t0x0, 0x1, %dr0") + f".L{nm}_end:\n")
# icalld of c6_leaf with a in %db[0]: returns what the callee returned
# (a + 1) plus 1000 * whether %dr2 (below the callee's window) survived.
func("icalld", wi("addd,0\t0x0, c6_leaf, %dr4", "addd,1\t0x0, 0x7, %dr2",
                  "addd,2\t%dr1, 0x0, %dr56") + nops(8)
     + wi("icalld,0\twbs = 0x1c, %dr4, %empty")
     + wi("cmpedb,0\t%dr2, 0x7, %pred0") + nops(3)
     + wi("addd,0\t%dr56, 0x0, %dr0") + wi("addd,0\t%dr0, 0x3e8, %dr0 ? %pred0"))
# A prepare and a ct through the same CTPR in one instruction (v6+):
# %ctpr1 first points at .Lold; 0 = went to the old target, 1 = to the
# new one, 2 = fell through.
func("disp_ct_same", wi("disp\t%ctpr1, .Lds_old") + nops(8)
     + wi("disp\t%ctpr1, .Lds_new", "ct\t%ctpr1")
     + wi("addd,0\t0x0, 0x2, %dr0") + wi("ibranch\t.Lds_end")
     + ".Lds_old:\n" + wi("addd,0\t0x0, 0x0, %dr0") + wi("ibranch\t.Lds_end")
     + ".Lds_new:\n" + wi("addd,0\t0x0, 0x1, %dr0") + ".Lds_end:\n")
# The same with the new disp one instruction before the ct (5 needed).
func("disp_ct_d1", wi("disp\t%ctpr1, .Ld1_old") + nops(8)
     + wi("disp\t%ctpr1, .Ld1_new") + wi("ct\t%ctpr1")
     + wi("addd,0\t0x0, 0x2, %dr0") + wi("ibranch\t.Ld1_end")
     + ".Ld1_old:\n" + wi("addd,0\t0x0, 0x0, %dr0") + wi("ibranch\t.Ld1_end")
     + ".Ld1_new:\n" + wi("addd,0\t0x0, 0x1, %dr0") + ".Ld1_end:\n")
# fillr / fillc from user mode, after a flush: 1 if they return.
for op in ("fillr", "fillc"):
    func(op, wi("flushr") + nops(8) + wi(op) + nops(8)
         + wi("addd,0\t0x0, 0x1, %dr0"))
# abgc / rbgc: %bgr before (bits 16-31) and after (bits 0-15).
for nm, op in (("abgc1", "abgc 1"), ("abgc3", "abgc 3"), ("abgc7", "abgc 7"),
               ("rbgc", "rbgc")):
    func(nm, wi("rrs,0\t%bgr, %r2") + nops(8) + wi(op) + nops(8)
         + wi("rrs,0\t%bgr, %r3") + nops(2)
         + wi("shld,0\t%dr2, 0x10, %dr2") + wi("ord,0\t%dr2, %dr3, %dr0"))
# With %bgr = c first: abgc 3 then rbgc, abgc 3 alone, rbgc alone,
# abgc 1 under a false and a true predicate (a != 0).
for nm, ops in (("bgr_abgc3_rbgc", [["abgc 3"], ["rbgc"]]),
                ("bgr_abgc3", [["abgc 3"]]), ("bgr_rbgc", [["rbgc"]]),
                ("bgr_abgc1_p", [["abgc 1 ? %pred0"]])):
    body = (wi("rrs,0\t%bgr, %r6", "andd,1\t%dr3, 0x7ff, %dr7",
               "cmpedb,3\t%dr1, 0x0, %pred1") + nops(3)
            + wi("pass\t%pred1, @p0", "landp\t~@p0, ~@p0, @p4",
                 "pass\t@p4, %pred0")
            + wi("rws,0\t%r7, %bgr") + nops(8))
    for o in ops:
        body += wi(*o) + nops(8)
    func(nm, body + wi("rrs,0\t%bgr, %r0") + nops(2)
         + wi("rws,0\t%r6, %bgr") + nops(8))
# abgc twice.
func("abgc1x2", wi("rrs,0\t%bgr, %r2") + nops(8) + wi("abgc 1") + nops(8)
     + wi("abgc 1") + nops(8) + wi("rrs,0\t%bgr, %r3") + nops(2)
     + wi("shld,0\t%dr2, 0x10, %dr2") + wi("ord,0\t%dr2, %dr3, %dr0"))
# modbgv a / vfbgv a, b with %bgr = c's low 11 bits set first (rws):
# the result (low 32 bits) and %bgr after (bits 32-47).
for nm, op in (("modbgv", "modbgv,1\t%r1, %r5"),
               ("vfbgv", "vfbgv,1\t%r1, %r2, %r5")):
    func(nm, wi("rrs,0\t%bgr, %r6", "andd,1\t%dr3, 0x7ff, %dr7")
         + wi("rws,0\t%r7, %bgr") + nops(8)
         + wi("adds,0\t0x0, 0x0, %r5") + wi(op) + nops(8)
         + wi("rrs,0\t%bgr, %r3") + nops(2)
         + wi("rws,0\t%r6, %bgr") + nops(8)
         + wi("shld,0\t%dr3, 0x20, %dr3", "andd,1\t%dr5, _f32s 0xffffffff, %dr5")
         + wi("ord,0\t%dr3, %dr5, %dr0"))

# --- Timing ------------------------------------------------------------

K = (16, 32)


def timed(name, setup, block, per_block_setup=None):
    """Two functions, K blocks each; block(i, nxt) gives block i's text
    ending in a transfer to label nxt."""
    for k in K:
        lab = lambda i, k=k: f".L{name}_{k}_b{i}"
        body = setup(k, lab) + nops(8) + wi("rrd,0\t%clkr, %dr10")
        for i in range(k):
            body += lab(i) + ":\n" + block(i, lab(i + 1))
        body += lab(k) + ":\n" + wi("rrd,0\t%clkr, %dr11") + nops(2)
        body += wi("subd,0\t%dr11, %dr10, %dr0")
        func(f"{name}_{k}", body, kind="time")


def regs_setup(k, lab):
    """%dr16 + i = the address of block i + 1."""
    s = ""
    for i in range(0, k, 2):
        ops = [f"addd,{c}\t0x0, _f32s {lab(i + 1 + j)}, %dr{16 + i + j}"
               for j, c in enumerate((0, 3)) if i + j < k]
        s += wi(*ops)
    return s


# A taken ibranchd per block, the target ready long before.
timed("t_ibranchd", regs_setup,
      lambda i, nxt: wi(f"ibranchd,0\t%dr{16 + i}, %empty"))
# The same with an ibranch (6 cycles, timing.md) and a ct prepared by a
# disp 5+ cycles before.
timed("t_ibranch", lambda k, lab: "", lambda i, nxt: wi(f"ibranch\t{nxt}"))
timed("t_ct", lambda k, lab: "",
      lambda i, nxt: wi(f"disp\t%ctpr1, {nxt}") + nops(5) + wi("ct\t%ctpr1"))
# The target computed D cycles before its ibranchd (addd, or ldd from a
# table of block addresses).
for d in range(1, 11):
    timed(f"t_addd_ibrd_d{d}", lambda k, lab: "",
          lambda i, nxt, d=d: wi(f"addd,0\t0x0, _f32s {nxt}, %dr2")
          + (nops(d - 1) if d > 1 else "")
          + wi("ibranchd,0\t%dr2, %empty"))
for d in range(1, 11):
    def tab_setup(k, lab, name=f"t_ldd_ibrd_d{d}"):
        return wi(f"addd,0\t0x0, _f32s .L{name}_{k}_tab, %dr1")

    def blk(i, nxt, d=d):
        return (wi(f"ldd,0\t%dr1, {8 * i:#x}, %dr2")
                + (nops(d - 1) if d > 1 else "")
                + wi("ibranchd,0\t%dr2, %empty"))
    timed(f"t_ldd_ibrd_d{d}", tab_setup, blk)
# A movtd D cycles before its ct, for comparison (9 on v3-v6).
for d in (1, 5, 9, 10):
    timed(f"t_movtd_ct_d{d}", lambda k, lab: "",
          lambda i, nxt, d=d: wi(f"addd,0\t0x0, _f32s {nxt}, %dr2") + nops(2)
          + wi("movtd,0\t%dr2, %ctpr1") + (nops(d - 1) if d > 1 else "")
          + wi("ct\t%ctpr1"))
# A call per block: icalld of c6_leaf against disp + call.
timed("t_icalld", lambda k, lab: wi("addd,0\t0x0, c6_leaf, %dr4") + nops(8),
      lambda i, nxt: wi("icalld,0\twbs = 0x1c, %dr4, %empty"))
timed("t_call", lambda k, lab: "",
      lambda i, nxt: wi("disp\t%ctpr1, c6_leaf") + nops(5)
      + wi("call\t%ctpr1, wbs = 0x1c"))
# disp and ct through one CTPR in one instruction (v6+), per block.
timed("t_disp_ct_same", lambda k, lab: "",
      lambda i, nxt: wi(f"disp\t%ctpr1, {nxt}", "ct\t%ctpr1"))


def tables():
    out = ["\n\t.data\n\t.align\t8\n"]
    for d in range(1, 11):
        for k in K:
            name = f"t_ldd_ibrd_d{d}"
            out.append(f".L{name}_{k}_tab:\n")
            out += [f"\t.dword\t.L{name}_{k}_b{i + 1}\n" for i in range(k)]
    return "".join(out)


def main():
    (HERE / "ctl6.s").write_text(HEADER + "".join(text) + tables())
    (HERE / "ctl6-cases.h").write_text(
        "/* SPDX-License-Identifier: GPL-3.0-or-later */\n"
        "/* Generated by tools/isa-probes/gen_ctl6.py.  */\n"
        + "".join(f"CASE ({n}, {k[0].upper()})\n" for n, k in cases))
    print(len(cases), "functions")


if __name__ == "__main__":
    main()
