/* Array prefetch (APB) streaming speed by area size (asz) and cache
   control (dcd), from L1 and from memory (spec/isa/apb.md, "Timing").
   apb-stream.s and apb-stream-cases.h are generated by
   gen_apb_stream.py.

     LCC=/opt/mcst/lcc-1.29.16.e2k-v3.4c.linux-6.1/bin/lcc
     $LCC -O1 tools/isa-probes/apb-stream.c tools/isa-probes/apb-stream.s \
       -o apb-stream
     ./apb-stream                         # on hardware

   Each line: the case (step in elements, dcd, asz), and the best of
   five runs in cycles per iteration for 2,048 iterations (data in L1
   after a first pass) and for 4 Mi iterations over a fresh stretch of
   a 512 MiB array (from memory).  */

#include <stdio.h>
#include <stdlib.h>
#include <string.h>

#define CASE(n, a, d, s) long stream_##n (const long *, unsigned long, long *);
#include "apb-stream-cases.h"
#undef CASE

static long *big;
static const long bign = 64L << 20;   /* 512 MiB of longs */
static long pos;                       /* next fresh element */

static double
best (long (*f) (const long *, unsigned long, long *), long n, int step,
      int fresh)
{
  double b = 1e30;
  for (int r = 0; r < 5; r++)
    {
      const long *a = big;
      if (fresh)
        {
          if (pos + n * step >= bign)
            pos = 0;
          a = big + pos;
          pos += n * step + 4096;
        }
      else
        f (a, 0xff2000000000UL | n, &(long) { 0 });
      long cyc = 0, s = f (a, 0xff2000000000UL | n, &cyc);
      long want = 0;
      for (long i = 0; i < n - 6; i++)   /* the loop adds 6 behind */
        want += a[i * step];
      if (s != want)
        return -1;
      if ((double) cyc / n < b)
        b = (double) cyc / n;
    }
  return b;
}

int
main (void)
{
  big = aligned_alloc (4096, bign * sizeof (long));
  for (long i = 0; i < bign; i++)
    big[i] = i;
  printf ("case          L1   memory  (cycles per element)\n");
#define CASE(n, a, d, s) \
  printf ("%-12s %5.2f %7.2f\n", #n, best (stream_##n, 2048, s, 0), \
          best (stream_##n, 4L << 20, s, 1));
#include "apb-stream-cases.h"
#undef CASE
  return 0;
}
