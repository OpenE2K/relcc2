/* ISA leftovers of the 2026-10-12 audit: whether a ,sm load under a
   diagnostic predicate reads memory and the tags of the predicates a
   callee starts with (spec/isa/predicates.md, speculation.md); UPSR.ac
   and array prefetch (x86-support.md); movaqp against fmt and mrng,
   and what an %aabfN write does to the AAU state the kernel saves
   (apb.md); what %lsr.ldovl changes (loops.md); a 128-bit register
   across a window spill with nfx = 1 (spec/abi/registers.md).
   isaleft*.s and isaleft*-cases.h are generated by gen_isaleft.py.

     D=tools/isa-probes
     L=/opt/mcst/lcc-1.29.16.e2k-v3.4c.linux-6.1/bin/lcc      # the 4C
     $L -O1 $D/isaleft.c $D/isaleft.s -o isaleft
     L=/opt/mcst/lcc-1.29.16.e2k-v5.8c2.linux-6.1/bin/lcc     # the 8C2
     L=/opt/mcst/lcc-1.29.16.e2k-v6.2c3.linux-6.1/bin/lcc     # the 2C3
     $L -O1 -DIL_V5 $D/isaleft.c $D/isaleft.s $D/isaleft-v5.s -o isaleft

     ./isaleft SECTION [FILTER]     # on hardware; SECTION is one of
       pred     ,sm loads (and DAM lock loads) under a diagnostic predicate
       ptag     predicate values and tags across a call
       apbq     movaqp and narrower movas against fmt and mrng
       aabf     %aabfN writes, then a trap: the AAU state in uc_extra
       seq CASE...  the named apbq/aabf (or ovst) cases in this order, in one
                process; @strncmp, @strlen, @strstr, @ct1, @ct2 between
                them call that function (2C3: a stand-alone program after
                another one and such a call dies with SIGILL, so run
                apbq and aabf there one case per process)
       ac       APB with UPSR.ac (each case in a child, with and without)
       ovst     stores into a streamed array, by ldovl, ldmc and asz
       ovs      streaming from memory by ldovl (cycles; run under flock)
       ovtouch  which pages after a stream's end the AAU touches
       qspill   (v5+) a 128-bit window register across a deep call or a
                signal handler, with nfx = 1 and 0.  2026-10-12, three
                runs each: with nfx = 1 the high half read 0 after a
                handler on the 8C2 and 2C3; after a call 1000 deep the
                8C2 gave a copy of the register's own low half once and
                0 twice, the 2C3 0 in the process's first deep call and
                the right value after; with nfx = 0 always right
                (spec/abi/registers.md, "nfx")
   FILTER keeps the cases whose names contain it.  */

