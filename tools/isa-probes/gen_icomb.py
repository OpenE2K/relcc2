"""Write icomb.s and icomb-ops.h: every integer combined operation of v3
X_Y (except merge_*, which takes a predicate), for icomb.c
(spec/isa/semantics.md, "FP min, max and combined operations").

  python3 tools/isa-probes/gen_icomb.py

Each function is  void ic_N(const unsigned long in[3], unsigned long
out[4]): it loads a, b, c and computes, in one function,
  out[0] = X_Y a, b, c          (the combined operation, ALC1)
  out[1] = X a, b               (the first stage as its own operation)
  out[2] = Y c, out[1]          (the second stage with c first; for rsub,
                                 sub out[1], c)
  out[3] = Y out[1], c          (the other order; for rsub, sub c, out[1])
so icomb.c can check that the combined operation is the two ordinary
operations chained, with the first stage's result as the second stage's
second operand (c first).
"""

import re
from pathlib import Path

import yaml

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
NAME = re.compile(r"^([a-z]+)_([a-z]+?)([ds])$")


def ops():
    data = yaml.safe_load((ROOT / "spec/isa/binutils-ops.yaml").read_text())
    out = {}
    for e in data["alu_ops"]:
        m = NAME.match(e["name"])
        if (m and 3 in e["isets"] and e["args"] in ("dddd", "ssss")
                and not e["name"].startswith(("f", "p", "q", "merge"))):
            out.setdefault(e["name"], m.groups())
    return sorted(out.items())


def fn(i, name, x, y, w):
    r = "%dr" if w == "d" else "%r"
    if y == "rsub":
        second = (f"sub{w},1\t{r}6, {r}4, {r}7", f"sub{w},1\t{r}4, {r}6, {r}8")
    else:
        second = (f"{y}{w},1\t{r}4, {r}6, {r}7", f"{y}{w},1\t{r}6, {r}4, {r}8")
    return f"""
	.global	ic_{i}
	.type	ic_{i}, #function
	.align	8
ic_{i}:
	{{
	  setwd	wsz = 0x8, nfx = 0x1, dbl = 0x0
	  return	%ctpr3
	  ldd,0	%dr0, 0x0, %dr2
	  ldd,2	%dr0, 0x8, %dr3
	  ldd,3	%dr0, 0x10, %dr4
	}}
	{{
	  addd,0	0x0, 0x0, %dr5
	  addd,1	0x0, 0x0, %dr6
	  addd,2	0x0, 0x0, %dr7
	  addd,3	0x0, 0x0, %dr8
	}}
	{{
	  nop 2
	}}
	{{
	  {name},1	{r}2, {r}3, {r}4, {r}5
	  {x}{w},0	{r}2, {r}3, {r}6
	}}
	{{
	  nop 2
	}}
	{{
	  {second[0]}
	}}
	{{
	  {second[1]}
	}}
	{{
	  nop 2
	}}
	{{
	  std,2	%dr1, 0x0, %dr5
	  std,5	%dr1, 0x8, %dr6
	}}
	{{
	  std,2	%dr1, 0x10, %dr7
	  std,5	%dr1, 0x18, %dr8
	}}
	{{
	  nop 5
	}}
	{{
	  ct	%ctpr3
	}}
	.size	ic_{i}, .-ic_{i}
"""


def main():
    ls = ops()
    (HERE / "icomb.s").write_text(
        "! SPDX-License-Identifier: GPL-3.0-or-later\n"
        "! Generated by tools/isa-probes/gen_icomb.py; see icomb.c.\n"
        "\t.ignore\tld_st_style\n\t.text\n"
        + "".join(fn(i, n, *g) for i, (n, g) in enumerate(ls)))
    (HERE / "icomb-ops.h").write_text(
        "/* SPDX-License-Identifier: GPL-3.0-or-later */\n"
        "/* Generated by tools/isa-probes/gen_icomb.py.  */\n"
        + "".join(f'OP ({i}, "{n}")\n' for i, (n, _) in enumerate(ls)))


if __name__ == "__main__":
    main()
