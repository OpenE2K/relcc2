"""Count how often lcc's system libraries use each operation.

Disassembles every shared library in the sysroot of an lcc cross
compiler (its fs/lib64 and fs/usr/lib64: glibc, libm, libstdc++, ...,
all built by MCST with lcc) with MCST objdump and counts the mnemonics.
spec/isa/operations-v*.md show the counts, so a compiler writer sees which
operations lcc relies on.  lcc is used only as a black box: this reads
the code it produced, nothing else.

  python3 tools/isa-extract/count_lcc_ops.py            # writes
                                                        # spec/isa/lcc-usage.yaml
"""

import argparse
import collections
import re
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OBJDUMP = ROOT / "toolchains" / "binutils" / "bin" / "e2k-linux-objdump"
TARGETS = {"v3": "e2k-v3", "v5": "e2k-v5.8c2"}
LCC = "/opt/mcst/lcc-1.29.16.{}.linux-6.1"
OP_RX = re.compile(r"^  ([a-z][a-z0-9_]*)\b")


def libraries(fs):
    """Every distinct shared library file under the sysroot's lib dirs."""
    seen, out = set(), []
    for d in (fs / "lib64", fs / "usr" / "lib64"):
        for f in sorted(d.glob("*.so*")):
            real = f.resolve()
            if real.is_file() and real not in seen and ".so" in real.name:
                seen.add(real)
                out.append(real)
    return out


def count(fs):
    total = collections.Counter()
    libs = libraries(fs)
    for lib in libs:
        p = subprocess.run([str(OBJDUMP), "-d", str(lib)], text=True,
                           capture_output=True)
        for line in p.stdout.splitlines():
            m = OP_RX.match(line)
            if m:
                total[m.group(1)] += 1
    return total, libs


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--out", type=Path,
                    default=ROOT / "spec" / "isa" / "lcc-usage.yaml")
    args = ap.parse_args()
    res = {}
    for key, tgt in TARGETS.items():
        fs = Path(LCC.format(tgt)) / "fs"
        res[key] = count(fs)
    lines = ["# SPDX-License-Identifier: CC-BY-SA-4.0",
             "# Generated by tools/isa-extract/count_lcc_ops.py: how many",
             "# times each operation appears in the shared libraries of lcc",
             "# 1.29.16's sysroots (code MCST built with lcc).",
             "sysroots:"]
    for key, tgt in TARGETS.items():
        c, libs = res[key]
        lines.append(f"  {key}: {{lcc: '{LCC.format(tgt)}', libraries: "
                     f"{len(libs)}, operations: {sum(c.values())}}}")
    names = sorted(set(res["v3"][0]) | set(res["v5"][0]))
    lines.append("counts:              # name: [v3 sysroot, v5 sysroot]")
    for n in names:
        lines.append(f"  {n}: [{res['v3'][0][n]}, {res['v5'][0][n]}]")
    args.out.write_text("\n".join(lines) + "\n")
    print(f"{len(names)} operations; written to {args.out}")


if __name__ == "__main__":
    main()
