"""Write pocchk.s and pocchk-cases.h: checks of the proof-of-concept back
end's findings I22, I24, I26, I27, P30, P38 and A20 (docs/spec-poc-
findings.md) for pocchk.c.

  python3 tools/isa-probes/gen_pocchk.py

Functions are  long pc_NAME(long *mem, long a, long b).  Value cases
return a result; timing cases (t_*) return %clkr cycles of a block of
work, which pocchk.c turns into cycles per step.
"""

from pathlib import Path

HERE = Path(__file__).resolve().parent
HEADER = """! SPDX-License-Identifier: GPL-3.0-or-later
! Generated by tools/isa-probes/gen_pocchk.py; see pocchk.c.
	.ignore	ld_st_style
	.ignore	strict_delay
	.text
"""
cases, text = [], []


def wi(*ops):
    return "\t{\n" + "".join(f"\t  {o}\n" for o in ops) + "\t}\n"


def nops(n):
    out = ""
    while n > 0:
        k = min(n, 8)
        out += wi(f"nop {k - 1}" if k > 1 else "nop")
        n -= k
    return out


def func(name, body, kind="V", dbl=0):
    fn = f"pc_{name}"
    cases.append((name, kind))
    text.append(f"\n\t.global\t{fn}\n\t.type\t{fn}, #function\n\t.align\t8\n"
                f"{fn}:\n"
                + wi(f"setwd\twsz = 0x10, nfx = 0x1, dbl = {dbl:#x}")
                + body + wi("return\t%ctpr3") + nops(6) + wi("ct\t%ctpr3")
                + f"\t.size\t{fn}, .-{fn}\n")


def pred_from_a():
    """%pred0 = (a != 0), %pred1 = (a == 0)."""
    return (wi("cmpedb,0\t%dr1, 0x0, %pred1") + nops(3)
            + wi("pass\t%pred1, @p0", "landp\t~@p0, ~@p0, @p4",
                 "pass\t@p4, %pred0") + nops(4))


def timed(name, setup, step, n=32):
    body = setup + nops(8) + wi("rrd,0\t%clkr, %dr10")
    for _ in range(n):
        body += step
    body += wi("rrd,0\t%clkr, %dr11") + nops(2)
    body += wi("subd,0\t%dr11, %dr10, %dr0")
    func(name, body, "T")


# I24: divide latency against the quotient's size.  x / 1 keeps x, so
# each step's quotient has x's size; the use comes GAP cycles after the
# divide (the next divide), and the step costs max(GAP, latency) + the
# stall rounding.  a = x.
for op, reg in (("sdivd", "%dr"), ("udivd", "%dr"), ("sdivs", "%r")):
    for gap in range(10, 26):
        timed(f"t_{op}_g{gap}", wi("addd,0\t0x0, 0x1, %dr3",
                                   "addd,1\t%dr1, 0x0, %dr2"),
              wi(f"{op},5\t{reg}2, {reg}3, {reg}2") + nops(gap - 1), n=16)

# I26: two writes of %dr5 in one wide instruction.  Value cases with
# opposite predicates (a selects) and with both enabled.
func("two_pred", pred_from_a() + wi("addd,0\t0x0, 0x1, %dr5 ? %pred0",
                                    "addd,1\t0x0, 0x2, %dr5 ? %pred1")
     + nops(3) + wi("addd,0\t%dr5, 0x0, %dr0"))
func("two_pred_x", pred_from_a() + wi("addd,0\t0x0, 0x1, %dr5 ? %pred0",
                                      "addd,3\t0x0, 0x2, %dr5 ? %pred1")
     + nops(3) + wi("addd,0\t%dr5, 0x0, %dr0"))
func("two_pred_ld", pred_from_a() + wi("std,2\t%dr0, 0x0, %dr2") + nops(3)
     + wi("ldd,0\t%dr0, 0x0, %dr5 ? %pred0",
          "addd,1\t0x0, 0x2, %dr5 ? %pred1")
     + nops(6) + wi("addd,0\t%dr5, 0x0, %dr0"))
for nm, a, b in (("both_01", "addd,0\t0x0, 0x1, %dr5", "addd,1\t0x0, 0x2, %dr5"),
                 ("both_10", "addd,1\t0x0, 0x2, %dr5", "addd,0\t0x0, 0x1, %dr5"),
                 ("both_03", "addd,0\t0x0, 0x1, %dr5", "addd,3\t0x0, 0x2, %dr5"),
                 ("both_ld01", "ldd,0\t%dr0, 0x0, %dr5", "addd,1\t0x0, 0x2, %dr5")):
    func(nm, wi("std,2\t%dr0, 0x0, %dr2") + nops(3) + wi(a, b) + nops(6)
         + wi("addd,0\t%dr5, 0x0, %dr0"))

# I27: a reader one cycle after a load into its operand under %pred0
# (a != 0: executed), or into another register (baseline).
for nm, dst in (("t_predld_same", "%dr2"), ("t_predld_other", "%dr6")):
    timed(nm, pred_from_a() + wi("addd,0\t%dr0, 0x0, %dr7"),
          wi(f"ldd,0\t%dr7, 0x0, {dst} ? %pred0")
          + wi("addd,0\t%dr2, 0x1, %dr2"))
timed("t_predmul_same", pred_from_a() + wi("addd,0\t0x0, 0x3, %dr3"),
      wi("muld,0\t%dr3, %dr3, %dr2 ? %pred0") + wi("addd,0\t%dr2, 0x1, %dr2"))

# P38: a 32-bit combined operation under dbl = 1 (and 0): the high half
# of its destination, preset to 0x5555....
for dbl in (0, 1):
    for op in ("shr_ands", "add_adds", "and_ors", "xor_xors"):
        func(f"{op}_dbl{dbl}",
             wi("addd,1\t0x0, _f64,_lts0 0x5555555555555555, %dr5")
             + nops(2) + wi(f"{op},1\t%r1, 0x3, %r2, %r5") + nops(3)
             + wi("addd,0\t%dr5, 0x0, %dr0"), dbl=dbl)
        func(f"{op.split('_')[0]}s_dbl{dbl}",
             wi("addd,1\t0x0, _f64,_lts0 0x5555555555555555, %dr5")
             + nops(2) + wi(f"{op.split('_')[0]}s,1\t%r1, 0x3, %r5")
             + nops(3) + wi("addd,0\t%dr5, 0x0, %dr0"), dbl=dbl)

# P30: compensation code reached by a check's rbranch reads %dr7, which
# the check's own wide instruction writes (1 -> 2): which value?
func("dam_comp_same_wi",
     wi("addd,0\t0x0, 0x1, %dr7", "addd,1\t0x0, 0x7, %dr3")
     + wi("std,2\t%dr0, 0x0, %dr3") + nops(4)
     + wi("ldd,0,sm\t%dr0, 0x0, %dr8, mas=0x4") + nops(2)
     + wi("std,2\t%dr0, 0x0, %dr2") + nops(2)
     + wi("ldd,5\t%dr0, 0x0, %dr8, mas=0x3", "addd,0\t0x0, 0x2, %dr7",
          "rbranch\t.Lcomp") + nops(2)
     + wi("addd,0\t0x0, 0x0, %dr0") + wi("ibranch\t.Lcomp_end")
     + ".Lcomp:\n" + wi("addd,0\t%dr7, 0x100, %dr0") + ".Lcomp_end:\n")

# I22: misaligned ldd/std cost: 4 independent loads (or 2 stores) a step
# at byte offset a from a 64-byte aligned base, and a dependent chase
# through a pointer at offset a (pocchk.c stores it there).
timed("t_ld4", wi("addd,0\t%dr0, %dr1, %dr7"),
      wi("ldd,0\t%dr7, 0x0, %dr12", "ldd,2\t%dr7, 0x8, %dr13",
         "ldd,3\t%dr7, 0x10, %dr14", "ldd,5\t%dr7, 0x18, %dr15"))
timed("t_st2", wi("addd,0\t%dr0, %dr1, %dr7"),
      wi("std,2\t%dr7, 0x0, %dr2", "std,5\t%dr7, 0x80, %dr2"))
timed("t_chase", wi("addd,0\t%dr0, %dr1, %dr2"),
      wi("ldd,0\t%dr2, 0x0, %dr2"))

# A20: %g1 and %g16 hold a marker while a counted loop of a iterations
# runs; pc_g_handler, installed as a SIGALRM handler by pocchk.c,
# overwrites both.  Result: bit 0 = %g1 changed, bit 1 = %g16 changed.
MAGIC = "_f64,_lts0 0x1122334455667788"
func("g_spin",
     wi("disp\t%ctpr1, .Lgspin", f"addd,0\t0x0, {MAGIC}, %dg1")
     + wi(f"addd,0\t0x0, {MAGIC}, %dg16") + nops(4)
     + ".Lgspin:\n" + wi("subd,0\t%dr1, 0x1, %dr1")
     + wi("nop 2", "cmpedb,0\t%dr1, 0x0, %pred0")
     + wi("ct\t%ctpr1 ? ~%pred0")
     + wi(f"xord,0\t%dg1, {MAGIC}, %dr5")
     + wi(f"xord,0\t%dg16, {MAGIC}, %dr6")
     + wi("cmpedb,0\t%dr5, 0x0, %pred1", "cmpedb,1\t%dr6, 0x0, %pred2")
     + nops(3) + wi("addd,0\t0x0, 0x0, %dr0")
     + wi("ord,0\t%dr0, 0x1, %dr0 ? ~%pred1")
     + wi("ord,0\t%dr0, 0x2, %dr0 ? ~%pred2"))
text.append("""
	.global	pc_g_handler
	.type	pc_g_handler, #function
	.align	8
pc_g_handler:
""" + wi("setwd\twsz = 0x4, nfx = 0x1, dbl = 0x0", "return\t%ctpr3")
            + wi("addd,0\t0x0, 0xbad, %dg1", "addd,1\t0x0, 0xbad, %dg16")
            + nops(5) + wi("ct\t%ctpr3") + "\t.size\tpc_g_handler, .-pc_g_handler\n")


def main():
    (HERE / "pocchk.s").write_text(HEADER + "".join(text))
    (HERE / "pocchk-cases.h").write_text(
        "/* SPDX-License-Identifier: GPL-3.0-or-later */\n"
        "/* Generated by tools/isa-probes/gen_pocchk.py.  */\n"
        + "".join(f"CASE ({n}, {k})\n" for n, k in cases))
    print(len(cases), "functions")


if __name__ == "__main__":
    main()
