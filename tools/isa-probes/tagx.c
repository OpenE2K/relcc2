/* Tag operations and deliberately tagged values, the tag operations'
   latencies, model checks of muls, muld, merges, merged, movts, movtd,
   movtq and fstoistr, and movaqp in an array prefetch program, on
   hardware (spec/isa/semantics.md, speculation.md, timing.md, apb.md).
   tagx.s, tagx-cases.h, tagx-v5.s and tagx-v5-cases.h are generated by
   gen_tagx.py.

     python3 tools/isa-probes/gen_tagx.py
     LCC=/opt/mcst/lcc-1.29.16.e2k-v3.4c.linux-6.1/bin/lcc   # the 4C
     $LCC -O1 tools/isa-probes/tagx.c tools/isa-probes/tagx.s -o tagx
     # v5+: the 8C2 (for the 2C3 use lcc-1.29.16.e2k-v6.2c3.linux-6.1)
     LCC5=/opt/mcst/lcc-1.29.16.e2k-v5.8c2.linux-6.1/bin/lcc
     $LCC5 -O1 -DTAGX_V5 tools/isa-probes/tagx.c tools/isa-probes/tagx.s \
         tools/isa-probes/tagx-v5.s -o tagx
     ./tagx [tags|lat|model|apb]     # every section without an argument;
                                     # lat under the shared timing lock
     cc -O1 tools/isa-probes/check_tagx.c -o check_tagx  # on an x86 host
     ./check_tagx < out.txt          # the model lines against SSE and C

   Lines:
     t CASE ARG: VALUE tag T gettags S | %dr9 VALUE tag T [| dt] N cycles
       ARG is "a=A tag B" (the value and the tag operand; A is one of
       four values with bit 30 of each half clear or set, because MCST's
       qemu calls a tag-1 half with bit 30 clear "empty" and with it set
       "diagnostic") or, for the address cases, the address kind
       VALUE is the register with its tag cleared; quad cases (v5) read
       %qpr8 back through stqp,sm and the fill MAS (%dr8 the low half,
       %dr9 the high half) and add "| direct VALUE tag T" for %dr8 as
       the operation left it
     t CASE ARG: signal SIG (NAME) si_code C in group G   (31: readout)
     lat KIND g G n N: CYCLES       the minimum of 7 runs
     latency KIND: CYCLES PER STEP for G = 1..6, (T(48) - T(16)) / 32
     m OP SET IN0 IN1 IN2 IN3 -> OUT0 OUT1 flags F
     apb CASE: cycles C, then each result register's value and tag  */

