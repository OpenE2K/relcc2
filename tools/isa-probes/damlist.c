/* A pipelined in-place list reversal with data speculation, CoreMark's
   core_list_reverse shape, in many placements of its lock load, check
   and store, counted with the hardware monitors: the proof-of-concept
   back end's finding I45 (docs/spec-poc-findings.md), for
   spec/isa/speculation.md and timing.md.  damlist.s and
   damlist-cases.h are generated by gen_damlist.py.

     LCC=/opt/mcst/lcc-1.29.16.e2k-v5.8c2.linux-6.1/bin/lcc
     $LCC -O1 tools/isa-probes/damlist.c tools/isa-probes/damlist.s \
         -o damlist
     taskset -c 2 ./damlist [CASES [LAYOUTS [EVENTS [N [DIR]]]]]
     ./damlist dump LAYOUTS - N         # each layout's slots, in order

   CASES and LAYOUTS are comma-separated name prefixes ("all" or "-" for
   every one); EVENTS is "core" (the default), "all" or a
   comma-separated list of event names; N the list length (default
   1024); DIR "pair" (the default: count the reversal and its undoing),
   "fwd" (the reversal) or "bwd" (the undoing).  Layouts: fwdS / bwdS
   put node i at i * S or (N - 1 - i) * S bytes, randS at a random
   permutation of the slots, cmS the first fifth descending and the
   rest permuted (the shape of CoreMark's list after its init), for
   slots of S bytes (8 or more; a node's next pointer is its first 8
   bytes); randS.SEED and cmS.SEED choose another permutation.

   Each line gives a case, a layout and, per event, the count per
   iteration of the reversal: the median of 15 runs, less the same for
   an empty function.  Every case is checked first: the list must come
   back reversed and then restored.  The t_ cases (a store, then a load
   D cycles later, its value used U cycles after the load) print the
   stall-free cycles a step and each event per step.

   4C, 8C2 and 2C3 (2026-10-13; N 33, 40 random layouts, the replayed
   orders of CoreMark's lists; spec/isa/timing.md "Store to load"): on
   the 8C2 a load issued 2 or 3 cycles after a store to the same 32-byte
   line, reading any byte the store did not write, is served by L2
   (L1_LD_HIT 0, L2_QUERY 2 a step) and its value comes 8 cycles late;
   the list reversal pays two stall steps for each store/next-lock pair
   in one line when the store is 2 or 3 cycles before the next lock,
   whatever the DAM, the check, the rbranch or the channels.  The 4C
   has no such window (only the reload of the stored doubleword 1 cycle
   after its store); the 2C3 sends a load of the stored doubleword at
   another width to L2 up to 4 cycles after the store.  A store under a
   false predicate sends nothing to L2 (t_y_pf_*).  */

