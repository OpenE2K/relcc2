"""Write pocchk4.s and pocchk4-cases.h for pocchk4.c: checks of the
proof-of-concept back end's findings I50 (where an x86 flag operation's
result goes in 2 cycles) and I51 (a 32-bit result read as 64 bits under
dbl = 0) in docs/spec-poc-findings.md, for spec/isa/timing.md and
x86-support.md.

  python3 tools/isa-probes/gen_pocchk4.py

Latency cases  long p4_lat_P__C__dD_gG(long *mem, long a, long b):
steps, each a producer P (into %r8 or %r10, alternately), G - 1 empty
cycles, and a consumer C of P's result in an instruction with nop 3 (so
a step is G + 4 cycles when C does not stall); setwd dbl = D.  Every
step's inputs are constants (%dr2 = 8, %dr3 = 0, %dr4 = 0, %dr5 = 3,
%dr6 = 1, %dr7 = 8, %pred0 true), so only P -> C can stall.  4 steps
warm up, then 12 run between two %clkr reads; the return value is the
difference (1 + the 12 steps' cycles).  Also predicate producers (a
cctop or a compare, false) into a ct that is not taken (%ctpr1 holds
p4_never), and a combined integer operation (add_addd in ALC1) into
both clusters, for comparison with the flag forms.

Write-back cases  p4_wb_P__X__C_dD: as a latency case with C D cycles
after P, and X in P's channel 2 cycles after P ("none": an empty
instruction there).

Issue cases  p4_tp_K: 32 wide instructions of independent operations
(two cctop, cctop and a flag operation, cctop and compares) after 4.

Width cases  p4_dbl_P_dD(long *mem, long a, long b): %dr8 preset to
0x5555555555555555, then P into %r8 under dbl = D; returns %dr8.

cctop cases  long p4_cc_K(long x): 1 if cctopK of x's low 32 bits
(%r0) is true, else 0 (K: the condition, the channel and ,sm).
"""

from pathlib import Path

HERE = Path(__file__).resolve().parent
HEADER = """! SPDX-License-Identifier: GPL-3.0-or-later
! Generated by tools/isa-probes/gen_pocchk4.py; see pocchk4.c.
	.ignore	ld_st_style
	.ignore	strict_delay
	.text
"""
cases, text = [], []
WARM, STEPS = 4, 12


def wi(*ops):
    return "\t{\n" + "".join(f"\t  {o}\n" for o in ops) + "\t}\n"


def nops(n):
    out = ""
    while n > 0:
        k = min(n, 8)
        out += wi(f"nop {k - 1}" if k > 1 else "nop")
        n -= k
    return out


def raw(name, body):
    fn = f"p4_{name}"
    text.append(f"\n\t.global\t{fn}\n\t.type\t{fn}, #function\n\t.align\t8\n"
                f"{fn}:\n{body}\t.size\t{fn}, .-{fn}\n")


def func(name, body, dbl=0, wsz=0x20):
    raw(name, wi(f"setwd\twsz = {wsz:#x}, nfx = 0x1, dbl = {dbl:#x}") + body
        + wi("return\t%ctpr3") + nops(6) + wi("ct\t%ctpr3"))


SETUP = (wi("disp\t%ctpr1, p4_never",
            "addd,0\t0x0, 0x8, %dr2", "addd,1\t0x0, 0x0, %dr3",
            "addd,2\t0x0, 0x0, %dr4", "addd,3\t0x0, 0x3, %dr5",
            "addd,4\t0x0, 0x1, %dr6", "addd,5\t0x0, 0x8, %dr7")
         + wi("addd,0\t0x0, 0x0, %dr8", "addd,1\t0x0, 0x0, %dr10",
              "addd,2\t0x0, 0x0, %dr20", "addd,3\t0x0, 0x0, %dr21",
              "addd,4\t0x0, 0x0, %dr22", "addd,5\t0x0, 0x0, %dr23")
         + wi("addd,0\t0x0, 0x0, %dr24", "cmpesb,1\t0x0, 0x0, %pred0"))


def timed(name, step, n=STEPS, dbl=0):
    """WARM steps, then N between two %clkr reads (STEP(i) gives step
    i's text)."""
    body = SETUP + nops(8)
    for i in range(WARM):
        body += step(i)
    body += wi("rrd,0\t%clkr, %dr28")
    for i in range(WARM, WARM + n):
        body += step(i)
    body += wi("rrd,0\t%clkr, %dr29") + nops(2)
    body += wi("subd,0\t%dr29, %dr28, %dr0")
    func(name, body, dbl)


# Producers: the operation with {d} its 32-bit (or {D} 64-bit)
# destination.  Values (dbl = 0 or 1): 8 for the 32-bit integer ones, a
# small flags word for the flag forms.
PROD = {
    # x86 flag forms (I50)
    "adds_fw0": "adds_fw,0\t%r2, %r3, {d}",
    "adds_fw3": "adds_fw,3\t%r2, %r3, {d}",
    "addd_fd0": "addd_fd,0\t%dr2, %dr3, {d}",
    "ands_fw0": "ands_fw,0\t%r2, %r7, {d}",
    "shls_fw0": "shls_fw,0\t%r6, %r5, %r4, {d}",
    "smulx_fw0": "smulx_fw,0\t%r2, %r6, {d}",
    "smulx_fw3": "smulx_fw,3\t%r2, %r6, {d}",
    "umulx_fw0": "umulx_fw,0\t%r2, %r6, {d}",
    # 32-bit integer results (I51)
    "adds0": "adds,0\t%r2, %r3, {d}",
    "adds3": "adds,3\t%r2, %r3, {d}",
    "xors0": "xors,0\t%r2, %r3, {d}",
    "ands0": "ands,0\t%r2, %r7, {d}",
    "shls0": "shls,0\t%r6, %r5, {d}",
    "merges0": "merges,0\t%r2, %r7, {d}, %pred0",
    "getfs0": "getfs,0\t%r2, 0x200, {d}",
    "muls0": "muls,0\t%r2, %r6, {d}",
    # predicates (false: 8 != 0, OF clear in 8), for the ct consumer
    "cctopo0p": "cctopo,0\t%r2, %pred1",
    "cctopo3p": "cctopo,3\t%r2, %pred1",
    "cmpesb0p": "cmpesb,0\t%r2, %r3, %pred1",
    # a combined integer operation (2 cycles, ALC1 or ALC4)
    "add_addd1": "add_addd,1\t%dr2, %dr3, %dr4, {D}",
    # 64-bit results (controls)
    "addd0": "addd,0\t%dr2, %dr3, {D}",
    "muld0": "muld,0\t%dr2, %dr6, {D}",
}

# Consumers: {s} the producer's register as 32 bits, {S} as 64 bits,
# {o} a store offset that differs every step.
CONS = {
    "cctopo0": "cctopo,0\t{s}, %pred1",
    "cctopo3": "cctopo,3\t{s}, %pred1",
    **{f"adds{c}": f"adds,{c}\t{{s}}, 0x1, %r20" for c in range(6)},
    "cmpesb0": "cmpesb,0\t{s}, 0x1, %pred2",
    "cmpesb3": "cmpesb,3\t{s}, 0x1, %pred2",
    "getfs0": "getfs,0\t{s}, 0x200, %r20",
    "merges0": "merges,0\t{s}, %r2, %r20, %pred0",
    "stw2": "stw,2\t%dr0, {o}, {s}",
    "stw5": "stw,5\t%dr0, {o}, {s}",
    "sxt0": "sxt,0\t0x2, {s}, %dr20",
    "fadds0": "fadds,0\t{s}, %r2, %r20",
    "smulx0": "smulx,0\t{s}, %r6, %dr20",
    "addd0": "addd,0\t{S}, 0x1, %dr20",
    "addd1": "addd,1\t{S}, 0x1, %dr20",
    "addd3": "addd,3\t{S}, 0x1, %dr20",
    "getfd0": "getfd,0\t{S}, 0xc00, %dr20",
    "getfd3": "getfd,3\t{S}, 0xc00, %dr20",
    "cmpedb0": "cmpedb,0\t{S}, 0x1, %pred2",
    "cmpedb3": "cmpedb,3\t{S}, 0x1, %pred2",
    "merged0": "merged,0\t{S}, %dr2, %dr20, %pred0",
    "lddidx0": "ldd,0\t%dr0, {S}, %dr20",
    "lddidx3": "ldd,3\t%dr0, {S}, %dr20",
    "std2": "std,2\t%dr0, {o}, {S}",
    "std5": "std,5\t%dr0, {o}, {S}",
    "stdidx2": "std,2\t%dr0, {S}, %dr2",
    "faddd0": "faddd,0\t{S}, %dr2, %dr20",
    "faddd3": "faddd,3\t{S}, %dr2, %dr20",
    # a conditional transfer, not taken (the predicate is false)
    "ct": "ct\t%ctpr1 ? %pred1",
}
W64 = ["addd0", "addd1", "addd3", "getfd0", "cmpedb0", "cmpedb3", "merged0",
       "lddidx0", "lddidx3", "std2", "std5", "stdidx2", "faddd0", "faddd3"]
W32 = ["adds0", "adds3", "cmpesb0", "stw2", "sxt0", "getfs0", "fadds0",
       "merges0"]
LAT = []    # (producer, consumer, dbl)
# I50: the flag forms.
LAT += [("adds_fw0", c, 0) for c in
        ["cctopo0", "cctopo3", "cmpesb0", "cmpesb3", "getfs0", "stw2"]
        + [f"adds{k}" for k in range(6)]]
LAT += [("adds_fw0", c, d) for d in (0, 1)
        for c in ("addd0", "addd3", "getfd0", "std2")]
LAT += [("adds_fw0", c, 0) for c in ("stw5", "smulx0", "fadds0", "merges0")]
LAT += [("adds_fw3", c, 0) for c in ("cctopo3", "cctopo0", "adds3", "adds0",
                                     "adds4", "stw2")]
LAT += [("adds_fw3", "addd3", d) for d in (0, 1)]
for p in ("addd_fd0", "ands_fw0", "shls_fw0"):
    LAT += [(p, c, 0) for c in ("cctopo0", "cctopo3", "adds0", "adds1",
                                "adds3")]
    LAT += [(p, "addd0", d) for d in (0, 1)]
LAT += [("smulx_fw0", c, 0) for c in ("cctopo0", "cctopo3", "adds0", "adds1",
                                      "adds3", "cmpesb0", "smulx0")]
LAT += [("smulx_fw0", "addd0", d) for d in (0, 1)]
LAT += [("smulx_fw0", "stw2", 0), ("smulx_fw0", "std2", 1)]
LAT += [("umulx_fw0", c, 0) for c in ("cctopo0", "cctopo3", "adds0", "addd0")]
LAT += [("smulx_fw3", c, 0) for c in ("cctopo3", "cctopo0", "adds3")]
LAT += [(p, c, 0) for p in ("adds0", "addd0") for c in ("cctopo0", "cctopo3")]
# I51: 32-bit integer results read as 64 bits.
LAT += [("adds0", c, d) for d in (0, 1) for c in W64]
LAT += [("adds0", c, 0) for c in W32]
LAT += [("adds3", c, d) for d in (0, 1)
        for c in ("addd0", "addd3", "getfd3", "std5")]
for p in ("xors0", "ands0", "shls0", "merges0", "getfs0"):
    LAT += [(p, c, 0) for c in ("addd0", "getfd0", "std2")]
    LAT += [(p, "addd0", 1)]
LAT += [("muls0", c, d) for d in (0, 1) for c in ("addd0", "adds0")]
LAT += [("addd0", c, 0) for c in ("adds0", "getfs0", "cmpesb0", "stw2")]
# cctop and a compare into a not-taken ct; a combined integer operation's
# result in both clusters (the flag forms' crossing, for comparison).
LAT += [(p, "ct", 0) for p in ("cctopo0p", "cctopo3p", "cmpesb0p")]
LAT += [("add_addd1", c, 0) for c in ("adds1", "adds0", "adds2", "adds3",
                                      "adds4", "stw2", "stw5")]
SLOW = {"smulx_fw0", "smulx_fw3", "umulx_fw0", "muls0", "muld0"}


def regs(i, wide_p):
    """Step i's producer destination and the consumer's views of it."""
    r = 8 if i % 2 == 0 else 10
    return (f"%dr{r}" if wide_p else f"%r{r}"), f"%r{r}", f"%dr{r}"


def step_text(p, c, i, g, x=None):
    dst, s, S = regs(i, p in ("addd0", "muld0", "add_addd1"))
    pop = PROD[p].format(d=dst, D=dst)
    cop = CONS[c].format(s=s, S=S, o=f"{8 * (i % 64):#x}")
    out = wi(pop)
    if x is None:
        out += nops(g - 1)
    else:
        # X 2 cycles after P, in P's channel; C G cycles after P.
        xs = [] if x == "none" else [XOPS[x]]
        out += nops(1)
        if g == 2:
            return out + wi(*xs, cop, "nop 3")
        out += wi(*(xs or ["nop"])) + nops(g - 3)
    return out + wi(cop, "nop 3")


for p, c, d in LAT:
    label = f"{p}__{c}__d{d}"
    for g in (range(1, 9) if p in SLOW else range(1, 7)):
        name = f"lat_{label}_g{g}"
        timed(name, lambda i, p=p, c=c, g=g: step_text(p, c, i, g), dbl=d)
        cases.append(f"LAT ({name}, \"{p} -> {c} dbl {d}\", {g})\n")

# Write-back conflicts: X in ALC0 2 cycles after a producer in ALC0.
XOPS = {
    "adds0": "adds,0\t%r2, %r3, %r21",
    "smulx_fw0": "smulx_fw,0\t%r2, %r6, %r22",
    "adds_fw0": "adds_fw,0\t%r2, %r3, %r23",
    "ldw0": "ldw,0\t%dr0, 0x0, %r24",
    "cmpesb0": "cmpesb,0\t%r2, %r3, %pred3",
    "cctopo0": "cctopo,0\t%r2, %pred3",
}
WB = []
for x in ["none"] + list(XOPS):
    for c in ("adds1", "cctopo0", "cctopo3"):
        WB += [("smulx_fw0", x, c, dd) for dd in (6, 7, 8)]
        WB += [("adds_fw0", x, c, dd) for dd in (2, 3, 4, 5)
               if not (c == "cctopo0" and dd == 2 and x != "none")]
    WB += [("muld0", x, "adds1", dd) for dd in (6, 7)]
for p, x, c, dd in WB:
    name = f"wb_{p}__{x}__{c}_d{dd}"
    timed(name, lambda i, p=p, c=c, dd=dd, x=x: step_text(p, c, i, dd, x))
    cases.append(f"WB ({name}, \"{p} + {x} -> {c}\", {dd})\n")

# Issue: N instructions of independent operations.
TP = {
    "empty": [],
    "cctop0_cctop3": ["cctopo,0\t%r2, %pred1", "cctopo,3\t%r3, %pred2"],
    "addsfw0_cctop3": ["adds_fw,0\t%r2, %r3, %r8", "cctopo,3\t%r4, %pred2"],
    "addsfw0_addsfw3": ["adds_fw,0\t%r2, %r3, %r8", "adds_fw,3\t%r2, %r3, %r10"],
    "cctop0_cmpesb1": ["cctopo,0\t%r2, %pred1", "cmpesb,1\t%r2, %r3, %pred2"],
    "cctop03_cmpesb14": ["cctopo,0\t%r2, %pred1", "cctopo,3\t%r3, %pred2",
                         "cmpesb,1\t%r2, %r3, %pred3",
                         "cmpesb,4\t%r2, %r3, %pred4"],
    "addsfw03_cmpesb14": ["adds_fw,0\t%r2, %r3, %r8",
                          "adds_fw,3\t%r2, %r3, %r10",
                          "cmpesb,1\t%r2, %r3, %pred3",
                          "cmpesb,4\t%r2, %r3, %pred4"],
}
for k, ops in TP.items():
    name = f"tp_{k}"
    timed(name, lambda i, ops=ops: wi(*(ops or ["nop"])), 32)
    cases.append(f"TP ({name}, \"{k}\", 32)\n")

# What the flag forms leave in the upper half under dbl = 0 and 1.
for p in ("adds_fw0", "addd_fd0", "ands_fw0", "smulx_fw0", "adds0"):
    for d in (0, 1):
        name = f"dbl_{p}_d{d}"
        func(name, SETUP + wi("addd,0\t0x0, _f64,_lts0 0x5555555555555555, %dr8")
             + nops(2) + wi(PROD[p].format(d="%r8", D="%dr8")) + nops(8)
             + wi("addd,0\t0x0, %dr8, %dr0"), d)
        cases.append(f"DB ({name}, \"{p} dbl {d}\")\n")

# cctop on any 32-bit value: x86 conditions on x's low half.
CC = [(f"{k}{c}", f"cctop{k},{c}\t%r0, %pred0")
      for k in ("o", "b", "e", "be", "s", "p", "l", "le") for c in (0, 3)]
CC += [("o0sm", "cctopo,0,sm\t%r0, %pred0"), ("o3sm", "cctopo,3,sm\t%r0, %pred0")]
for k, op in CC:
    raw(f"cc_{k}", wi("setwd\twsz = 0x8, nfx = 0x1, dbl = 0x0")
        + wi(op, "addd,1\t0x0, 0x0, %dr1") + nops(2)
        + wi("addd,1\t0x0, 0x1, %dr1 ? %pred0") + nops(1)
        + wi("addd,0\t0x0, %dr1, %dr0", "return\t%ctpr3") + nops(6)
        + wi("ct\t%ctpr3"))
    cases.append(f"CC (cc_{k}, \"{k}\")\n")


# The latency cases' %ctpr1 target (never reached: their ct is not taken).
raw("never", wi("setwd\twsz = 0x8, nfx = 0x1, dbl = 0x0", "return\t%ctpr3")
    + nops(6) + wi("ct\t%ctpr3"))


def write():
    (HERE / "pocchk4.s").write_text(HEADER + "".join(text))
    (HERE / "pocchk4-cases.h").write_text(
        "/* SPDX-License-Identifier: GPL-3.0-or-later */\n"
        "/* Generated by tools/isa-probes/gen_pocchk4.py.  */\n"
        + "".join(cases))
    print(len(cases), "functions")


if __name__ == "__main__":
    write()
