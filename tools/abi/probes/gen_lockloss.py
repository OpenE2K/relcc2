#!/usr/bin/env python3
# SPDX-License-Identifier: GPL-3.0-or-later
"""Write lockloss.s and lockloss-v5.s for lockloss.c: what makes the
wait-unlock store of an atomic read-modify-write fail (spec/abi/atomics.md).

Every single-thread kernel is lcc's fetch-add shape (a lone `nop 1`, the
lock-wait load `ldd,0 ... mas = 0x7`, `addd`, the wait-unlock store
`std,2 ... mas = 0x2` with `rbranch`) with something put between the load
and the store, but `rbranch` goes to a counter instead of back to the
load, so each attempt is tried once:

    long ll_NAME (long *p, long *aux, long n)   n attempts; returns failures

The second-thread kernels run until *stop is nonzero:

    long llb_load (long *a, volatile long *stop)       plain loads of a
    long llb_store (long *a, volatile long *stop, long v)   plain stores
    long llb_rmw_D (long *a, volatile long *stop)       fetch-add of a with
        D cycles between the load and the store, retried as lcc does;
        returns successes + (retries << 32)
    long llb_try_D (...)     the same, not retried: successes + (fails << 32)

Usage: gen_lockloss.py [OUTDIR]  (default: this directory)."""

import os
import sys

HEAD = """! SPDX-License-Identifier: GPL-3.0-or-later
! Generated by gen_lockloss.py; do not edit.
\t.ignore\tld_st_style
\t.text
"""


def delay(cycles):
    """About CYCLES empty cycles (whole nop 7 instructions)."""
    return ".rept %d\n\t{\n\t  nop 7\n\t}\n\t.endr\n" % max(1, cycles // 8)


def instr(*ops):
    return "\t{\n" + "".join("\t  %s\n" % o for o in ops) + "\t}\n"


# Single-thread cases: (name, what, pre, between, lock, unlock)
# pre: instructions before the loop head's nop 1; between: after the
# addd; lock/unlock override the lock-wait load and the store.
LOCK = "ldd,0\t%dr0, 0x0, %dr4, mas = 0x7"
UNLOCK = "std,2\t%dr0, 0x0, %dr5, mas = 0x2"

CASES = []


def case(name, what, between="", pre="", lock=LOCK, unlock=UNLOCK,
         v5=False, rb=True, after=""):
    """rb: rbranch in the unlock's instruction; after: instructions after
    it (before the loop's own)."""
    CASES.append(dict(name=name, what=what, between=between, pre=pre,
                      lock=lock, unlock=unlock, v5=v5, rb=rb, after=after))


case("nothing", "nothing between (lcc's fetch-add)")
case("ld0_other", "ldd,0 from another page",
     instr("ldd,0\t%dr1, 0x0, %dr6"))
case("ld3_other", "ldd,3 from another page",
     instr("ldd,3\t%dr1, 0x0, %dr6"))
case("ld2_other", "ldd,2 from another page",
     instr("ldd,2\t%dr1, 0x0, %dr6"))
for off in (0, 8, 32, 64):
    case("ld_off%d" % off, "ldd,0 from p+%d" % off,
         instr("ldd,0\t%%dr0, 0x%x, %%dr6" % off))
case("st_other", "std,2 to another page",
     instr("std,2\t%dr1, 0x0, %dr7"))
case("st5_other", "std,5 to another page",
     instr("std,5\t%dr1, 0x0, %dr7"))
for off in (0, 8, 16, 24, 32, 48, 64, 128, 256, 4096, 8192, 65536):
    case("st_off%d" % off, "std,2 to p+%d" % off,
         instr("std,2\t%%dr0, 0x%x, %%dr7" % off))
case("stb_off1", "stb,2 to p+1 (inside the locked word)",
     instr("stb,2\t%dr0, 0x1, %dr7"))
case("w_stw_off4", "ldw lock of p, stw,2 to p+4, stw unlock",
     instr("stw,2\t%dr0, 0x4, %dr7"),
     lock="ldw,0\t%dr0, 0x0, %dr4, mas = 0x7",
     unlock="stw,2\t%dr0, 0x0, %dr5, mas = 0x2")
case("w_nothing", "ldw lock, stw unlock, nothing between",
     lock="ldw,0\t%dr0, 0x0, %dr4, mas = 0x7",
     unlock="stw,2\t%dr0, 0x0, %dr5, mas = 0x2")
case("lock_other", "a second lock-wait load, of another page",
     instr("ldd,0\t%dr1, 0x0, %dr6, mas = 0x7"))
case("lock_same", "a second lock-wait load of p",
     instr("ldd,0\t%dr0, 0x0, %dr6, mas = 0x7"))
case("call", "a call of an empty function",
     instr("call\t%ctpr1, wbs = 0x4"),
     pre=instr("disp\t%ctpr1, ll_empty"))
case("syscall", "a call of a function doing getppid ()",
     instr("call\t%ctpr1, wbs = 0x4"),
     pre=instr("disp\t%ctpr1, ll_sys"))
case("syscall_asm", "getppid () by sdisp entry 3, no memory access",
     instr("call\t%ctpr1, wbs = 0x4"),
     pre=instr("sdisp\t%ctpr1, 0x3", "addd,0\t0x0, 0x40, %db[0]"))
case("fastcall_asm", "fast getcpu (0, 0) by sdisp entry 6",
     instr("call\t%ctpr1, wbs = 0x4"),
     pre=instr("sdisp\t%ctpr1, 0x6", "addd,0\t0x0, 0x2, %db[0]",
               "addd,1\t0x0, 0x0, %db[1]", "addd,3\t0x0, 0x0, %db[2]"))
case("ibranch", "a taken ibranch to the next instruction",
     instr("ibranch\t.Libr_%(n)s") + ".Libr_%(n)s:\n")
case("rrd_clkr", "rrd %clkr",
     instr("rrd,0\t%clkr, %dr6"))
case("wait", "wait ld_c, st_c",
     instr("wait\tld_c = 1, st_c = 1"))
for cyc in (8, 64, 512, 4096, 32768):
    case("delay%d" % cyc, "about %d empty cycles" % cyc, delay(cyc))
# The store side (question 5).
case("ust_other", "the wait-unlock store to another page",
     unlock="std,2\t%dr1, 0x0, %dr5, mas = 0x2")
case("ust_off8", "the wait-unlock store to p+8",
     unlock="std,2\t%dr0, 0x8, %dr5, mas = 0x2")
case("ust_nolock", "a plain load instead of the lock-wait load",
     lock="ldd,0\t%dr0, 0x0, %dr4")
case("ust_ldw", "lock-wait ldd, unlock with stw",
     unlock="stw,2\t%dr0, 0x0, %dr5, mas = 0x2")
case("ust_ch5", "the wait-unlock store in ALC5",
     unlock="std,5\t%dr0, 0x0, %dr5, mas = 0x2")
# Abandoned locks and the end of a lock.
case("abandon", "lock-wait, no store (every attempt counted as failed)",
     unlock="", rb=False, after=instr("ibranch\t.Lf_%(n)s"))
case("abandon_ld", "lock-wait, no store, then ldd,0 of another page",
     unlock="", rb=False,
     after=instr("ldd,0\t%dr1, 0x0, %dr6") + instr("ibranch\t.Lf_%(n)s"))
case("abandon_st", "lock-wait, no store, then std,2 to another page",
     unlock="", rb=False,
     after=instr("std,2\t%dr1, 0x0, %dr7") + instr("ibranch\t.Lf_%(n)s"))
case("unlock_twice", "two wait-unlock stores; rbranch on the second",
     unlock="std,2\t%dr0, 0x0, %dr5, mas = 0x2", rb=False,
     after=instr("std,2\t%dr0, 0x0, %dr5, mas = 0x2",
                 "rbranch\t.Lf_%(n)s"))
case("rb_late", "rbranch one instruction after the store",
     rb=False, after=instr("rbranch\t.Lf_%(n)s"))
case("rb_late_lost", "ldd,0 of another page between; rbranch one "
     "instruction after the store",
     instr("ldd,0\t%dr1, 0x0, %dr6"), rb=False,
     after=instr("rbranch\t.Lf_%(n)s"))
case("rb_late2_lost", "the same, rbranch two instructions after",
     instr("ldd,0\t%dr1, 0x0, %dr6"), rb=False,
     after=instr("nop 1") + instr("rbranch\t.Lf_%(n)s"))
# mod 5 (question 4).
case("m5_nothing", "lock-wait mod 5 (mas 0x5) ldd,0, nothing between",
     lock="ldd,0\t%dr0, 0x0, %dr4, mas = 0x5")
case("m5_st_off8", "lock-wait mod 5 ldd,0, std,2 to p+8 between",
     instr("std,2\t%dr0, 0x8, %dr7"),
     lock="ldd,0\t%dr0, 0x0, %dr4, mas = 0x5")
case("m5_st_other", "lock-wait mod 5 ldd,0, std,2 to another page",
     instr("std,2\t%dr1, 0x0, %dr7"),
     lock="ldd,0\t%dr0, 0x0, %dr4, mas = 0x5")
case("m5_ld_off8", "lock-wait mod 5 ldd,0, ldd,0 of p+8 between",
     instr("ldd,0\t%dr0, 0x8, %dr6"),
     lock="ldd,0\t%dr0, 0x0, %dr4, mas = 0x5")
# 16-byte pairs (v5+): ldq takes channels 0 and 2.
QLOCK5 = "ldq,0\t%dr0, 0x0, %qr4, mas = 0x5"
QUNLOCK = "stq,2\t%dr0, 0x0, %qr4, mas = 0x2"
case("q5_nothing", "ldq mod 5 (ALC0+2), stq unlock", lock=QLOCK5,
     unlock=QUNLOCK, v5=True)
case("q5_st_off16", "ldq mod 5, std,5 to p+16 between",
     instr("std,5\t%dr0, 0x10, %dr7"), lock=QLOCK5, unlock=QUNLOCK, v5=True)
case("q5_st_off8", "ldq mod 5, std,5 to p+8 (inside the pair) between",
     instr("std,5\t%dr0, 0x8, %dr7"), lock=QLOCK5, unlock=QUNLOCK, v5=True)
case("qp7_nothing", "ldqp,0 mod 7, stqp,2 unlock (lcc's 16-byte RMW)",
     lock="ldqp,0\t%dr0, 0x0, %xr4, mas = 0x7",
     unlock="stqp,2\t%dr0, 0x0, %xr4, mas = 0x2", v5=True)
case("qp7_st_off16", "ldqp mod 7, std,5 to p+16 between",
     instr("std,5\t%dr0, 0x10, %dr7"),
     lock="ldqp,0\t%dr0, 0x0, %xr4, mas = 0x7",
     unlock="stqp,2\t%dr0, 0x0, %xr4, mas = 0x2", v5=True)


def kernel(c):
    n = c["name"]
    q = c["lock"].startswith(("ldq", "ldqp"))
    # A 16-byte lock loads %qr4/%xr4 (%dr4, %dr5); the stored value is the
    # same register with its low half incremented.
    # (A 128-bit %xr4 is left as loaded: the store writes the old value.)
    op = ("addd,1\t0x0, 0x0, %dr6" if c["lock"].startswith("ldqp")
          else "addd,0\t%dr4, 0x1, %dr4" if q
          else "addd,0\t%dr4, 0x1, %dr5")
    def fill(t):
        return t.replace("%(n)s", n)
    body = fill(c["between"])
    s = "\t.global\tll_%s\n\t.type\tll_%s, #function\n\t.align\t8\nll_%s:\n" % (
        n, n, n)
    s += instr("setwd\twsz = 0x8, nfx = 0x1, dbl = 0x0",
               "setbn\trsz = 0x3, rbs = 0x4, rcur = 0x0",
               "addd,0\t0x0, 0x0, %dr3",
               "addd,1\t0x0, 0x77, %dr7")
    s += ".Lh_%s:\n" % n
    s += c["pre"]
    s += instr("nop 1")                       # MCSTBug #163716 (hwbugs.md)
    s += instr(c["lock"], "nop 4")
    s += instr(op)
    s += body
    if c["unlock"]:
        s += instr(c["unlock"], *(["rbranch\t.Lf_%s" % n] if c["rb"] else []))
    s += fill(c["after"])
    s += ".Ln_%s:\n" % n
    s += instr("subd,0\t%dr2, 0x1, %dr2")
    s += instr("cmpldb,0\t0x0, %dr2, %pred0")
    s += instr("ibranch\t.Lh_%s ? %%pred0" % n)
    s += instr("return\t%ctpr3", "addd,0\t%dr3, 0x0, %dr0")
    s += instr("ct\t%ctpr3")
    s += ".Lf_%s:\n" % n
    s += instr("addd,0\t%dr3, 0x1, %dr3", "ibranch\t.Ln_%s" % n)
    s += "\t.size\tll_%s, .-ll_%s\n\n" % (n, n)
    return s


def fn_head(name):
    return ("\t.global\t%s\n\t.type\t%s, #function\n\t.align\t8\n%s:\n"
            % (name, name, name))


def common():
    s = fn_head("ll_empty")
    s += instr("setwd\twsz = 0x4, nfx = 0x1, dbl = 0x0", "return\t%ctpr3")
    s += instr("ct\t%ctpr3")
    s += "\t.size\tll_empty, .-ll_empty\n\n"
    s += fn_head("ll_clkr")
    s += instr("setwd\twsz = 0x4, nfx = 0x1, dbl = 0x0", "return\t%ctpr3",
               "rrd,0\t%clkr, %dr0")
    s += instr("ct\t%ctpr3")
    s += "\t.size\tll_clkr, .-ll_clkr\n\n"
    # Plain loads and stores until *stop.
    for kind in ("load", "store"):
        name = "llb_" + kind
        s += fn_head(name)
        s += instr("setwd\twsz = 0x8, nfx = 0x1, dbl = 0x0",
                   "addd,0\t0x0, 0x0, %dr3")
        s += ".Lh_%s:\n" % name
        for _ in range(8):
            s += instr("ldd,0\t%dr0, 0x0, %dr4" if kind == "load"
                       else "std,2\t%dr0, 0x0, %dr2")
        s += instr("ldd,0\t%dr1, 0x0, %dr5", "addd,1\t%dr3, 0x8, %dr3")
        s += instr("cmpedb,0\t%dr5, 0x0, %pred0")
        s += instr("ibranch\t.Lh_%s ? %%pred0" % name)
        s += instr("return\t%ctpr3", "addd,0\t%dr3, 0x0, %dr0")
        s += instr("ct\t%ctpr3")
        s += "\t.size\t%s, .-%s\n\n" % (name, name)
    # Fetch-add until *stop, D cycles between lock and unlock; retried
    # (rmw) or not (try).
    for retry in (True, False):
        for d in ((0, 64, 512) if retry
                  else (0, 64, 512, 1024, 1536, 2048, 3072, 4096)):
            name = "llb_%s_%d" % ("rmw" if retry else "try", d)
            s += fn_head(name)
            s += instr("setwd\twsz = 0x8, nfx = 0x1, dbl = 0x0",
                       "addd,0\t0x0, 0x0, %dr3", "addd,1\t0x0, 0x0, %dr8")
            s += ".Lh_%s:\n" % name
            s += instr("nop 1")
            s += instr(LOCK, "nop 4")
            s += instr("addd,0\t%dr4, 0x1, %dr5")
            if d:
                s += delay(d)
            s += instr(UNLOCK, "rbranch\t.Lf_%s" % name)
            s += instr("addd,0\t%dr3, 0x1, %dr3")
            s += ".Ln_%s:\n" % name
            s += instr("ldd,0\t%dr1, 0x0, %dr6")
            s += instr("cmpedb,0\t%dr6, 0x0, %pred0")
            s += instr("ibranch\t.Lh_%s ? %%pred0" % name)
            s += instr("shld,0\t%dr8, 0x20, %dr8")
            s += instr("return\t%ctpr3", "ord,0\t%dr3, %dr8, %dr0")
            s += instr("ct\t%ctpr3")
            s += ".Lf_%s:\n" % name
            s += instr("addd,0\t%dr8, 0x1, %dr8",
                       "ibranch\t.L%s_%s" % ("h" if retry else "n", name))
            s += "\t.size\t%s, .-%s\n\n" % (name, name)
    # A lock taken and abandoned: lock-wait, about 4096 cycles without a
    # memory access, then the load of *stop (which ends the lock).
    name = "llb_abandon_4096"
    s += fn_head(name)
    s += instr("setwd\twsz = 0x8, nfx = 0x1, dbl = 0x0",
               "addd,0\t0x0, 0x0, %dr3")
    s += ".Lh_%s:\n" % name
    s += instr("nop 1")
    s += instr(LOCK, "nop 4")
    s += delay(4096)
    s += instr("ldd,0\t%dr1, 0x0, %dr6", "addd,1\t%dr3, 0x1, %dr3")
    s += instr("cmpedb,0\t%dr6, 0x0, %pred0")
    s += instr("ibranch\t.Lh_%s ? %%pred0" % name)
    s += instr("return\t%ctpr3", "addd,0\t%dr3, 0x0, %dr0")
    s += instr("ct\t%ctpr3")
    s += "\t.size\t%s, .-%s\n\n" % (name, name)
    # The longest plain load of *a (in %clkr cycles, the load and a use).
    name = "llb_maxlat"
    s += fn_head(name)
    s += instr("setwd\twsz = 0x8, nfx = 0x1, dbl = 0x0",
               "addd,0\t0x0, 0x0, %dr3")
    s += ".Lh_%s:\n" % name
    s += instr("rrd,0\t%clkr, %dr4")
    s += instr("ldd,0\t%dr0, 0x0, %dr5")
    s += instr("addd,0\t%dr5, 0x0, %dr6")
    s += instr("rrd,0\t%clkr, %dr7")
    s += instr("subd,0\t%dr7, %dr4, %dr8")
    s += instr("cmpbdb,0\t%dr3, %dr8, %pred0")
    s += instr("addd,0\t%dr8, 0x0, %dr3 ? %pred0")
    s += instr("ldd,0\t%dr1, 0x0, %dr6")
    s += instr("cmpedb,0\t%dr6, 0x0, %pred1")
    s += instr("ibranch\t.Lh_%s ? %%pred1" % name)
    s += instr("return\t%ctpr3", "addd,0\t%dr3, 0x0, %dr0")
    s += instr("ct\t%ctpr3")
    s += "\t.size\t%s, .-%s\n\n" % (name, name)
    # About 4096 cycles without a lock (the baseline for the above).
    name = "llb_idle_4096"
    s += fn_head(name)
    s += instr("setwd\twsz = 0x8, nfx = 0x1, dbl = 0x0",
               "addd,0\t0x0, 0x0, %dr3")
    s += ".Lh_%s:\n" % name
    s += delay(4096)
    s += instr("ldd,0\t%dr1, 0x0, %dr6", "addd,1\t%dr3, 0x1, %dr3")
    s += instr("cmpedb,0\t%dr6, 0x0, %pred0")
    s += instr("ibranch\t.Lh_%s ? %%pred0" % name)
    s += instr("return\t%ctpr3", "addd,0\t%dr3, 0x0, %dr0")
    s += instr("ct\t%ctpr3")
    s += "\t.size\t%s, .-%s\n\n" % (name, name)
    return s


def main():
    out = sys.argv[1] if len(sys.argv) > 1 else os.path.dirname(
        os.path.abspath(__file__))
    base = HEAD + common() + "".join(kernel(c) for c in CASES
                                       if not c["v5"])
    v5 = HEAD + "".join(kernel(c) for c in CASES if c["v5"])
    with open(os.path.join(out, "lockloss.s"), "w") as f:
        f.write(base)
    with open(os.path.join(out, "lockloss-v5.s"), "w") as f:
        f.write(v5)
    # The case list for the driver.
    with open(os.path.join(out, "lockloss-cases.h"), "w") as f:
        f.write("/* SPDX-License-Identifier: GPL-3.0-or-later */\n"
                "/* Generated by gen_lockloss.py; do not edit.  */\n")
        for c in CASES:
            f.write("%sLL_CASE (%s, \"%s\")\n%s" % (
                "#ifdef LL_V5\n" if c["v5"] else "", c["name"],
                c["what"].replace('"', '\\"'),
                "#endif\n" if c["v5"] else ""))


if __name__ == "__main__":
    main()
