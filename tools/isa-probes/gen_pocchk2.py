"""Write pocchk2.s and pocchk2-cases.h: checks of the proof-of-concept
back end's findings I28, I31, I32, I34, I37, I41 and A21
(docs/spec-poc-findings.md) for pocchk2.c.

  python3 tools/isa-probes/gen_pocchk2.py

Functions are  long p2_NAME(long *mem, long a, long b).  Timing cases
(t_*) return %clkr cycles of a block of work; the others a value.
"""

from pathlib import Path

HERE = Path(__file__).resolve().parent
HEADER = """! SPDX-License-Identifier: GPL-3.0-or-later
! Generated by tools/isa-probes/gen_pocchk2.py; see pocchk2.c.
	.ignore	ld_st_style
	.ignore	strict_delay
	.text
"""
cases, text = [], []
ONE, HALF, QUARTER = ("0x3ff0000000000000", "0x3fe0000000000000",
                      "0x3fd0000000000000")


def wi(*ops):
    return "\t{\n" + "".join(f"\t  {o}\n" for o in ops) + "\t}\n"


def nops(n):
    out = ""
    while n > 0:
        k = min(n, 8)
        out += wi(f"nop {k - 1}" if k > 1 else "nop")
        n -= k
    return out


def raw(name, body):
    """A function with BODY as it is (it sets its own window)."""
    fn = f"p2_{name}"
    text.append(f"\n\t.global\t{fn}\n\t.type\t{fn}, #function\n\t.align\t8\n"
                f"{fn}:\n{body}\t.size\t{fn}, .-{fn}\n")


def func(name, body, kind="V", wsz=0x10):
    cases.append((name, kind))
    raw(name, wi(f"setwd\twsz = {wsz:#x}, nfx = 0x1, dbl = 0x0") + body
        + wi("return\t%ctpr3") + nops(6) + wi("ct\t%ctpr3"))


def timed(name, setup, step, n=32, wsz=0x10):
    body = setup + nops(8) + wi("rrd,0\t%clkr, %dr28")
    for i in range(n):
        body += step(i) if callable(step) else step
    body += wi("rrd,0\t%clkr, %dr29") + nops(2)
    body += wi("subd,0\t%dr29, %dr28, %dr0")
    func(name, body, "T", wsz)


def lit(v):
    return f"_f64,_lts0 {v}"


# I34: fmul_addd chained through its first, second or third operand
# (the addend); GAP empty cycles after each step.
for kind, op in (("op1", "fmul_addd,0\t%dr2, %dr4, %dr5, %dr2"),
                 ("op2", "fmul_addd,0\t%dr4, %dr2, %dr5, %dr2"),
                 ("addend", "fmul_addd,0\t%dr4, %dr5, %dr2, %dr2")):
    for gap in range(10):
        timed(f"t_fma_{kind}_g{gap}",
              wi(f"addd,0\t0x0, {lit(ONE)}, %dr2")
              + wi(f"addd,0\t0x0, {lit(HALF)}, %dr4")
              + wi(f"addd,0\t0x0, {lit(QUARTER)}, %dr5"),
              wi(op) + nops(gap), n=16)

# I37: four independent loads to a + {0, b, 2b, 3b}, then 10 empty
# cycles, then (A) their registers overwritten, (B) nothing, (D) read;
# (C) the step without the loads.  a advances by 4b a step.
LD4 = ["ldd,0\t%dr7, 0x0, %dr20", "ldd,2\t%dr7, %dr11, %dr21",
       "ldd,3\t%dr7, %dr12, %dr22", "ldd,5\t%dr7, %dr13, %dr23",
       "addd,1\t%dr7, %dr14, %dr7"]
SET4 = (wi("addd,0\t0x0, %dr1, %dr7", "addd,1\t0x0, %dr2, %dr11",
           "shld,3\t%dr2, 0x1, %dr12", "shld,4\t%dr2, 0x2, %dr14")
        + wi("addd,0\t%dr11, %dr12, %dr13"))
for case, after in (("A", wi("addd,0\t0x0, 0x0, %dr20", "addd,1\t0x0, 0x0, %dr21",
                             "addd,3\t0x0, 0x0, %dr22", "addd,4\t0x0, 0x0, %dr23")),
                    ("B", ""),
                    ("D", wi("ord,0\t%dr20, %dr21, %dr24", "ord,1\t%dr22, %dr23, %dr25"))):
    timed(f"t_dead_{case}", SET4, wi(*LD4) + nops(10) + after)
timed("t_dead_C", SET4, wi(LD4[-1]) + nops(10))

# I31: what a call costs by the callee's window size.  The leaf sets
# window W and returns; the caller (window 16) hands over 4 pairs.
for w in (4, 8, 16, 32, 64, 112):
    raw(f"leaf{w}", wi(f"setwd\twsz = {w:#x}, nfx = 0x1, dbl = 0x0",
                       "return\t%ctpr3") + nops(6) + wi("ct\t%ctpr3"))
    timed(f"t_call_w{w}", "",
          wi(f"disp\t%ctpr1, p2_leaf{w}") + nops(4) + wi("call\t%ctpr1, wbs = 0xc"),
          n=16)


# Recursion: p2_recW_B calls itself (window W, wbs B) until the depth
# in %dg16 (a global, so that no window register above %dr63 is needed)
# reaches 0.  t_rec* time a call of depth a.
def rec(w, b):
    name = f"rec{w}_{b}"
    raw(name, wi(f"setwd\twsz = {w:#x}, nfx = 0x1, dbl = 0x0",
                 f"disp\t%ctpr1, p2_{name}", "cmpedb,0\t%dg16, 0x0, %pred0")
        + wi("subd,0\t%dg16, 0x1, %dg16") + nops(4)
        + wi(f"call\t%ctpr1, wbs = {b:#x} ? ~%pred0")
        + wi("return\t%ctpr3") + nops(6) + wi("ct\t%ctpr3"))
    body = (wi(f"disp\t%ctpr1, p2_{name}", "addd,0\t0x0, %dr1, %dg16")
            + nops(6) + wi("rrd,0\t%clkr, %dr28")
            + wi("call\t%ctpr1, wbs = 0xc") + wi("rrd,0\t%clkr, %dr29")
            + nops(2) + wi("subd,0\t%dr29, %dr28, %dr0"))
    func(f"t_{name}", body, "T")


for w in (8, 16, 32, 48, 64, 112):
    rec(w, w - 4)
rec(48, 28)
rec(40, 28)
# I32: wbs smaller than half the window.
for w, b in ((16, 8), (16, 7), (32, 16), (32, 15), (32, 12)):
    rec(w, b)

# setwd inside a function: two empty instructions, setwd to the same
# size twice, grow 16 -> 32 pairs and back.
timed("t_setwd_none", "", wi("nop") + wi("nop"))
timed("t_setwd_same", "", wi("setwd\twsz = 0x10, nfx = 0x1, dbl = 0x0")
      + wi("setwd\twsz = 0x10, nfx = 0x1, dbl = 0x0"))
timed("t_setwd_grow", "", wi("setwd\twsz = 0x20, nfx = 0x1, dbl = 0x0")
      + wi("setwd\twsz = 0x10, nfx = 0x1, dbl = 0x0"))


# A21: 16 read-modify-writes on 16 cache lines of mem: lock-wait load
# (MAS 0x7), K empty cycles, the operation, unlock store (MAS 0x2) with
# rbranch back to the load, as lcc's templates.
def atomics(name, k, kind, k2=0):
    def step(i):
        lbl = f".L{name}_{i}"
        off = f"{64 * i:#x}"
        s = f"{lbl}:\n" + wi(f"ldd,0\t%dr0, {off}, %dr20, mas=0x7") + nops(k)
        if kind == "add":
            s += wi("addd,0\t%dr20, 0x1, %dr21")
        elif kind == "cas":
            s += wi("cmpedb,0\t%dr20, 0x0, %pred0") + nops(k2)
            s += wi("merged,0\t%dr20, 0x1, %dr21, %pred0")
        else:
            s += ""
        data = "%dr22" if kind == "xchg" else "%dr21"
        s += wi(f"std,2\t%dr0, {off}, {data}, mas=0x2", f"rbranch\t{lbl}")
        return s
    timed(name, wi("addd,0\t0x0, 0x5, %dr22"), step, n=16)


for k in range(6):
    atomics(f"t_atom_add_n{k}", k, "add")
for k in range(4):
    atomics(f"t_atom_xchg_n{k}", k, "xchg")
for k, k2 in ((2, 1), (3, 1), (7, 0)):
    atomics(f"t_atom_cas_n{k}_{k2}", k, "cas", k2)

# I28: two stores in one instruction D bytes apart (ALC2 and ALC5), as
# std pairs and as AAU staad pairs; a store and a load D bytes apart.
AAU = (wi("addd,0\t0x0, %dr0, %dr7", "addd,1\t%dr0, %dr1, %dr8",
          "addd,3\t0x0, 0x0, %dr24", "addd,4\t0x0, 0x7, %dr3")
       + nops(2)
       + wi("aaurwd,2\t%dr7, %aad0", "aaurwd,5\t%dr8, %aad1")
       + wi("aaurwd,2\t%dr24, %aasti1", "aaurwd,5\t%dr24, %aasti2"))
for d in (8, 64, 256):
    # std with fixed bases and literal offsets; t_st2_std_inc_d* advance
    # the bases with an addd each (ALC1's result reaches ALC5's store
    # across clusters a cycle late: a stall step, nothing store-specific,
    # as t_stbase_k* show).
    timed(f"t_st2_std_d{d}", wi("addd,0\t0x0, %dr0, %dr7",
                                "addd,1\t%dr0, %dr1, %dr8",
                                "addd,3\t0x0, 0x7, %dr3"),
          lambda i: wi(f"std,2\t%dr7, {8 * i:#x}, %dr3",
                       f"std,5\t%dr8, {8 * i:#x}, %dr3"))
    timed(f"t_st2_std_inc_d{d}", wi("addd,0\t0x0, %dr0, %dr7",
                                    "addd,1\t%dr0, %dr1, %dr8",
                                    "addd,3\t0x0, 0x7, %dr3"),
          wi("std,2\t%dr7, 0x0, %dr3", "std,5\t%dr8, 0x0, %dr3",
             "addd,0\t%dr7, 0x8, %dr7", "addd,1\t%dr8, 0x8, %dr8"))
    timed(f"t_st2_staad_d{d}", AAU,
          wi("staad,2\t%dr3, %aad0[ %aasti1 ]", "incr,2\t%aaincr0",
             "staad,5\t%dr3, %aad1[ %aasti2 ]", "incr,5\t%aaincr0"))
    timed(f"t_stld_std_d{d}", wi("addd,0\t0x0, %dr0, %dr7",
                                 "addd,1\t%dr0, %dr1, %dr8",
                                 "addd,3\t0x0, 0x7, %dr3"),
          lambda i: wi(f"std,2\t%dr7, {8 * i:#x}, %dr3",
                       f"ldd,0\t%dr8, {8 * i:#x}, %dr20"))
    # The same at fixed addresses (every instruction stores to the same
    # two places, as bench.py's stst_*/stld_* kernels do).
    timed(f"t_st2_std_fix_d{d}", wi("addd,0\t0x0, %dr0, %dr7",
                                    "addd,1\t%dr0, %dr1, %dr8",
                                    "addd,3\t0x0, 0x7, %dr3"),
          wi("std,2\t%dr7, 0x0, %dr3", "std,5\t%dr8, 0x0, %dr3"))
    timed(f"t_st2_staad_fix_d{d}", AAU,
          wi("staad,2\t%dr3, %aad0[ %aasti1 ]", "staad,5\t%dr3, %aad1[ %aasti2 ]"))
    timed(f"t_stld_std_fix_d{d}", wi("addd,0\t0x0, %dr0, %dr7",
                                     "addd,1\t%dr0, %dr1, %dr8",
                                     "addd,3\t0x0, 0x7, %dr3"),
          wi("std,2\t%dr7, 0x0, %dr3", "ldd,0\t%dr8, 0x0, %dr20"))
    timed(f"t_stld_staad_fix_d{d}", AAU,
          wi("staad,2\t%dr3, %aad0[ %aasti1 ]", "ldd,0\t%dr8, 0x0, %dr20"))
    timed(f"t_stld_staad_d{d}", AAU,
          wi("staad,2\t%dr3, %aad0[ %aasti1 ]", "incr,2\t%aaincr0",
             "ldd,0\t%dr8, 0x0, %dr20", "addd,1\t%dr8, 0x8, %dr8"))


# The base register of a store (or a load) written K cycles before it:
# K registers take turns, each advanced by 8K in the instruction that
# uses it, so it was last written K instructions before (the PoC's I35).
for k in range(1, 7):
    setup = wi("addd,3\t0x0, 0x7, %dr3") + "".join(
        wi(f"addd,0\t%dr0, {8 * j:#x}, %dr{8 + j}") for j in range(k))
    timed(f"t_stbase_k{k}", setup,
          lambda i, k=k: wi(f"std,2\t%dr{8 + i % k}, 0x0, %dr3",
                            f"addd,0\t%dr{8 + i % k}, {8 * k:#x}, %dr{8 + i % k}"))
    timed(f"t_ldbase_k{k}", setup,
          lambda i, k=k: wi(f"ldd,0\t%dr{8 + i % k}, 0x0, %dr20",
                            f"addd,1\t%dr{8 + i % k}, {8 * k:#x}, %dr{8 + i % k}"))
    timed(f"t_stdata_k{k}", setup,
          lambda i, k=k: wi(f"std,2\t%dr0, {8 * i:#x}, %dr{8 + i % k}",
                            f"addd,0\t%dr{8 + i % k}, {8 * k:#x}, %dr{8 + i % k}"))

# I41: an APB loop as apb-loop.s's loopA, summing the first n elements
# of an area: (disp) base a, disp -64, n = b; (back_w, back_d) base a,
# %aaincr1 = -1 written with aaurw / aaurwd, n = 8.
def apb(name, base_setup, prog, n_reg):
    body = (wi(f"ldisp\t%ctpr2, .L{name}_prog", *base_setup,
               f"addd,0\t0x0, {lit('0xff2000000000')}, %dr3",
               "addd,1\t0x0, 0x0, %dr8", "addd,3\t0x0, 0x0, %dr9",
               "addd,4\t0x0, 0x0, %dr10")
            + wi(f"insfd,0\t%dr3, _f32s,_lts0 0x8800, {n_reg}, %dr3")
            + wi(f"disp\t%ctpr1, .L{name}_loop", "rwd,0\t%dr3, %lsr")
            + wi("nop 7", "bap") + wi("nop 7") + wi("nop 7")
            + f".L{name}_loop:\n"
            + wi("loop_mode", "alc\talcf=1, alct=1", f"ct\t%ctpr1 ? %NOT_LOOP_END",
                 "movad,0\tarea=0, ind=0, am=1, be=0, %dr8",
                 "addd,0\t%dr9, %dr8, %dr9", "addd,1\t%dr10, 0x1, %dr10")
            + wi("nop 7", "disp\t%ctpr2, disp=0x0")
            + wi("addd,0\t%dr9, %dr8, %dr0"))
    func(name, body)
    text.append(f"\t.align\t8\n.L{name}_prog:\n" + wi(prog))


apb("apb_disp", ["aaurwd,2\t%dr1, %aad0"],
    "fapb\tct=1, dcd=0, fmt=4, mrng=8, d=0, incr=0, ind=0, asz=5, abs=0, disp=-64",
    "%dr2")
# The backward area: %aaincr1 = -1 (written with aaurw or aaurwd) and
# the element count 8 are set before the AAU writes.
def apb_back(w, wr, disp=0, low=""):
    name = f"apb_back{low}_{w}"
    body = (wi("subd,0\t0x0, 0x1, %dr11", "addd,1\t0x0, 0x8, %dr12") + nops(2)
            + wi(f"ldisp\t%ctpr2, .L{name}_prog", "aaurwd,2\t%dr1, %aad0", wr,
                 f"addd,0\t0x0, {lit('0xff2000000000')}, %dr3",
                 "addd,1\t0x0, 0x0, %dr8", "addd,3\t0x0, 0x0, %dr9",
                 "addd,4\t0x0, 0x0, %dr10")
            + wi("insfd,0\t%dr3, _f32s,_lts0 0x8800, %dr12, %dr3")
            + wi(f"disp\t%ctpr1, .L{name}_loop", "rwd,0\t%dr3, %lsr")
            + wi("nop 7", "bap") + wi("nop 7") + wi("nop 7")
            + f".L{name}_loop:\n"
            + wi("loop_mode", "alc\talcf=1, alct=1", "ct\t%ctpr1 ? %NOT_LOOP_END",
                 "movad,0\tarea=0, ind=0, am=1, be=0, %dr8",
                 "addd,0\t%dr9, %dr8, %dr9", "addd,1\t%dr10, 0x1, %dr10")
            + wi("nop 7", "disp\t%ctpr2, disp=0x0")
            + wi("addd,0\t%dr9, %dr8, %dr0"))
    func(name, body)
    text.append(f"\t.align\t8\n.L{name}_prog:\n"
                + wi("fapb\tct=1, dcd=0, fmt=4, mrng=8, d=0, incr=1, ind=0, "
                     f"asz=5, abs=0, disp={disp}"))


# back: base at the first element read (the highest), disp 0; backlow:
# base at the lowest element, the start 56 bytes above it (lcc's way).
for low, disp in (("", 0), ("low", 56)):
    apb_back("w", "aaurw,5\t%r11, %aaincr1", disp, low)
    apb_back("d", "aaurwd,5\t%dr11, %aaincr1", disp, low)


def write():
    (HERE / "pocchk2.s").write_text(HEADER + "".join(text))
    (HERE / "pocchk2-cases.h").write_text(
        "/* SPDX-License-Identifier: GPL-3.0-or-later */\n"
        "/* Generated by tools/isa-probes/gen_pocchk2.py.  */\n"
        + "".join(f"CASE ({n}, {k})\n" for n, k in cases))
    print(len(cases), "functions")


if __name__ == "__main__":
    write()
