static int fds[4];
static const struct ev *cur[4];

static void
set_open (int k)
{
  static const struct ev ticks = { "TICKS", 0x272 };
  cur[0] = &ticks;
  cur[1] = &dim1[k % NDIM1];
  cur[2] = &ddm[k][0];
  cur[3] = &ddm[k][1];
  for (int j = 0; j < 4; j++)
    fds[j] = pmu_open (cur[j]->cfg);
}

static void
set_close (void)
{
  for (int j = 0; j < 4; j++)
    if (fds[j] >= 0)
      close (fds[j]);
}

static void
set_start (void)
{
  for (int j = 0; j < 4; j++)
    if (fds[j] >= 0)
      ioctl (fds[j], PERF_EVENT_IOC_RESET, 0);
  for (int j = 0; j < 4; j++)
    if (fds[j] >= 0)
      ioctl (fds[j], PERF_EVENT_IOC_ENABLE, 0);
}

static void
set_stop (unsigned long *v)
{
  for (int j = 0; j < 4; j++)
    if (fds[j] >= 0)
      ioctl (fds[j], PERF_EVENT_IOC_DISABLE, 0);
  for (int j = 0; j < 4; j++)
    {
      v[j] = ~0UL;
      if (fds[j] >= 0 && read (fds[j], &v[j], sizeof v[j]) != sizeof v[j])
        v[j] = ~0UL;
    }
}

static void
set_print (const unsigned long *v, double iters)
{
  for (int j = 0; j < 4; j++)
    if (v[j] == ~0UL)
      printf ("  %s -", cur[j]->name);
    else
      printf ("  %s %.3f", cur[j]->name, v[j] / iters);
  printf ("\n");
}

/* --- memory ------------------------------------------------------------- */

static long
huge_kb (void)
{
  FILE *f = fopen ("/proc/self/smaps_rollup", "r");
  char line[256];
  long kb = -1;
  while (f && fgets (line, sizeof line, f))
    if (sscanf (line, "AnonHugePages: %ld", &kb) == 1)
      break;
  if (f)
    fclose (f);
  return kb;
}

static void *
region (long bytes, int huge)
{
  long big = 2L << 20;
  char *p = mmap (NULL, bytes + big, PROT_READ | PROT_WRITE,
                  MAP_PRIVATE | MAP_ANONYMOUS, -1, 0);
  if (p == MAP_FAILED)
    {
      perror ("mmap");
      exit (1);
    }
  char *q = (char *) (((unsigned long) p + big - 1) & ~(big - 1));
  madvise (q, bytes, huge ? MADV_HUGEPAGE : MADV_NOHUGEPAGE);
  return q;
}

static const unsigned long LSR = 0xff2000000000UL;   /* vlc, ldovl 255 */

/* --- col: column walks (pocchk3.c's col) -------------------------------- */

static long rows, cols = 600;
static long *ma, *mb;

/* The C functions take five arguments; call them through this type.  */
typedef long (*col_fn) (const long *, const long *, unsigned long, long,
                        long *);

static int
col_run1 (const struct ent *e, int same, long *cycles, int check)
{
  col_fn f = (col_fn) e->f;
  int k = (int) e->off, bad = 0;
  const char *kinds = e->how;
  long tot = 0;
  for (long c = 0; c < cols; c++)
    {
      const long *a = ma + c, *b;
      if (k < 2)
        b = a;
      else if (kinds[1] == '1')
        b = mb + c * rows;
      else
        b = same ? ma + c + 1 : mb + c;
      long cyc;
      long s = f (a, b, LSR | rows, cols, &cyc);
      tot += cyc;
      if (check)
        {
          long want = 0;
          for (long i = 0; i < rows - 6; i++)
            {
              want += a[i * cols];
              if (k > 1)
                want += kinds[1] == '1' ? b[i] : b[i * cols];
            }
          bad += s != want;
        }
    }
  *cycles = tot;
  return bad;
}

static void
col_run (long r, int huge, int same)
{
  rows = r;
  long bytes = (rows * cols * 8 + (2L << 20)) & ~((2L << 20) - 1);
  ma = region (bytes, huge);
  mb = region (bytes, huge);
  for (long i = 0; i < rows * cols; i++)
    {
      ma[i] = i ^ 0x5a5a;
      mb[i] = 3 * i + 1;
    }
  double iters = (double) rows * cols;
  printf ("column walks, %ld x %ld longs (%ld KB each, stride %ld B), %s, "
          "b %s; AnonHugePages %ld KiB\n", rows, cols, rows * cols * 8 / 1024,
          cols * 8, huge ? "MADV_HUGEPAGE" : "MADV_NOHUGEPAGE",
          same ? "= a's next column" : "its own matrix", huge_kb ());
  for (int i = 0; i < NENTS; i++)
    {
      const struct ent *e = &ents[i];
      if (!want (e, "C") || (same && (e->off < 2 || e->how[1] == '1')))
        continue;
      long cyc, best = 1L << 60;
      int bad = col_run1 (e, same, &cyc, 1);
      for (int p = 0; p < 3; p++)
        {
          col_run1 (e, same, &cyc, 0);
          best = cyc < best ? cyc : best;
        }
      printf ("%-8s cycles an iteration %.2f (best of 3 passes)%s\n",
              e->name + 4, best / iters, bad ? "  WRONG SUMS" : "");
      for (int k = 0; k < NSETS; k++)
        {
          unsigned long v[4];
          set_open (k);
          set_start ();
          col_run1 (e, same, &cyc, 0);
          set_stop (v);
          set_close ();
          printf ("  ");
          set_print (v, iters);
        }
    }
  munmap (ma, bytes);
  munmap (mb, bytes);
}

/* --- bk: a[i] * b[...] (pocchk3.c's bk) --------------------------------- */

typedef double (*bk_fn) (const double *, const double *, unsigned long,
                         long *, long);
static double *pool;
static const long pooln = 64L << 20;   /* 512 MiB of doubles */
static const long fresh0 = 4L << 20;   /* fresh stretches start here */
static long pos = 4L << 20;

static const double *
fresh (long n)
{
  if (pos + n + 4096 > pooln)
    pos = fresh0;
  const double *p = pool + pos;
  pos += n + 4096;
  return p;
}

/* The loop alone (what the monitors count).  */
static double
bk_call (const struct ent *e, const double *a, const double *b, long n,
         long *cyc)
{
  bk_fn f = (bk_fn) e->f;
  long t = n + e->off;
  return f (a, b, LSR | t, cyc, (t - 1) * 8);
}

/* One run: cycles an iteration; *bad counts wrong sums.  */
static double
bk_one (const struct ent *e, const double *a, const double *b, long n,
        int *bad)
{
  long d = e->off, t = n + d, cyc;
  char as = e->how[0], bs = e->how[1];
  double s = bk_call (e, a, b, n, &cyc), want = 0;
  for (long j = 0; j < n; j++)
    {
      double av = as == 'K' || as == 'N' ? 1 : as == 'Z' ? a[0] : a[j];
      double bv = bs == 'K' ? 1 : bs == 'C' ? b[0] : bs == 'F' ? b[j]
                  : b[t - 1 - j];
      want += av * bv;
    }
  if (s != want)
    (*bad)++;
  return (double) cyc / t;
}

/* Placements: 22 both arrays warm in L2 (n = 20,000, 160 KB each); 2m
   a warm, b a fresh stretch; m2 the reverse; mm both fresh; MM both
   fresh, n = 4 Mi (pocchk3.c's memory runs).  */
static void
bk_case (const struct ent *e, const char *pl)
{
  long n = pl[0] == 'M' ? 4L << 20 : 20000, d = e->off;
  long gap = ((n + d + 511) & ~511L) + 40;
  const double *wa = pool, *wb = pool + gap;
  int bad = 0, warm_a = pl[0] == '2', warm_b = pl[1] == '2';
  double best = 1e30;
  for (int r = 0; r < 6; r++)
    {
      const double *a = warm_a ? wa : fresh (gap);
      const double *b = warm_b ? wb : fresh (gap);
      double c = bk_one (e, a, b, n, &bad);
      if (r > 0 || !(warm_a || warm_b))
        best = c < best ? c : best;
      if (pl[0] == 'M' && r == 2)
        break;
    }
  printf ("%-9s %s  cycles an iteration %.3f%s\n", e->name + 3, pl, best,
          bad ? "  WRONG SUMS" : "");
  for (int k = 0; k < NSETS; k++)
    {
      unsigned long v[4];
      const double *a = warm_a ? wa : fresh (gap);
      const double *b = warm_b ? wb : fresh (gap);
      long cyc;
      /* Warm the warm array again, with a different fresh one.  */
      if (warm_a || warm_b)
        bk_call (e, warm_a ? wa : fresh (gap), warm_b ? wb : fresh (gap), n,
                 &cyc);
      set_open (k);
      set_start ();
      bk_call (e, a, b, n, &cyc);
      set_stop (v);
      set_close ();
      printf ("   ");
      set_print (v, (double) (n + d));
    }
}

static void
bk_run (int huge, const char *only)
{
  pool = region (pooln * 8, huge);
  for (long i = 0; i < pooln; i++)
    pool[i] = i % 7 + 1;
  printf ("a[i] * b[...] at II 4, %s, AnonHugePages %ld KiB\n",
          huge ? "MADV_HUGEPAGE" : "MADV_NOHUGEPAGE", huge_kb ());
  static const char *pls[] = { "22", "2m", "m2", "mm", "MM" };
  for (int i = 0; i < NENTS; i++)
    {
      const struct ent *e = &ents[i];
      if (!want (e, "B"))
        continue;
      for (int p = 0; p < 5; p++)
        if (!only || strstr (only, pls[p]))
          bk_case (e, pls[p]);
    }
  munmap (pool, pooln * 8);
}

int
main (int argc, char **argv)
{
  setvbuf (stdout, NULL, _IOLBF, 0);
  pagesize = sysconf (_SC_PAGESIZE);
  if (argc < 2)
    {
      fprintf (stderr, "usage: %s values|cost|col|bk [...]\n", argv[0]);
      return 2;
    }
  const char *s = argv[1];
  const char *f = getenv ("AL_FILTER");
  filter = f && *f ? f : NULL;
  if (strcmp (s, "values") == 0)
    {
      if (argc > 2)
        filter = argv[2];
      values ();
    }
  else if (strcmp (s, "cost") == 0)
    cost ();
  else if (strcmp (s, "col") == 0)
    {
      int huge = argc > 2 && strcmp (argv[2], "huge") == 0;
      col_run (500, huge, 0);
      col_run (4000, huge, 0);
      col_run (4000, huge, 1);
    }
  else if (strcmp (s, "bk") == 0)
    bk_run (!(argc > 2 && strcmp (argv[2], "nohuge") == 0),
            argc > 3 ? argv[3] : NULL);
  else
    return 2;
  return 0;
}
