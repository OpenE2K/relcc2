"""Write mas6.s and mas6-cases.h: the MAS encodings v6 adds (kernel
asm/mas.h: bit 4 "m1" set; with mod 3 the load-acquire / store-release
form, bit 6 "mt"; otherwise m2 = bits 0-1: 0 normal, 1 lock check or
"watch for modification", 2 speculative, 3 speculative lock check), for
mas6.c (spec/isa/speculation.md, "Other MAS kinds").

  python3 tools/isa-probes/gen_mas6.py

Value cases are  void m6_NAME(unsigned long *out, void *buf, unsigned long v):
loads put the value and its tag in out[0], out[1]; stores write v to
buf[1].  Timing cases (t_*) return the %clkr cycles of 32 dependent
loads (a pointer chase through buf[0] = buf) or 32 stores, so mas6.c
prints cycles per operation.  Only kinds that stay inside the program's
own memory are tried: no ch1 (bit 2 with m1), no mod 1/7 forms.
"""

from pathlib import Path

HERE = Path(__file__).resolve().parent
HEADER = """! SPDX-License-Identifier: GPL-3.0-or-later
! Generated by tools/isa-probes/gen_mas6.py; see mas6.c.
	.ignore	ld_st_style
	.text
"""
cases, text = [], []


def wi(*ops):
    return "\t{\n" + "".join(f"\t  {o}\n" for o in ops) + "\t}\n"


def func(name, body, kind):
    fn = f"m6_{name}"
    cases.append((name, kind))
    text.append(f"\n\t.global\t{fn}\n\t.type\t{fn}, #function\n\t.align\t8\n"
                f"{fn}:\n" + wi("setwd\twsz = 0x10, nfx = 0x1, dbl = 0x0",
                                "return\t%ctpr3")
                + body + wi("nop 5") + wi("ct\t%ctpr3")
                + f"\t.size\t{fn}, .-{fn}\n")


def load(name, mas, ch, sm=False):
    s = ",sm" if sm else ""
    func(name, wi("addd,0\t0x0, 0x0, %dr4")
         + wi(f"ldd,{ch}{s}\t%dr1, 0x0, %dr4, mas={mas:#x}") + wi("nop 7")
         + wi("gettagd,2\t%dr4, %r5") + wi("nop 2")
         + wi("puttagd,5\t%dr4, 0x0, %dr6") + wi("nop 2")
         + wi("std,2\t%dr0, 0x0, %dr6", "std,5\t%dr0, 0x8, %dr5"), "L")


def store(name, mas, ch):
    func(name, wi(f"std,{ch}\t%dr1, 0x8, %dr2, mas={mas:#x}") + wi("nop 7"),
         "S")


for mas in (0x13, 0x53):
    for ch in (0, 2, 3, 5):
        load(f"ld_{mas:02x}_c{ch}", mas, ch)
load("ld_12_c0", 0x12, 0)
load("ld_12_c2", 0x12, 2)
load("ld_12sm_c0", 0x12, 0, True)
load("ld_12sm_c2", 0x12, 2, True)
load("ld_10sm_c0", 0x10, 0, True)
load("ld_00sm_c0", 0x0, 0, True)
load("ld_03sm_c0", 0x3, 0, True)
load("ld_11_c0", 0x11, 0)
load("ld_11_c2", 0x11, 2)
for mas in (0x13, 0x53):
    for ch in (2, 5):
        store(f"st_{mas:02x}_c{ch}", mas, ch)
# A "watch for modification" load, then a store to the same address by
# the same thread, then a plain load of it.
func("watch_store", wi("ldd,0\t%dr1, 0x8, %dr4, mas=0x11") + wi("nop 7")
     + wi("std,2\t%dr1, 0x8, %dr2") + wi("nop 7")
     + wi("ldd,0\t%dr1, 0x8, %dr5") + wi("nop 7")
     + wi("std,2\t%dr0, 0x0, %dr4", "std,5\t%dr0, 0x8, %dr5"), "L")


def chase(name, mas, sm=False):
    s = ",sm" if sm else ""
    m = f", mas={mas:#x}" if mas is not None else ""
    body = wi("addd,0\t%dr1, 0x0, %dr4") + wi("nop 7")
    body += wi("rrd,0\t%clkr, %dr10")
    for _ in range(32):
        body += wi(f"ldd,0{s}\t%dr4, 0x0, %dr4{m}")
    body += wi("addd,0\t%dr4, 0x0, %dr5") + wi("rrd,0\t%clkr, %dr11")
    body += wi("nop 2") + wi("subd,0\t%dr11, %dr10, %dr0")
    func(name, body, "T")


def stores(name, mas):
    m = f", mas={mas:#x}" if mas is not None else ""
    body = wi("rrd,0\t%clkr, %dr10")
    for i in range(32):
        body += wi(f"std,2\t%dr1, {8 * (i % 8):#x}, %dr2{m}")
    body += wi("rrd,0\t%clkr, %dr11") + wi("nop 2")
    body += wi("subd,0\t%dr11, %dr10, %dr0")
    func(name, body, "T")


chase("t_chase_00", None)
chase("t_chase_13", 0x13)
chase("t_chase_53", 0x53)
chase("t_chase_12sm", 0x12, True)
chase("t_chase_10", 0x10)
def wait_stores(name):
    """lcc's release store: wait ld_c, st_c, then a plain std."""
    body = wi("rrd,0\t%clkr, %dr10")
    for i in range(32):
        body += wi("wait\tld_c = 1, st_c = 1")
        body += wi(f"std,2\t%dr1, {8 * (i % 8):#x}, %dr2")
    body += wi("rrd,0\t%clkr, %dr11") + wi("nop 2")
    body += wi("subd,0\t%dr11, %dr10, %dr0")
    func(name, body, "T")


wait_stores("t_st_wait")
stores("t_st_00", None)
stores("t_st_13", 0x13)
stores("t_st_53", 0x53)


def main():
    (HERE / "mas6.s").write_text(HEADER + "".join(text))
    (HERE / "mas6-cases.h").write_text(
        "/* SPDX-License-Identifier: GPL-3.0-or-later */\n"
        "/* Generated by tools/isa-probes/gen_mas6.py.  */\n"
        + "".join(f"CASE ({n}, {k})\n" for n, k in cases))
    print(len(cases), "cases")


if __name__ == "__main__":
    main()
