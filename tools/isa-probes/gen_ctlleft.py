"""Write ctlleft.s, ctlleft6.s and ctlleft-cases.h for ctlleft.c: the
control-transfer leftovers (spec/isa/control-transfer.md, predicates.md,
loops.md, operations-v3/v6):

  vfrpsz   which parameter-area sizes `vfrpsz rpsz = N` lets through
           (callers handing over 0..12 pairs), and which `wbs` a
           system call's `call` may use;
  t9       ctcond type 9 (`%MLOCK || %cmpN`, `|| %clpN`): what it
           tests, with and without a lock, and what it costs;
  spin     a test-and-set spinlock whose loop branch is type 9;
  fetch    branches into code that is not in the instruction cache:
           `disp` distance, `ipd`, `pref` (also before an `ibranch` and
           across a call), three-line targets from memory, and
           straight-line fetch of 8- to 64-byte wide instructions;
  v6       (ctlleft6.s, v6 only) qpcheck* latency, abgc/rbgc against
           rrs %bgr and vfbgv, fillr/fillc cost.

  python3 tools/isa-probes/gen_ctlleft.py

Value cases are  long cl_NAME(long *mem, long a, long b, long c);  timing
cases (KIND T) come as cl_NAME_16 and cl_NAME_32 (16 and 32 blocks) and
return %clkr cycles; fetch cases are  long cl_NAME(long *mem, long mode)
and return the cycles from the window's first instruction to the target
(mode 0: everything cached; 1: a 256 KiB run of other code first, 2: a
512 KiB run; ctlleft.c adds a 64 MiB data stream for mode 3).
"""

from pathlib import Path

HERE = Path(__file__).resolve().parent

HEADER = """! SPDX-License-Identifier: GPL-3.0-or-later
! Generated by tools/isa-probes/gen_ctlleft.py; see ctlleft.c.
	.ignore	ld_st_style
	.ignore	strict_delay
	.text
"""

cases = {"": [], "6": []}       # file suffix -> [(name, kind)]
text = {"": [], "6": []}


def wi(*ops):
    return "\t{\n" + "".join(f"\t  {o}\n" for o in ops) + "\t}\n"


def nops(n):
    """N cycles of nothing (N >= 0)."""
    out = ""
    while n > 0:
        k = min(n, 8)
        out += wi(f"nop {k - 1}" if k > 1 else "nop")
        n -= k
    return out


def raw(fn, body, f=""):
    text[f].append(f"\n\t.global\t{fn}\n\t.type\t{fn}, #function\n"
                   f"\t.align\t8\n{fn}:\n{body}\t.size\t{fn}, .-{fn}\n")


def func(name, body, kind="V", f="", wsz=0x20):
    cases[f].append((name, kind))
    raw(f"cl_{name}", wi(f"setwd\twsz = {wsz:#x}, nfx = 0x1, dbl = 0x0")
        + body + wi("return\t%ctpr3") + nops(5) + wi("ct\t%ctpr3"), f)


def taken_or_not(lab, *ops):
    """An instruction OPS whose transfer goes to LAB_t: 1 if taken, 2 if
    not, left in %dr0."""
    return (wi(*ops) + wi("addd,0\t0x0, 0x2, %dr0") + wi(f"ibranch\t{lab}_e")
            + f"{lab}_t:\n" + wi("addd,0\t0x0, 0x1, %dr0") + f"{lab}_e:\n")


def timed(name, setup, block, f=""):
    """cl_NAME_16 and cl_NAME_32: K blocks; block(i, nxt) is block i,
    ending where block i + 1 (label nxt) starts."""
    cases[f].append((name, "T"))
    for k in (16, 32):
        lab = lambda i, k=k: f".L{name}_{k}_b{i}"
        body = setup + nops(8) + wi("rrd,0\t%clkr, %dr10")
        for i in range(k):
            body += lab(i) + ":\n" + block(i, lab(i + 1))
        body += lab(k) + ":\n" + wi("rrd,0\t%clkr, %dr11") + nops(2)
        body += wi("subd,0\t%dr11, %dr10, %dr0")
        raw(f"cl_{name}_{k}", wi("setwd\twsz = 0x20, nfx = 0x1, dbl = 0x0")
            + body + wi("return\t%ctpr3") + nops(5) + wi("ct\t%ctpr3"), f)


# ---------------------------------------------------------------- vfrpsz
# Callees: vfrpsz rpsz = N with setwd wsz = 0x10 in the first
# instruction (CS1 opcode 1 always carries a setwd: gas fills in wsz 0
# when none is written), the same check in the second instruction, the
# kernel's own entry (vfrpsz 4, setwd 4, setbp 0) and no check at all.
RPSZ = (0, 1, 2, 3, 4, 5, 6, 7, 8, 12, 16, 31)
PAIRS = (0, 1, 2, 3, 4, 5, 6, 7, 8, 12)
VF = []


def vf_callee(name, first, rest=""):
    VF.append(name)
    raw(f"vf_{name}", wi(*first, "return\t%ctpr3") + rest + nops(5)
        + wi("ct\t%ctpr3"))


SETWD16 = "setwd\twsz = 0x10, nfx = 0x1, dbl = 0x0"
vf_callee("none", [SETWD16])
for n in RPSZ:
    vf_callee(f"r{n}", [f"vfrpsz\trpsz = {n:#x}", SETWD16])
for n in (0, 4, 8):
    vf_callee(f"late{n}", [SETWD16],
              wi(f"vfrpsz\trpsz = {n:#x}", SETWD16))
vf_callee("k4", ["vfrpsz\trpsz = 0x4",
                 "setwd\twsz = 0x4, nfx = 0x1, dbl = 0x0", "setbp\tpsz = 0x0"])
# Which check traps in k4 with 5+ pairs: the window size alone (setwd
# wsz = 4, CS1 opcode 0) and a wide vfrpsz with that small window.
vf_callee("w4", ["setwd\twsz = 0x4, nfx = 0x1, dbl = 0x0"])
vf_callee("k4r16", ["vfrpsz\trpsz = 0x10",
                    "setwd\twsz = 0x4, nfx = 0x1, dbl = 0x0"])
vf_callee("alone0", ["vfrpsz\trpsz = 0x0"])
vf_callee("alone4", ["vfrpsz\trpsz = 0x4"])

# Callers: long vf_callP (void (*f) (void)) with wsz 0x10 calls f with
# wbs = 0x10 - P, so f's parameter area is P pairs; returns 1.
for p in PAIRS:
    raw(f"vf_call{p}", wi(SETWD16) + wi("movtd,0\t%dr0, %ctpr1") + nops(9)
        + wi(f"call\t%ctpr1, wbs = {16 - p:#x}")
        + wi("return\t%ctpr3", "addd,0\t0x0, 0x1, %dr0") + nops(5)
        + wi("ct\t%ctpr3"))

# System calls (entry 3, getpid = 20) with P pairs handed over:
# long sc_getpidP (void) returns the result.
for p in range(1, 9):
    w = 16 - p
    raw(f"sc_getpid{p}", wi(SETWD16, "sdisp\t%ctpr1, 0x3",
                             f"addd,0\t0x0, 0x14, %dr{2 * w}")
        + nops(6) + wi(f"call\t%ctpr1, wbs = {w:#x}")
        + wi("return\t%ctpr3", f"addd,0\t%dr{2 * w}, 0x0, %dr0") + nops(5)
        + wi("ct\t%ctpr3"))

# ---------------------------------------------------------------- type 9
# a = %dr1, b = %dr2, c = %dr3.  1 = taken, 2 = not taken.
for k in (0, 1, 3, 4):
    func(f"t9_cmp{k}", taken_or_not(
        f".Lc{k}", f"cmpedb,{k}\t%dr1, %dr2, %pred0",
        f"ibranch\t.Lc{k}_t ? %MLOCK || %cmp{k}"))
func("t9_ncmp0", taken_or_not(".Lnc0", "cmpedb,0\t%dr1, %dr2, %pred0",
                              "ibranch\t.Lnc0_t ? %MLOCK || ~%cmp0"))
func("t9_cmp01", taken_or_not(
    ".Lc01", "cmpedb,0\t%dr1, %dr2, %pred0", "cmpedb,1\t%dr1, %dr3, %pred1",
    "ibranch\t.Lc01_t ? %MLOCK || %cmp0 || %cmp1"))
func("t9_ncmp34", taken_or_not(
    ".Lc34", "cmpedb,3\t%dr1, %dr2, %pred0", "cmpedb,4\t%dr1, %dr3, %pred1",
    "ibranch\t.Lc34_t ? %MLOCK || ~%cmp3 || ~%cmp4"))
func("t9_rbcmp0", taken_or_not(".Lrb0", "cmpedb,0\t%dr1, %dr2, %pred0",
                               "rbranch\t.Lrb0_t ? %cmp0"))
# A compare with a different predicate destination than the CT reads:
# the condition comes from the ALC, not from %predN.
func("t9_cmp0_p7", wi("cmpedb,0\t%dr3, %dr3, %pred0") + nops(3)
     + taken_or_not(".Lp7", "cmpedb,0\t%dr1, %dr2, %pred7",
                    "ibranch\t.Lp7_t ? %MLOCK || %cmp0"))
# gas rejects %cmpN with no integer compare written with ",N" in that
# ALC ("no integer comparison with an explicitly specified ALC matches
# %cmp1 in ctcond"), an FP compare (fcmpeqdb) included, so neither is
# probed here.
# The compare under a false predicate (%pred1 = (c == c + 1) false).
func("t9_predf0", wi("addd,0\t%dr3, 0x1, %dr9") + nops(1)
     + wi("cmpedb,1\t%dr3, %dr9, %pred1") + nops(3)
     + taken_or_not(".Lpf0", "cmpedb,0\t%dr1, %dr2, %pred0 ? %pred1",
                    "ibranch\t.Lpf0_t ? %MLOCK || %cmp0"))
# The same with a true predicate (%pred1 = (c == c)).
func("t9_predt0", wi("cmpedb,1\t%dr3, %dr3, %pred1") + nops(3)
     + taken_or_not(".Lpt0", "cmpedb,0\t%dr1, %dr2, %pred0 ? %pred1",
                    "ibranch\t.Lpt0_t ? %MLOCK || %cmp0"))
# A cmpand (a & b == 0: never for these values).
func("t9_cmpand0", taken_or_not(".Lca0", "cmpandedb,0\t%dr1, %dr2, %pred0",
                                "ibranch\t.Lca0_t ? %MLOCK || %cmp0"))
func("t9_ncmpand0", taken_or_not(".Lnca0", "cmpandedb,0\t%dr1, %dr2, %pred0",
                                 "ibranch\t.Lnca0_t ? %MLOCK || ~%cmp0"))
# A cmpand that is true for some inputs (b & 1 == 0: b = 6), so the
# branch is seen to follow the cmpand rather than only read false.
func("t9_cmpandb1", taken_or_not(".Lcab1", "cmpandedb,0\t%dr2, 0x1, %pred0",
                                 "ibranch\t.Lcab1_t ? %MLOCK || %cmp0"))
# The compare under a false predicate with %pred0 set true before: a
# false %cmp0 then cannot be the old %pred0.
func("t9_predf0_p0t", wi("addd,0\t%dr3, 0x1, %dr9",
                         "cmpedb,1\t%dr3, %dr3, %pred0") + nops(1)
     + wi("cmpedb,1\t%dr3, %dr9, %pred1") + nops(3)
     + taken_or_not(".Lpf0t", "cmpedb,0\t%dr1, %dr2, %pred0 ? %pred1",
                    "ibranch\t.Lpf0t_t ? %MLOCK || %cmp0"))
# Mixed negation in a pair: %cmp0 || ~%cmp1.
func("t9_cmp0ncmp1", taken_or_not(
    ".Lc0n1", "cmpedb,0\t%dr1, %dr2, %pred0", "cmpedb,1\t%dr1, %dr3, %pred1",
    "ibranch\t.Lc0n1_t ? %MLOCK || %cmp0 || ~%cmp1"))
# CLPs: %pred0 = (a == b), %pred1 = (a == c), computed before; the
# branch instruction's CLP N (output @p(4 + N)) is their AND.
for n, neg in ((0, ""), (0, "~"), (1, ""), (2, "")):
    nm = f"t9_{'n' if neg else ''}clp{n}"
    func(nm, wi("cmpedb,0\t%dr1, %dr2, %pred0", "cmpedb,1\t%dr1, %dr3, %pred1")
         + nops(3)
         + taken_or_not(f".L{nm}", "pass\t%pred0, @p0", "pass\t%pred1, @p1",
                        f"landp\t@p0, @p1, @p{4 + n}",
                        f"pass\t@p{4 + n}, %pred2",
                        f"ibranch\t.L{nm}_t ? %MLOCK || {neg}%clp{n}"))
# With a lock: mem[0] is locked (lock-wait load), then the wait-unlock
# store of b and a compare of the loaded value with a in one instruction
# with the type-9 branch.  "brk" puts a load of mem[8] (another 64-byte
# block) between them, which breaks the lock (atomics.md): %MLOCK true.
for nm, cond, brk in (("t9_lock", "%cmp0", False),
                      ("t9_nlock", "~%cmp0", False),
                      ("t9_lockbrk", "%cmp0", True),
                      ("t9_nlockbrk", "~%cmp0", True)):
    body = (wi("ldd,0\t%dr0, 0x0, %dr5, mas = 0x7")
            + (wi("ldd,3\t%dr0, 0x40, %dr6") if brk else "") + nops(2)
            + taken_or_not(f".L{nm}", "cmpedb,0\t%dr5, %dr1, %pred0",
                           "std,2\t%dr0, 0x0, %dr2, mas = 0x2",
                           f"ibranch\t.L{nm}_t ? %MLOCK || {cond}"))
    func(nm, body)
# The same lock with a plain rbranch next to an unrelated compare.
func("rb_lockbrk", wi("ldd,0\t%dr0, 0x0, %dr5, mas = 0x7")
     + wi("ldd,3\t%dr0, 0x40, %dr6") + nops(2)
     + taken_or_not(".Lrbl", "cmpedb,0\t%dr5, %dr1, %pred0",
                    "std,2\t%dr0, 0x0, %dr2, mas = 0x2", "rbranch\t.Lrbl_t"))

# Spinlock (test-and-set) for the threaded test: void spin9_lock (int *),
# spinc_lock (int *) (lcc-style exchange, then a separate test), and
# spin_unlock (int *) (wait + store 0, lcc's release store).
LOCK_HEAD = wi(SETWD16, "return\t%ctpr3", "adds,0\t0x0, 0x1, %r6")
raw("spin9_lock", LOCK_HEAD + ".Ls9_r:\n" + wi("nop 1")
    + wi("ldw,0\t%dr0, 0x0, %r5, mas = 0x7") + nops(2)
    + wi("cmpesb,0\t%r5, 0x0, %pred0", "stw,2\t%dr0, 0x0, %r6, mas = 0x2",
         "ibranch\t.Ls9_r ? %MLOCK || ~%cmp0")
    + nops(1) + wi("ct\t%ctpr3"))
raw("spinc_lock", LOCK_HEAD + ".Lsc_r:\n" + wi("nop 1")
    + wi("ldw,0\t%dr0, 0x0, %r5, mas = 0x7") + nops(1)
    + wi("stw,2\t%dr0, 0x0, %r6, mas = 0x2", "rbranch\t.Lsc_r")
    + wi("cmpesb,0\t%r5, 0x0, %pred0") + nops(2)
    + wi("ibranch\t.Lsc_r ? ~%pred0") + wi("ct\t%ctpr3"))
raw("spin_unlock", wi(SETWD16, "return\t%ctpr3", "adds,0\t0x0, 0x0, %r6")
    + wi("wait\tld_c = 1, st_c = 1") + wi("stw,2\t%dr0, 0x0, %r6")
    + nops(4) + wi("ct\t%ctpr3"))

# Timing.  %dr5 = 0, %dr3 = 1; %pred5 false, %pred6 true.
T_INIT = (wi("addd,0\t0x0, 0x0, %dr5", "addd,1\t0x0, 0x1, %dr3",
             "addd,2\t%dr0, 0x0, %dr7") + nops(1)
          + wi("cmpedb,0\t%dr5, %dr3, %pred5", "cmpedb,1\t%dr5, %dr5, %pred6")
          + nops(3))
timed("t_nop", T_INIT, lambda i, nxt: wi("nop"))
timed("t_t9_nt", T_INIT, lambda i, nxt: wi(
    "cmpedb,0\t%dr5, %dr3, %pred0", f"ibranch\t{nxt} ? %MLOCK || %cmp0"))
timed("t_t9_tk", T_INIT, lambda i, nxt: wi(
    "cmpedb,0\t%dr5, %dr5, %pred0", f"ibranch\t{nxt} ? %MLOCK || %cmp0"))
timed("t_t9clp_nt", T_INIT, lambda i, nxt: wi(
    "pass\t%pred5, @p0", "pass\t%pred6, @p1", "landp\t@p0, @p1, @p4",
    "pass\t@p4, %pred2", f"ibranch\t{nxt} ? %MLOCK || %clp0"))
timed("t_rb_nt", T_INIT, lambda i, nxt: wi(f"ibranch\t{nxt} ? %MLOCK"))
timed("t_ib_tk", T_INIT, lambda i, nxt: wi(f"ibranch\t{nxt}"))
for d in (1, 2, 3, 4):
    timed(f"t_cmpib_nt_d{d}", T_INIT, lambda i, nxt, d=d:
          wi("cmpedb,0\t%dr5, %dr3, %pred0") + nops(d - 1)
          + wi(f"ibranch\t{nxt} ? %pred0"))
# Uncontended test-and-set, one lock word per 64-byte block (mem + 64 i),
# storing 0 so the word stays free: type 9 against lcc-style exchange
# plus a separate test.  A failure jumps to the end (best-of rejects it).
timed("t_tas9", T_INIT, lambda i, nxt:
      wi("nop 1") + wi(f"ldw,0\t%dr7, {64 * i:#x}, %r8, mas = 0x7") + nops(2)
      + wi("cmpesb,0\t%r8, 0x0, %pred0",
           f"stw,2\t%dr7, {64 * i:#x}, %r5, mas = 0x2",
           f"ibranch\t{nxt} ? %MLOCK || ~%cmp0"))
for n in (0, 1, 3, 4):
    timed(f"t_tas9_n{n}", T_INIT, lambda i, nxt, n=n:
          wi("nop 1") + wi(f"ldw,0\t%dr7, {64 * i:#x}, %r8, mas = 0x7")
          + nops(n)
          + wi("cmpesb,0\t%r8, 0x0, %pred0",
               f"stw,2\t%dr7, {64 * i:#x}, %r5, mas = 0x2",
               f"ibranch\t{nxt} ? %MLOCK || ~%cmp0"))
for n in (0, 2, 3):
    timed(f"t_tasc_n{n}", T_INIT, lambda i, nxt, n=n:
          wi("nop 1") + wi(f"ldw,0\t%dr7, {64 * i:#x}, %r8, mas = 0x7")
          + nops(n)
          + wi(f"stw,2\t%dr7, {64 * i:#x}, %r5, mas = 0x2", f"rbranch\t{nxt}")
          + wi("cmpesb,0\t%r8, 0x0, %pred0") + nops(2)
          + wi(f"ibranch\t{nxt} ? ~%pred0"))
# The exchange alone (no test), as atomics.md's "exchange, 1".
timed("t_xchg_n1", T_INIT, lambda i, nxt:
      wi("nop 1") + wi(f"ldw,0\t%dr7, {64 * i:#x}, %r8, mas = 0x7") + nops(1)
      + wi(f"stw,2\t%dr7, {64 * i:#x}, %r5, mas = 0x2", f"rbranch\t{nxt}"))
for d in (1, 3):
    timed(f"t_cmpib_tk_d{d}", T_INIT, lambda i, nxt, d=d:
          wi("cmpedb,0\t%dr5, %dr5, %pred0") + nops(d - 1)
          + wi(f"ibranch\t{nxt} ? %pred0"))
timed("t_t9clp_tk", T_INIT, lambda i, nxt: wi(
    "pass\t%pred6, @p0", "pass\t%pred6, @p1", "landp\t@p0, @p1, @p4",
    "pass\t@p4, %pred2", f"ibranch\t{nxt} ? %MLOCK || %clp0"))
timed("t_t9_tk3", T_INIT, lambda i, nxt: wi(
    "cmpedb,3\t%dr5, %dr5, %pred0", f"ibranch\t{nxt} ? %MLOCK || %cmp3"))
# An if-then: a type-9 branch over one instruction, not taken / taken,
# against a compare + ibranch ? pred (distance 3).
timed("t_t9_skip_nt", T_INIT, lambda i, nxt: wi(
    "cmpedb,0\t%dr5, %dr3, %pred0", f"ibranch\t{nxt} ? %MLOCK || %cmp0")
    + wi("addd,0\t%dr5, 0x0, %dr9"))
# A predicate written long before, branch taken: the plain ibranch cost.
timed("t_predib_tk", T_INIT, lambda i, nxt: wi(f"ibranch\t{nxt} ? %pred6"))
timed("t_tasc", T_INIT, lambda i, nxt:
      wi("nop 1") + wi(f"ldw,0\t%dr7, {64 * i:#x}, %r8, mas = 0x7") + nops(1)
      + wi(f"stw,2\t%dr7, {64 * i:#x}, %r5, mas = 0x2", f"rbranch\t{nxt}")
      + wi("cmpesb,0\t%r8, 0x0, %pred0") + nops(2)
      + wi(f"ibranch\t{nxt} ? ~%pred0"))

