# Trace kernels for the 2C3's "some runs" state, d 1, u 5 only, no
# baseline: sXPAIR puts the four steps at offset X of the buffer;
# tLlTPAIR uses L places (1, 2 or 4) and T empty cycles after each use.
TRACE = {}
TPAIRS = {"ww4": ("stw", 0, "ldw", 4), "dd8": ("std", 0, "ldd", 8),
          "dd0": ("std", 0, "ldd", 0)}
for x in (0, 256, 512, 768):
    for tp, (so, sof, lo, lof) in TPAIRS.items():
        TRACE[f"s{x}{tp}"] = ("same", [(so, x + sof)], (lo, x + lof),
                              f"{so} +{x + sof}, {lo} +{x + lof}, every step there", 1, 0)
# cJrRPAIR: four places, step k at place (k + R) mod 4, only step J's
# load near its store.
for j in range(4):
    for rot in range(4):
        for tp in ("ww4", "dd8"):
            so, sof, lo, lof = TPAIRS[tp]
            TRACE[f"c{j}r{rot}{tp}"] = (
                "same", [(so, sof)], (lo, lof),
                f"{so} +{sof}, {lo} +{lof}, only step {j} (place {(j + rot) % 4})",
                4, 0, j, rot)
for ln in (1, 2, 4):
    for tail in (0, 4, 8, 16, 24, 40, 80):
        for tp, (so, sof, lo, lof) in TPAIRS.items():
            TRACE[f"t{ln}l{tail}{tp}"] = (
                "same", [(so, sof)], (lo, lof),
                f"{so} +{sof}, {lo} +{lof}, {ln} places, {tail} cycles after each use",
                ln, tail)


def gen(pairs, sfile, hfile):
    text, cases = [], []
    for pname, (mode, stores, load, desc, *opt) in pairs.items():
        if mode == "same":
            ln, tail, *jr = opt
            only, rot = jr if jr else (None, 0)
            fn = f"{pname}_d1_u5"
            text.append(kernel(fn, stores, load, 1, 5, "fix", lines=ln,
                               tail=tail, only=only, rot=rot))
            cases.append(f'MS ({fn}, "{pname}", 0, "fix", 1, {5 + tail}, "{desc}")\n')
            continue
        for base in (False, True):
            nm = pname + ("_b" if base else "")
            st = [(op, off + 128) for op, off in stores] if base else stores
            for d in (DS_BASE if base else DS):
                if d == 0 and len(st) > 1:
                    continue        # gas: no ALC5 store with an ALC0 load
                for u in US:
                    fn = f"{nm}_d{d}_u{u}"
                    text.append(kernel(fn, st, load, d, u, mode))
                    cases.append(f'MS ({fn}, "{pname}", {int(base)}, '
                                 f'"{mode}", {d}, {u}, "{desc}")\n')
    (HERE / sfile).write_text(HEADER + "".join(text))
    (HERE / hfile).write_text(GEN_H + "".join(cases))
    return len(cases)


V3.update(TRACE)
n3 = gen(V3, "memorycxx_stld.s", "memorycxx_stld-cases.h")
n5 = gen(V5, "memorycxx_stld-v5.s", "memorycxx_stld-v5-cases.h")
print(n3, "v3 cases,", n5, "v5 cases")
