static const int modes[4] = { FE_TONEAREST, FE_DOWNWARD, FE_UPWARD,
                              FE_TOWARDZERO };
static const char *const mname[4] = { "nearest", "down", "up", "zero" };
/* rounding of the model: 0 nearest even, 1 down, 2 up, 3 toward zero,
   4 nearest away (C round) */

#define FL (FE_INVALID | FE_DIVBYZERO | FE_OVERFLOW | FE_UNDERFLOW \
            | FE_INEXACT)

/* Round the IEEE value X of width W (64 or 32) to an integral value in
   mode R; *INX is set for a finite non-integral X, *INV for a
   signalling NaN.  Integer arithmetic only.  */
static u64
model (u64 x, int w, int r, int *inx, int *inv)
{
  int fb = w == 64 ? 52 : 23, eb = w == 64 ? 11 : 8;
  int bias = (1 << (eb - 1)) - 1;
  u64 sign = 1UL << (w - 1), emask = ((1UL << eb) - 1) << fb;
  u64 one = (u64) bias << fb;
  int e = (int) ((x & emask) >> fb) - bias;
  *inx = *inv = 0;
  if ((x & emask) == emask)
    {
      if (x & ((1UL << fb) - 1))        /* NaN */
        {
          *inv = !(x & (1UL << (fb - 1)));
          return x | (1UL << (fb - 1));
        }
      return x;
    }
  if (e >= fb)
    return x;
  int neg = (x & sign) != 0;
  if (e < 0)
    {
      if ((x & ~sign) == 0)
        return x;
      *inx = 1;
      int up = 0;                       /* magnitude becomes 1 */
      if (r == 1)
        up = neg;
      else if (r == 2)
        up = !neg;
      else if (r == 0)
        up = e == -1 && (x & ((1UL << fb) - 1)) != 0;
      else if (r == 4)
        up = e == -1;
      return (x & sign) | (up ? one : 0);
    }
  int f = fb - e;                       /* fraction bits, 1..fb */
  u64 mask = (1UL << f) - 1, m = x & mask, t = x & ~mask;
  if (m == 0)
    return x;
  *inx = 1;
  u64 half = 1UL << (f - 1);
  int up = 0;
  if (r == 1)
    up = neg;
  else if (r == 2)
    up = !neg;
  else if (r == 0)
    up = m > half || (m == half && ((t >> f) & 1));
  else if (r == 4)
    up = m >= half;
  return up ? t + (1UL << f) : t;
}

static u32 lcg_state = 12345;
static u32
lcg (void)
{
  lcg_state = lcg_state * 1103515245u + 12345u;
  return lcg_state >> 1;
}

