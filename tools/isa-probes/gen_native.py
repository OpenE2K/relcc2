"""Write native-rot.s (v3-v5) and native6.s (v6) for native.c: delays of
the %bgr rotation and the v6 wait for a memory change
(spec/isa/x86-support.md).

  python3 tools/isa-probes/gen_native.py

nat_rot_K_dD: %g24-%g31 hold 24-31 with %bgr cur 0, then rotation K
(abgd: abg 1 from val 0x7f; abgi: abg 2 after an abgd; rws: rws of
0x1ff, cur 1; v6 abgc: abgc 1; rbgc after abgc 1) and a read of %dg24 in
ALC0 D cycles later (0: the same wide instruction); returns what it
read.  The physical register %g24 names is 24 + cur, so the value tells
whether the read saw the new rotation.  %bgr is put back after.
nat_rot_rws_wait: the rws with a wait all_e before the read.
nat_watch (long *p, long v): if *p == v, wait for a change of *p's
cache line (load with MAS 0x11, then wait mem_mod = 1, int = 1);
returns the %clkr cycles it took.
"""

from pathlib import Path

HERE = Path(__file__).resolve().parent


def wi(*ops):
    return "\t{\n" + "".join(f"\t  {o}\n" for o in ops) + "\t}\n"


def nops(n):
    out = ""
    while n > 0:
        k = min(n, 8)
        out += wi(f"nop {k - 1}" if k > 1 else "nop")
        n -= k
    return out


def fn(name, body):
    return (f"\n\t.global\t{name}\n\t.type\t{name}, #function\n"
            f"\t.align\t8\n{name}:\n{body}\t.size\t{name}, .-{name}\n")


def setbgr(v):
    return (wi(f"addd,0\t0x0, {v:#x}, %dr11") + nops(2)
            + wi("rws,0\t%r11, %bgr") + wi("wait\tall_e = 1") + nops(5))


def rot(kind, d, wait=False):
    b = wi("setwd\twsz = 0x8, nfx = 0x1, dbl = 0x0", "return\t%ctpr3")
    b += wi("rrs,0\t%bgr, %r10")
    b += setbgr(0x7f if kind in ("abgd", "abgi") else 0xff)
    b += wi(*[f"addd,{c}\t0x0, {24 + c:#x}, %dg{24 + c}" for c in range(6)])
    b += wi("addd,0\t0x0, 0x1e, %dg30", "addd,1\t0x0, 0x1f, %dg31")
    b += nops(5)
    if kind == "abgi":
        b += wi("abg\t1") + nops(6)
        op = "abg\t2"
    elif kind == "rbgc":
        b += wi("abgc 1") + nops(6)
        op = "rbgc"
    else:
        op = {"abgd": "abg\t1", "abgc": "abgc 1"}.get(kind)
    rd = "addd,0\t0x0, %dg24, %dr0"
    if kind == "rws":
        b += wi("addd,0\t0x0, 0x1ff, %dr11") + nops(2)
        op = "rws,0\t%r11, %bgr"
    if wait:
        b += wi(op) + wi("wait\tall_e = 1") + wi(rd)
    elif d == 0 and kind != "rws":
        b += wi(op, rd)
    elif d == 0:
        b += wi(op, "addd,1\t0x0, %dg24, %dr0")
    else:
        b += wi(op) + nops(d - 1) + wi(rd)
    b += nops(5) + wi("rws,0\t%r10, %bgr") + wi("wait\tall_e = 1") + nops(5)
    b += wi("ct\t%ctpr3")
    return fn(f"nat_rot_{kind}_wait" if wait else f"nat_rot_{kind}_d{d}", b)


WATCH = fn("nat_watch",
           wi("setwd\twsz = 0x8, nfx = 0x1, dbl = 0x0", "return\t%ctpr3")
           + wi("rrd,0\t%clkr, %dr4")
           + wi("nop 4", "disp\t%ctpr1, .Lwatched",
                "ldd,0\t%dr0, 0x0, %dr2, mas = 0x11")
           + wi("nop 2", "cmpedb,0\t%dr2, %dr1, %pred0")
           + wi("ct\t%ctpr1 ? ~%pred0")
           + wi("wait\tmem_mod = 1, int = 1")
           + ".Lwatched:\n" + wi("rrd,0\t%clkr, %dr5") + nops(2)
           + wi("subd,0\t%dr5, %dr4, %dr0") + nops(5) + wi("ct\t%ctpr3"))

def bgrstate(kind):
    """nat_bgr_KIND (long *out): out[0] = %bgr, out[1] = %dg24 and out[2] =
    %dg25 read after the rotation and a wait all_e."""
    b = wi("setwd\twsz = 0x8, nfx = 0x1, dbl = 0x0", "return\t%ctpr3")
    b += wi("rrs,0\t%bgr, %r10") + setbgr(0xff)
    b += wi(*[f"addd,{c}\t0x0, {24 + c:#x}, %dg{24 + c}" for c in range(6)])
    b += wi("addd,0\t0x0, 0x1e, %dg30", "addd,1\t0x0, 0x1f, %dg31")
    b += nops(5)
    if kind == "rws":
        b += wi("addd,0\t0x0, 0x1ff, %dr11") + nops(2) + wi("rws,0\t%r11, %bgr")
    else:
        b += wi(kind)
    b += wi("wait\tall_e = 1") + nops(5)
    b += wi("rrs,0\t%bgr, %r12") + nops(2)
    b += wi("std,2\t%dr0, 0x0, %dr12", "std,5\t%dr0, 0x8, %dg24")
    b += wi("std,2\t%dr0, 0x10, %dg25")
    b += nops(5) + wi("rws,0\t%r10, %bgr") + wi("wait\tall_e = 1") + nops(5)
    b += wi("ct\t%ctpr3")
    return fn(f"nat_bgr_{kind.split()[0]}", b)


HEAD = ("! SPDX-License-Identifier: GPL-3.0-or-later\n"
        "! Generated by tools/isa-probes/gen_native.py; see native.c.\n"
        "\t.ignore\tld_st_style\n\t.text\n")


def main():
    ds = (0, 1, 2, 3, 4, 5, 8, 9, 10, 11, 12)
    (HERE / "native-rot.s").write_text(
        HEAD + "".join(rot(k, d) for k in ("abgd", "abgi", "rws")
                       for d in ds) + rot("rws", 0, True)
        + bgrstate("rws"))
    (HERE / "native6.s").write_text(
        HEAD + "".join(rot(k, d) for k in ("abgc", "rbgc", "rws")
                       for d in ds) + rot("rws", 0, True)
        + bgrstate("rws") + bgrstate("abgc 1") + WATCH)


if __name__ == "__main__":
    main()
