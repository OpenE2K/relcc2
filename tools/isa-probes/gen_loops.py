"""Write loops.s: loop-mode cases for loops.c (spec/isa/loops.md).

  python3 tools/isa-probes/gen_loops.py     # rewrites loops.s, loops-cases.h

Every case is  long loop_NAME(unsigned long *out, long lsr, long *buf)
with lsr in %dr1 and buf (64 longs, zeroed by the caller) in %dr2.  It
writes %lsr, reads %lsr and %ilcr back, runs its loop, and stores into
out[]: 0 iterations (%dr10, counted by an instruction without loop_mode),
1-3 counts of operations conditioned on %pcnt0, %pcnt1, %lcntex (%dr11..
%dr13), 4 %lsr and 5 %ilcr right after the write, 6 %lsr and 7 %ilcr
after the loop, 8-15 %dr16..%dr23 (the rotating area).  It returns the
cycles of the loop.
"""

from pathlib import Path

HERE = Path(__file__).resolve().parent

HEADER = """! SPDX-License-Identifier: GPL-3.0-or-later
! Generated by tools/isa-probes/gen_loops.py; see loops.c.
\t.ignore\tld_st_style
\t.text
"""

# The back edge as lcc writes it.
BACK = ["loop_mode", "alc\talcf=1, alct=1", "ct\t%ctpr1 ? %NOT_LOOP_END"]


def case(name, body, setbn="rsz = 0x3, rbs = 0x8, rcur = 0x0", setbp=None,
         early=None):
    """BODY: the loop's wide instructions; the last one should end with
    BACK.  %dr10 counts iterations in a separate instruction."""
    out = [f"\n\t.global\tloop_{name}\n\t.type\tloop_{name}, #function\n"
           f"\t.align\t8\nloop_{name}:\n"]

    def wi(*ops):
        out.append("\t{\n" + "".join(f"\t  {o}\n" for o in ops) + "\t}\n")

    wi("setwd\twsz = 0x20, nfx = 0x1, dbl = 0x0", f"setbn\t{setbn}",
       *([f"setbp\t{setbp}"] if setbp else []), "return\t%ctpr3")
    wi(*[f"addd,{c % 6}\t0x0, 0x0, %dr{r}" for c, r in
         enumerate(range(10, 14))])
    wi(*[f"addd,{c}\t0x0, 0x{0x100 + c:x}, %dr{16 + c}" for c in range(6)])
    wi("addd,0\t0x0, 0x106, %dr22", "addd,1\t0x0, 0x107, %dr23",
       "disp\t%ctpr1, .L" + name + "_loop")
    if early is None:
        wi("rwd,0\t%dr1, %lsr")
        wi("nop 5")
        wi("rrd,0\t%lsr, %dr4")
        wi("rrd,0\t%ilcr, %dr5")
        wi("nop 5")
        wi("rrd,0\t%clkr, %dr8")
    else:
        # The loop's first instruction EARLY cycles after the write.
        wi("rrd,0\t%clkr, %dr8")
        wi("rwd,0\t%dr1, %lsr", *([f"nop {early - 1}"] if early > 1 else []))
    out.append(f".L{name}_loop:\n")
    for g in body:
        wi(*g)
    wi("rrd,0\t%clkr, %dr9")
    wi("rrd,0\t%lsr, %dr6")
    wi("rrd,0\t%ilcr, %dr7")
    wi("nop 5")
    regs = [10, 11, 12, 13, 4, 5, 6, 7] + list(range(16, 24))
    for k in range(0, 16, 2):
        wi(f"std,2\t%dr0, {8 * k:#x}, %dr{regs[k]}",
           f"std,5\t%dr0, {8 * (k + 1):#x}, %dr{regs[k + 1]}")
    wi("subd,0\t%dr9, %dr8, %dr0", "nop 5")
    wi("ct\t%ctpr3")
    return (name, "".join(out) + f"\t.size\tloop_{name}, .-loop_{name}\n")


def main():
    cases = []

    def add(name, body, **kw):
        cases.append(case(name, body, **kw))

    count = ["addd,3\t%dr10, 0x1, %dr10"]
    # How many times the loop runs, for the %lsr the caller passes.
    add("count", [count, BACK])
    # %pcnt0, %pcnt1 and %lcntex as conditions in each iteration.
    add("preds", [count + [
        "addd,0\t%dr11, 0x1, %dr11 ? %pcnt0",
        "addd,1\t%dr12, 0x1, %dr12 ? %pcnt1"],
        ["pass\t%lcntex, @p0", "andp\t@p0, @p0, @p4", "pass\t@p4, %pred5"],
        ["nop 2"],
        ["addd,0\t%dr13, 0x1, %dr13 ? %pred5"] + BACK])
    # Stores in a loop_mode instruction: each iteration stores its number
    # (1, 2, ...) at buf[iteration - 1]; a second store in the same
    # instruction writes buf[32 + iteration - 1].
    add("stores", [count + ["shld,1\t%dr10, 0x3, %dr14"],
                   ["nop 1"],
                   BACK + ["std,2\t%dr2, %dr14, %dr10",
                           "addd,0\t%dr14, 0x100, %dr15"],
                   ])
    add("stores2", [count + ["shld,1\t%dr10, 0x3, %dr14"],
                    ["addd,0\t%dr14, 0x100, %dr15"],
                    ["nop 1"],
                    BACK + ["std,2\t%dr2, %dr14, %dr10",
                            "std,5\t%dr2, %dr15, %dr10"]])
    # The same store in an instruction without loop_mode.
    add("stores_nolm", [count + ["shld,1\t%dr10, 0x3, %dr14"],
                        ["nop 1"],
                        ["std,2\t%dr2, %dr14, %dr10"],
                        BACK])
    # Rotation: each iteration writes its number to %b[0], then abn.
    add("rotate", [count, ["nop 1"],
                   ["addd,0\t0x0, %dr10, %b[0]"] + BACK
                   + ["abn\tabnf=1, abnt=1"]])
    # Predicate rotation (setbp psz = 3): iteration i sets %pred0 =
    # (i even), then abp; afterwards %pred0..3 go to %dr16..19.
    add("rotate_pred", [count, ["nop 1"],
                        ["cmpandedb,0\t%dr10, 0x1, %pred0"],
                        ["nop 2"],
                        BACK + ["abp\tabpf=1, abpt=1"],
                        ["nop 2"],
                        [f"merged,{c}\t0x0, 0x1, %dr{16 + c}, %pred{c}"
                         for c in range(4)]],
        setbp="psz = 0x3")
    # The first loop-end check D cycles after rwd %lsr (the previous
    # case left lcnt 0, so a stale read ends the loop at once).
    for d in range(1, 7):
        add(f"early{d}", [count + BACK], early=d)
    # %lcntex after the loop.
    add("lcntex_after", [count, BACK, ["pass\t%lcntex, @p0",
                                       "andp\t@p0, @p0, @p4",
                                       "pass\t@p4, %pred5"],
                         ["nop 2"], ["addd,0\t%dr13, 0x1, %dr13 ? %pred5"]])
    # Loads in a loop_mode instruction from buf + 8 * iteration, not
    # speculative: the caller puts buf 5 elements before an unmapped page,
    # so iterations 6 and later fault unless the load is suppressed.
    add("loads", [count + ["shld,1\t%dr10, 0x3, %dr14"], ["nop 1"],
                  BACK + ["ldd,0\t%dr2, %dr14, %dr24"]])
    # Throughput: an empty loop_mode loop of one instruction, and the
    # counting loop.
    add("one", [BACK])
    (HERE / "loops.s").write_text(HEADER + "".join(t for _, t in cases))
    (HERE / "loops-cases.h").write_text(
        "/* SPDX-License-Identifier: GPL-3.0-or-later */\n"
        "/* Generated by tools/isa-probes/gen_loops.py.  */\n"
        + "".join(f"CASE ({n})\n" for n, _ in cases))


if __name__ == "__main__":
    main()
