"""Write fcomb.s and fcomb-ops.h: every combined FP operation of v3
(f*_*, pf*_*), for fcomb.c, which runs them on hardware
(spec/isa/semantics.md, "FP min, max and combined operations").

  python3 tools/isa-probes/gen_fcomb.py

Each function is  void fc_N(const unsigned long in[3], unsigned long
*out): it loads a, b, c from in[0..2], runs  op a, b, c, dst  (gas
operand order) in ALC0 and stores dst.
"""

import re
from pathlib import Path

import yaml

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
OPS = re.compile(r"^p?f(add|sub|mul|hadd|hsub|addsub)_(add|sub|rsub|mul|"
                 r"hadd|hsub|addsub)[sd]$")


def ops():
    data = yaml.safe_load((ROOT / "spec/isa/binutils-ops.yaml").read_text())
    out = {}
    for e in data["alu_ops"]:
        if OPS.match(e["name"]) and 3 in e["isets"]:
            out.setdefault(e["name"], e["args"])
    return sorted(out.items())


def fn(i, name, args):
    r = "%r" if args == "ssss" else "%dr"
    return f"""
	.global	fc_{i}
	.type	fc_{i}, #function
	.align	8
fc_{i}:
	{{
	  setwd	wsz = 0x8, nfx = 0x1, dbl = 0x0
	  return	%ctpr3
	  ldd,0	%dr0, 0x0, %dr2
	  ldd,2	%dr0, 0x8, %dr3
	  ldd,3	%dr0, 0x10, %dr4
	}}
	{{
	  nop 3
	}}
	{{
	  {name},0	{r}2, {r}3, {r}4, {r}5
	}}
	{{
	  nop 7
	}}
	{{
	  std,2	%dr1, 0x0, %dr5
	}}
	{{
	  nop 5
	}}
	{{
	  ct	%ctpr3
	}}
	.size	fc_{i}, .-fc_{i}
"""


def main():
    ls = ops()
    (HERE / "fcomb.s").write_text(
        "! SPDX-License-Identifier: GPL-3.0-or-later\n"
        "! Generated by tools/isa-probes/gen_fcomb.py; see fcomb.c.\n"
        "\t.ignore\tld_st_style\n\t.text\n"
        + "".join(fn(i, n, a) for i, (n, a) in enumerate(ls)))
    (HERE / "fcomb-ops.h").write_text(
        "/* SPDX-License-Identifier: GPL-3.0-or-later */\n"
        "/* Generated by tools/isa-probes/gen_fcomb.py.  */\n"
        + "".join(f'OP ({i}, "{n}", "{a}")\n' for i, (n, a) in
                  enumerate(ls)))


if __name__ == "__main__":
    main()
