/* Square root and reciprocal operations: fsqrts, fsqrtid + fsqrttd,
   frcps, frsqrts, the packed pfsqrts and pfsqrttd, against fdivs/fdivd
   (spec/isa/semantics.md).  sqrt.s and sqrt-ops.h are generated by
   gen_sqrt.py; check_sqrt.py compares the output with exactly rounded
   results on the host.

     LCC=/opt/mcst/lcc-1.29.16.e2k-v3.4c.linux-6.1/bin/lcc
     $LCC -O3 tools/isa-probes/sqrt.c tools/isa-probes/sqrt.s -o sqrt
     ./sqrt > out.txt                     # on hardware
     python3 tools/isa-probes/check_sqrt.py out.txt

   Output lines: "OP MODE X Y RESULT FLAGS" in hex (MODE: %pfpfr rounding,
   0 nearest, 1 down, 2 up, 3 toward zero; RESULT the whole 64-bit
   destination; FLAGS %pfpfr bits 0-5), then "lat OP CYCLES-PER-STEP".  */

#include <stdio.h>
#include <string.h>

typedef unsigned long u64;
#define OP(n) void sq_##n (const u64 *, u64 *, unsigned);
#define LAT(n) long lat_##n (u64, long);
#include "sqrt-ops.h"
#undef OP
#undef LAT

static u64 seed = 88172645463325252UL;

static u64
rnd (void)
{
  seed ^= seed << 13;
  seed ^= seed >> 7;
  seed ^= seed << 17;
  return seed;
}

static u64 dspecial[] = {
  0, 0x8000000000000000UL, 0x3ff0000000000000UL, 0x4000000000000000UL,
  0x4010000000000000UL, 0x3fd0000000000000UL, 0x7ff0000000000000UL,
  0xfff0000000000000UL, 0x7ff8000000000000UL, 0x7ff4000000000000UL,
  0xbff0000000000000UL, 1, 0x000fffffffffffffUL, 0x0010000000000000UL,
  0x7fefffffffffffffUL, 0x3ff0000000000001UL, 0x3fefffffffffffffUL,
};
static unsigned fspecial[] = {
  0, 0x80000000, 0x3f800000, 0x40000000, 0x40800000, 0x3e800000,
  0x7f800000, 0xff800000, 0x7fc00000, 0x7fa00000, 0xbf800000, 1,
  0x007fffff, 0x00800000, 0x7f7fffff, 0x3f800001, 0x3f7fffff,
};

static void
run (const char *name, void (*f) (const u64 *, u64 *, unsigned), u64 x,
     u64 y, int mode)
{
  u64 in[2] = { x, y }, out[2];
  f (in, out, 0x1f80 | mode << 13);
  printf ("%s %d %016lx %016lx %016lx %02lx\n", name, mode, x, y, out[0],
          out[1] & 0x3f);
}

int
main (void)
{
  for (int mode = 0; mode < 4; mode++)
    {
      /* Doubles: specials and random positive ones of every exponent.  */
      for (unsigned i = 0; i < sizeof dspecial / sizeof *dspecial; i++)
        {
          run ("fsqrt2", sq_fsqrt2, dspecial[i], 0, mode);
          run ("fsqrtid", sq_fsqrtid, dspecial[i], 0, mode);
        }
      for (int i = 0; i < 4000; i++)
        {
          u64 x = rnd () & 0x7fffffffffffffffUL;
          if ((x >> 52) == 0x7ff)
            x &= ~(1UL << 62);
          run ("fsqrt2", sq_fsqrt2, x, 0, mode);
          if (i < 200)
            run ("fsqrtid", sq_fsqrtid, x, 0, mode);
          run ("fdivd", sq_fdivd, 0x3ff0000000000000UL, x, mode);
        }
      /* Floats in the low half.  */
      for (unsigned i = 0; i < sizeof fspecial / sizeof *fspecial; i++)
        {
          run ("fsqrts", sq_fsqrts, fspecial[i], 0, mode);
          run ("frcps", sq_frcps, fspecial[i], 0, mode);
          run ("frsqrts", sq_frsqrts, fspecial[i], 0, mode);
        }
      for (int i = 0; i < 4000; i++)
        {
          unsigned x = (unsigned) rnd () & 0x7fffffff;
          if ((x >> 23) == 0xff)
            x &= ~(1U << 30);
          run ("fsqrts", sq_fsqrts, x, 0, mode);
          run ("frcps", sq_frcps, x, 0, mode);
          run ("frsqrts", sq_frsqrts, x, 0, mode);
          run ("fdivs", sq_fdivs, 0x3f800000, x, mode);
        }
    }
  /* fsqrttd with fsqrtid's result changed in one significand bit: does
     it refine its second operand or need it exact?  */
  for (int i = 0; i < 300; i++)
    {
      u64 x = (rnd () & 0x3fffffffffffffffUL) | 0x2000000000000000UL, in[2],
          out[2];
      in[0] = x;
      in[1] = 0;
      sq_fsqrtid (in, out, 0x1f80);
      u64 t = out[0];
      static const int bits[] = { -1, 18, 22, 26, 30, 34, 40, 46, 51 };
      for (unsigned k = 0; k < sizeof bits / sizeof *bits; k++)
        {
          u64 tk = bits[k] < 0 ? t : t ^ (1UL << bits[k]);
          printf ("tdpert%d ", bits[k]);
          run ("fsqrttd_y", sq_fsqrttd_y, x, tk, 0);
        }
    }
  /* What the packed forms and fsqrttd with a given second operand do.  */
  static const u64 pairs[][2] = {
    { 0x4080000040000000UL, 0 },   /* floats 4.0 (high), 2.0 (low) */
    { 0x4110000041c80000UL, 0 },   /* 9.0, 25.0 */
    { 0x4010000000000000UL, 0x4000000000000000UL },  /* 4.0, 2.0 */
    { 0x4010000000000000UL, 0x3fe0000000000000UL },  /* 4.0, 0.5 */
    { 0x4022000000000000UL, 0 },                     /* 9.0, 0 */
  };
  for (unsigned i = 0; i < sizeof pairs / sizeof *pairs; i++)
    {
      run ("pfsqrts", sq_pfsqrts, pairs[i][0], pairs[i][1], 0);
      run ("pfsqrttd_y", sq_pfsqrttd_y, pairs[i][0], pairs[i][1], 0);
      run ("fsqrttd_y", sq_fsqrttd_y, pairs[i][0], pairs[i][1], 0);
      run ("fsqrtid", sq_fsqrtid, pairs[i][0], 0, 0);
    }
#define LAT(n) \
  { \
    long b = 1L << 60; \
    for (int r = 0; r < 20; r++) \
      { \
        long c = lat_##n (0x4010000040800000UL, 0); \
        b = c < b ? c : b; \
      } \
    printf ("lat %s %.2f\n", #n, b / 32.0); \
  }
#define OP(n)
#include "sqrt-ops.h"
#undef OP
#undef LAT
  return 0;
}
