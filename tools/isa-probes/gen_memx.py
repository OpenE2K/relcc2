"""Write memx.s and memx-v5.s: memory-access cases for memx.c.

  python3 tools/isa-probes/gen_memx.py   # rewrites memx.s, memx-v5.s and
                                         # their -cases.h files

What they ask (spec/isa/speculation.md, semantics.md, hwbugs.md):
- the fill load (MAS mod 4 without ,sm), lcc's spill reload: does it
  bring back the tag a ,sm store left in memory, in which channels, and
  what clears that tag (other loads, partial and misaligned stores);
  the TAGGED_LDW erratum (stw,sm then ldw fill);
- loads whose address is diagnostic, and %dt_al on them;
- misaligned 16-byte accesses (ldqp, stqp, ldq, stq; v5 and later) and
  misaligned lock-wait atomics;
- accesses that cross into an invalid or untouched page.

Every case is  long memx_NAME(unsigned long *out, long a, long b, long c)
built by gen_spec.case(): out[0] = %dr8 with its tag cleared, out[1] =
its tag, out[2] = 1 if an rbranch was taken, out[4..5] = %qpr8 in quad
cases; it returns the cycles between two reads of %clkr.  %dr12 is made
diagnostic by a speculative load from NULL where a case needs it.
"""

from pathlib import Path

from gen_spec import case

HERE = Path(__file__).resolve().parent

HEADER = """! SPDX-License-Identifier: GPL-3.0-or-later
! Generated by tools/isa-probes/gen_memx.py; see memx.c.
	.ignore	ld_st_style
	.text
"""

NOP = ["nop 7"]
# %dr12 = a diagnostic value (a semi-speculative load from NULL).
DIAG = [["addd,0\t0x0, 0x0, %dr13"], ["ldd,0,sm\t%dr13, 0x0, %dr12"], NOP, NOP]
# %r12 diagnostic in its low half only (a 32-bit speculative load).
DIAGW = [["addd,0\t0x0, 0x0, %dr13"], ["ldw,0,sm\t%dr13, 0x0, %r12"], NOP, NOP]
# One-cycle filler instruction.
FILL1 = ["addd,1\t0x0, 0x0, %dr15"]
# For 16-byte results that may be diagnostic: store %qpr8 with stqp,sm to
# out[6..7] (memory keeps the tags), fill both halves back (the fill MAS
# restores tags, case fill_d*), and leave their tags in %dr8 (low half's
# in bits 0-3, high half's in bits 4-7) with %qpr8 otherwise clean, so
# the harness's own stqp of %qpr8 doesn't trap.
QSAFE = [["stqp,2,sm\t%dr0, 0x30, %qpr8"], NOP,
         ["ldd,0\t%dr0, 0x30, %dr13, mas=0x4",
          "ldd,3\t%dr0, 0x38, %dr14, mas=0x4"], NOP, NOP,
         ["addd,0\t0x0, 0x0, %dr15", "addd,1\t0x0, 0x0, %dr16"],
         ["gettagd,2\t%dr13, %r15"], ["gettagd,2\t%dr14, %r16"], NOP,
         ["andd,0\t%dr15, 0xf, %dr15", "andd,1\t%dr16, 0xf, %dr16"],
         ["shld,0\t%dr16, 0x4, %dr16"], ["ord,0\t%dr15, %dr16, %dr17"],
         ["qppackdl,1\t0x0, 0x0, %qpr8"], NOP,
         ["addd,0\t0x0, %dr17, %dr8"], NOP]


def build():
    v3, v5 = [], []

    def add(lst, name, groups, **kw):
        text = case(name, groups, **kw).replace(f"spec_{name}",
                                                f"memx_{name}")
        lst.append((name, text))

    # 1. Spill with std,sm, reload with the fill MAS.  b = an aligned
    # 16-byte slot, c = a valid value.
    spill_d = DIAG + [["std,2,sm\t%dr2, 0x0, %dr12"], NOP]
    spill_v = [["std,2,sm\t%dr2, 0x0, %dr3"], NOP]
    for ch in (0, 2, 3, 5):
        add(v3, f"fill_d{ch}", spill_d
            + [[f"ldd,{ch}\t%dr2, 0x0, %dr8, mas=0x4"], NOP, NOP])
    add(v3, "fill_v0", spill_v + [["ldd,0\t%dr2, 0x0, %dr8, mas=0x4"],
                                  NOP, NOP])
    add(v3, "plain_d", spill_d + [["ldd,0\t%dr2, 0x0, %dr8"], NOP, NOP])
    add(v3, "plainsm_d", spill_d + [["ldd,0,sm\t%dr2, 0x0, %dr8"], NOP, NOP])
    add(v3, "spec3_d", spill_d + [["ldd,0,sm\t%dr2, 0x0, %dr8, mas=0x3"],
                                  NOP, NOP])
    add(v3, "lock4_d", spill_d + [["ldd,0,sm\t%dr2, 0x0, %dr8, mas=0x4"],
                                  NOP, NOP])
    # Using the filled value: non-speculative (trap?) and speculative.
    fill14 = [["ldd,0\t%dr2, 0x0, %dr14, mas=0x4"], NOP, NOP]
    add(v3, "fill_use", spill_d + fill14 + [["addd,0\t%dr14, 0x1, %dr8"], NOP])
    add(v3, "fill_usesm", spill_d + fill14
        + [["addd,0,sm\t%dr14, 0x1, %dr8"], NOP])
    add(v3, "fill_std", spill_d + fill14 + [["std,2\t%dr2, 0x8, %dr14"], NOP])
    add(v3, "fill_dt", spill_d + fill14
        + [["rbranch\t%%LOCKED ? %dt_al0", "addd,0,sm\t%dr14, 0x1, %dr8"],
           NOP])
    # A plain store of a valid value over the slot, then fill.
    add(v3, "fill_after_std", spill_d + [["std,2\t%dr2, 0x0, %dr3"], NOP]
        + [["ldd,0\t%dr2, 0x0, %dr8, mas=0x4"], NOP, NOP])
    add(v3, "fill_after_stdsm_v", spill_d + spill_v
        + [["ldd,0\t%dr2, 0x0, %dr8, mas=0x4"], NOP, NOP])
    # Partial and misaligned overwrites of a diagnostic slot.
    for nm, st in (("stw0", "stw,2\t%dr2, 0x0, %r3"),
                   ("stw4", "stw,2\t%dr2, 0x4, %r3"),
                   ("stb1", "stb,2\t%dr2, 0x1, %r3"),
                   ("stb5", "stb,2\t%dr2, 0x5, %r3"),
                   ("stdm4", "std,2\t%dr2, 0x4, %dr3"),
                   ("stdm2", "std,2\t%dr2, 0x2, %dr3"),
                   ("std8", "std,2\t%dr2, 0x8, %dr3")):
        add(v3, f"part_{nm}", spill_d + [[st], NOP]
            + [["ldd,0\t%dr2, 0x0, %dr8, mas=0x4"], NOP, NOP])
    # An 8-byte store at b - 4 (over the slot's low half).
    add(v3, "part_stdp4", spill_d + [["subd,0\t%dr2, 0x4, %dr16"],
                                     ["std,2\t%dr16, 0x0, %dr3"], NOP]
        + [["ldd,0\t%dr2, 0x0, %dr8, mas=0x4"], NOP, NOP])
    # 32-bit spills: stw,sm of a diagnostic word, fill with ldw or ldd.
    spill_w = DIAGW + [["stw,2,sm\t%dr2, 0x0, %r12"], NOP]
    for ch in (0, 2, 3, 5):
        add(v3, f"fillw_d{ch}", spill_w
            + [[f"ldw,{ch}\t%dr2, 0x0, %r8, mas=0x4"], NOP, NOP])
    add(v3, "fillw_ldd", spill_w + [["ldd,0\t%dr2, 0x0, %dr8, mas=0x4"],
                                    NOP, NOP])
    add(v3, "fillw_hi", DIAGW + [["stw,2,sm\t%dr2, 0x4, %r12"], NOP]
        + [["ldd,0\t%dr2, 0x0, %dr8, mas=0x4"], NOP, NOP])
    add(v3, "fillw_plain", spill_w + [["ldw,0\t%dr2, 0x0, %r8"], NOP, NOP])
    # ldw fills of the halves of a diagnostic doubleword.
    add(v3, "filld_ldw0", spill_d + [["ldw,0\t%dr2, 0x0, %r8, mas=0x4"],
                                     NOP, NOP])
    add(v3, "filld_ldw4", spill_d + [["ldw,0\t%dr2, 0x4, %r8, mas=0x4"],
                                     NOP, NOP])
    # The TAGGED_LDW erratum: stw,sm then ldw fill of the same word,
    # D instructions later (1 = the next instruction); the slot holds
    # 0x5555... before.  Diagnostic and valid data.
    for d in (1, 2, 3, 5):
        gap = [FILL1] * (d - 1)
        add(v3, f"tldw_d{d}", DIAGW + [["stw,2,sm\t%dr2, 0x0, %r12"]] + gap
            + [["ldw,0\t%dr2, 0x0, %r8, mas=0x4"], NOP, NOP])
        add(v3, f"tldw_v{d}", [["stw,2,sm\t%dr2, 0x0, %r3"]] + gap
            + [["ldw,0\t%dr2, 0x0, %r8, mas=0x4"], NOP, NOP])
        add(v3, f"tldd_d{d}", DIAG + [["std,2,sm\t%dr2, 0x0, %dr12"]] + gap
            + [["ldd,0\t%dr2, 0x0, %dr8, mas=0x4"], NOP, NOP])
        add(v3, f"tldd_v{d}", [["std,2,sm\t%dr2, 0x0, %dr3"]] + gap
            + [["ldd,0\t%dr2, 0x0, %dr8, mas=0x4"], NOP, NOP])

    # The erratum in more shapes, all at distance 1: every store and fill
    # channel; the load's address computed from another register (b - 4,
    # offset 4); a clean word stored over a diagnostic one.
    for sc in (2, 5):
        for lc in (0, 2, 3, 5):
            add(v3, f"tm_s{sc}l{lc}", DIAGW
                + [[f"stw,{sc},sm\t%dr2, 0x0, %r12"],
                   [f"ldw,{lc}\t%dr2, 0x0, %r8, mas=0x4"], NOP, NOP])
    add(v3, "tm_alias", DIAGW + [["subd,1\t%dr2, 0x4, %dr16"], NOP,
                                 ["stw,2,sm\t%dr2, 0x0, %r12"],
                                 ["ldw,0\t%dr16, 0x4, %r8, mas=0x4"], NOP, NOP])
    add(v3, "tm_dv", DIAG + [["std,2,sm\t%dr2, 0x0, %dr12"], NOP,
                             ["stw,2,sm\t%dr2, 0x0, %r3"],
                             ["ldw,0\t%dr2, 0x0, %r8, mas=0x4"], NOP, NOP])
    add(v3, "tm_dv5", DIAG + [["std,2,sm\t%dr2, 0x0, %dr12"], NOP,
                              ["stw,5,sm\t%dr2, 0x0, %r3"],
                              ["ldw,3\t%dr2, 0x0, %r8, mas=0x4"], NOP, NOP])

    # 2. A diagnostic load address.  a = a valid cell.
    add(v3, "da_ldsm", DIAG + [["ldd,0,sm\t%dr12, 0x0, %dr8"], NOP, NOP])
    add(v3, "da_ldspec", DIAG + [["ldd,0,sm\t%dr12, 0x0, %dr8, mas=0x3"],
                                 NOP, NOP])
    add(v3, "da_ld", DIAG + [["ldd,0\t%dr12, 0x0, %dr8"], NOP, NOP])
    add(v3, "da_ldsm_off", DIAG + [["ldd,0,sm\t%dr1, %dr12, %dr8"], NOP, NOP])
    add(v3, "da_ldsm3", DIAG + [["ldd,3,sm\t%dr12, 0x0, %dr8"], NOP, NOP])
    add(v3, "da_dt0", DIAG + [["rbranch\t%%LOCKED ? %dt_al0",
                               "ldd,0,sm\t%dr12, 0x0, %dr8"], NOP, NOP])
    add(v3, "da_dt3", DIAG + [["rbranch\t%%LOCKED ? %dt_al3",
                               "ldd,3,sm\t%dr12, 0x0, %dr8"], NOP, NOP])
    add(v3, "da_dt0_off", DIAG + [["rbranch\t%%LOCKED ? %dt_al0",
                                   "ldd,0,sm\t%dr1, %dr12, %dr8"], NOP, NOP])
    add(v3, "da_dt0_valid", [["rbranch\t%%LOCKED ? %dt_al0",
                              "ldd,0,sm\t%dr1, 0x0, %dr8"], NOP, NOP])
    add(v3, "da_ldsm_valid", [["ldd,0,sm\t%dr1, 0x0, %dr8"], NOP, NOP])
    # A half-diagnostic address (low half tagged by ldw,sm).
    add(v3, "da_half", DIAGW + [["ldd,0,sm\t%dr12, 0x0, %dr8"], NOP, NOP])

    # 3. Misaligned lock-wait atomic (lcc's fetch-add template, no
    # retry loop: a lost lock goes to the rbranch label).  a = target.
    atom = [["nop 1"], ["ldd,0\t%dr1, 0x0, %dr8, mas=0x7", "nop 4"],
            ["addd,0\t%dr8, 0x1, %dr14"],
            ["std,2\t%dr1, 0x0, %dr14, mas=0x2", "rbranch\t%%LOCKED"], NOP]
    add(v3, "atom_d", atom)
    atomw = [["nop 1"], ["ldw,0\t%dr1, 0x0, %r8, mas=0x7", "nop 4"],
             ["adds,0\t%r8, 0x1, %r14"],
             ["stw,2\t%dr1, 0x0, %r14, mas=0x2", "rbranch\t%%LOCKED"], NOP]
    add(v3, "atom_w", atomw)

    # 4. Accesses that cross a page boundary.  a = the address.
    add(v3, "pc_ldsm", [["ldd,0,sm\t%dr1, 0x0, %dr8"], NOP, NOP])
    add(v3, "pc_ldspec", [["ldd,0,sm\t%dr1, 0x0, %dr8, mas=0x3"], NOP, NOP])
    add(v3, "pc_ld", [["ldd,0\t%dr1, 0x0, %dr8"], NOP, NOP])
    add(v3, "pc_ldwsm", [["ldw,0,sm\t%dr1, 0x0, %r8"], NOP, NOP])
    add(v3, "pc_ldw", [["ldw,0\t%dr1, 0x0, %r8"], NOP, NOP])
    add(v3, "pc_std", [["std,2\t%dr1, 0x0, %dr3"], NOP])
    add(v3, "pc_stdsm", [["std,2,sm\t%dr1, 0x0, %dr3"], NOP])
    add(v3, "pc_stw", [["stw,2\t%dr1, 0x0, %r3"], NOP])
    add(v3, "pc_fill", [["ldd,0\t%dr1, 0x0, %dr8, mas=0x4"], NOP, NOP])
    add(v3, "pc_ldsm_dt", [["ldd,0,sm\t%dr1, 0x0, %dr12, mas=0x3"], NOP, NOP,
                           ["rbranch\t%%LOCKED ? %dt_al0",
                            "addd,0,sm\t%dr12, 0x1, %dr8"], NOP])

    # v5 and later: 16-byte accesses.  a = the address, b and c the
    # halves to store.  %qpr8 comes back in out[4..5].
    q = dict(quad=True)
    for ch in (0, 2, 3, 5):
        add(v5, f"q_ldqp{ch}", [[f"ldqp,{ch}\t%dr1, 0x0, %qpr8"], NOP, NOP], **q)
    add(v5, "q_ldqpsm", [["ldqp,0,sm\t%dr1, 0x0, %qpr8"], NOP, NOP] + QSAFE,
        **q)
    add(v5, "q_ldqpspec", [["ldqp,0,sm\t%dr1, 0x0, %qpr8, mas=0x3"], NOP,
                           NOP] + QSAFE, **q)
    # QSAFE's own check: a wholly diagnostic quad (ldqp,sm from NULL).
    add(v5, "q_diag", [["addd,0\t0x0, 0x0, %dr13"],
                       ["ldqp,0,sm\t%dr13, 0x0, %qpr8"], NOP, NOP] + QSAFE,
        **q)
    add(v5, "q_ldq", [["ldq,0\t%dr1, 0x0, %qr12"], NOP, NOP,
                      ["qppackdl,1\t%dr13, %dr12, %qpr8"], NOP], **q)
    pack = [["qppackdl,1\t%dr3, %dr2, %qpr14"], NOP]
    for ch in (2, 5):
        add(v5, f"q_stqp{ch}", pack + [[f"stqp,{ch}\t%dr1, 0x0, %qpr14"],
                                       NOP], **q)
    add(v5, "q_stq", [["addd,0\t0x0, %dr2, %dr12", "addd,1\t0x0, %dr3, %dr13"],
                      NOP, ["stq,2\t%dr1, 0x0, %qr12"], NOP], **q)
    # A 16-byte lock-wait atomic (lcc's v5 inline form): load, add 1 to
    # the low half, store.
    add(v5, "q_atom", [["nop 1"], ["ldqp,0\t%dr1, 0x0, %qpr8, mas=0x7",
                                   "nop 4"],
                       ["qpaddd,0\t%qpr8, %qpr8, %qpr14"],
                       ["stqp,2\t%dr1, 0x0, %qpr14, mas=0x2",
                        "rbranch\t%%LOCKED"], NOP], **q)
    # Quad spill and fill of a diagnostic register.
    add(v5, "q_fill", [["addd,0\t0x0, 0x0, %dr13"],
                       ["ldqp,0,sm\t%dr13, 0x0, %qpr12"], NOP, NOP,
                       ["stqp,2,sm\t%dr2, 0x0, %qpr12"], NOP,
                       ["ldqp,0\t%dr2, 0x0, %qpr8, mas=0x4"], NOP, NOP]
        + QSAFE, **q)
    add(v5, "q_fill_use", [["addd,0\t0x0, 0x0, %dr13"],
                           ["ldqp,0,sm\t%dr13, 0x0, %qpr12"], NOP, NOP,
                           ["stqp,2,sm\t%dr2, 0x0, %qpr12"], NOP,
                           ["ldqp,0\t%dr2, 0x0, %qpr14, mas=0x4"], NOP, NOP,
                           ["qpaddd,0\t%qpr14, %qpr14, %qpr8"], NOP], **q)
    # Page crossing, 16 bytes.
    add(v5, "pcq_ldqpsm", [["ldqp,0,sm\t%dr1, 0x0, %qpr8"], NOP, NOP]
        + QSAFE, **q)
    add(v5, "pcq_ldqpspec", [["ldqp,0,sm\t%dr1, 0x0, %qpr8, mas=0x3"], NOP,
                             NOP] + QSAFE, **q)
    add(v5, "pcq_ldqp", [["ldqp,0\t%dr1, 0x0, %qpr8"], NOP, NOP], **q)
    add(v5, "pcq_stqp", pack + [["stqp,2\t%dr1, 0x0, %qpr14"], NOP], **q)
    # Streams: 32 ldqp (two an instruction, ALC0 and ALC2) or 32 stqp
    # (ALC2 and ALC5) at a, a + 16, ...; cycles only.
    lds, sts = [], []
    for k in range(16):
        lds.append([f"ldqp,0\t%dr1, {32 * k:#x}, %qpr{16 + (2 * k) % 16}",
                    f"ldqp,2\t%dr1, {32 * k + 16:#x}, %qpr{17 + (2 * k) % 16}"])
        sts.append([f"stqp,2\t%dr1, {32 * k:#x}, %qpr14",
                    f"stqp,5\t%dr1, {32 * k + 16:#x}, %qpr14"])
    add(v5, "qs_ldqp", lds + [NOP, NOP], **q)
    add(v5, "qs_stqp", pack + sts + [NOP], **q)
    # The same with ldq/stq (register pairs, %qr16..%qr30).  ldq takes
    # channels (0, 2) or (3, 5), stq (2, 5): two ldq but one stq an
    # instruction (bundle.md).
    ldq, stq = [], []
    for k in range(16):
        ldq.append([f"ldq,0\t%dr1, {32 * k:#x}, %qr{16 + (4 * k) % 16}",
                    f"ldq,3\t%dr1, {32 * k + 16:#x}, %qr{18 + (4 * k) % 16}"])
    for k in range(32):
        stq.append([f"stq,2\t%dr1, {16 * k:#x}, %qr12"])
    add(v5, "qs_ldq", ldq + [NOP, NOP], **q)
    add(v5, "qs_stq", stq + [NOP], **q)
    ldd, std = [], []
    for k in range(16):
        ldd.append([f"ldd,0\t%dr1, {16 * k:#x}, %dr{16 + (2 * k) % 16}",
                    f"ldd,2\t%dr1, {16 * k + 8:#x}, %dr{17 + (2 * k) % 16}"])
        std.append([f"std,2\t%dr1, {16 * k:#x}, %dr3",
                    f"std,5\t%dr1, {16 * k + 8:#x}, %dr3"])
    add(v3, "ds_ldd", ldd + [NOP, NOP])
    add(v3, "ds_std", std + [NOP])
    return v3, v5


def main():
    v3, v5 = build()
    for path, cs in (("memx", v3), ("memx-v5", v5)):
        (HERE / f"{path}.s").write_text(HEADER + "".join(t for _, t in cs))
        (HERE / f"{path}-cases.h").write_text(
            "/* SPDX-License-Identifier: GPL-3.0-or-later */\n"
            "/* Generated by tools/isa-probes/gen_memx.py.  */\n"
            + "".join(f"CASE ({n})\n" for n, _ in cs))


if __name__ == "__main__":
    main()
