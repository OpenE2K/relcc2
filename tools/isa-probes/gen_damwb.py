"""Write damwb.s and damwb-cases.h for damwb.c: checks of the
proof-of-concept back end's findings P69 (a lock load and a check of an
earlier lock in one wide instruction, up to four MASes in CS1) and P81
(a write-back conflict behind a second FP-side operation) in
docs/spec-poc-findings.md, for spec/isa/speculation.md, bundle.md and
timing.md.

  python3 tools/isa-probes/gen_damwb.py

DAM cases  long dw_NAME(long *mem, long a, long b): mem[0..3] hold 100,
200, 300, 400.  A is locked into %dr8 from mem[0] (and D into %dr14 from
mem[3]) first; then a store of 0x777 to mem[0] (D: mem[3]) either with
MAS 0x4, which leaves the entry ("stale": an intact check keeps 100), or
plain, which removes it ("kill": the check reloads 0x777); then the
shared instruction locks B into %dr12 from mem[1] (C into %dr13 from
mem[2]) and checks A (D), with one rbranch; then a store of 0x888 to
mem[1] (C: mem[2]), stale or kill; then B (C) is checked.  Every
rbranch goes to compensation code that sets a bit in %dr10 and comes
back with ibranch to the next instruction, as lcc's does.  The case
stores %dr8, %dr12, %dr13, %dr14 and %dr10 to mem[16..20].  Every
entry a case makes is checked (removed) before it returns.

Write-back cases  long dw_wb_NAME(long *mem, long a, long b): 16 steps
(after 4) between two %clkr reads, each a producer P in ALC0 (a chain),
Y one cycle after it in ALC0, X two cycles after it, and P's consumer C
at P's latency, then C's latency to the next P; returns the cycles
(1 + 16 steps).  A step takes P -> C + C -> P cycles without a stall
(muld, smulx_fw: 6 + 1; fmuld -> faddd,3: 6 + 6), 4 more with one.
"""

from pathlib import Path

HERE = Path(__file__).resolve().parent
HEADER = """! SPDX-License-Identifier: GPL-3.0-or-later
! Generated by tools/isa-probes/gen_damwb.py; see damwb.c.
	.ignore	ld_st_style
	.ignore	strict_delay
	.text
"""
cases, text = [], []


def wi(*ops):
    return "\t{\n" + "".join(f"\t  {o}\n" for o in ops) + "\t}\n"


def nops(n):
    out = ""
    while n > 0:
        k = min(n, 8)
        out += wi(f"nop {k - 1}" if k > 1 else "nop")
        n -= k
    return out


def func(name, body, tail="", wsz=0x10):
    fn = f"dw_{name}"
    text.append(f"\n\t.global\t{fn}\n\t.type\t{fn}, #function\n\t.align\t8\n"
                f"{fn}:\n"
                + wi(f"setwd\twsz = {wsz:#x}, nfx = 0x1, dbl = 0x0",
                     "return\t%ctpr3")
                + body + nops(6) + wi("ct\t%ctpr3") + tail
                + f"\t.size\t{fn}, .-{fn}\n")


# ---------------------------------------------------------------- DAM

LOCK = {  # register, offset, channel -> lock load
    "A": "ldd,{c},sm\t%dr0, 0x0, %dr8, mas=0x4",
    "B": "ldd,{c},sm\t%dr0, 0x8, %dr12, mas=0x4",
    "C": "ldd,{c},sm\t%dr0, 0x10, %dr13, mas=0x4",
    "D": "ldd,{c},sm\t%dr0, 0x18, %dr14, mas=0x4",
}
CHECK = {
    "A": "ldd,{c}\t%dr0, 0x0, %dr8, mas=0x3",
    "B": "ldd,{c}\t%dr0, 0x8, %dr12, mas=0x3",
    "C": "ldd,{c}\t%dr0, 0x10, %dr13, mas=0x3",
    "D": "ldd,{c}\t%dr0, 0x18, %dr14, mas=0x3",
}
OFF = {"A": 0x0, "B": 0x8, "C": 0x10, "D": 0x18}
VAL = {"A": "%dr9", "D": "%dr9", "B": "%dr11", "C": "%dr11"}  # 0x777, 0x888


def store(reg, how):
    mas = ", mas=0x4" if how == "stale" else ""
    return wi(f"std,2\t%dr0, {OFF[reg]:#x}, {VAL[reg]}{mas}") + nops(2)


def dam_case(name, early, shared, late, kills, same_addr=False):
    """EARLY: [(reg, channel)] locked first; SHARED: the shared
    instruction's ops as [("lock"|"check", reg, channel)]; LATE: regs
    checked after it (ALC5, one at a time); KILLS: {reg: "stale"|"kill"}
    for the stores before (A, D) or after (B, C) the shared
    instruction.  SAME_ADDR: B is locked from mem[0] (A's word)."""
    lab = f".Ldw_{name}"
    body = wi("addd,0\t0x0, 0x0, %dr10",
              "addd,1\t0x0, _f16s,_lts0lo 0x777, %dr9",
              "addd,3\t0x0, _f16s,_lts0hi 0x888, %dr11",
              "addd,4\t0x0, 0x0, %dr15")
    # Registers a case may store unwritten: not empty (tagged) words.
    body += wi("addd,0\t0x0, 0x0, %dr8", "addd,1\t0x0, 0x0, %dr12",
               "addd,3\t0x0, 0x0, %dr13", "addd,4\t0x0, 0x0, %dr14")
    # Keep every CTPR prepared around the rbranches (hwbugs.md,
    # BRANCH_ACTIVATES_CTPR on v6); nothing transfers through 1 and 2.
    body += wi(f"disp\t%ctpr1, {lab}_end") + wi(f"disp\t%ctpr2, {lab}_end")
    body += nops(2)
    for reg, ch in early:
        body += wi(LOCK[reg].format(c=ch))
    body += nops(3)
    for reg in ("A", "D"):
        if reg in kills:
            body += store(reg, kills[reg])
    ops = []
    for kind, reg, ch in shared:
        op = (LOCK if kind == "lock" else CHECK)[reg].format(c=ch)
        if same_addr and reg == "B":
            op = op.replace("0x8, %dr12", "0x0, %dr12")
        ops.append(op)
    body += wi(*ops, f"rbranch\t{lab}_c0") + f"{lab}_r0:\n" + nops(3)
    for reg in ("B", "C"):
        if reg in kills:
            r = reg
            if same_addr and reg == "B":
                body += (wi(f"std,2\t%dr0, 0x0, %dr11"
                            + (", mas=0x4" if kills[reg] == "stale" else ""))
                         + nops(2))
            else:
                body += store(r, kills[r])
    for i, reg in enumerate(late, 1):
        op = CHECK[reg].format(c=5)
        if same_addr and reg == "B":
            op = op.replace("0x8, %dr12", "0x0, %dr12")
        body += wi(op, f"rbranch\t{lab}_c{i}") + f"{lab}_r{i}:\n" + nops(3)
    body += wi("std,2\t%dr0, 0x80, %dr8", "std,5\t%dr0, 0x88, %dr12")
    body += wi("std,2\t%dr0, 0x90, %dr13", "std,5\t%dr0, 0x98, %dr14")
    body += wi("std,2\t%dr0, 0xa0, %dr10")
    body += wi("addd,0\t0x0, %dr10, %dr0")
    tail = f"{lab}_end:\n" + wi("nop")
    for i in range(len(late) + 1):
        tail += (f"{lab}_c{i}:\n"
                 + wi(f"ibranch\t{lab}_r{i}",
                      f"ord,0\t%dr10, {1 << i:#x}, %dr10"))
    func(name, body, tail)
    # Expected %dr8, %dr12, %dr13, %dr14 (-1: not used) and %dr10.
    exp = {r: -1 for r in "ABCD"}
    flags = 0
    first = {"A": 100, "B": 200, "C": 300, "D": 400}
    if same_addr:
        first["B"] = 0x777          # A's store, stale or kill, wrote it
    for reg, _ in early:
        exp[reg] = first[reg] if kills.get(reg) == "stale" else 0x777
        if kills.get(reg) == "kill":
            flags |= 1
    for kind, reg, _ in shared:
        if kind == "lock":
            exp[reg] = first[reg]
    for i, reg in enumerate(late, 1):
        if kills.get(reg) == "kill":
            exp[reg] = 0x888
            flags |= 1 << i
    cases.append(f"DAM ({name}, {exp['A']}, {exp['B']}, {exp['C']}, "
                 f"{exp['D']}, {flags})\n")


# One lock and one check in the shared instruction, in each pairing of
# a lock channel (0, 3) with a check channel (2, 5).
for lc, cc in ((3, 5), (0, 2), (0, 5), (3, 2)):
    for ka in ("stale", "kill"):
        for kb in ("stale", "kill"):
            dam_case(f"l{lc}c{cc}_a{ka}_b{kb}", [("A", 0)],
                     [("lock", "B", lc), ("check", "A", cc)], ["B"],
                     {"A": ka, "B": kb})

# B locked from A's word in the instruction that checks A.
for ka in ("stale", "kill"):
    for kb in ("none", "kill"):
        k = {"A": ka}
        if kb != "none":
            k["B"] = kb
        dam_case(f"same_a{ka}_b{kb}", [("A", 0)],
                 [("lock", "B", 3), ("check", "A", 5)], ["B"], k,
                 same_addr=True)

# Four MASes: two locks (ALC0, ALC3) and two checks (ALC2, ALC5), one
# rbranch, as lcc's NPB IS full_verify kernel.
for name, k in (("all_stale", {"A": "stale", "D": "stale", "B": "stale",
                               "C": "stale"}),
                ("kill_a", {"A": "kill", "D": "stale", "B": "stale",
                            "C": "stale"}),
                ("kill_d", {"A": "stale", "D": "kill", "B": "stale",
                            "C": "stale"}),
                ("kill_b", {"A": "stale", "D": "stale", "B": "kill",
                            "C": "stale"}),
                ("kill_c", {"A": "stale", "D": "stale", "B": "stale",
                            "C": "kill"})):
    dam_case(f"four_{name}", [("A", 0), ("D", 3)],
             [("lock", "B", 0), ("check", "A", 2), ("lock", "C", 3),
              ("check", "D", 5)], ["B", "C"], k)

# ------------------------------------------------------- write-back

PROD = {  # producer (a chain through %dr20 / %r20), consumer C, P -> C
    # latency, C -> next P latency, %dr20's start value
    "muld": ("muld,0\t%dr20, %dr21, %dr20", "addd,1\t%dr20, %dr24, %dr20",
             6, 1, "0x5"),
    "fmuld": ("fmuld,0\t%dr20, %dr22, %dr20", "faddd,3\t%dr20, %dr25, %dr20",
              6, 6, "_f64,_lts0 0x3ff0000000000000"),
    "smulxfw": ("smulx_fw,0\t%r20, %r21, %r20", "adds,1\t%r20, %r24, %r20",
                6, 1, "0x5"),
}
YOPS = {
    "none": None,
    "muld": "muld,0\t%dr26, %dr21, %dr27",
    "fmuld": "fmuld,0\t%dr23, %dr22, %dr28",
    "faddd": "faddd,0\t%dr23, %dr25, %dr29",
    "smulxfw": "smulx_fw,0\t%r26, %r21, %r30",
}
XOPS = {
    "none": None,
    "addd0": "addd,0\t%dr26, %dr24, %dr31",
    "addd2": "addd,2\t%dr26, %dr24, %dr31",
    "ldd0": "ldd,0\t%dr0, 0x0, %dr32",
}


def wb_step(p, y, x, xat):
    pop, cop, lat, back, _ = PROD[p]
    slots = [[pop]] + [[] for _ in range(lat - 1)]
    if YOPS[y]:
        slots[1].append(YOPS[y])
    if XOPS[x]:
        slots[xat].append(XOPS[x])
    out = "".join(wi(*s) if s else wi("nop") for s in slots)
    return out + wi(cop) + nops(back - 1)


def wb_case(p, y, x, xat=2):
    name = f"wb_{p}__{y}__{x}_at{xat}"
    setup = wi("addd,0\t0x0, 0x1, %dr21",
               "addd,1\t0x0, 0x0, %dr24",
               "addd,2\t0x0, 0x3, %dr26",
               "addd,3\t0x0, _f64,_lts0 0x3ff0000000000000, %dr22",
               "addd,4\t0x0, 0x0, %dr25")
    setup += wi(f"addd,0\t0x0, {PROD[p][4]}, %dr20",
                "addd,1\t0x0, _f64,_lts2 0x4000000000000000, %dr23") + nops(4)
    body = setup
    for _ in range(4):
        body += wb_step(p, y, x, xat)
    body += nops(8) + wi("rrd,0\t%clkr, %dr2")
    for _ in range(16):
        body += wb_step(p, y, x, xat)
    body += wi("rrd,0\t%clkr, %dr3") + nops(2)
    body += wi("subd,0\t%dr3, %dr2, %dr0")
    func(name, body, wsz=0x20)
    cases.append(f"WB ({name}, \"P {p}, Y {y} +1, X {x} +{xat}\", "
                 f"{PROD[p][2] + PROD[p][3]})\n")


for p in ("muld", "fmuld", "smulxfw"):
    for y in ("none", "muld", "fmuld", "faddd", "smulxfw"):
        for x in ("none", "addd0", "addd2", "ldd0"):
            wb_case(p, y, x)
    # X two cycles after Y instead (3 after P): Y's result goes nowhere.
    for y in ("muld", "smulxfw"):
        wb_case(p, y, "addd0", 3)

(HERE / "damwb.s").write_text(HEADER + "".join(text))
(HERE / "damwb-cases.h").write_text(
    "/* Generated by tools/isa-probes/gen_damwb.py.  */\n" + "".join(cases))
