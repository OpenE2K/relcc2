"""Write sqrt.s and sqrt-ops.h for sqrt.c: the square-root and reciprocal
operations (spec/isa/semantics.md, "Square root and reciprocals").

  python3 tools/isa-probes/gen_sqrt.py

sq_NAME(const u64 in[2], u64 out[2], unsigned pfpfr): sets %pfpfr to the
given value (rounding mode, flags cleared), runs the operation on in[0]
(and in[1]) in ALC5, stores the whole 64-bit destination (preset to
0x5555555555555555) in out[0] and %pfpfr in out[1], and restores
%pfpfr.  lat_NAME(u64 x, long n): n dependent repetitions, returns
cycles.
"""

from pathlib import Path

HERE = Path(__file__).resolve().parent

# name: operations, from x in %dr2 / %r2 (and y in %dr3) to %dr5 / %r5.
OPS = {
    "fsqrts": ["fsqrts,5\t%r2, %r5"],
    "fsqrtid": ["fsqrtid,5\t%dr2, %dr5"],
    "fsqrt2": ["fsqrtid,5\t%dr2, %dr6", "fsqrttd,5\t%dr2, %dr6, %dr5"],
    "fsqrttd_y": ["fsqrttd,5\t%dr2, %dr3, %dr5"],
    "frcps": ["frcps,5\t%r2, %r5"],
    "frsqrts": ["frsqrts,5\t%r2, %r5"],
    "pfsqrts": ["pfsqrts,5\t%r2, %r5"],
    "pfsqrttd_y": ["pfsqrttd,5\t%dr2, %dr3, %dr5"],
    "fdivs": ["fdivs,5\t%r2, %r3, %r5"],
    "fdivd": ["fdivd,5\t%dr2, %dr3, %dr5"],
}

# Latency chains: one step, from %dr2 back to %dr2.
LAT = {
    "fsqrts": ["fsqrts,5\t%r2, %r2"],
    "fsqrtid": ["fsqrtid,5\t%dr2, %dr2"],
    "fsqrt2": ["fsqrtid,5\t%dr2, %dr6", "fsqrttd,5\t%dr2, %dr6, %dr2"],
    "frcps": ["frcps,5\t%r2, %r2"],
    "frsqrts": ["frsqrts,5\t%r2, %r2"],
}


def wi(*ops):
    return "\t{\n" + "".join(f"\t  {o}\n" for o in ops) + "\t}\n"


def op_fn(name, ops):
    b = wi("setwd\twsz = 0x8, nfx = 0x1, dbl = 0x0", "return\t%ctpr3",
           "adds,1\t%r2, 0x0, %r4")
    b += wi("rrs,0\t%pfpfr, %r8")
    b += wi("ldd,0\t%dr0, 0x0, %dr2", "ldd,2\t%dr0, 0x8, %dr3")
    b += wi("addd,0\t0x0, _f64,_lts0 0x5555555555555555, %dr5",
            "addd,1\t0x0, _f64,_lts1 0x5555555555555555, %dr6")
    b += wi("nop 2")
    b += wi("rws,0\t%r4, %pfpfr")
    b += wi("nop 7")
    for o in ops:
        b += wi(o)
    b += wi("nop 7") + wi("nop 7")
    b += wi("rrs,0\t%pfpfr, %r9")
    b += wi("nop 2")
    b += wi("std,2\t%dr1, 0x0, %dr5", "stw,5\t%dr1, 0x8, %r9")
    b += wi("rws,0\t%r8, %pfpfr")
    b += wi("nop 7")
    b += wi("ct\t%ctpr3")
    return (f"\n\t.global\tsq_{name}\n\t.type\tsq_{name}, #function\n"
            f"\t.align\t8\nsq_{name}:\n{b}\t.size\tsq_{name}, .-sq_{name}\n")


def lat_fn(name, ops, steps=32):
    b = wi("setwd\twsz = 0x8, nfx = 0x1, dbl = 0x0", "return\t%ctpr3",
           "addd,0\t%dr0, 0x0, %dr2")
    b += wi("nop 7") + wi("rrd,0\t%clkr, %dr4")
    for _ in range(steps):
        for o in ops:
            b += wi(o)
    b += wi("rrd,0\t%clkr, %dr5") + wi("subd,0\t%dr5, %dr4, %dr0")
    b += wi("nop 5") + wi("ct\t%ctpr3")
    return (f"\n\t.global\tlat_{name}\n\t.type\tlat_{name}, #function\n"
            f"\t.align\t8\nlat_{name}:\n{b}\t.size\tlat_{name}, "
            f".-lat_{name}\n")


def main():
    text = ("! SPDX-License-Identifier: GPL-3.0-or-later\n"
            "! Generated by tools/isa-probes/gen_sqrt.py; see sqrt.c.\n"
            "\t.ignore\tld_st_style\n\t.text\n")
    text += "".join(op_fn(n, o) for n, o in OPS.items())
    text += "".join(lat_fn(n, o) for n, o in LAT.items())
    (HERE / "sqrt.s").write_text(text)
    (HERE / "sqrt-ops.h").write_text(
        "/* SPDX-License-Identifier: GPL-3.0-or-later */\n"
        "/* Generated by tools/isa-probes/gen_sqrt.py.  */\n"
        + "".join(f"OP ({n})\n" for n in OPS)
        + "".join(f"LAT ({n})\n" for n in LAT))


if __name__ == "__main__":
    main()
