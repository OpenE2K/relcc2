/* Whether aaurw/aaurwd pay a cluster-crossing cost on an integer operand,
   and how long a not-taken ct waits after return or disp (isa-score's
   model; spec/isa/timing.md, control-transfer.md).  aaurwct.s and
   aaurwct-cases.h are generated by gen_aaurwct.py.  Prints the median
   cycles (%clkr) of 101 calls of each case.

     LCC=/opt/mcst/lcc-1.29.16.e2k-v3.4c.linux-6.1/bin/lcc   # or v5.8c2
     $LCC -O2 tools/isa-probes/aaurwct.c tools/isa-probes/aaurwct.s \
         -o aaurwct
     taskset -c 1 ./aaurwct                     # on hardware  */

#include <stdio.h>
#include <stdlib.h>

unsigned long aw_clk (void);
#define CASE(n) void aw_##n (void);
#include "aaurwct-cases.h"
#undef CASE

static unsigned long t[101];

static int
cmp (const void *p, const void *q)
{
  unsigned long u = *(const unsigned long *) p, v = *(const unsigned long *) q;
  return u < v ? -1 : u > v;
}

static unsigned long
med (void (*f) (void))
{
  for (int i = 0; i < 101; i++)
    {
      unsigned long t0 = aw_clk ();
      f ();
      t[i] = aw_clk () - t0;
    }
  qsort (t, 101, sizeof *t, cmp);
  return t[50];
}

int
main (void)
{
#define CASE(n) printf ("%s %lu\n", #n, med (aw_##n));
#include "aaurwct-cases.h"
#undef CASE
  return 0;
}
