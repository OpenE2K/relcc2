FETCH = []      # names, in order


def fetch_case(name, window, tshape=1, far=False):
    """A 4 KiB page: entry at 0, the target T at 512 (TSHAPE lines of
    straight code ending in the clock read), the window at 2048 (it
    starts with the first clock read and ends with the transfer to T).
    FAR puts T on a page of its own instead."""
    FETCH.append(name)
    fn = f"cl_{name}"
    L = f".L{name}"
    # T is a global symbol: gas resolves a pref to a local label to its
    # section offset (R_E2K_PREF against *ABS*), so the linked pref would
    # point elsewhere.
    t = f"{fn}_T"
    entry = (wi("setwd\twsz = 0x20, nfx = 0x1, dbl = 0x0",
                f"disp\t%ctpr2, {L}_back",
                "cmpedb,0\t%dr1, 0x0, %pred0", "cmpedb,1\t%dr1, 0x1, %pred1")
             + wi("disp\t%ctpr1, cl_flush512", f"addd,2\t0x0, {L}_cont, %dr20",
                  f"addd,3\t0x0, {t}, %dr21")
             + wi("disp\t%ctpr3, cl_flush256", "addd,0\t0x0, 0x1, %dr50",
                  "addd,1\t0x0, 0x1, %dr51") + nops(4)
             + wi(f"ibranch\t{L}_cont ? %pred0") + wi("ct\t%ctpr3 ? %pred1")
             + wi("ct\t%ctpr1"))
    tcode = f"\t.balign\t256\n\t.global\t{t}\n{t}:\n"
    for _ in range(8 * tshape - 1):
        tcode += wi(*[f"addd,{c}\t%dr5, %dr5, %dr{40 + c}" for c in range(6)])
    tcode += wi("rrd,0\t%clkr, %dr11",
                *[f"addd,{c}\t%dr5, %dr5, %dr{40 + c}" for c in range(1, 6)])
    tcode += wi("ct\t%ctpr2")
    body = (f"\n\t.balign\t4096\n\t.global\t{fn}\n\t.type\t{fn}, #function\n"
            f"{fn}:\n" + entry)
    if not far:
        body += "\t.balign\t512\n" + tcode
    body += f"\t.balign\t2048\n{L}_cont:\n" + window(t)
    body += (f"{L}_back:\n" + wi("subd,0\t%dr11, %dr10, %dr0", "return\t%ctpr3")
             + nops(5) + wi("ct\t%ctpr3") + f"\t.size\t{fn}, .-{fn}\n")
    text[""].append(body)
    if far:
        FAR.append("\n\t.balign\t4096\n" + tcode)


