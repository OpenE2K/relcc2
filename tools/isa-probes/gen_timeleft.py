def macro(name, args, body):
    macros.append(f"\t.macro\t{name}{(' ' + args) if args else ''}\n{body}\t.endm\n")
    return name
WARM, STEPS = 4, 12
ONE = "_f64,_lts0 0x3ff0000000000000"


def wi(*ops):
    return "\t{\n" + "".join(f"\t  {o}\n" for o in ops) + "\t}\n"


def nops(n):
    out = ""
    while n > 0:
        k = min(n, 8)
        out += wi(f"nop {k - 1}" if k > 1 else "nop")
        n -= k
    return out


def raw(name, body, part=""):
    fn = f"tl_{name}"
    text[part].append(f"\n\t.global\t{fn}\n\t.type\t{fn}, #function\n"
                      f"\t.align\t8\n{fn}:\n{body}\t.size\t{fn}, .-{fn}\n")


RET = wi("return\t%ctpr3") + nops(6) + wi("ct\t%ctpr3")


def func(name, body, dbl=0, wsz=0x20, part=""):
    ret = "\ttl_ret\n" if part == "" else RET
    raw(name, wi(f"setwd\twsz = {wsz:#x}, nfx = 0x1, dbl = {dbl:#x}") + body
        + ret, part)


