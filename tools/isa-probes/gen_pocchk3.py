"""Write pocchk3.s and pocchk3-cases.h: checks of the proof-of-concept
back end's array prefetch findings I47, I48 and I49
(docs/spec-poc-findings.md) for pocchk3.c.

  python3 tools/isa-probes/gen_pocchk3.py

Three kinds of function:

  p3_m_* (I48)    gen_apb.py's cases: long f(unsigned long *out,
                  void *base, void *base2) runs eight wide instructions
                  of two movaX from one area (ind 0 with am = 0, and
                  ind = mrng - size with am = 1) and stores each result
                  and its tag in out[], for every format, mrng, step and
                  base offset listed below.
  p3_col_* (I47)  long f(const long *a, const long *b, unsigned long lsr,
                  long stride, long *cycles): a one-instruction loop_mode
                  loop (as gen_apb_stream.py's) that reads a and b
                  (stride elements a step) through one or two areas laid
                  out as the name says (L the left half of the buffer,
                  R the right, the digit the asz), and returns the sum
                  of the first lcnt - 6 elements of both.
  p3_bk_* (I49)   double f(const double *a, const double *blo,
                  unsigned long lsr, long *cycles, long span): a loop of
                  one wide instruction taking 4 cycles (II 4) that sums
                  a[i] * b[...] with b read backward from blo + span down
                  to blo (or forward from blo), each stream through a
                  plain load issued D iterations before its use (into the
                  rotating registers) or through array prefetch; the
                  name gives the variant (the comment above bk()).

*cycles is the %clkr difference across the loop.
"""

from pathlib import Path

import gen_apb

HERE = Path(__file__).resolve().parent
HEADER = """! SPDX-License-Identifier: GPL-3.0-or-later
! Generated by tools/isa-probes/gen_pocchk3.py; see pocchk3.c.
	.ignore	ld_st_style
	.text
"""
SIZE = {1: 1, 2: 2, 3: 4, 4: 8}
text, mcases, colcases, bkcases = [], [], [], []


def wi(*ops):
    return "\t{\n" + "".join(f"\t  {o}\n" for o in ops if o) + "\t}\n"


def fn(name, body, prog=None):
    t = (f"\n\t.global\t{name}\n\t.type\t{name}, #function\n\t.align\t8\n"
         f"{name}:\n{body}")
    if prog:
        t += f"\t.align\t8\n.L{name}_prog:\n{prog}"
    text.append(t + f"\t.size\t{name}, .-{name}\n")


# I48: which mrng an area may have, per format, step and base offset.
# Two movas a row (ind 0 without am, ind mrng - size with am), 8 rows.
def mcase(fmt, mrng, step, off, disp=0, aaind=0):
    """STEP in bytes (negative: a backward area); OFF is added to the
    base by the caller, DISP in the program, AAIND through %aaind1."""
    size = SIZE[fmt]
    name = (f"m_f{fmt}_r{mrng}_s{step}_o{off}".replace("-", "m")
            + (f"_disp{disp}" if disp else "") + (f"_ind{aaind}" if aaind else ""))
    incr = step // size
    prog = [({"fmt": fmt, "mrng": mrng % 32, "incr": 1 if incr != 1 else 0,
              "asz": 5, "disp": disp, "ind": 1 if aaind else 0}, None)]
    setup = [("%aad0", "%dr1")]
    if incr != 1:
        setup.append(("%aaincr1", incr))
    if aaind:
        setup.append(("%aaind1", aaind))
    rows = [[gen_apb.mova(0, ind=0, am=0, fmt=fmt),
             gen_apb.mova(1, ind=mrng - size, am=1, fmt=fmt)]] * 8
    t = gen_apb.case(name, prog, rows, setup)
    text.append(t.replace(f"apb_{name}", f"p3_{name}"))
    mcases.append((name, fmt, mrng, step, off, disp + aaind))


for fmt in (1, 2, 3, 4):
    for mrng in range(SIZE[fmt], 33):
        mcase(fmt, mrng, SIZE[fmt], 0)
# A step of 8 bytes keeps every element at the same offset in its
# doubleword: the base's offset picks it.
for fmt, offs in ((1, range(8)), (2, (0, 2, 4, 6)), (3, (0, 4))):
    for mrng in range(24, 33):
        for off in offs:
            mcase(fmt, mrng, 8, off)
# lcc's v3 shape for a 32-byte record of bytes (a 32-byte step).
for off in (0, 1, 7):
    mcase(1, 32, 32, off)
# Byte areas with other steps; the start moved by disp or %aaind
# instead of the base; backward areas (the base at the lowest byte read,
# the start 64 bytes above it).
for step in (2, 4, 12, 24, 40):
    for mrng in (25, 26, 27, 28, 29, 32):
        mcase(1, mrng, step, 0)
for start in (1, 2, 4):
    for mrng in (25, 26, 28, 29, 32):
        mcase(1, mrng, 8, 0, disp=start)
        mcase(1, mrng, 8, 0, aaind=start)
for step in (-1, -2, -8):
    for mrng in (25, 26, 28, 29, 32):
        mcase(1, mrng, step, 0, disp=64)


# I47: two column walks, the areas laid out as NAME says: L = left half
# (channels 0, 1), R = right half (2, 3), the digit the asz.
def col(name, layout):
    """LAYOUT: list of (half, asz) per array; the first array is a."""
    instr = {"L": [], "R": []}
    used = {"L": 0, "R": 0}
    movas = []
    for j, (half, asz) in enumerate(layout):
        idx = len(instr[half])
        ch = (0 if half == "L" else 2) + (idx % 2)
        movas.append(f"movad,{ch}\tarea={idx}, ind=0, am=1, be=0, %b[{j}]")
        instr[half].append((asz, f"dcd=0, fmt=4, mrng=8, d={j}, incr=1, "
                                 f"ind=0, asz={asz}, abs={used[half]}, disp=0"))
        used[half] += 2 ** asz
    n = max(len(instr["L"]), len(instr["R"]))
    prog = ""
    for i in range(n):
        ops = []
        if i < len(instr["L"]):
            ops.append(f"fapb\tct={int(i == n - 1)}, {instr['L'][i][1]}")
        if i < len(instr["R"]):
            ops.append(f"fapb\tdpl=0, {instr['R'][i][1]}")
        prog += wi(*ops)
    adds = [f"addd,{j}\t%dr{9 + j}, %b[{12 + j}], %dr{9 + j}"
            for j in range(len(layout))]
    body = (wi("setwd\twsz = 0x10, nfx = 0x1, dbl = 0x0",
               "setbn\trsz = 0x7, rbs = 0x8, rcur = 0x0", "return\t%ctpr3")
            + "".join(wi(*(f"addd,{c}\t0x0, 0x0, %b[{6 * k + c}]"
                           for c in range(6) if 6 * k + c < 16))
                      for k in range(3))
            + wi(f"ldisp\t%ctpr2, .Lp3_col_{name}_prog", "aaurwd,2\t%dr0, %aad0",
                 "aaurwd,5\t%dr1, %aad1", "addd,0\t0x0, 0x0, %dr9",
                 "addd,1\t0x0, 0x0, %dr10")
            + wi("aaurwd,2\t%dr3, %aaincr1", "disp\t%ctpr1, .Lp3_col_" + name
                 + "_loop", "rwd,0\t%dr2, %lsr")
            + wi("nop 7", "bap") + wi("nop 7") + wi("nop 7", "rrd,0\t%clkr, %dr6")
            + f".Lp3_col_{name}_loop:\n"
            + wi("loop_mode", "alc\talcf=1, alct=1", "abn\tabnf=1, abnt=1",
                 "ct\t%ctpr1 ? %NOT_LOOP_END", *movas, *adds)
            + wi("rrd,0\t%clkr, %dr7")
            + wi("nop 7", "disp\t%ctpr2, disp=0x0")
            + wi("addd,0\t%dr9, %dr10, %dr0", "subd,1\t%dr7, %dr6, %dr8")
            + wi("std,2\t%dr4, 0x0, %dr8")
            + wi("ct\t%ctpr3"))
    fn(f"p3_col_{name}", body, prog)
    colcases.append((name, len(layout)))


for name, layout in (("L3", [("L", 3)]), ("L4", [("L", 4)]), ("L5", [("L", 5)]),
                     ("LL3", [("L", 3), ("L", 3)]), ("LL4", [("L", 4), ("L", 4)]),
                     ("LR3", [("L", 3), ("R", 3)]), ("LR4", [("L", 4), ("R", 4)]),
                     ("LR5", [("L", 5), ("R", 5)])):
    col(name, layout)

# I49: a[i] * b[...] summed, II 4.  Variant name: a's source, b's
# source, then options.  Sources: P plain load D iterations ahead
# (a forward; b backward), F plain load of b forward, A array prefetch
# (b backward: the area's base at blo, its start in %aaind1, %aaincr1 =
# -1, written with aaurwd), B array prefetch of b forward, C a plain
# load of b's lowest element every iteration (an L1 hit), K the
# constant 1.0 (no stream).  Options: bN = b's plain load in ALC N;
# aszN = a's area size; dN = the plain loads N iterations ahead.
ONE = "0x3ff0000000000000"


def bk(name, asrc, bsrc, bch=2, asz=5, d=12):
    ring = 2 * d + 2
    rsz = ring // 2 - 1
    wsz = 8 + ring // 2 + 2
    wsz += wsz % 2
    fch, ach = 3, 4
    if bch == 3:
        fch, ach = 0, 1      # fmuld and faddd in one cluster
        assert asrc != "P"
    bup = 5 if bch != 5 else 2
    ops = []
    areas = []          # (fields) in program order; first left, second right
    if asrc == "P":
        ops += ["ldd,0\t%dr5, 0x0, %b[0]", "addd,1\t%dr5, 0x8, %dr5"]
    elif asrc == "A":
        areas.append(("a", f"dcd=0, fmt=4, mrng=8, d=0, incr=0, ind=0, "
                           f"asz={asz}, abs=0, disp=0"))
    else:
        ops.append("addd,1\t%dr12, 0x0, %b[0]")
    if bsrc in "PF":
        ops += [f"ldd,{bch}\t%dr6, 0x0, %b[1]",
                f"{'subd' if bsrc == 'P' else 'addd'},{bup}\t%dr6, 0x8, %dr6"]
    elif bsrc == "C":
        ops.append(f"ldd,{bch}\t%dr6, 0x0, %b[1]")
    elif bsrc == "A":
        areas.append(("b", "dcd=0, fmt=4, mrng=8, d=1, incr=1, ind=1, "
                           "asz=5, abs=0, disp=0"))
    elif bsrc == "B":
        areas.append(("b", "dcd=0, fmt=4, mrng=8, d=1, incr=0, ind=0, "
                           "asz=5, abs=0, disp=0"))
    else:
        ops.append("addd,5\t%dr12, 0x0, %b[1]")
    prog = ""
    for k, (who, fields) in enumerate(areas):
        ch = 0 if k == 0 else 2
        ops.append(f"movad,{ch}\tarea=0, ind=0, am=1, be=0, "
                   f"%b[{0 if who == 'a' else 1}]")
    if areas:
        left = f"fapb\tct=1, {areas[0][1]}"
        right = f"fapb\tdpl=0, {areas[1][1]}" if len(areas) > 1 else None
        prog = wi(left, right)
    ops += [f"fmuld,{fch}\t%b[{2 * d}], %b[{2 * d + 1}], %dr10",
            f"faddd,{ach}\t%dr11, %dr10, %dr11"]
    zero = [f"%b[{k}]" for k in range(ring)] + ["%dr10", "%dr11"]
    body = wi(f"setwd\twsz = {wsz:#x}, nfx = 0x1, dbl = 0x0",
              f"setbn\trsz = {rsz:#x}, rbs = 0x8, rcur = 0x0", "return\t%ctpr3")
    for k in range(0, len(zero), 6):
        body += wi(*(f"addd,{c}\t0x0, 0x0, {r}"
                     for c, r in enumerate(zero[k:k + 6])))
    bstart = "%dr4" if bsrc == "P" else "0x0"
    body += wi("addd,0\t%dr0, 0x0, %dr5", f"addd,1\t%dr1, {bstart}, %dr6",
               f"addd,3\t0x0, _f64,_lts0 {ONE}, %dr12", "subd,4\t0x0, 0x1, %dr13")
    if areas:
        body += wi(f"ldisp\t%ctpr2, .Lp3_bk_{name}_prog",
                   "aaurwd,2\t%dr0, %aad0", "aaurwd,5\t%dr1, %aad1")
        body += wi("aaurwd,2\t%dr4, %aaind1", "aaurwd,5\t%dr13, %aaincr1")
    body += wi(f"disp\t%ctpr1, .Lp3_bk_{name}_loop", "rwd,0\t%dr2, %lsr")
    body += wi("nop 7", "bap" if areas else None) + wi("nop 7")
    body += wi("nop 7", "rrd,0\t%clkr, %dr14")
    body += (f".Lp3_bk_{name}_loop:\n"
             + wi("loop_mode", "alc\talcf=1, alct=1", "abn\tabnf=1, abnt=1",
                  "ct\t%ctpr1 ? %NOT_LOOP_END", "nop 3", *ops))
    body += wi("rrd,0\t%clkr, %dr15")
    body += wi("nop 7", "disp\t%ctpr2, disp=0x0" if areas else None)
    body += wi("faddd,4\t%dr11, %dr10, %dr0", "subd,1\t%dr15, %dr14, %dr9")
    body += wi("std,2\t%dr3, 0x0, %dr9") + wi("nop 3") + wi("ct\t%ctpr3")
    fn(f"p3_bk_{name}", body, prog)
    bkcases.append((name, asrc, bsrc, d))


for a in "PAK":
    for b in "PFABK":
        if a == "K" and b == "K":
            continue
        bk(f"{a}{b}", a, b)
for a, b in (("P", "P"), ("A", "P"), ("A", "F")):
    bk(f"{a}{b}_d24", a, b, d=24)
bk("AP_b3", "A", "P", bch=3)
bk("AP_b5", "A", "P", bch=5)
bk("PP_b5", "P", "P", bch=5)
bk("AP_asz3", "A", "P", asz=3)
bk("AF_asz3", "A", "F", asz=3)
bk("AC", "A", "C")
bk("PC", "P", "C")
bk("KC", "K", "C")


def write():
    (HERE / "pocchk3.s").write_text(HEADER + "".join(text))
    (HERE / "pocchk3-cases.h").write_text(
        "/* SPDX-License-Identifier: GPL-3.0-or-later */\n"
        "/* Generated by tools/isa-probes/gen_pocchk3.py.  */\n"
        + "".join(f"MCASE ({n}, {f}, {r}, {s}, {o}, {st})\n"
                  for n, f, r, s, o, st in mcases)
        + "".join(f"COLCASE ({n}, {k})\n" for n, k in colcases)
        + "".join(f"BKCASE ({n}, '{a}', '{b}', {d})\n"
                  for n, a, b, d in bkcases))
    print(len(mcases), "mrng cases,", len(colcases), "column walks,",
          len(bkcases), "backward-stream loops")


if __name__ == "__main__":
    write()
