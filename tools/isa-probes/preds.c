/* Predicates: whether a reader in a wide instruction with a taken
   transfer waits for a compare one instruction before (i17_*), what
   andp and landp do with a diagnostic operand (lp_*), and a two-level
   landp tree (tree_*).  preds.s and preds-cases.h are generated by
   gen_preds.py (spec/isa/timing.md, semantics.md).

     LCC=/opt/mcst/lcc-1.29.16.e2k-v3.4c.linux-6.1/bin/lcc
     $LCC -O3 tools/isa-probes/preds.c tools/isa-probes/preds.s -o preds
     ./preds                              # on hardware  */

#include <setjmp.h>
#include <signal.h>
#include <stdio.h>
#include <string.h>

#define CASE(n) long pr_##n (void);
#include "preds-cases.h"
#undef CASE

static sigjmp_buf env;
static int code;

static void
handler (int sig, siginfo_t *si, void *uc)
{
  (void) uc;
  code = si->si_code;
  siglongjmp (env, sig);
}

int
main (void)
{
  struct sigaction sa;
  memset (&sa, 0, sizeof sa);
  sa.sa_sigaction = handler;
  sa.sa_flags = SA_SIGINFO | SA_NODEFER;
  sigaction (SIGILL, &sa, NULL);
  sigaction (SIGSEGV, &sa, NULL);
#define CASE(n) \
  if (strcmp (#n, "leaf") != 0) \
  { \
    int sig = sigsetjmp (env, 1); \
    if (sig) \
      printf ("%-26s signal %d code %d\n", #n, sig, code); \
    else \
      printf ("%-26s %ld\n", #n, pr_##n ()); \
  }
#include "preds-cases.h"
#undef CASE
  return 0;
}
