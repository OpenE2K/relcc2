"""Write memorycxx_dam.s and memorycxx_dam-cases.h for memorycxx_dam.c:
a store in a DAM lock load's own wide instruction (spec/isa/
speculation.md, "What keeps or loses an entry"; bundle.md, "Memory
accesses in one wide instruction").

  python3 tools/isa-probes/gen_memorycxx_dam.py

Case  long md_NAME(long *mem, long *out): mem[0] holds 100 and every
other doubleword the probe reads holds its own index times 1000 + 1
(set by the harness).  The case locks %dr8 from mem[0] (ldd,LCH,sm
.. mas=0x4), stores 0x777 (%dr9) with STORE at offset OFF from mem in
the place given by WHERE, waits, then checks %dr8 (ldd,CCH .. mas=0x3)
with rbranch to compensation code that sets %dr10 and returns with
ibranch.  The check's own wide instruction copies the lock's value
(%dr8 before the check writes it) into %dr11.  out[0] = %dr8 after the
check, out[1] = %dr11 (what the lock read), out[2] = %dr10 (1: rbranch
taken).

WHERE: "same" (the store in the lock's wide instruction), "after" (the
store in the next instruction: the known "lost" control), "before"
(the store one instruction before the lock: the known "no conflict"
control), "none" (no store).  gas accepts a store in the lock's
instruction only in the lock's cluster: ALC2 with a lock in ALC0, ALC5
with a lock in ALC3 ("the combination of STORE in ALC5 with LOAD in
ALC0 is prohibited", and ALC2 with ALC3).

Every CTPR is kept prepared around the rbranch (hwbugs.md,
BRANCH_ACTIVATES_CTPR on v6), and every entry a case makes is checked
before it returns.
"""

from pathlib import Path

HERE = Path(__file__).resolve().parent
HEADER = """! SPDX-License-Identifier: GPL-3.0-or-later
! Generated by tools/isa-probes/gen_memorycxx_dam.py; see memorycxx_dam.c.
	.ignore	ld_st_style
	.ignore	strict_delay
	.text
"""
cases, text = [], []


def wi(*ops):
    ops = [o for o in ops if o]
    return "\t{\n" + "".join(f"\t  {o}\n" for o in ops or ["nop"]) + "\t}\n"


def nops(n):
    out = ""
    while n > 0:
        k = min(n, 8)
        out += wi(f"nop {k - 1}" if k > 1 else "nop")
        n -= k
    return out


# Stores: (tag, op, offset, mas suffix).  The value register is %dr9
# (0x777) for every width.
STORES = {
    "d0": ("std", 0x0, ""),        # the locked doubleword, all of it
    "w4": ("stw", 0x4, ""),        # its upper half
    "b0": ("stb", 0x0, ""),        # its first byte
    "d8": ("std", 0x8, ""),        # the next doubleword, same 32-byte line
    "d32": ("std", 0x20, ""),      # the next 32-byte line
    "d4k": ("std", 0x1000, ""),    # 4 KiB on: the same low 12 bits
    "d4k8": ("std", 0x1008, ""),   # 4 KiB + 8: other low 12 bits
    "d16k": ("std", 0x4000, ""),   # 16 KiB on: the same low 14 bits
    "d0m4": ("std", 0x0, ", mas=0x4"),  # the locked doubleword, MAS mod 4
}
REG = {"std": "%dr9", "stw": "%r9", "stb": "%r9"}


def case(where, st, lch, gap=2, cch=None):
    sch = 2 if lch == 0 else 5
    if cch is None:
        cch = 5 if lch == 0 else 2
    name = f"{where}_{st}_l{lch}" + (f"_g{gap}" if gap != 2 else "") \
        + (f"_c{cch}" if cch != (5 if lch == 0 else 2) else "")
    lab = f".Lmd_{name}"
    lock = f"ldd,{lch},sm\t%dr0, 0x0, %dr8, mas=0x4"
    store = None
    if st != "none":
        op, off, mas = STORES[st]
        store = f"{op},{sch}\t%dr0, {off:#x}, {REG[op]}{mas}"
    body = wi("setwd\twsz = 0x10, nfx = 0x1, dbl = 0x0", "return\t%ctpr3")
    body += wi("addd,0\t0x0, 0x0, %dr10",
               "addd,1\t0x0, _f16s,_lts0lo 0x777, %dr9",
               "addd,3\t0x0, 0x0, %dr8", "addd,4\t0x0, 0x0, %dr11")
    body += wi(f"disp\t%ctpr1, {lab}_end") + wi(f"disp\t%ctpr2, {lab}_end")
    body += nops(3)
    if where == "before":
        body += wi(store) + wi(lock)
    elif where == "same":
        body += wi(lock, store)
    elif where == "after":
        body += wi(lock) + wi(store)
    else:
        body += wi(lock)
    body += nops(gap - (1 if where == "after" else 0))
    body += wi(f"ldd,{cch}\t%dr0, 0x0, %dr8, mas=0x3",
               "addd,0\t0x0, %dr8, %dr11", f"rbranch\t{lab}_c")
    body += f"{lab}_r:\n" + nops(3)
    body += wi("std,2\t%dr1, 0x0, %dr8", "std,5\t%dr1, 0x8, %dr11")
    body += wi("std,2\t%dr1, 0x10, %dr10")
    body += wi("addd,0\t0x0, %dr10, %dr0") + nops(5) + wi("ct\t%ctpr3")
    tail = (f"{lab}_end:\n" + wi("nop")
            + f"{lab}_c:\n"
            + wi(f"ibranch\t{lab}_r", "ord,0\t%dr10, 0x1, %dr10"))
    fn = f"md_{name}"
    text.append(f"\n\t.global\t{fn}\n\t.type\t{fn}, #function\n"
                f"\t.align\t8\n{fn}:\n{body}{tail}\t.size\t{fn}, .-{fn}\n")
    off = STORES[st][1] if st != "none" else -1
    cases.append(f'MD ({name}, "{where}", "{st}", {lch}, {off})\n')


for lch in (0, 3):
    for st in STORES:
        case("same", st, lch)
    for st in ("d0", "w4", "d8", "d4k"):
        case("after", st, lch)
        case("before", st, lch)
    case("none", "none", lch)
# The check sooner and later after a lock with the store in its
# instruction.
for gap in (1, 4, 8):
    for st in ("d0", "d8", "d4k"):
        case("same", st, 0, gap=gap)
# The check in the lock's cluster.
for st in ("d0", "d8", "d4k"):
    case("same", st, 0, cch=2)
    case("same", st, 3, cch=5)

(HERE / "memorycxx_dam.s").write_text(HEADER + "".join(text))
(HERE / "memorycxx_dam-cases.h").write_text(
    "/* SPDX-License-Identifier: GPL-3.0-or-later */\n"
    "/* Generated by tools/isa-probes/gen_memorycxx_dam.py.  */\n"
    + "".join(cases))
print(len(cases), "cases")
