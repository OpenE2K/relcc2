"""Write apb.s: one function per array-prefetch (APB) case, called from
apb.c to observe on hardware what movaX returns (spec/isa/apb.md).

  python3 tools/isa-probes/gen_apb.py     # rewrites apb.s

Each case is  long apb_NAME(long *out, char *base, char *base2).
It writes AAU registers, loads an APB program with ldisp, starts it with
bap, waits GAP cycles, runs wide instructions with movaX into %dr8 and
up, and stores each result as two words: the value with its tag cleared
and the tag (gettagd).  The return value is the %clkr difference from
the instruction before the first mova to the one after the last.
"""

from pathlib import Path

HERE = Path(__file__).resolve().parent

HEADER = """! SPDX-License-Identifier: GPL-3.0-or-later
! Generated by tools/isa-probes/gen_apb.py; see apb.c.
	.ignore	ld_st_style
	.text

	.global	apb_nop
	.type	apb_nop, #function
	.align	8
apb_nop:
	{
	  return	%ctpr3
	}
	{
	  ct	%ctpr3
	}
	.size	apb_nop, .-apb_nop
"""

FAPB = dict(dcd=0, fmt=4, mrng=8, d=0, incr=0, ind=0, asz=5, abs=0, disp=0)


def fapb(half, last, f):
    f = {**FAPB, **f}
    flag = f"ct={int(last)}" if half == "l" else "dpl=0"
    return (f"fapb\t{flag}, dcd={f['dcd']}, fmt={f['fmt']}, mrng={f['mrng']}, "
            f"d={f['d']}, incr={f['incr']}, ind={f['ind']}, asz={f['asz']}, "
            f"abs={f['abs']}, disp={f['disp']}")


MOVA = {1: "movab", 2: "movah", 3: "movaw", 4: "movad"}


def mova(ch, area=0, ind=0, am=1, be=0, fmt=4):
    return (ch, f"{MOVA[fmt]},{ch}\tarea={area}, ind={ind}, am={am}, be={be}")


def case(name, prog, rows, setup=(), gap=21, between=None, aau_reads=()):
    """PROG: list of (left fields, right fields or None); the last
    instruction's left half carries ct=1, which ends the program.
    ROWS: wide instructions, each a list of mova() tuples; between[i]
    is a list of extra wide instructions (each a list of ops) emitted
    after row i (-1: before the first row, after the gap).
    SETUP: (aau register, source) with source '%dr1', '%dr2', an int, or
    (register, byte offset).
    AAU_READS: AAU registers read with aaurrd after the last row."""
    between = between or {}
    out = []

    def wi(*ops):
        out.append("\t{\n" + "".join(f"\t  {o}\n" for o in ops) + "\t}\n")

    wi("setwd\twsz = 0x20, nfx = 0x1, dbl = 0x0", "return\t%ctpr3")
    # AAU register writes: constants via %dr3.
    first = [f"ldisp\t%ctpr2, .L{name}_prog"]
    for reg, src in setup:
        if isinstance(src, int):
            wi(f"addd,0\t0x0, _f64,_lts0 {src & (1 << 64) - 1:#x}, %dr3")
            src = "%dr3"
        elif isinstance(src, tuple):
            wi(f"addd,0\t{src[0]}, _f64,_lts0 {src[1]:#x}, %dr3")
            src = "%dr3"
        wi(*first, f"aaurwd,2\t{src}, {reg}")
        first = []
    if first:
        wi(*first)
    wi("bap")
    left = gap
    while left > 0:
        # A wide instruction with nop N takes N + 1 cycles.
        n = min(left, 8)
        wi(f"nop {n - 1}" if n > 1 else "nop")
        left -= n
    for extra in between.get(-1, []):
        wi(*extra)
    wi("rrd,0\t%clkr, %dr4")
    dst = 8
    for i, row in enumerate(rows):
        ops = []
        for ch, text in row:
            ops.append(f"{text}, %dr{dst}")
            dst += 1
        wi(*ops)
        for extra in between.get(i, []):
            wi(*extra)
    wi("rrd,0\t%clkr, %dr5")
    reads = []
    for j, reg in enumerate(aau_reads):
        reads.append((j, reg))
        wi(f"aaurrd,2\t{reg}, %dr{40 + j}")
    # Results: value with the tag cleared, then the tag.
    wi("nop 7")
    for k in range(8, dst):
        wi(f"gettagd,2\t%dr{k}, %r6", f"puttagd,5\t%dr{k}, 0x0, %dr7")
        wi("nop 2")
        wi(f"std,2\t%dr0, {(k - 8) * 16:#x}, %dr7",
           f"std,5\t%dr0, {(k - 8) * 16 + 8:#x}, %dr6")
    for j, reg in reads:
        wi(f"std,2\t%dr0, {0x400 + j * 8:#x}, %dr{40 + j}")
    wi("disp\t%ctpr2, disp=0x0", "subd,0\t%dr5, %dr4, %dr0")
    wi("ct\t%ctpr3")
    progtext = []
    assert prog[-1][0] is not None, "the last instruction needs ct=1"
    for i, (lf, rf) in enumerate(prog):
        last = i == len(prog) - 1
        ops = [fapb("l", last, lf)] if lf is not None else []
        if rf is not None:
            ops.append(fapb("r", last, rf))
        progtext.append("\t{\n" + "".join(f"\t  {o}\n" for o in ops) + "\t}\n")
    case.counts = (dst - 8, len(reads))
    return (f"\n\t.global\tapb_{name}\n\t.type\tapb_{name}, #function\n"
            f"\t.align\t8\napb_{name}:\n" + "".join(out)
            + f"\t.align\t8\n.L{name}_prog:\n" + "".join(progtext)
            + f"\t.size\tapb_{name}, .-apb_{name}\n")


def seq(n, **kw):
    """N wide instructions with one mova each in channel 0."""
    return [[mova(0, **kw)] for _ in range(n)]


CASES = []


def add(name, *a, **kw):
    text = case(name, *a, **kw)
    CASES.append((name, text, case.counts))


def main():
    base = [("%aad0", "%dr1")]
    # Element order and the area step: fmt d, AAINCR0 = 1.
    add("basic", [({}, None)], seq(8), base)
    # Byte offsets inside the record (mrng 32), am only on the last.
    add("ind", [({"mrng": 0}, None)],
        [[mova(0, ind=0, am=0), mova(1, ind=8, am=0)],
         [mova(0, ind=16, am=0), mova(1, ind=24, am=1)],
         [mova(0, ind=0, am=0), mova(1, ind=24, am=1)]], base)
    # ind beyond mrng: mrng 8, read at ind 8.
    add("mrng", [({"mrng": 8}, None)],
        [[mova(0, ind=8, am=1)], [mova(0, ind=0, am=1)]], base)
    # disp and AAIND: start at base + AAIND + disp.
    add("disp", [({"disp": 40}, None)], seq(3), base)
    add("aaind", [({"ind": 1, "disp": 8}, None)], seq(3),
        base + [("%aaind1", 64)])
    # AAINCR in elements: 3 doubles, then -1.
    add("incr3", [({"incr": 1}, None)], seq(3), base + [("%aaincr1", 3)])
    add("incrm1", [({"incr": 1, "ind": 1}, None)], seq(3),
        base + [("%aaincr1", -1), ("%aaind1", 800)])
    # Two movas with am=1 on one area in one instruction.
    add("am2", [({"mrng": 16}, None)],
        [[mova(0, ind=0, am=1), mova(1, ind=8, am=1)]] * 3, base)
    # No am at all: the head never moves.
    add("noam", [({}, None)], seq(3, am=0), base)
    # Narrow movas on fmt d (zero- or sign-extended?), and a mova wider
    # than fmt.
    add("narrow", [({"fmt": 4, "mrng": 8}, None)],
        [[mova(0, ind=3, am=0, fmt=1), mova(1, ind=7, am=0, fmt=1)],
         [mova(0, ind=6, am=0, fmt=2), mova(1, ind=4, am=1, fmt=3)]],
        base)
    add("wide", [({"fmt": 3, "mrng": 8}, None)],
        [[mova(0, ind=0, am=1, fmt=4)], [mova(0, ind=0, am=1, fmt=3)]],
        base)
    # be = 1: byte-swapped.
    add("be", [({}, None)], [[mova(0, be=1)], [mova(0, be=0)]], base)
    # Left and right halves: channel 0-1 areas vs channel 2-3 areas.
    add("halves", [({"d": 0}, {"d": 1})],
        [[mova(0, am=1), mova(2, am=1)], [mova(1, am=1), mova(3, am=1)]],
        base + [("%aad1", "%dr2")])
    # Several areas in the left half: area i = instruction i.
    add("areas", [({"d": 0, "asz": 3, "abs": 0}, None),
                  ({"d": 1, "asz": 3, "abs": 8}, None),
                  ({"d": 0, "asz": 3, "abs": 16, "disp": 512}, None)],
        [[mova(0, area=0), mova(1, area=1)], [mova(0, area=2)],
         [mova(0, area=0), mova(1, area=1)], [mova(0, area=2)]],
        base + [("%aad1", "%dr2")])
    # Two areas sharing one buffer region (abs 0 both).
    add("overlap", [({"d": 0, "asz": 3, "abs": 0}, None),
                    ({"d": 1, "asz": 3, "abs": 0}, None)],
        [[mova(0, area=0), mova(1, area=1)]] * 4,
        base + [("%aad1", "%dr2")])
    # Misaligned base for fmt d (v3: only aligned loads).
    add("misalign", [({}, None)], seq(3), [("%aad0", ("%dr1", 4))])
    # bap -> first mova distance.
    for g in (0, 1, 2, 3, 4, 6, 8, 10, 12, 14, 16, 18, 20, 24, 32):
        add(f"gap{g}", [({}, None)], seq(4), base, gap=g)
    # What stops the program: a call, a disp to %ctpr1, a write to
    # %ctpr2, eap (+ bap), %aabf0 = 0.
    nop7 = ["nop 7"]
    add("call", [({}, None)], seq(4), base, between={
        1: [["disp\t%ctpr1, apb_nop"], nop7, ["call\t%ctpr1, wbs = 0x10"],
            nop7, nop7]})
    add("ctpr1", [({}, None)], seq(4), base, between={
        1: [["disp\t%ctpr1, apb_nop"], nop7, nop7]})
    add("ctpr2", [({}, None)], seq(4), base, between={
        1: [["disp\t%ctpr2, apb_nop"], nop7, nop7]})
    add("eap", [({}, None)], seq(4), base, between={
        1: [["eap"], nop7, nop7]})
    add("eapbap", [({}, None)], seq(4), base, between={
        1: [["eap"], nop7, ["bap"], nop7, nop7, nop7]})
    add("aabf", [({}, None)], seq(4), base, between={
        1: [["adds,0\t0x0, 0x0, %r3"], ["aaurw,2\t%r3, %aabf0"], nop7, nop7]})
    # AAU state registers after a few movas (they read as 0 in user
    # mode on the 4C).
    add("state", [({}, None)], seq(2), base,
        aau_reads=("%aasr", "%aaldv", "%aaldm", "%aaldi0", "%aafstr"))
    # Reads that cross into an unmapped page (apb.c passes a base 16
    # bytes before a PROT_NONE page).
    add("guard", [({}, None)], seq(4), base)
    # A trap between movas: a load from %dr2, which apb.c points at a
    # page not touched yet (page fault) or a PROT_NONE page whose
    # SIGSEGV handler makes it readable and returns (signal).
    load = [["ldd,0\t%dr2, 0x0, %dr3"], ["nop 7"], ["nop 7"]]
    add("pagefault", [({}, None)], seq(4), base, between={1: load})
    add("signal", [({}, None)], seq(4), base, between={1: load})
    # The smallest areas: asz 0 with 8- and 32-byte records.
    add("tiny8", [({"asz": 0}, None)], seq(24), base)
    add("tiny32", [({"asz": 0, "mrng": 0}, None)],
        [[mova(0, ind=0, am=0), mova(1, ind=24, am=1)]] * 12, base)
    add("asz1_32", [({"asz": 1, "mrng": 0}, None)],
        [[mova(0, ind=0, am=0), mova(1, ind=24, am=1)]] * 12, base)
    # mova -> consumer latency with the data ready (gap 40): each mova
    # is followed by an instruction that uses its result, or by an
    # independent one (the baseline).
    for name, use in (("lat_use", True), ("lat_base", False)):
        add(name, [({}, None)], seq(8), base, gap=40, between={
            i: [[f"addd,0\t%dr{8 + i}, 0x1, %dr3" if use
                 else "addd,0\t%dr2, 0x1, %dr3"]] for i in range(8)})
    # One consumer, of the first mova only, D instructions later.
    for d in (1, 2, 3, 4, 5, 6, 7, 8, 16):
        for name, reg in (("one", "%dr8"), ("oneb", "%dr2")):
            add(f"{name}_d{d}", [({}, None)], seq(8), base, gap=40, between={
                0: [["nop"]] * (d - 1) + [[f"addd,0\t{reg}, 0x1, %dr3"]]})
    # The same with the consumer in ALC3 (other cluster), and with the
    # mova in channel 2 (right half of the buffer).
    for d in (4, 5, 6, 7):
        add(f"onec3_d{d}", [({}, None)], seq(8), base, gap=40, between={
            0: [["nop"]] * (d - 1) + [["addd,3\t%dr8, 0x1, %dr3"]]})
        add(f"onem2_d{d}", [({}, {})], [[mova(2)] for _ in range(8)],
            base, gap=40, between={
            0: [["nop"]] * (d - 1) + [["addd,0\t%dr8, 0x1, %dr3"]]})
    # Cold start: apb.c evicts the array from the caches first.
    for g in (0, 24, 40, 80):
        add(f"cold{g}", [({}, None)], seq(4), base, gap=g)
    out = [HEADER] + [text for _, text, _ in CASES]
    (HERE / "apb.s").write_text("".join(out))
    # The list of cases for apb.c.
    (HERE / "apb-cases.h").write_text(
        "/* SPDX-License-Identifier: GPL-3.0-or-later */\n"
        "/* Generated by tools/isa-probes/gen_apb.py.  */\n"
        + "".join(f"CASE ({n}, {r}, {a})\n" for n, _, (r, a) in CASES))


if __name__ == "__main__":
    main()
