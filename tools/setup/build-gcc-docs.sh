#!/bin/sh
# SPDX-License-Identifier: GPL-3.0-or-later
# Build GCC's manuals from the Texinfo sources of the GCC checkout in
# toolchains/gcc into toolchains/gcc-docs/: Info files (info/gccint.info,
# info/gcc.info) and HTML, one page per node (html/gccint, html/gcc,
# html/install).
#
# gccint is the internals manual (machine descriptions, target macros and
# hooks, passes, RTL); gcc is the user manual; install covers configuring
# and building. Needs makeinfo (GNU texinfo).
#
# Usage: tools/setup/build-gcc-docs.sh [GCC_SOURCE_DIR]
set -e

root=$(cd "$(dirname "$0")/../.." && pwd)
src=${1:-$root/toolchains/gcc}/gcc
out=$root/toolchains/gcc-docs
inc="-I $src/doc -I $src/doc/include -I $out"

mkdir -p "$out/info" "$out/html"
# gcc-vers.texi is normally generated by GCC's build (gcc/Makefile.in).
{
	echo "@set version-GCC $(cat "$src/BASE-VER")"
	if [ "$(cat "$src/DEV-PHASE")" = experimental ]; then
		echo "@set DEVELOPMENT"
	else
		echo "@clear DEVELOPMENT"
	fi
	echo "@set srcdir $src"
	echo "@set BUGURL @uref{https://gcc.gnu.org/bugs/}"
} > "$out/gcc-vers.texi"

for manual in gccint gcc; do
	makeinfo $inc --no-split -o "$out/info/$manual.info" "$src/doc/$manual.texi"
	makeinfo $inc --html -o "$out/html/$manual" "$src/doc/$manual.texi"
done
makeinfo $inc --html -o "$out/html/install" "$src/doc/install.texi"
echo "$out"
