"""Write spec.s: speculative operations for spec.c (spec/isa/speculation.md).

  python3 tools/isa-probes/gen_spec.py     # rewrites spec.s

Every case is  long spec_NAME(unsigned long *out, long a, long b, long c)
with a..c in %dr1..%dr3.  It runs its operations between two reads of
%clkr and stores out[0] = %dr8 with its tag cleared, out[1] = the tag of
%dr8, out[2] = 1 if an rbranch (%MLOCK) was taken, out[3] = %pfpfr after
the operations (its flags cleared before).  It returns the cycles.
"""

from pathlib import Path

HERE = Path(__file__).resolve().parent

HEADER = """! SPDX-License-Identifier: GPL-3.0-or-later
! Generated by tools/isa-probes/gen_spec.py; see spec.c.
	.ignore	ld_st_style
	.text

	.global	spec_nop
	.type	spec_nop, #function
	.align	8
spec_nop:
	{
	  setwd	wsz = 0x4, nfx = 0x1, dbl = 0x0
	  return	%ctpr3
	}
	{
	  nop 5
	}
	{
	  ct	%ctpr3
	}
	.size	spec_nop, .-spec_nop
"""


def case(name, groups, keep_flags=False):
    """GROUPS: wide instructions (lists of operations) run after %dr8 = 0
    and, unless KEEP_FLAGS, the %pfpfr flag reset; '%%LOCKED' in an
    operation names the label an rbranch goes to."""
    out = []

    def wi(*ops):
        out.append("\t{\n" + "".join(f"\t  {o}\n" for o in ops) + "\t}\n")

    wi("setwd\twsz = 0x40, nfx = 0x1, dbl = 0x0", "return\t%ctpr3")
    wi("addd,1\t0x0, 0x0, %dr8", "addd,2\t0x0, 0x0, %dr9",
       "rrs,0\t%pfpfr, %r10")
    wi("nop 5")
    wi("ands,0\t%r10, 0xffffffc0, %r11" if not keep_flags
       else "ors,0\t%r10, 0x3f, %r11")
    wi("rws,0\t%r11, %pfpfr")
    wi("nop 7")
    wi("rrd,0\t%clkr, %dr4")
    for g in groups:
        wi(*[o.replace("%%LOCKED", f".L{name}_locked") for o in g])
    wi("rrd,0\t%clkr, %dr5")
    wi("ibranch\t.L" + name + "_out")
    out.append(f".L{name}_locked:\n")
    wi("addd,1\t0x0, 0x1, %dr9", "rrd,0\t%clkr, %dr5")
    out.append(f".L{name}_out:\n")
    wi("nop 7", "rrs,0\t%pfpfr, %r12")
    wi("nop 5", "gettagd,2\t%dr8, %r6", "puttagd,5\t%dr8, 0x0, %dr7")
    wi("nop 2")
    wi("std,2\t%dr0, 0x0, %dr7", "std,5\t%dr0, 0x8, %dr6")
    wi("std,2\t%dr0, 0x10, %dr9", "stw,5\t%dr0, 0x18, %r12",
       "rws,0\t%r10, %pfpfr")
    wi("subd,0\t%dr5, %dr4, %dr0", "nop 5")
    wi("ct\t%ctpr3")
    return (f"\n\t.global\tspec_{name}\n\t.type\tspec_{name}, #function\n"
            f"\t.align\t8\nspec_{name}:\n" + "".join(out)
            + f"\t.size\tspec_{name}, .-spec_{name}\n")


CASES = []


def add(name, groups, **kw):
    CASES.append((name, case(name, groups, **kw)))


def main():
    nop = ["nop 7"]
    # Control speculation: a speculative load from the address in a.
    add("ldsm", [["ldd,0,sm\t%dr1, 0x0, %dr8"], nop, nop])
    add("ld", [["ldd,0\t%dr1, 0x0, %dr8"], nop, nop])
    add("ldwsm", [["ldw,0,sm\t%dr1, 0x0, %r8"], nop, nop])
    # A fully speculative load (sm, MAS mod 3) from a.
    add("ldspec", [["ldd,0,sm\t%dr1, 0x0, %dr8, mas=0x3"], nop, nop])
    # Division by b, integer and FP.
    add("sdivsm", [["sdivd,5,sm\t%dr1, %dr2, %dr8"], nop, nop, nop])
    add("fdivsm", [["fdivd,5,sm\t%dr1, %dr2, %dr8"], nop, nop, nop])
    add("fdiv", [["fdivd,5\t%dr1, %dr2, %dr8"], nop, nop, nop])
    add("faddsm", [["faddd,0,sm\t%dr1, %dr2, %dr8"], nop])
    # A diagnostic value (speculative load from a) used afterwards.
    ld = [["ldd,0,sm\t%dr1, 0x0, %dr3"], nop, nop]
    add("use_addsm", ld + [["addd,0,sm\t%dr3, 0x1, %dr8"], nop])
    add("use_add", ld + [["addd,0\t%dr3, 0x1, %dr8"], nop])
    # Compare a diagnostic value into a predicate, then use the predicate.
    add("use_cmpsm_merge", ld + [["cmpedb,0,sm\t%dr3, 0x0, %pred0"], nop,
                                 ["merged,0\t0x1, 0x2, %dr8, %pred0"], nop])
    add("use_cmpsm_pred", ld + [["cmpedb,0,sm\t%dr3, 0x0, %pred0"], nop,
                                ["addd,0\t0x0, 0x7, %dr8 ? %pred0"], nop])
    add("use_cmpsm_ct", ld + [["cmpedb,0,sm\t%dr3, 0x0, %pred0",
                               "disp\t%ctpr1, %%LOCKED"], nop,
                              ["ct\t%ctpr1 ? %pred0"], nop])
    add("use_cmp", ld + [["cmpedb,0\t%dr3, 0x0, %pred0"], nop])
    # Data speculation: a load with MAS 0x4, a store (to c), then a check
    # load with MAS 0x3 and rbranch.
    for st, what in (("none", None), ("same", "std,2\t%dr2, 0x0, %dr3"),
                     ("other", "std,2\t%dr2, 0x8, %dr3"),
                     ("part", "stw,2\t%dr2, 0x4, %r3"),
                     ("before", None)):
        groups = []
        if st == "before":
            groups.append(["std,2\t%dr2, 0x0, %dr3"])
            groups.append(nop)
        groups += [["ldd,0,sm\t%dr2, 0x0, %dr8, mas=0x4"], nop]
        if what:
            groups.append([what])
            groups.append(nop)
        groups.append(["ldd,0\t%dr2, 0x0, %dr8, mas=0x3", "rbranch\t%%LOCKED"])
        groups.append(nop)
        groups.append(["addd,0\t0x0, 0x0, %dr11"])
        groups.append(["mmurw,2\t%dr11, %dam_inv"])
        add(f"dam_{st}", groups)
    # Variants to find what the hardware accepts: check load in ALC5
    # (as lcc puts it), without the %dam_inv write, without rbranch.
    for st, what in (("none5", None), ("same5", "std,2\t%dr2, 0x0, %dr3"),
                     ("other5", "std,2\t%dr2, 0x8, %dr3"),
                     ("part5", "stw,2\t%dr2, 0x4, %r3")):
        groups = [["ldd,0,sm\t%dr2, 0x0, %dr8, mas=0x4"], nop]
        if what:
            groups += [[what], nop]
        groups += [["ldd,5\t%dr2, 0x0, %dr8, mas=0x3", "rbranch\t%%LOCKED"],
                   nop]
        add(f"dam_{st}", groups)
    add("dam_ld4only", [["ldd,0,sm\t%dr2, 0x0, %dr8, mas=0x4"], nop, nop])
    add("dam_ld3only", [["ldd,5\t%dr2, 0x0, %dr8, mas=0x3"], nop, nop])
    add("dam_rbronly", [["rbranch\t%%LOCKED"], nop])
    add("dam_inv", [["addd,0\t0x0, 0x0, %dr11"], ["mmurw,2\t%dr11, %dam_inv"], nop])
    # FP: is an inexact or overflowing result diagnostic, and what does a
    # diagnostic FP result do to later operations?
    add("fdivsm_use", [["fdivd,5,sm\t%dr1, %dr2, %dr3"], nop, nop, nop,
                       ["faddd,0\t%dr3, 0x0, %dr8"], nop])
    add("fdivsm_usesm", [["fdivd,5,sm\t%dr1, %dr2, %dr3"], nop, nop, nop,
                         ["faddd,0,sm\t%dr3, 0x0, %dr8"], nop])
    add("fmulsm", [["fmuld,0,sm\t%dr1, %dr2, %dr8"], nop])
    # The same FP operations with all six %pfpfr flags already set (as
    # the kernel starts a process).
    add("fdivsm_kf", [["fdivd,5,sm\t%dr1, %dr2, %dr8"], nop, nop, nop],
        keep_flags=True)
    add("fmulsm_kf", [["fmuld,0,sm\t%dr1, %dr2, %dr8"], nop], keep_flags=True)
    add("fdivsm_use_kf", [["fdivd,5,sm\t%dr1, %dr2, %dr3"], nop, nop, nop,
                          ["faddd,0\t%dr3, 0x0, %dr8"], nop], keep_flags=True)
    # Which channels take the check load, and is the check keyed by the
    # destination register?
    for ch in (2, 3):
        add(f"dam_same_ch{ch}", [["ldd,0,sm\t%dr2, 0x0, %dr8, mas=0x4"], nop,
                                 ["std,2\t%dr2, 0x0, %dr3"], nop,
                                 [f"ldd,{ch}\t%dr2, 0x0, %dr8, mas=0x3",
                                  "rbranch\t%%LOCKED"], nop])
    add("dam_same_otherreg", [["ldd,0,sm\t%dr2, 0x0, %dr9, mas=0x4"], nop,
                              ["std,2\t%dr2, 0x0, %dr3"], nop,
                              ["ldd,5\t%dr2, 0x0, %dr8, mas=0x3",
                               "rbranch\t%%LOCKED"], nop])
    add("dam_same_otheraddr", [["ldd,0,sm\t%dr2, 0x8, %dr8, mas=0x4"], nop,
                               ["std,2\t%dr2, 0x0, %dr3"], nop,
                               ["ldd,5\t%dr2, 0x0, %dr8, mas=0x3",
                                "rbranch\t%%LOCKED"], nop])
    add("dam_before5", [["std,2\t%dr2, 0x0, %dr3"], nop,
                        ["ldd,0,sm\t%dr2, 0x0, %dr8, mas=0x4"], nop,
                        ["ldd,5\t%dr2, 0x0, %dr8, mas=0x3",
                         "rbranch\t%%LOCKED"], nop])
    add("dam_nosm", [["ldd,0\t%dr2, 0x0, %dr8, mas=0x4"], nop,
                     ["std,2\t%dr2, 0x0, %dr3"], nop,
                     ["ldd,5\t%dr2, 0x0, %dr8, mas=0x3", "rbranch\t%%LOCKED"],
                     nop])
    # Clean data-speculation tests: the table is cleared first.
    inv = [["addd,0\t0x0, 0x0, %dr11"], ["mmurw,2\t%dr11, %dam_inv"], nop]

    def check(reg, off=0):
        return [[f"ldd,5\t%dr2, {off:#x}, %dr{reg}, mas=0x3",
                 "rbranch\t%%LOCKED"], nop]

    def spld(reg, off=0, ch=0):
        return [[f"ldd,{ch},sm\t%dr2, {off:#x}, %dr{reg}, mas=0x4"], nop]

    st0 = [["std,2\t%dr2, 0x0, %dr3"], nop]
    st8 = [["std,2\t%dr2, 0x8, %dr3"], nop]
    add("k_match", inv + spld(8) + check(8))
    add("k_otherreg", inv + spld(12) + check(8))
    add("k_otheraddr", inv + spld(8, 8) + check(8))
    add("k_noentry", inv + check(8))
    add("k_store", inv + spld(8) + st0 + check(8))
    add("k_store_other", inv + spld(8) + st8 + check(8))
    add("k_store_otherreg", inv + spld(12) + st0 + check(8))
    add("k_twice", inv + spld(8) + check(8) + check(8))
    # The destination register overwritten between the speculative load
    # and its check.
    add("k_overwrite", inv + spld(8) + [["addd,0\t0x0, 0x5, %dr8"], nop]
        + check(8))
    # Registered address +8, check of +0, with a store to +0 or +8.
    add("k_oa_st0", inv + spld(8, 8) + st0 + check(8))
    add("k_oa_st8", inv + spld(8, 8) + st8 + check(8))
    add("k_call", inv + [["ldd,0,sm\t%dr2, 0x0, %dr8, mas=0x4",
                          "disp\t%ctpr1, spec_nop"], nop,
                         ["call\t%ctpr1, wbs = 0x3c"], ["return\t%ctpr3"],
                         nop] + check(8))
    # A call empties every CTPR, so the return is prepared again after it;
    # wbs leaves the callee's 4-pair window enough (wsz - wbs <= 4).
    call = [["disp\t%ctpr1, spec_nop"], nop, ["call\t%ctpr1, wbs = 0x3c"],
            ["return\t%ctpr3"], nop]
    add("k_callonly", inv + call)
    add("k_call_check", inv + call + check(8))
    add("k_call_ld_check", inv + call + spld(8) + check(8))
    add("k_ld_call", inv + spld(8) + call)
    # A trap (page fault on the untouched page in a) between the
    # speculative load and its check.
    add("k_trap", inv + spld(8) + [["ldd,0\t%dr1, 0x0, %dr12"], nop, nop]
        + check(8))
    # Capacity: N speculative loads into %dr16.. from b + 8i, then a
    # check of the first (into %dr16, from b).
    for n in (2, 4, 8, 16, 24, 32, 48):
        groups = list(inv)
        for i in range(n):
            groups += [[f"ldd,{(0, 3)[i % 2]},sm\t%dr2, {8 * i:#x}, "
                        f"%dr{16 + i}, mas=0x4"]]
        groups += [nop] + [["ldd,5\t%dr2, 0x0, %dr16, mas=0x3",
                            "rbranch\t%%LOCKED"], nop]
        add(f"k_cap{n}", groups)
    # The check load alone (no mas=0x4 load before it).
    add("dam_checkonly", [["ldd,0\t%dr2, 0x0, %dr8, mas=0x3",
                           "rbranch\t%%LOCKED"], nop])
    (HERE / "spec.s").write_text(HEADER + "".join(t for _, t in CASES))
    (HERE / "spec-cases.h").write_text(
        "/* SPDX-License-Identifier: GPL-3.0-or-later */\n"
        "/* Generated by tools/isa-probes/gen_spec.py.  */\n"
        + "".join(f"CASE ({n})\n" for n, _ in CASES))


if __name__ == "__main__":
    main()
