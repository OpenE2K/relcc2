# abgc / rbgc against the readers of %bgr: rrs %bgr (cur = bits 8-10)
# and vfbgv.  %bgr is saved and restored around each case.
def bgr_case(name, start, op, k, reader):
    """%bgr = START, then OP, then READER K instructions later (0: in
    OP's instruction); %dr0 = what rrs read (or 1 if vfbgv didn't
    trap)."""
    body = (wi("rrs,0\t%bgr, %r6", f"adds,1\t0x0, {start:#x}, %r7",
               "adds,2\t0x0, 0x0, %r8", "adds,3\t0x0, 0x100, %r9")
            + wi("rws,0\t%r7, %bgr") + nops(12))
    if k == 0:
        body += wi(op, reader)
    else:
        body += wi(op) + nops(k - 1) + wi(reader)
    body += nops(8) + wi("rws,0\t%r6, %bgr") + nops(8)
    if reader.startswith("rrs"):
        body += wi("andd,0\t%dr3, 0x7ff, %dr0")
    else:
        body += wi("addd,0\t0x0, 0x1, %dr0")
    func(name, body, "V", V6)


