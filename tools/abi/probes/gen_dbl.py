"""Write dbl.s and dbl-ops.h for dbl.c: which operations WD.dbl makes
zero-extend their 32-bit result (spec/abi/registers.md, "dbl").

  python3 tools/abi/probes/gen_dbl.py

Each p_N(long *out, int *src, int v) loads 0x2222222222222222 from out
into the destination, runs one operation that writes 32 bits under
setwd dbl = 0 or 1, and stores the whole 64-bit destination to out.
%r2 holds v = 0x12345678.  The destination is %r3, or the global %g20
for the *_g cases.
"""

from pathlib import Path

HERE = Path(__file__).resolve().parent

# name: (setup instructions, the operation), %r3 is the destination.
OPS = {
    "adds": ([], "adds,0\t%r2, 0x0, {d}"),
    "ands": ([], "ands,0\t%r2, %r2, {d}"),
    "andns": ([], "andns,0\t%r2, 0x0, {d}"),
    "shls": ([], "shls,0\t%r2, 0x0, {d}"),
    "sars": ([], "sars,0\t%r2, 0x0, {d}"),
    "scls": ([], "scls,0\t%r2, 0x0, {d}"),
    "muls": ([], "muls,0\t%r2, 0x1, {d}"),
    "sdivs": ([], "sdivs,5\t%r2, 0x1, {d}"),
    "udivs": ([], "udivs,5\t%r2, 0x1, {d}"),
    "getfs": ([], "getfs,0\t%r2, 0x0, {d}"),
    "merges_t": (["cmpesb,0\t%r2, %r2, %pred0"],
                 "merges,0\t%r2, %r2, {d}, %pred0"),
    "merges_f": (["cmpesb,0\t%r2, 0x0, %pred0"],
                 "merges,0\t%r2, %r2, {d}, %pred0"),
    "popcnts": ([], "popcnts,1\t%r2, {d}"),
    "lzcnts": ([], "lzcnts,1\t%r2, {d}"),
    "adds_pred": (["cmpesb,0\t%r2, %r2, %pred0"],
                  "adds,0\t%r2, 0x0, {d} ? %pred0"),
    "adds_sm": ([], "adds,0,sm\t%r2, 0x0, {d}"),
    "ldw": ([], "ldw,0\t%r1, 0x0, {d}"),
    "sxt": ([], "sxt,0\t0x2, %r2, {D}"),
    "fadds": ([], "fadds,0\t%r2, %r2, {d}"),
    "fstois": (["adds,0\t0x0, _f32s,_lts0 0x41200000, %r4"],
               "fstois,0\t%r4, {d}"),
    "fdtois": (["addd,0\t0x0, _f64,_lts0 0x4024000000000000, %dr4"],
               "fdtois,0\t%dr4, {d}"),
    "fstoistr": (["adds,0\t0x0, _f32s,_lts0 0x41200000, %r4"],
                 "fstoistr,0\t%r4, {d}"),
    "movts": ([], "movts,0\t%r2, {d}"),
    # The destination a global register (I16).
    "adds_g": ([], "adds,0\t%r2, 0x0, {g}"),
    "muls_g": ([], "muls,0\t%r2, 0x1, {g}"),
}


def fn(name, dbl, setup, op):
    glob = name.endswith("_g")
    dst, dstd = ("%g20", "%dg20") if glob else ("%r3", "%dr3")
    text = op.format(d=dst, g=dst, D=dstd)
    pre = "".join(f"\t{{\n\t  {s}\n\t}}\n" for s in setup)
    return f"""
	.global	p_{name}_{dbl}
	.type	p_{name}_{dbl}, #function
	.align	8
p_{name}_{dbl}:
	{{
	  setwd	wsz = 0x4, nfx = 0x1, dbl = {dbl:#x}
	  return	%ctpr3
	  ldd,0	%dr0, 0x0, {dstd}
	}}
	{{
	  nop 5
	}}
{pre}	{{
	  nop 2
	}}
	{{
	  {text}
	}}
	{{
	  nop 7
	}}
	{{
	  nop 7
	}}
	{{
	  ct	%ctpr3
	  std,2	%dr0, 0x0, {dstd}
	}}
	.size	p_{name}_{dbl}, .-p_{name}_{dbl}
"""


def main():
    text = ("! SPDX-License-Identifier: GPL-3.0-or-later\n"
            "! Generated by tools/abi/probes/gen_dbl.py; see dbl.c.\n"
            "\t.ignore\tld_st_style\n\t.text\n")
    for name, (setup, op) in OPS.items():
        for dbl in (0, 1):
            text += fn(name, dbl, setup, op)
    (HERE / "dbl.s").write_text(text)
    (HERE / "dbl-ops.h").write_text(
        "/* SPDX-License-Identifier: GPL-3.0-or-later */\n"
        "/* Generated by tools/abi/probes/gen_dbl.py.  */\n"
        + "".join(f"OP ({n})\n" for n in OPS))


if __name__ == "__main__":
    main()
