"""Write memorycxx_stld.s, memorycxx_stld-v5.s and their -cases.h files
for memorycxx_stld.c: store-to-load costs that timing.md ("Store to
load") leaves open: line-crossing stores and loads, AAU stores, stores
to lines not in L1, a load of another width outside the stored bytes,
the 2C3's "some runs" state, and (v5 and later) 16-byte stores and
loads.

  python3 tools/isa-probes/gen_memorycxx_stld.py

Case  long ms_NAME_dD_uU(long *buf, long iters): ITERS iterations of a
loop of 4 steps; step k stores at buf + 256 k + SOFF (one instruction,
STORES), loads at buf + 256 k + LOFF D cycles later (ALC0), and uses
the loaded value U cycles after the load (ord,1 into %dr10, the next
step's store data), so a step takes D + U + 1 cycles when nothing
stalls.  Returns the %clkr cycles of the loop.  The value's latency is
the smallest U that adds nothing (the stall rule: an operand e cycles
early stalls 4 ceil(e / 4)).

Every pair also gets a baseline ("NAME~b") with the stores 128 bytes on
(another 32-byte line, no 16 KiB alias): it times the same stores and
load without the conflict.

Modes: "fix" (the same 1 KiB every iteration: L1 hits), "move" (the
pointer advances 1 KiB an iteration through a region the harness has
evicted from L1 but left in L2), "aau" (the stores are staad through
%aad0 = buf, %aasti1 = 0, offsets as literals).

setwd dbl = 1, so narrow loads and the 64-bit ord don't wait on each
other (registers.md).  v5 cases (16-byte) go to memorycxx_stld-v5.s.
"""

from pathlib import Path

HERE = Path(__file__).resolve().parent
HEADER = """! SPDX-License-Identifier: GPL-3.0-or-later
! Generated by tools/isa-probes/gen_memorycxx_stld.py; see memorycxx_stld.c.
	.ignore	ld_st_style
	.ignore	strict_delay
	.text
"""
GEN_H = ("/* SPDX-License-Identifier: GPL-3.0-or-later */\n"
         "/* Generated by tools/isa-probes/gen_memorycxx_stld.py.  */\n")
STEPS, STRIDE = 4, 256
DS = (0, 1, 2, 3, 4, 6)
DS_BASE = (1, 3)
US = tuple(range(3, 17)) + (18, 20, 24)


def wi(*ops):
    ops = [o for o in ops if o]
    return "\t{\n" + "".join(f"\t  {o}\n" for o in ops or ["nop"]) + "\t}\n"


def nops(n):
    out = ""
    while n > 0:
        k = min(n, 8)
        out += wi(f"nop {k - 1}" if k > 1 else "nop")
        n -= k
    return out


DATA = {"std": "%dr10", "stw": "%r10", "sth": "%r10", "stb": "%r10",
        "stqp": "%qpr10", "staad": "%dr10"}
DEST = {"ldd": "%dr11", "ldw": "%r11", "ldh": "%r11", "ldb": "%r11",
        "ldqp": "%qpr11"}


def store_op(op, ch, off, mode):
    if op == "staad":
        return f"staad,{ch}\t%dr10, %aad0[ %aasti1 + {off:#x} ]"
    return f"{op},{ch}\t%dr13, {off:#x}, {DATA[op]}"


def kernel(name, stores, load, d, u, mode, lines=STEPS, tail=0,
           only=None, rot=0):
    """STORES: [(op, offset)], placed in ALC2 then ALC5; LOAD: (op,
    offset) in ALC0.  LINES: how many places (256 bytes apart) the four
    steps use, step k the ((k + ROT) mod LINES)th; TAIL: empty cycles
    after each step's use; ONLY: if set, only step ONLY loads near its
    store, the others load 128 bytes on (a line nothing stores to)."""
    sl = d + u + 1 + tail
    plen = STEPS * sl
    slots = [[] for _ in range(plen)]
    for k in range(STEPS):
        t0 = k * sl
        sk = STRIDE * ((k + rot) % lines)
        for (op, off), ch in zip(stores, (2, 5)):
            slots[t0].append(store_op(op, ch, sk + off, mode))
        lop, loff = load
        if only is not None and k != only:
            loff += 128
        slots[t0 + d].append(f"{lop},0\t%dr13, {sk + loff:#x}, "
                             f"{DEST[lop]}")
        slots[t0 + d + u].append("ord,1\t%dr10, %dr11, %dr10")
    slots[0].append("subd,4\t%dr12, 0x1, %dr12")
    slots[1].append("cmpedb,4\t%dr12, 0x0, %pred0")
    slots[plen - 1].append("ct\t%ctpr1 ? ~%pred0")
    if mode == "move":
        slots[plen - 1].append(f"addd,0\t%dr13, {STEPS * STRIDE:#x}, %dr13")
    lab = f".Lms_{name}"
    body = wi("setwd\twsz = 0x20, nfx = 0x1, dbl = 0x1", "return\t%ctpr3")
    body += wi("addd,0\t0x0, %dr1, %dr12", "addd,1\t0x0, %dr0, %dr13",
               "addd,3\t0x0, 0x0, %dr10", "addd,4\t0x0, 0x0, %dr11")
    if any(op == "stqp" for op, _ in stores):
        body += wi("qppackdl,0\t%dr10, %dr10, %qpr10")
    if mode == "aau":
        body += wi("aaurwd,2\t%dr0, %aad0", "aaurwd,5\t%dr11, %aasti1")
        body += nops(8)
    body += wi(f"disp\t%ctpr1, {lab}_loop") + nops(5)
    body += wi("rrd,0\t%clkr, %dr28")
    body += f"{lab}_loop:\n"
    i = 0
    while i < plen:
        if slots[i]:
            body += wi(*slots[i])
            i += 1
        else:
            j = i
            while j < plen and not slots[j]:
                j += 1
            body += nops(j - i)
            i = j
    body += wi("rrd,0\t%clkr, %dr29") + nops(2)
    body += wi("subd,0\t%dr29, %dr28, %dr0") + nops(3) + wi("ct\t%ctpr3")
    fn = f"ms_{name}"
    return (f"\n\t.global\t{fn}\n\t.type\t{fn}, #function\n"
            f"\t.align\t1024\n{fn}:\n{body}\t.size\t{fn}, .-{fn}\n")


