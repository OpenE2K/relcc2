"""Write mas_hint.s: streaming loops with each MAS cache hint (bits 5-6),
for mas_hint.c (spec/isa/timing.md, "Memory").

  python3 tools/isa-probes/gen_mas_hint.py

hint_{ld,st}_{00,20,40,60}(long *p, unsigned long lsr): a loop counted by
%lsr (lcnt iterations) whose one instruction does four ldd (ALC0, 2, 3,
5) or two std (ALC2, 5) with that MAS, one per 64-byte line, and
advances p by 256 (loads) or 128 (stores) bytes.
"""

from pathlib import Path

HERE = Path(__file__).resolve().parent


def fn(kind, mas):
    name = f"hint_{kind}_{mas:02x}"
    m = f", mas={mas:#x}" if mas else ""
    if kind == "ld":
        ops = [f"ldd,{c}\t%dr0, {o:#x}, %dr{8 + k}{m}"
               for k, (c, o) in enumerate(zip((0, 2, 3, 5), (0, 64, 128, 192)))]
        step = 256
    else:
        ops = [f"std,{c}\t%dr0, {o:#x}, %dr3{m}"
               for c, o in zip((2, 5), (0, 64))]
        step = 128
    body = "".join(f"\t  {o}\n" for o in ops)
    return f"""
	.global	{name}
	.type	{name}, #function
	.align	8
{name}:
	{{
	  setwd	wsz = 0x10, nfx = 0x1, dbl = 0x0
	  return	%ctpr3
	  addd,0	0x0, 0x1, %dr3
	}}
	{{
	  disp	%ctpr1, .L{name}
	  rwd,0	%dr1, %lsr
	}}
	{{
	  nop 5
	}}
.L{name}:
	{{
	  alc	alcf=1, alct=1
	  ct	%ctpr1 ? %NOT_LOOP_END
	  addd,1	%dr0, {step:#x}, %dr0
{body}	}}
	{{
	  nop 5
	}}
	{{
	  ct	%ctpr3
	}}
	.size	{name}, .-{name}
"""


def main():
    text = ("! SPDX-License-Identifier: GPL-3.0-or-later\n"
            "! Generated by tools/isa-probes/gen_mas_hint.py; see "
            "mas_hint.c.\n\t.ignore\tld_st_style\n\t.text\n")
    for kind in ("ld", "st"):
        for mas in (0x00, 0x20, 0x40, 0x60):
            text += fn(kind, mas)
    (HERE / "mas_hint.s").write_text(text)


if __name__ == "__main__":
    main()
