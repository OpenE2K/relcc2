"""Write foldp93.s and foldp93-cases.h: 16-byte array prefetch streams
from aligned and misaligned bases, for foldp93.c (the proof-of-concept
back end's P93; spec/isa/apb.md, "128-bit movas (v5+)" and "v6").

  python3 tools/isa-probes/gen_foldp93.py

Each function is  long fp93_NAME(const char *a, unsigned long lsr,
long *cycles): a one-instruction loop_mode loop counted by %lsr, as in
apb-stream.s, that reads one area of asz 5 (2 KiB) through its movas
and adds what they read into accumulators six iterations later (past
the mova's latency of 5), so the loop can run an iteration a cycle; it
returns the sum of the 64-bit words of the first lcnt - 6 iterations.
*cycles is the %clkr difference across the loop.  The base offset
(0, 4 or 8 bytes off a 16-byte boundary) is the C side's.

  q1   one movaqp an iteration, fmt 5 area, 16 bytes a step
  q2   two movaqp an iteration (ind 0 and 16), fmt 5, 32 bytes a step
       (lcc's v5 and v6 sum loops)
  d2   two movad an iteration (ind 0 and 8), fmt 4, 16 bytes a step
       (the 8-byte halves of a 16-byte vector)
  w1   one movaqp an iteration from a fmt 4 area, 16 bytes a step (v6
       only: v5 gives a diagnostic value for a mova wider than fmt)
"""

from pathlib import Path

HERE = Path(__file__).resolve().parent

# kind: (fmt, AAINCR1, movas, consumers, epilogue)
KINDS = {
    "q1": (5, 1,
           ["movaqp,0\tarea=0, ind=0, am=1, be=0, %b[0]"],
           ["qpaddd,0\t%r9, %b[12], %r9"],
           "qp"),
    "q2": (5, 2,
           ["movaqp,0\tarea=0, ind=0, am=0, be=0, %b[1]",
            "movaqp,1\tarea=0, ind=16, am=1, be=0, %b[0]"],
           ["qpaddd,0\t%r9, %b[13], %r9",
            "qpaddd,3\t%r11, %b[12], %r11"],
           "qp"),
    "d2": (4, 2,
           ["movad,0\tarea=0, ind=0, am=0, be=0, %b[1]",
            "movad,1\tarea=0, ind=8, am=1, be=0, %b[0]"],
           ["addd,0\t%dr9, %b[13], %dr9",
            "addd,3\t%dr11, %b[12], %dr11"],
           "d"),
    "w1": (4, 2,
           ["movaqp,0\tarea=0, ind=0, am=1, be=0, %b[0]"],
           ["qpaddd,0\t%r9, %b[12], %r9"],
           "qp"),
}


def fn(kind):
    fmt, step, movas, uses, epi = KINDS[kind]
    name = kind
    zero = []
    for i in range(0, 16, 4):
        zero.append("\t{\n" + "".join(
            f"\t  qppackdl,{ch}\t0x0, 0x0, %b[{i + j}]\n"
            for j, ch in enumerate((0, 1, 3, 4))) + "\t}\n")
    if epi == "qp":
        tail = """	{
	  qpswitchd,0	%r9, %r12
	  qpswitchd,1	%r11, %r13
	}
	{
	  addd,0	%dr9, %dr12, %dr14
	  addd,1	%dr11, %dr13, %dr15
	}
"""
    else:
        tail = """	{
	  addd,0	%dr9, 0x0, %dr14
	  addd,1	%dr11, 0x0, %dr15
	}
"""
    body = "".join(f"\n\t  {m}" for m in movas + uses)
    return f"""
	.global	fp93_{name}
	.type	fp93_{name}, #function
	.align	8
fp93_{name}:
	{{
	  setwd	wsz = 0x10, nfx = 0x0, dbl = 0x0
	  setbn	rsz = 0x7, rbs = 0x8, rcur = 0x0
	  return	%ctpr3
	}}
{"".join(zero)}	{{
	  qppackdl,0	0x0, 0x0, %r9
	  qppackdl,1	0x0, 0x0, %r11
	}}
	{{
	  ldisp	%ctpr2, .L{name}_prog
	  aaurwd,2	%dr0, %aad0
	  addd,4	0x0, {step:#x}, %dr10
	}}
	{{
	  aaurw,2	%r10, %aaincr1
	  disp	%ctpr1, .L{name}_loop
	  rwd,0	%dr1, %lsr
	}}
	{{
	  nop 7
	  bap
	}}
	{{
	  nop 7
	}}
	{{
	  nop 7
	  rrd,0	%clkr, %dr4
	}}
.L{name}_loop:
	{{
	  loop_mode
	  alc	alcf=1, alct=1
	  abn	abnf=1, abnt=1
	  ct	%ctpr1 ? %NOT_LOOP_END{body}
	}}
	{{
	  rrd,0	%clkr, %dr5
	}}
	{{
	  nop 7
	  disp	%ctpr2, disp=0x0
	}}
{tail}	{{
	  addd,0	%dr14, %dr15, %dr0
	  subd,1	%dr5, %dr4, %dr6
	}}
	{{
	  std,2	%dr2, 0x0, %dr6
	}}
	{{
	  ct	%ctpr3
	}}
	.align	8
.L{name}_prog:
	{{
	  fapb	ct=1, dcd=0, fmt={fmt}, mrng=0, d=0, incr=1, ind=0, asz=5, abs=0, disp=0
	}}
	.size	fp93_{name}, .-fp93_{name}
"""


def main():
    (HERE / "foldp93.s").write_text(
        "! SPDX-License-Identifier: GPL-3.0-or-later\n"
        "! Generated by tools/isa-probes/gen_foldp93.py; see foldp93.c.\n"
        "\t.ignore\tld_st_style\n\t.text\n"
        + "".join(fn(k) for k in KINDS))
    (HERE / "foldp93-cases.h").write_text(
        "/* SPDX-License-Identifier: GPL-3.0-or-later */\n"
        "/* Generated by tools/isa-probes/gen_foldp93.py.  */\n"
        + "".join(f"CASE ({k}, {16 if k != 'q2' else 32}, "
                  f"{1 if k == 'w1' else 0})\n" for k in KINDS))


if __name__ == "__main__":
    main()
