/* Hardware checks behind the proof-of-concept back end's port-plan
   findings P76 (round to integral), P78 (flag operations), P82 (FP
   compares into a register feeding integer tests) and P85 (the inline
   square root) in docs/spec-poc-findings.md.  pocchk5.s and
   pocchk5-cases.h are generated by gen_pocchk5.py.

     python3 tools/isa-probes/gen_pocchk5.py
     LCC=/opt/mcst/lcc-1.29.16.e2k-v3.linux-6.1/bin/lcc
     $LCC -O1 tools/isa-probes/pocchk5.c tools/isa-probes/pocchk5.s -lm -o pocchk5
     ./pocchk5 [round|sqrt|libm|dg|lat]   # every section without an
                                          # argument; lat under the
                                          # shared timing lock

   round: fdtoifd, fstoifs and pfstoifs with every immediate 0-15 in the
     four rounding modes over special and random values, against an
     integer model of the roundings (no FP arithmetic in this file),
     result bits and the five flags; then glibc's floor, ceil, trunc,
     roundeven, round, rint, nearbyint (and the float forms) against the
     same model, called with the flags clear (counting where they raise
     inexact) and again with every flag set (values only).  Each group
     runs in a child process, so a SIGILL in libm ends only that group.
   sqrt: fsqrtid + fsqrttd and fsqrts against glibc's sqrt and sqrtf
     (called with every flag set, so glibc's speculative code gives
     numbers), result bits, and the invalid flag of the inline forms.
   libm: the tag of a glibc result with chosen flags set beforehand
     (each case in a child): a nonzero tag is a diagnostic value, which
     traps at its first non-speculative use.
   dg: flag operations and cctop with ,sm on a diagnostic operand (the
     tag of the result), and without ,sm (the signal, in a child).
   lat: as pocchk4.c: "P -> C: S2 .. S8 | latency L", Sg the stall of a
     consumer g cycles after the producer (cycles a step minus g + 4,
     the best of 9 runs), L the smallest g from which none stalls.  */

