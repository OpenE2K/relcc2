"""Write pocchk5.s and pocchk5-cases.h for pocchk5.c: checks behind the
proof-of-concept back end's port-plan findings P76, P78, P82 and P85
(docs/spec-poc-findings.md): round to integral against glibc, the
inline double square root against glibc, flag operations and cctop on
a diagnostic operand, and the latency from an FP compare into a
register (fcmpud*f, fcmpod*f) to integer consumers in either cluster.

  python3 tools/isa-probes/gen_pocchk5.py

Latency cases  long p5_lat_P__C_gG(long *mem, long a, long b): WARM
steps, then STEPS between two %clkr reads; a step is the producer P
(into %r8 or %r10, alternately), G - 1 empty cycles and the consumer C
of P's result in an instruction with nop 3, so a step is G + 4 cycles
when C does not stall.  Inputs are constants (%dr2 = 1.0, %dr3 = 2.0).

Diagnostic cases  long p5_dg_K(long a): K's result after an operand
made diagnostic with puttagd,sm a, 0xa (speculation.md, "Diagnostic
values made on purpose"); the value cases return gettagd of the result
(the result's own bits are not read), the trap cases (tr_*) use it
without ,sm.

Value helpers (hand-written below): p5_rnd_d(imm, x) = fdtoifd imm, x;
p5_rnd_s(imm, x) = fstoifs; p5_rnd_ps(imm, x) = pfstoifs;
p5_sqrt_d(x) = fsqrtid + fsqrttd; p5_sqrt_s(x) = fsqrts;
p5_calltag(fn, x) = the tags of fn(x)'s result.
"""

from pathlib import Path

HERE = Path(__file__).resolve().parent
HEADER = """! SPDX-License-Identifier: GPL-3.0-or-later
! Generated by tools/isa-probes/gen_pocchk5.py; see pocchk5.c.
	.ignore	ld_st_style
	.ignore	strict_delay
	.text
"""
cases, text = [], []
WARM, STEPS = 4, 12
ONE, TWO = "0x3ff0000000000000", "0x4000000000000000"


def wi(*ops):
    return "\t{\n" + "".join(f"\t  {o}\n" for o in ops) + "\t}\n"


def nops(n):
    out = ""
    while n > 0:
        k = min(n, 8)
        out += wi(f"nop {k - 1}" if k > 1 else "nop")
        n -= k
    return out


def raw(name, body):
    fn = f"p5_{name}"
    text.append(f"\n\t.global\t{fn}\n\t.type\t{fn}, #function\n\t.align\t8\n"
                f"{fn}:\n{body}\t.size\t{fn}, .-{fn}\n")


def func(name, body, wsz=0x20):
    raw(name, wi(f"setwd\twsz = {wsz:#x}, nfx = 0x1, dbl = 0x0") + body
        + wi("return\t%ctpr3") + nops(6) + wi("ct\t%ctpr3"))


# --- value helpers -------------------------------------------------------
func("rnd_d", wi("fdtoifd,0\t%dr0, %dr1, %dr0") + nops(4), wsz=4)
func("rnd_s", wi("fstoifs,0\t%r0, %r1, %r0") + nops(4), wsz=4)
func("rnd_ps", wi("pfstoifs,0\t%dr0, %dr1, %dr0") + nops(4), wsz=4)
func("sqrt_d", wi("fsqrtid,5\t%dr0, %dr1") + nops(11)
     + wi("fsqrttd,5\t%dr0, %dr1, %dr0") + nops(14), wsz=4)
func("sqrt_s", wi("fsqrts,5\t%r0, %r0") + nops(12), wsz=4)
# p5_calltag(fn, x): call fn(x) and return the tags of its result
# (gettagd never traps), so a diagnostic result is seen without a use.
raw("calltag",
    wi("setwd\twsz = 0x8, nfx = 0x1, dbl = 0x0",
       "setbn\trsz = 0x3, rbs = 0x4, rcur = 0x0", "movtd,0\t%dr0, %ctpr1")
    + wi("addd,0\t0x0, %dr1, %db[0]") + nops(8)
    + wi("call\t%ctpr1, wbs = 0x4")
    + wi("return\t%ctpr3", "gettagd,2\t%db[0], %r0") + nops(6)
    + wi("ct\t%ctpr3"))

# --- diagnostic operands (P78) -------------------------------------------
# %dr1 = diagnostic copy of a; %dr2, %dr3 preset to 0; the result's tag
# (gettagd, which never traps) is returned.
MKDG = (wi("puttagd,2,sm\t%dr0, 0xa, %dr1", "addd,0\t0x0, 0x0, %dr2",
           "addd,1\t0x0, 0x0, %dr3", "addd,3\t0x0, 0x800, %dr4")
        + nops(2))
DG = {
    # value cases: name -> (operations after MKDG, register whose tag)
    "mk": ([], "%dr1"),
    "adds_fw_sm": ([wi("adds_fw,0,sm\t%r1, 0x1, %r2")], "%dr2"),
    "addd_fd_sm": ([wi("addd_fd,0,sm\t%dr1, 0x1, %r2")], "%dr2"),
    "smulx_fw_sm": ([wi("smulx_fw,3,sm\t%r1, 0x3, %r2")], "%dr2"),
    "cctopo_sm": ([wi("cctopo,0,sm\t%r1, %pred0"), nops(2),
                   wi("addd,1,sm\t0x0, 0x1, %dr3 ? %pred0")], "%dr3"),
    "cctopo_sm_neg": ([wi("cctopo,3,sm\t%r1, %pred0"), nops(2),
                       wi("addd,1,sm\t0x0, 0x1, %dr3 ? ~%pred0")], "%dr3"),
    "cmpedb_sm": ([wi("cmpedb,0,sm\t%dr1, 0x0, %pred0"), nops(2),
                   wi("addd,1,sm\t0x0, 0x1, %dr3 ? %pred0")], "%dr3"),
    # controls: an ordinary operand
    "ok_adds_fw_sm": ([wi("adds_fw,0,sm\t%r0, 0x1, %r2")], "%dr2"),
    "ok_cctopo_sm": ([wi("cctopo,0,sm\t%r4, %pred0"), nops(2),
                      wi("addd,1,sm\t0x0, 0x1, %dr3 ? %pred0")], "%dr3"),
}
for name, (ops, reg) in DG.items():
    func(f"dg_{name}", MKDG + "".join(ops) + nops(4)
         + wi(f"gettagd,2\t{reg}, %r0") + nops(1), wsz=8)
    cases.append(f"DG ({name})\n")
# trap cases: the diagnostic operand without ,sm (run in a child)
TR = {
    "adds_fw": wi("adds_fw,0\t%r1, 0x1, %r2"),
    "cctopo": wi("cctopo,0\t%r1, %pred0") + nops(2)
    + wi("addd,1\t0x0, 0x1, %dr3 ? %pred0"),
}
for name, ops in TR.items():
    func(f"tr_{name}", MKDG + ops + nops(4) + wi("addd,0\t0x0, %dr3, %dr0"),
         wsz=8)
    cases.append(f"TR ({name})\n")

# --- latency of fcmp*f into integer consumers (P82) ----------------------
SETUP = (wi("addd,0\t0x0, _f64,_lts0 " + ONE + ", %dr2",
            "addd,1\t0x0, _f64,_lts2 " + TWO + ", %dr3",
            "addd,2\t0x0, 0x0, %dr8", "addd,3\t0x0, 0x0, %dr10",
            "addd,4\t0x0, 0x0, %dr20", "addd,5\t0x0, 0x0, %dr21")
         + wi("cmpesb,0\t0x0, 0x0, %pred0"))


def timed(name, step):
    body = SETUP + nops(8)
    for i in range(WARM):
        body += step(i)
    body += wi("rrd,0\t%clkr, %dr28")
    for i in range(WARM, WARM + STEPS):
        body += step(i)
    body += wi("rrd,0\t%clkr, %dr29") + nops(2)
    body += wi("subd,0\t%dr29, %dr28, %dr0")
    func(name, body)


# Producers in channel k: {d} the destination.
PROD = {
    "fcmpuddf": "fcmpuddf,{k}\t%dr2, %dr3, {d}",
    "fcmpoddf": "fcmpoddf,{k}\t%dr2, %dr3, {d}",
    "fcmpudsf": "fcmpudsf,{k}\t%r2, %r3, {d}",
    "fcmpeqd": "fcmpeqd,{k}\t%dr2, %dr3, {D}",
    "faddd": "faddd,{k}\t%dr2, %dr3, {D}",
}
# Consumers in channel k: {s} the result as 32 bits, {S} as 64 bits.
CONS = {
    "cmpandesb": "cmpandesb,{k}\t{s}, 0x40, %pred1",
    "cmpesb": "cmpesb,{k}\t{s}, 0x1, %pred1",
    "cctope": "cctope,{k}\t{s}, %pred1",
    "xors": "xors,{k}\t{s}, 0x1, %r20",
    "adds": "adds,{k}\t{s}, 0x1, %r20",
    "getfs": "getfs,{k}\t{s}, 0x40, %r20",
    "getfd": "getfd,{k}\t{S}, 0x40, %dr20",
    "addd": "addd,{k}\t{S}, 0x1, %dr20",
}
PAIRS = [(0, 0), (0, 1), (0, 3), (0, 4), (3, 3), (3, 0)]
LAT = []
for c in CONS:
    for pk, ck in PAIRS:
        if c == "cctope" and ck not in (0, 3):
            continue
        LAT.append(("fcmpuddf", pk, c, ck))
for p in ("fcmpoddf", "fcmpudsf"):
    LAT += [(p, 0, c, ck) for c in ("xors", "cmpandesb") for ck in (0, 3)]
for p in ("fcmpeqd", "faddd"):
    LAT += [(p, 0, "addd", ck) for ck in (0, 1, 3)]


def step_text(p, pk, c, ck, i, g):
    r = 8 if i % 2 == 0 else 10
    pop = PROD[p].format(k=pk, d=f"%r{r}", D=f"%dr{r}")
    cop = CONS[c].format(k=ck, s=f"%r{r}", S=f"%dr{r}")
    return wi(pop) + nops(g - 1) + wi(cop, "nop 3")


for p, pk, c, ck in LAT:
    for g in range(2, 9):
        name = f"lat_{p}{pk}__{c}{ck}_g{g}"
        timed(name, lambda i, p=p, pk=pk, c=c, ck=ck, g=g:
              step_text(p, pk, c, ck, i, g))
        cases.append(f"LAT ({name}, \"{p},{pk} -> {c},{ck}\", {g})\n")


def write():
    (HERE / "pocchk5.s").write_text(HEADER + "".join(text))
    (HERE / "pocchk5-cases.h").write_text(
        "/* SPDX-License-Identifier: GPL-3.0-or-later */\n"
        "/* Generated by tools/isa-probes/gen_pocchk5.py.  */\n"
        + "".join(cases))
    print(len(cases), "cases")


if __name__ == "__main__":
    write()
