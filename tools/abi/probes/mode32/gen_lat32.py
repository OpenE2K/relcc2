"""Write lat32.s, lat32-cases.h, lat32-v5.s and lat32-v5-cases.h for
lat32.c: the latencies of 32-bit mode's ldgd*/stgd* against ld*/st*,
and getpl -> ct/call against movtd and disp, all timed in one 32-bit
process (spec/abi/mode32.md, "Addresses and memory access").

  python3 tools/abi/probes/mode32/gen_lat32.py

Every kernel is `long long l32_NAME (long long p)', called with the
32-bit address p of lat32.c's buffer zero-extended to 64 bits (so %dr0
is a usable 64-bit address and %r0 the 32-bit one), setwd dbl = 0, and
returns the cycles between two %clkr reads. Each comes in two lengths;
lat32.c prints the difference divided by the difference in steps, so
the frame and the clock reads cancel.

LAT  a chain of steps, each a producer in an instruction with nop g-1
     and its consumer g cycles later (the next step's producer, or an
     ALU op that a second fixed gap separates from the next load).
     A step costs g when g >= the latency L, else g + 4 ceil((L-g)/4)
     (timing.md, "Stalls cost more than the latency"). 16 and 32 steps.
RT   a store, s-1 empty cycles, a load of the same address, 2 empty
     cycles, an ALU op on the loaded value that feeds the next store's
     data (timing.md, "Store to load"). 16 and 32 steps.
TP   wide instructions of independent loads or stores, 16 and 32.
CT   blocks of a prepare (getpl, movtd or disp into %ctpr2), D-1 empty
     cycles and a ct %ctpr2 to the next block, or a call %ctpr2 of a
     leaf that prepares its return on entry and returns 6 cycles later
     (wbs = 0x1c: the leaf gets the caller's last 4 register pairs, as
     many as its setwd asks for; a smaller setwd than the window it is
     handed is SIGILL).
     A block costs max(D, delay) + 1 (control-transfer.md, "Costs");
     4 and 10 blocks. These functions are aligned to 1 KiB and keep
     their labels and call return addresses below offset 0x1c0, so
     gas's CODE_PLACEMENT workaround inserts nothing (AGENTS.md,
     Gotchas; check with objdump that no block holds an extra empty
     instruction).

Buffer (lat32.c): p+0 holds p as a doubleword (the self-pointer for
ld*/ldgd* chases); p+8 holds (p+8) + 0x80000000 as a word (the chase
whose ldgdw sum wraps: ldgdw %r9, %r6 with %r6 = 0x80000000); p+64..
p+127 are zero (index chases: the loaded zero is the next index);
p+256.. is store space for the round trips; p+512 holds p+512 as a
doubleword, followed by a zero doubleword (the 16-byte chases); p+1024..
p+1535 is store space for the throughput kernels.
"""

from pathlib import Path

HERE = Path(__file__).resolve().parent
HEADER = """! SPDX-License-Identifier: GPL-3.0-or-later
! Generated by tools/abi/probes/mode32/gen_lat32.py; see lat32.c.
! 32-bit mode (lcc -mptr32) only: ldgd* and getpl need a 32-bit process.
	.ignore	ld_st_style
	.ignore	strict_delay
	.text
"""


def wi(*ops):
    return "\t{\n" + "".join(f"\t  {o}\n" for o in ops) + "\t}\n"


def nops(n):
    """n empty cycles as separate instructions (n >= 0)."""
    out = ""
    while n > 0:
        k = min(n, 8)
        out += wi(f"nop {k - 1}" if k > 1 else "nop")
        n -= k
    return out


def step(op, g):
    """op in an instruction followed by g-1 empty cycles."""
    if g <= 8:
        return wi(op, f"nop {g - 1}") if g > 1 else wi(op)
    return wi(op, "nop 7") + nops(g - 8)


SETUP = (wi("addd,0\t0x0, %dr0, %dr2",
            "addd,1\t%dr0, 0x40, %dr5",
            "addd,3\t0x0, 0x0, %dr4",
            "addd,4\t0x0, 0x0, %dr10",
            "adds,2\t0x0, _f32s,_lts0 0x80000000, %r6",
            "adds,5\t%r0, _f32s,_lts1 0x80000008, %r9")
         + wi("addd,0\t%dr0, 0x200, %dr12", "addd,1\t%dr0, 0x400, %dr14",
              "nop 7"))


class Gen:
    def __init__(self):
        self.text = []
        self.cases = []

    def func(self, name, body, align=64, wsz=0x20):
        fn = f"l32_{name}"
        self.text.append(
            f"\n\t.global\t{fn}\n\t.type\t{fn}, #function\n"
            f"\t.align\t{align}\n{fn}:\n"
            + wi(f"setwd\twsz = {wsz:#x}, nfx = 0x1, dbl = 0x0")
            + body
            + wi("return\t%ctpr3") + nops(5) + wi("ct\t%ctpr3")
            + f"\t.size\t{fn}, .-{fn}\n")

    def timed(self, name, setup, steps, tail="", align=64):
        """setup, %clkr, the steps, tail, %clkr, the difference."""
        self.func(name, setup + wi("rrd,0\t%clkr, %dr20") + steps + tail
                  + wi("rrd,0\t%clkr, %dr21")
                  + wi("subd,0\t%dr21, %dr20, %dr0"), align=align)

    def lat(self, base, label, ops, gaps, final, fixed=None):
        """A chain for each g in gaps. ops: the producers of successive
        steps (used in turn), each the next one's consumer; final: the
        consumer of the last. fixed = (alu, g2, "first"): each step is
        the producer, g, then alu, g2 (the producer -> alu latency);
        (alu, g2, "second"): the producer, g2, then alu, g (the alu ->
        next producer latency)."""
        for g in gaps:
            for n in (16, 32):
                body = ""
                for i in range(n):
                    op = ops[i % len(ops)]
                    if fixed is None:
                        body += step(op, g)
                    else:
                        cons, g2, which = fixed
                        if which == "first":
                            body += step(op, g) + step(cons, g2)
                        else:
                            body += step(op, g2) + step(cons, g)
                self.timed(f"{base}_g{g}_n{n}", SETUP, body, wi(final))
            plus = 0 if fixed is None else fixed[1]
            self.cases.append(f'LAT ({base}_g{g}, "{label}", {g}, {plus})')

    def rt(self, base, label, st, ld, alu, gaps):
        for s in gaps:
            for n in (16, 32):
                body = ""
                for _ in range(n):
                    body += step(st, s) + step(ld, 3) + wi(alu)
                self.timed(f"{base}_s{s}_n{n}", SETUP, body)
            self.cases.append(f'RT ({base}_s{s}, "{label}", {s})')

    def tp(self, base, label, make):
        for n in (16, 32):
            body = "".join(wi(*make(i)) for i in range(n))
            self.timed(f"{base}_n{n}", SETUP, body)
        self.cases.append(f'TP ({base}, "{label}")')

    def ct(self, base, label, kind, d, call):
        for n in (4, 10):
            fn = f"l32_{base}_d{d}_n{n}"
            labels = [f".L{fn}_{i}" for i in range(n)]
            setup = SETUP
            # The targets' addresses, as 32-bit literals: one register
            # a block (a call: one for all, which keeps the code short,
            # see the CT note above), four to an instruction.
            targets = ["l32_leaf"] if call else labels
            if kind == "getpl":
                regs = [f"%r{24 + 2 * i}" for i in range(len(targets))]
                mov = "adds"
            else:
                regs = [f"%dr{24 + 2 * i}" for i in range(len(targets))]
                mov = "addd"
            movs = [f"{mov},{(0, 1, 3, 4)[k % 4]}\t0x0, "
                    f"_f32s,_lts{k % 4} {t}, {r}"
                    for k, (t, r) in enumerate(zip(targets, regs))]
            if call:
                regs = regs * n
            if kind != "disp":
                setup = SETUP + "".join(
                    wi(*movs[i:i + 4]) for i in range(0, len(movs), 4)) \
                    + nops(8)
            body = ""
            for i in range(n):
                tgt = "l32_leaf" if call else labels[i]
                if kind == "getpl":
                    prep = f"getpl,0\t{regs[i]}, %ctpr2"
                elif kind == "movtd":
                    prep = f"movtd,0\t{regs[i]}, %ctpr2"
                else:
                    prep = f"disp\t%ctpr2, {tgt}"
                xfer = "call\t%ctpr2, wbs = 0x1c" if call else "ct\t%ctpr2"
                body += step(prep, d) + wi(xfer)
                if not call:
                    body += f"{labels[i]}:\n"
            self.timed(f"{base}_d{d}_n{n}", setup, body, align=1024)
        # A block costs D + 1 from the delay on (a call: D + 8, with the
        # leaf's 7 cycles).
        self.cases.append(f'CT ({base}_d{d}, "{label}", {d}, '
                          f'{8 if call else 1})')

    def write(self, sname, hname, extra=""):
        (HERE / sname).write_text(HEADER + extra + "".join(self.text))
        (HERE / hname).write_text(
            "/* Generated by tools/abi/probes/mode32/gen_lat32.py; "
            "see lat32.c.  */\n" + "\n".join(self.cases) + "\n")


LEAF = """
	.global	l32_leaf
	.type	l32_leaf, #function
	.align	64
l32_leaf:
""" + wi("setwd\twsz = 0x4, nfx = 0x1, dbl = 0x0", "return\t%ctpr3") \
    + nops(5) + wi("ct\t%ctpr3") + "\t.size\tl32_leaf, .-l32_leaf\n"

G8 = range(1, 9)
v3 = Gen()
# Load -> next load's address (a pointer chase), same channel.
v3.lat("ldd_c0", "ldd,0 -> ldd,0 address", ["ldd,0\t%dr2, 0x0, %dr2"], G8,
       "ord,0\t%dr2, 0x0, %dr22")
v3.lat("ldw_c0", "ldw,0 -> ldw,0 address (64-bit read)",
       ["ldw,0\t%dr2, 0x0, %r2"], G8, "ord,0\t%dr2, 0x0, %dr22")
for c in (0, 2, 3, 5):
    v3.lat(f"ldgdw_c{c}", f"ldgdw,{c} -> ldgdw,{c} src1",
           [f"ldgdw,{c}\t%r2, 0x0, %r2"], G8, "ors,0\t%r2, 0x0, %r22")
v3.lat("ldgdd_c0", "ldgdd,0 -> ldgdd,0 src1 (low half)",
       ["ldgdd,0\t%r2, 0x0, %dr2"], G8, "ors,0\t%r2, 0x0, %r22")
v3.lat("ldgdw_wrap", "ldgdw,0 -> ldgdw,0, sum wraps",
       ["ldgdw,0\t%r9, %r6, %r9"], G8, "ors,0\t%r9, 0x0, %r22")
# Load -> next load's index (src2).
for w in ("b", "h", "w", "d"):
    dst = "%dr4" if w == "d" else "%r4"
    v3.lat(f"ldgd{w}_idx", f"ldgd{w},0 -> ldgd{w},0 src2",
           [f"ldgd{w},0\t%r5, %r4, {dst}"], G8, "ors,0\t%r4, 0x0, %r22")
    v3.lat(f"ld{w}_idx", f"ld{w},0 -> ld{w},0 src2",
           [f"ld{w},0\t%dr5, %dr4, %dr4"], G8, "ord,0\t%dr4, 0x0, %dr22")
# Across the clusters (ALC0 <-> ALC3).
v3.lat("ldgdw_x", "ldgdw,0 <-> ldgdw,3 src1",
       ["ldgdw,0\t%r2, 0x0, %r2", "ldgdw,3\t%r2, 0x0, %r2"], G8,
       "ors,0\t%r2, 0x0, %r22")
v3.lat("ldd_x", "ldd,0 <-> ldd,3 address",
       ["ldd,0\t%dr2, 0x0, %dr2", "ldd,3\t%dr2, 0x0, %dr2"], G8,
       "ord,0\t%dr2, 0x0, %dr22")
# Load -> ALU op (g), ALU op -> next load (4).
v3.lat("ldgdw_alu", "ldgdw,0 -> adds,0",
       ["ldgdw,0\t%r2, 0x0, %r2"], G8, "ors,0\t%r2, 0x0, %r22",
       fixed=("adds,0\t%r2, 0x0, %r2", 4, "first"))
v3.lat("ldd_alu", "ldd,0 -> addd,0",
       ["ldd,0\t%dr2, 0x0, %dr2"], G8, "ord,0\t%dr2, 0x0, %dr22",
       fixed=("addd,0\t%dr2, 0x0, %dr2", 4, "first"))
# ALU op -> next load's address (g); load -> ALU op (6).
v3.lat("alu_ldgdw", "adds,0 -> ldgdw,0 src1",
       ["ldgdw,0\t%r2, 0x0, %r2"], range(1, 5), "ors,0\t%r2, 0x0, %r22",
       fixed=("adds,0\t%r2, 0x0, %r2", 6, "second"))
v3.lat("alu_ldd", "addd,0 -> ldd,0 address",
       ["ldd,0\t%dr2, 0x0, %dr2"], range(1, 5), "ord,0\t%dr2, 0x0, %dr22",
       fixed=("addd,0\t%dr2, 0x0, %dr2", 6, "second"))
# Register pairs: ldgdq (v2-v6; 64-bit mode's ldq is v5+, below), ALC0+2,
# the chase through the low half.
v3.lat("ldgdq", "ldgdq,0 -> ldgdq,0 src1 (pair's low word)",
       ["ldgdq,0\t%r12, 0x0, %qr12"], G8, "ors,0\t%r12, 0x0, %r22")
# Store -> load of the same word -> ALU op -> next store's data.
v3.rt("stgdw", "stgdw,2 -> ldgdw,0 -> ors", "stgdw,2\t%r5, 0xc0, %r10",
      "ldgdw,0\t%r5, 0xc0, %r10", "ors,0\t%r10, 0x0, %r10", (1, 2))
v3.rt("stw", "stw,2 -> ldw,0 -> ors", "stw,2\t%dr5, 0xc0, %r10",
      "ldw,0\t%dr5, 0xc0, %r10", "ors,0\t%r10, 0x0, %r10", (1, 2))
v3.rt("stgdd", "stgdd,2 -> ldgdd,0 -> ord", "stgdd,2\t%r5, 0xc0, %dr10",
      "ldgdd,0\t%r5, 0xc0, %dr10", "ord,0\t%dr10, 0x0, %dr10", (1, 2))
v3.rt("std", "std,2 -> ldd,0 -> ord", "std,2\t%dr5, 0xc0, %dr10",
      "ldd,0\t%dr5, 0xc0, %dr10", "ord,0\t%dr10, 0x0, %dr10", (1, 2))
v3.rt("stgdw5", "stgdw,5 -> ldgdw,3 -> ors", "stgdw,5\t%r5, 0xc0, %r10",
      "ldgdw,3\t%r5, 0xc0, %r10", "ors,3\t%r10, 0x0, %r10", (1, 2))
# Throughput: 4 loads (ALC0, 2, 3, 5) or 2 stores (ALC2, 5) a cycle.
v3.tp("ldgdw4", "4 ldgdw (ALC0, 2, 3, 5)",
      lambda i: [f"ldgdw,{c}\t%r5, {8 * k:#x}, %r{40 + k}"
                 for k, c in enumerate((0, 2, 3, 5))])
v3.tp("ldw4", "4 ldw (ALC0, 2, 3, 5)",
      lambda i: [f"ldw,{c}\t%dr5, {8 * k:#x}, %r{40 + k}"
                 for k, c in enumerate((0, 2, 3, 5))])
v3.tp("ldgdw4lit", "4 ldgdw with a 32-bit literal",
      lambda i: [f"ldgdw,{c}\t%r5, _f32s,_lts{k} {8 * k + 0x1000:#x}, "
                 f"%r{40 + k}" for k, c in enumerate((0, 2, 3, 5))])
v3.tp("stgdw2", "2 stgdw (ALC2, 5), new addresses",
      lambda i: [f"stgdw,2\t%r14, {16 * i:#x}, %r4",
                 f"stgdw,5\t%r14, {16 * i + 8:#x}, %r4"])
v3.tp("stw2", "2 stw (ALC2, 5), new addresses",
      lambda i: [f"stw,2\t%dr14, {16 * i:#x}, %r4",
                 f"stw,5\t%dr14, {16 * i + 8:#x}, %r4"])
# Prepares -> ct to the next block, and -> call of a leaf.
for d in range(1, 13):
    v3.ct("getpl_ct", "getpl,0 -> ct", "getpl", d, False)
for d in range(1, 13):
    v3.ct("movtd_ct", "movtd,0 -> ct", "movtd", d, False)
for d in range(1, 8):
    v3.ct("disp_ct", "disp -> ct", "disp", d, False)
for d in range(1, 13):
    v3.ct("getpl_call", "getpl,0 -> call", "getpl", d, True)
for d in (1, 3, 5, 7, 9, 11):
    v3.ct("disp_call", "disp -> call", "disp", d, True)
v3.write("lat32.s", "lat32-cases.h", LEAF)

# v5 and later: the single-register 128-bit loads (ldqp bypasses L1 on
# v5, timing.md "Elbrus-8C2"; through L1 on v6).
v5 = Gen()
G14 = range(1, 15)
v5.lat("ldgdqp", "ldgdqp,0 -> ldgdqp,0 src1 (low word)",
       ["ldgdqp,0\t%r12, 0x0, %qpr12"], G14, "ors,0\t%r12, 0x0, %r22")
v5.lat("ldqp", "ldqp,0 -> ldqp,0 address (low half)",
       ["ldqp,0\t%dr12, 0x0, %qpr12"], G14, "ord,0\t%dr12, 0x0, %dr22")
v5.lat("ldq", "ldq,0 -> ldq,0 address (pair's low half)",
       ["ldq,0\t%dr12, 0x0, %qr12"], G8, "ord,0\t%dr12, 0x0, %dr22")
v5.write("lat32-v5.s", "lat32-v5-cases.h")
