"""Write aaurwct.s and aaurwct-cases.h for aaurwct.c: two timing facts
isa-score's model needed (tools/isa-score/README.md; spec/isa/timing.md,
control-transfer.md):

1. Does `aaurw`/`aaurwd` wait for an integer operand written by the other
   cluster one cycle before, as an ALU operation does (+1, a 4-cycle
   stall), or take it like a store's data (no crossing cost)?  `addd` in
   ALC3 (other cluster) or ALC0, then `aaurw(d)` in ALC2 or ALC5 to
   %aaind1, %aabf0 or %aaincr1; controls: an `addd,2` and an `std,2`
   reading the same register.
2. How long a not-taken `ct ? %pred` waits for a CTPR prepared by `return`
   (and, for comparison, by `disp`) 1 to 7 cycles before it.

Each case is a function; aaurwct.c times 101 calls of each with %clkr and
prints the median.  Run: python3 tools/isa-probes/gen_aaurwct.py
"""

from pathlib import Path

REP = 16
HERE = Path(__file__).resolve().parent
cases = []


def fn(name, body):
    cases.append((name, body))


for src_ch, tag in ((3, "x"), (0, "s")):
    for dst, op, reg in (("aaind1", "aaurwd", "%dr1"),
                         ("aabf0", "aaurw", "%r1"),
                         ("aaincr1", "aaurwd", "%dr1")):
        for ch in (2, 5):
            fn(f"{tag}_{dst}_{ch}",
               [[f"addd,{src_ch} 0x0, %dr0, %dr1"],
                [f"{op},{ch} {reg}, %{dst}"]] * REP)
    fn(f"{tag}_alu", [[f"addd,{src_ch} 0x0, %dr0, %dr1"],
                      ["addd,2 %dr1, 0x0, %dr2"]] * REP)
    fn(f"{tag}_st", [[f"addd,{src_ch} 0x0, %dr0, %dr1"],
                     ["std,2 %dr3, 0x0, %dr1"]] * REP)
fn("base", [["addd,0 0x0, %dr0, %dr1"], ["addd,0 0x0, %dr0, %dr2"]] * REP)
for prep in ("return", "disp"):
    for d in range(1, 8):
        body = [["cmpesb,0 0x0, 0x1, %pred0"], ["nop 2"]]
        if prep == "return":
            body += [["return %ctpr3"]]
            ct = "ct %ctpr3 ? %pred0"
        else:
            body += [["disp %ctpr1, aw_leaf"]]
            ct = "ct %ctpr1 ? %pred0"
        if d > 1:
            body += [[f"nop {d - 2}"]]   # an instruction plus d - 2 empty cycles
        body += [[ct]]
        fn(f"ct_{prep}_d{d}", body)


def wide(ops):
    return "\t{\n" + "".join(f"\t  {o}\n" for o in ops) + "\t}"


out = ["! SPDX-License-Identifier: GPL-3.0-or-later",
       "! Generated by tools/isa-probes/gen_aaurwct.py.",
       "\t.text", "\t.ignore ld_st_style",
       "", "! unsigned long aw_clk (void): %clkr.",
       "\t.global\taw_clk", "\t.type\taw_clk, #function", "\t.align\t8",
       "aw_clk:",
       wide(["setwd wsz = 0x4, nfx = 0x1, dbl = 0x0", "return %ctpr3",
             "rrd,0 %clkr, %dr0"]),
       wide(["ct %ctpr3"]),
       "\t.size\taw_clk, .-aw_clk",
       "", "\t.global\taw_leaf", "\t.type\taw_leaf, #function", "\t.align\t8",
       "aw_leaf:", wide(["return %ctpr3"]), wide(["nop 5"]), wide(["ct %ctpr3"]),
       "\t.size\taw_leaf, .-aw_leaf"]
for name, body in cases:
    out += ["", f"\t.global\taw_{name}", f"\t.type\taw_{name}, #function",
            "\t.align\t256", f"aw_{name}:",   # one I-cache line each
            wide(["setwd wsz = 0x8, nfx = 0x1, dbl = 0x0",
                  "addd,1 0x0, 0x0, %dr0", "getsp,0 -64, %dr3"]),
            wide(["nop 5"])]
    out += [wide(ins) for ins in body]
    out += [wide(["return %ctpr3"]), wide(["nop 5"]), wide(["ct %ctpr3"]),
            f"\t.size\taw_{name}, .-aw_{name}"]
(HERE / "aaurwct.s").write_text("\n".join(out) + "\n")

h = ["/* SPDX-License-Identifier: GPL-3.0-or-later */",
     "/* Generated by tools/isa-probes/gen_aaurwct.py.  */"]
h += [f"CASE ({name})" for name, _ in cases]
(HERE / "aaurwct-cases.h").write_text("\n".join(h) + "\n")
