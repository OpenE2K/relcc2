# Longer windows in one 256-byte line: a chain of N dependent divides
# (1 / 1, about 11 cycles each on v3) between the prepare and the
# transfer.  The cached time (mode 0) gives the window's length.
DIV = "sdivd,5\t%dr50, %dr51, %dr50"


def w_div(n, kind, ipd=None):
    sfx = "" if ipd is None else f"; ipd {ipd}"

    def w(t):
        first = {"ib": [T0], "disp": [T0, f"disp\t%ctpr1, {t}{sfx}"],
                 "pref": [T0, f"pref\t%ipr0, {t}"],
                 "prefib": [T0, f"pref\t%ipr0, {t}"]}[kind]
        out = wi(*first) + "".join(wi(DIV) for _ in range(n))
        if kind in ("ib", "prefib"):
            return out + wi(f"ibranch\t{t}")
        if kind == "pref":
            out += wi(f"disp\t%ctpr1, {t}") + nops(4)
        return out + wi("ct\t%ctpr1")
    return w


