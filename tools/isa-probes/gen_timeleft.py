def fetch_case(name, block, skip=0):
    """BLOCK(NXT) gives a block's text ending in a transfer to NXT; each
    block starts SKIP bytes into its 1 KiB slot."""
    mac = macro(f"m_fe_{name}", "nxt", block("\\nxt"))
    for k in FK:
        fn = f"fe_{name}_k{k}"

        def lab(i):
            return f".L{fn}_b{i}"
        b = FETCH_SETUP + wi("rrd,0\t%clkr, %dr28", f"disp\t%ctpr1, {lab(0)}") + nops(5)
        b += wi("ct\t%ctpr1")
        sk = f"\t.skip\t{skip}\n" if skip else ""
        for i in range(k):
            b += f"\t.balign\t1024\n{sk}{lab(i)}:\n\t{mac}\t{lab(i + 1)}\n"
        b += f"\t.balign\t1024\n{lab(k)}:\n"
        b += wi("rrd,0\t%clkr, %dr29") + nops(2) + wi("subd,0\t%dr29, %dr28, %dr0")
        func(fn, b, wsz=0x40)
    cases[""].append(f"FE (fe_{name}, \"{name}\")\n")


