"""Write ops.c: a program that calls every register-only operation
builtin of lcc (spec/abi/lcc-builtins.yaml, with lcc's own signatures
from lcc-builtins-check.yaml) on a fixed set of inputs and prints one
hash of the results per builtin.  Built by two compilers and run on the
same machine, equal lines mean the builtins compute the same; run.py
does that, with models.c (the builtins that are not one operation).

  python3 tools/abi/builtins/gen.py [-o DIR]

Builtins of a later ISA than the target are left out by #if __iset__.
Memory builtins (ld_*, st_*, pst_*, prefetch, clflush) and the tag
builtins are in models.c instead.  Arguments lcc requires as constants
are called with several values it accepts.
"""

import argparse
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[3]
CTYPE = {"uint64": "u64", "uint32": "u32", "int": "int", "int64": "long long",
         "v2di": "v2di", "long double": "long double", "N": "int",
         "unsigned int": "u32", "unsigned": "u32", "long": "long",
         "void": "void"}
SKIP_PREFIX = ("ld_", "st_", "pst_")
SKIP = {"prefetch", "clflush", "puttagd", "puttagqp"}
CONSTS = [0, 1, 2, 3, 5, 7, 8, 15, 16, 0x5a, 0xa5, 0xff]
NV = 192


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("-o", type=Path, default=ROOT / "toolchains" / "builtins")
    a = ap.parse_args()
    manual = [b for b in yaml.safe_load((ROOT / "spec/abi/lcc-builtins.yaml")
                                        .read_text())["builtins"]
              if b["group"] == "op"]
    check = yaml.safe_load((ROOT / "spec/abi/lcc-builtins-check.yaml")
                           .read_text())["builtins"]
    out = [HEAD]
    names = []
    for b in manual:
        if b["op"] in SKIP or b["op"].startswith(SKIP_PREFIX):
            continue
        c = check[b["name"]]
        sig = c.get("lcc_signature", {"returns": b["returns"],
                                      "args": [x["type"] for x in b["args"]]})
        ret = CTYPE[sig["returns"].split(" | ")[0]]
        consts = {int(k): v for k, v in c.get("constant_args", {}).items()}
        args = [CTYPE[t.split(" | ")[0]] for t in sig["args"]]
        out.append(function(b["op"], c["iset"], ret, args, consts))
        names.append((b["op"], c["iset"]))
    out.append("int\nmain (void)\n{\n  init ();\n")
    for n, iset in names:
        out.append(f"#if __iset__ >= {iset}\n  t_{n} ();\n#endif\n")
    out.append("  return 0;\n}\n")
    (a.o / "ops.c").write_text("".join(out))
    print(len(names), "builtins")


def accepted(spec):
    """The constants of CONSTS lcc accepts, from constant_args' runs."""
    ok = set()
    for r in spec["accepted"]:
        lo, _, hi = str(r).partition("..")
        lo, hi = int(lo), int(hi or lo)
        ok |= {x for x in CONSTS if lo <= x <= hi}
    return sorted(ok)


def function(op, iset, ret, args, consts):
    """t_OP: call __builtin_e2k_OP NV times (and once per constant tuple),
    hashing the results."""
    vals = []
    for k, t in enumerate(args):
        if k in consts:
            vals.append(None)
        elif t == "v2di":
            vals.append(f"vq ({k}, i)")
        elif t == "long double":
            vals.append(f"vx ({k}, i)")
        else:
            vals.append(f"({t}) v ({k}, i)")
    # One call per combination of constants (most builtins have none).
    combos = [[]]
    for k in sorted(consts):
        combos = [c + [x] for c in combos for x in accepted(consts[k])]
    calls = []
    for combo in combos:
        it = iter(combo)
        argl = [str(next(it)) if x is None else x for x in vals]
        call = f"__builtin_e2k_{op} ({', '.join(argl)})"
        if ret == "void":
            calls.append(f"      {call};\n")
        else:
            calls.append(f"      {{ {ret} r = {call}; h = mix (h, &r, "
                         f"{'10' if ret == 'long double' else 'sizeof r'}); }}\n")
    return (f"#if __iset__ >= {iset}\nstatic void\nt_{op} (void)\n{{\n"
            f"  u64 h = FNV;\n  for (int i = 0; i < {NV}; i++)\n    {{\n"
            + "".join(calls) + "    }\n"
            f"  printf (\"{op} %016llx\\n\", h);\n}}\n#endif\n")


HEAD = r"""/* SPDX-License-Identifier: GPL-3.0-or-later */
/* Generated by tools/abi/builtins/gen.py: one hash of the results of
   each register-only operation builtin of lcc over fixed inputs.  */
#include <stdio.h>
#include <string.h>
#include <e2kintrin.h>

typedef unsigned long long u64;
typedef unsigned int u32;
typedef long long v2di __attribute__ ((vector_size (16)));

#define FNV 0xcbf29ce484222325ULL
/* Inputs: edge cases for integer, packed and FP data, then pseudo-random
   values; volatile, so that no compiler folds the calls.  */
static volatile u64 V[64] = {
  0, 1, -1ULL, 0x8000000000000000ULL, 0x7fffffffffffffffULL,
  0x0123456789abcdefULL, 0xfedcba9876543210ULL, 0x00ff00ff00ff00ffULL,
  0x3ff0000000000000ULL, 0x7ff8000000000000ULL, 0x7ff0000000000000ULL,
  0x000000003f800000ULL, 0x3f8000003f800000ULL, 0x7fc000007fc00000ULL,
  0x0000000080000000ULL, 0xbff0000000000000ULL, 0x8000000080000000ULL,
  0x7f7fffff7f800000ULL, 0x0001000200030004ULL, 0x8080808080808080ULL,
  0x0000000100000002ULL, 0x4059000000000000ULL, 0x00000000000000ffULL,
  0xc1e0000000000000ULL, 0x0007000600050004ULL, 0x0000003f0000001fULL,
};

static void
init (void)
{
  u64 x = 0x9e3779b97f4a7c15ULL;
  for (int i = 26; i < 64; i++)
    {
      x = x * 6364136223846793005ULL + 1442695040888963407ULL;
      V[i] = x ^ (x >> 29);
    }
}

static u64
v (int k, int i)
{
  return V[(i * (2 * k + 7) + k * 11 + i / 64) % 64];
}

static v2di
vq (int k, int i)
{
  v2di r = { (long long) v (k, i), (long long) v (k + 3, i + 1) };
  return r;
}

static long double
vx (int k, int i)
{
  u64 b = v (k, i);
  double d;
  memcpy (&d, &b, 8);
  return (long double) d * (i % 3 ? 1.0L : 3.0L);
}

static u64
mix (u64 h, const void *p, int n)
{
  const unsigned char *b = p;
  for (int i = 0; i < n; i++)
    h = (h ^ b[i]) * 0x100000001b3ULL;
  return h;
}

"""

if __name__ == "__main__":
    main()
