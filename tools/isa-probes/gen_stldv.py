"""Write stldv.s and stldv-cases.h: a store and an overlapping load in
the next wide instruction (or D instructions later), for stldv.c, which
checks the loaded value (spec/isa/hwbugs.md: MCST's erratum #123567, "a
load after an intersecting store can read wrong data from L1").

  python3 tools/isa-probes/gen_stldv.py

Each case is  unsigned long sv_N(unsigned char *p, unsigned long v):
it stores v (its low bytes) at p + SOFF and returns what a load of LSIZE
bytes at p + LOFF reads, zero-extended.
"""

from pathlib import Path

HERE = Path(__file__).resolve().parent
ST = {1: "stb", 2: "sth", 4: "stw", 8: "std"}
LD = {1: "ldb", 2: "ldh", 4: "ldw", 8: "ldd"}
REG = {1: "%r1", 2: "%r1", 4: "%r1", 8: "%dr1"}
DST = {1: "%r2", 2: "%r2", 4: "%r2", 8: "%dr2"}

# (store size, store offset, load size, load offset)
SHAPES = [(8, 0, 8, 0), (4, 0, 8, 0), (4, 4, 8, 0), (1, 3, 8, 0),
          (2, 6, 4, 4), (8, 0, 4, 4), (8, 0, 1, 7), (4, 0, 4, 0),
          (1, 0, 1, 0), (8, 8, 8, 0)]
CHANNELS = [(2, 0), (2, 3), (5, 0), (5, 3), (2, 5), (5, 2)]


def wi(*ops):
    return "\t{\n" + "".join(f"\t  {o}\n" for o in ops) + "\t}\n"


def main():
    out = ["! SPDX-License-Identifier: GPL-3.0-or-later\n"
           "! Generated by tools/isa-probes/gen_stldv.py; see stldv.c.\n"
           "\t.ignore\tld_st_style\n\t.text\n"]
    cases = []
    for ss, so, ls, lo in SHAPES:
        for sc, lc in CHANNELS:
            for d in (1, 2):
                i = len(cases)
                name = f"st{ss}@{so}_ld{ls}@{lo}_alc{sc}{lc}_d{d}"
                cases.append(name)
                fn = f"sv_{i}"
                body = wi("setwd\twsz = 0x8, nfx = 0x1, dbl = 0x0",
                          "return\t%ctpr3")
                body += wi(f"{ST[ss]},{sc}\t%dr0, {so:#x}, {REG[ss]}")
                if d > 1:
                    body += wi(f"nop {d - 2}" if d > 2 else "nop")
                body += wi(f"{LD[ls]},{lc}\t%dr0, {lo:#x}, {DST[ls]}")
                body += wi("nop 5", "addd,1\t%dr2, 0x0, %dr0")
                body += wi("ct\t%ctpr3")
                out.append(f"\n\t.global\t{fn}\n\t.type\t{fn}, #function\n"
                           f"\t.align\t8\n{fn}:\n{body}\t.size\t{fn}, .-{fn}\n")
    (HERE / "stldv.s").write_text("".join(out))
    (HERE / "stldv-cases.h").write_text(
        "/* SPDX-License-Identifier: GPL-3.0-or-later */\n"
        "/* Generated by tools/isa-probes/gen_stldv.py.  */\n"
        + "".join(f'CASE ({i}, "{n}", {s[0]}, {s[1]}, {s[2]}, {s[3]})\n'
                  for i, (n, s) in enumerate(
                      (n, SHAPES[i // (2 * len(CHANNELS))])
                      for i, n in enumerate(cases))))
    print(len(cases), "cases")


if __name__ == "__main__":
    main()
