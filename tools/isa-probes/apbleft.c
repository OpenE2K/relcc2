/* The open items of spec/isa/apb.md's "Not checked yet": AAU loads
   (ldaab, ldaah, ldaaw with a MAS, the speculative forms with a cache
   hint or be, misaligned AAU loads) and what misaligned AAU accesses
   cost; and hardware monitor counts (spec/isa/monitors.md) for why two
   column walks in one half of the prefetch buffer are slow with 4 KiB
   pages ("Which half an area is in") and why plain loads that miss L1
   slow down beside an area ("Plain loads beside an area").
   apbleft*.s and apbleft*-cases.h are generated by gen_apbleft.py.

     D=tools/isa-probes
     L=/opt/mcst/lcc-1.29.16.e2k-v3.4c.linux-6.1/bin/lcc      # the 4C
     $L -O1 $D/apbleft.c $D/apbleft.s -o apbleft
     L=/opt/mcst/lcc-1.29.16.e2k-v5.8c2.linux-6.1/bin/lcc     # the 8C2
     $L -O1 -DAL_V5 $D/apbleft.c $D/apbleft.s $D/apbleft-v5.s -o apbleft
     L=/opt/mcst/lcc-1.29.16.e2k-v6.2c3.linux-6.1/bin/lcc     # the 2C3
     $L -O1 -DAL_V5 -DAL_V6 $D/apbleft.c $D/apbleft.s $D/apbleft-v5.s \
       -o apbleft

     ./apbleft values [FILTER]   AAU loads and stores: what they return
                                 or write, signals
     ./apbleft cost              misaligned access costs (cycles per
                                 wide instruction; run under flock)
     ./apbleft col [huge]        column walks: cycles and monitor
                                 counts per iteration (4 KiB pages
                                 unless "huge")
     ./apbleft bk [nohuge]       a[i] * b[...] loops: the same
     On the 4C run col and bk on one node (node 0 has CPUs 0-3):
       numactl --cpunodebind=0 --membind=0 taskset -c 2 ./apbleft bk

   Monitor counts: each line is one run with four counters, TICKS on
   DIM0, one instruction event on DIM1 and two data events on DDM0 and
   DDM1, divided by the loop's iterations.  */

