"""Write timeleftv.s, timeleftv-cases.h and timeleftv-runs.h for
timeleftv.c: the checks made while integrating timeleft.c's results
(spec/isa/timing.md, predicates.md).

  python3 tools/isa-probes/gen_timeleftv.py

Predicate cases tlv_pr_P_C_gG(long *mem, long, long): as timeleft.c's
latency cases, 4 + 12 steps of a compare P into %pred1 (true or false,
integer, FP or 80-bit), G - 1 empty cycles and a consumer C under
%pred1 (addd in ALC0 or ALC3, negated, merged, std, ldd, faddd, ct) in
an instruction with nop 3; %clkr cycles of the 12 timed steps (+ 1).

Store-to-load cases tlv_slG(mem, p, q): 32 steps of a store to [p], G
empty cycles, a load from [q] and a use feeding the next store.

Divider runs tlv_dr_*: N copies of an operation G cycles apart, then 20
empty cycles, 4 + 8 times; pairs tlv_dp_*: A, G - 1 empty cycles, B,
15 empty cycles, 4 + 12 times.  Layout s writes the empty cycles as
instructions of their own ({ fsqrts } { nop 8 }), layout c as a nop in
the operation's instruction first ({ fsqrts; nop 7 } { nop 1 }).
Operands: fsqrts of 1.0 (fsqrts) or 0.0 (fsqrts0); pfsqrts of a
register whose low single is 0.0 (pfsqrts) or 1.0 (pfsqrts1).
"""
from pathlib import Path

HERE = Path(__file__).resolve().parent
out = ["! SPDX-License-Identifier: GPL-3.0-or-later\n! Generated by tools/isa-probes/gen_timeleftv.py; see timeleftv.c.\n\t.ignore\tld_st_style\n\t.ignore\tstrict_delay\n\t.text\n"]
cases = []
GEN_H = ("/* SPDX-License-Identifier: GPL-3.0-or-later */\n"
         "/* Generated by tools/isa-probes/gen_timeleftv.py.  */\n")


def wi(*ops):
    return "\t{\n" + "".join(f"\t  {o}\n" for o in ops) + "\t}\n"


def nops(n):
    s = ""
    while n > 0:
        k = min(n, 8)
        s += wi(f"nop {k - 1}" if k > 1 else "nop")
        n -= k
    return s


RET = wi("return\t%ctpr3") + nops(6) + wi("ct\t%ctpr3")
ONE = "_f64,_lts0 0x3ff0000000000000"
SETUP = (wi("disp\t%ctpr1, tlv_never", "addd,0\t0x0, 0x8, %dr2",
            "addd,1\t0x0, 0x0, %dr3", "addd,2\t0x0, 0x0, %dr4")
         + wi(f"addd,2\t0x0, {ONE}, %dr12") + nops(12))


def func(name, body, dbl=0):
    out.append(f"\n\t.global\ttlv_{name}\n\t.type\ttlv_{name}, #function\n"
               f"\t.align\t8\ntlv_{name}:\n"
               + wi(f"setwd\twsz = 0x20, nfx = 0x1, dbl = {dbl:#x}")
               + body + RET + f"\t.size\ttlv_{name}, .-tlv_{name}\n")


PROD = {
    "cmpF": "cmpesb,0\t%r2, %r3, %pred1",      # 8 == 0: false
    "cmpT": "cmpesb,0\t%r3, %r3, %pred1",      # 0 == 0: true
    "fcmpF": "fcmpltdb,0\t%dr12, %dr12, %pred1",  # 1 < 1: false
    "fcmpT": "fcmpledb,0\t%dr12, %dr12, %pred1",  # 1 <= 1: true
    "fcmpT3": "fcmpledb,3\t%dr12, %dr12, %pred1",
    "fxcmpT": "fxcmpledb,0\t%dr14, %dr12, %pred1",
}
CONS = {
    "padd0": "addd,0\t%dr2, 0x1, {t} ? %pred1",
    "padd3": "addd,3\t%dr2, 0x1, {t} ? %pred1",
    "pnadd0": "addd,0\t%dr2, 0x1, {t} ? ~%pred1",
    "merged0": "merged,0\t%dr2, %dr3, {t}, %pred1",
    "pstd2": "std,2\t%dr0, {o}, %dr2 ? %pred1",
    "pldd0": "ldd,0\t%dr0, {o}, {t} ? %pred1",
    "pfadd0": "faddd,0\t%dr12, %dr12, {t} ? %pred1",
    "ct": "ct\t%ctpr1 ? %pred1",
    "ctn": "ct\t%ctpr1 ? ~%pred1",
}
FX_SETUP = wi("fdtofx,0\t%dr12, %dr14") + nops(8)
for p in PROD:
    for c in CONS:
        true = p.endswith("T") or p.endswith("T3")
        if (c == "ct" and true) or (c == "ctn" and not true):
            continue        # a taken ct would leave the function
        for g in range(1, 8):
            def step(i, p=p, c=c, g=g):
                return (wi(PROD[p]) + nops(g - 1)
                        + wi(CONS[c].format(t=f"%dr{30 + i % 8}",
                                            o=f"{8 * (i % 32) + 0x200:#x}"),
                             "nop 3"))
            body = SETUP + (FX_SETUP if p.startswith("fx") else "")
            for i in range(4):
                body += step(i)
            body += wi("rrd,0\t%clkr, %dr28")
            for i in range(4, 16):
                body += step(i)
            body += wi("rrd,0\t%clkr, %dr29") + nops(2) + wi("subd,0\t%dr29, %dr28, %dr0")
            name = f"pr_{p}_{c}_g{g}"
            func(name, body)
            cases.append(f"PR (pr_{p}_{c}_g{g}, \"{p} -> {c}\", {g})\n")

# Store to [p], G empty cycles, load from [q], use feeding the next store.
for gap in range(0, 6):
    body = wi("addd,0\t0x0, 0x0, %dr4") + nops(2) + wi("rrd,0\t%clkr, %dr28")
    for _ in range(32):
        body += (wi("std,2\t%dr1, 0x0, %dr4") + nops(gap)
                 + wi("ldd,0\t%dr2, 0x0, %dr4") + wi("ord,0\t%dr4, 0x0, %dr4"))
    body += nops(2) + wi("rrd,0\t%clkr, %dr29") + nops(2) + wi("subd,0\t%dr29, %dr28, %dr0")
    func(f"sl{gap}", body)

# fsqrts runs G apart: N copies, then 20 empty cycles, 4 + 8 times;
# layout s: separate nop instructions; c: {fsqrts; nop G-1}.
runs = []
for g in (2, 5):
    for n in (2, 3, 4, 5, 6, 8, 12, 16, 24, 32):
        for lay in "sc":
            def rstep(i, g=g, n=n, lay=lay):
                t = ""
                for j in range(n):
                    op = f"fsqrts,5\t%r12, %r{30 + j % 16}"
                    last = j == n - 1
                    if lay == "c" and not last and g > 1:
                        t += wi(op, f"nop {g - 1}")
                    else:
                        t += wi(op) + ("" if last else nops(g - 1))
                return t + nops(20)
            body = wi("fdtofs,0\t%dr12, %r12") + nops(8)
            for i in range(4):
                body += rstep(i)
            body += wi("rrd,0\t%clkr, %dr28")
            for i in range(4, 12):
                body += rstep(i)
            body += wi("rrd,0\t%clkr, %dr29") + nops(2) + wi("subd,0\t%dr29, %dr28, %dr0")
            func(f"dr_{lay}_g{g}_n{n}", SETUP + body)
            runs.append(f"DR (dr_{lay}_g{g}_n{n}, \"fsqrts {lay}\", {g}, {n})\n")
DIVOP = {"fsqrts": "fsqrts,5\t%r12, {d}", "fdivd": "fdivd,5\t%dr16, %dr16, {D}",
         "sdivd": "sdivd,5\t%dr2, %dr2, {D}", "smodx": "smodx,5\t%dr2, %r2, {d}",
         "pfsqrts": "pfsqrts,5\t%dr16, {D}", "fdivs": "fdivs,5\t%r12, %r12, {d}",
         "fsqrttd": "fsqrttd,5\t%dr16, %dr17, {D}", "pfdivd": "pfdivd,5\t%dr16, %dr16, {D}",
         "fxdivxx": "fxdivxx,5\t%dr18, %dr18, {D}", "fxsqrtuxx": "fxsqrtuxx,5\t%dr18, %dr19, {D}",
         "pfsqrts1": "pfsqrts,5\t%dr20, {D}", "fsqrts0": "fsqrts,5\t%r3, {d}"}


def dop(k, j):
    return DIVOP[k].format(d=f"%r{30 + j % 16}", D=f"%dr{30 + j % 16}")


def lay_op(op, cyc, lay):
    """OP followed by CYC empty cycles: separate nops (s) or a nop in
    OP's instruction plus separate ones (c)."""
    if lay == "c" and cyc > 0:
        k = min(cyc, 7)
        return wi(op, f"nop {k}") + nops(cyc - k)
    return wi(op) + nops(cyc)


for a, g in (("sdivd", 2), ("fxdivxx", 2), ("fxsqrtuxx", 2), ("fxsqrtuxx", 3),
             ("fsqrttd", 2), ("fsqrttd", 3), ("pfdivd", 2), ("fdivd", 2)):
    for n in (3, 4, 5, 6, 8, 16, 32):
        for lay in "sc":
            def ostep(i, a=a, g=g, n=n, lay=lay):
                t = ""
                for j in range(n):
                    last = j == n - 1
                    t += lay_op(dop(a, j), 0 if last else g - 1, lay)
                return t + nops(20)
            body = (wi("fdtofs,0\t%dr12, %r12", "addd,1\t0x0, %dr12, %dr16",
                       "fdtofx,3\t%dr12, %dr18") + nops(6)
                    + wi("fsqrtid,5\t%dr16, %dr17") + nops(6)
                    + wi("fxsqrtixx,5\t%dr18, %dr19") + nops(16))
            for i in range(4):
                body += ostep(i)
            body += wi("rrd,0\t%clkr, %dr28")
            for i in range(4, 12):
                body += ostep(i)
            body += wi("rrd,0\t%clkr, %dr29") + nops(2) + wi("subd,0\t%dr29, %dr28, %dr0")
            func(f"dr_{lay}_{a}_g{g}_n{n}", SETUP + body)
            runs.append(f"DR (dr_{lay}_{a}_g{g}_n{n}, \"{a} {lay}\", {g}, {n})\n")
PAIRS = ([("pfsqrts1", "pfsqrts1", range(1, 15)),
          ("pfsqrts1", "fdivd", range(1, 15)),
          ("fsqrts0", "fsqrts0", range(1, 15))]
         + [(a, b, range(1, 15))
            for a in ("fsqrts", "pfsqrts", "fsqrttd", "fdivs", "fdivd",
                      "sdivd", "fxdivxx", "fxsqrtuxx", "pfdivd", "smodx")
            for b in dict.fromkeys((a, "fdivd", "fsqrts"))])
for a, b, gs in PAIRS:
    for lay in "sc":
        for g in gs:
            def pstep(i, a=a, b=b, g=g, lay=lay):
                return lay_op(dop(a, 2 * i), g - 1, lay) + lay_op(dop(b, 2 * i + 1), 15, lay)
            body = (wi("fdtofs,0\t%dr12, %r12", "addd,1\t0x0, %dr12, %dr16",
                       "fdtofx,3\t%dr12, %dr18",
                       "addd,2\t0x0, _f64,_lts0 0x3f8000003f800000, %dr20") + nops(6)
                    + wi("fsqrtid,5\t%dr16, %dr17") + nops(6)
                    + wi("fxsqrtixx,5\t%dr18, %dr19") + nops(16))
            for i in range(4):
                body += pstep(i)
            body += wi("rrd,0\t%clkr, %dr28")
            for i in range(4, 16):
                body += pstep(i)
            body += wi("rrd,0\t%clkr, %dr29") + nops(2) + wi("subd,0\t%dr29, %dr28, %dr0")
            func(f"dp_{lay}_{a}_{b}_g{g}", SETUP + body)
            runs.append(f"DP (dp_{lay}_{a}_{b}_g{g}, \"{a} -> {b} {lay}\", {g}, 0)\n")
(HERE / "timeleftv-runs.h").write_text(GEN_H + "".join(runs))
out.append("\n\t.global\ttlv_never\n\t.type\ttlv_never, #function\n\t.align\t8\ntlv_never:\n"
           + wi("setwd\twsz = 0x8, nfx = 0x1, dbl = 0x0", "return\t%ctpr3")
           + nops(6) + wi("ct\t%ctpr3") + "\t.size\ttlv_never, .-tlv_never\n")
(HERE / "timeleftv.s").write_text("".join(out))
(HERE / "timeleftv-cases.h").write_text(GEN_H + "".join(cases))
print(len(cases), "cases")
