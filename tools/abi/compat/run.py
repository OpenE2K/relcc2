"""Build and run the ABI compatibility tests for every compiler pair.

For each unit generated by gen.py and each ordered pair of compilers
(caller, callee), the caller file is built by the first compiler, the callee
file by the second, and both are linked with main.c by the reference
compiler (lcc). The program runs under RUNNER (by default MCST's qemu-e2k
user mode) or, with --remote, on an Elbrus machine over SSH. A program
that doesn't finish is rerun one test at a time to find the tests that
crash.

Usage:
  run.py GENDIR [-o OUTDIR] [--target T] [--cc NAME=COMMAND]...
         [--cxx NAME=COMMAND]...
         [--runner COMMAND | --remote [USER@]HOST [--ssh-key FILE]
          [--ssh-port N] [--remote-dir DIR] [--remote-jobs N]]
         [--pairs CALLER:CALLEE,...] [--known FILE] [-j N]

Failures listed in known.txt (known differences of the reference
compilers) are counted separately; any other failure makes the exit
status 1.

--target picks lcc by the suffix of its installed directory,
/opt/mcst/lcc-1.29.16.e2k-TARGET.linux-6.1 (default v5.8c2; use v3 for
code that runs on every CPU). Without /opt/mcst the lcc unpacked by
fetch-lcc.sh in toolchains/lcc-1.29.16-e2k-v5 is used, for v5 only. The
ISA version in TARGET also sets Unipro's -march and qemu-e2k's -cpu.

Default compilers: lcc at -O2 and, if toolchains/unipro is installed,
unipro at -O2. --cc adds a compiler or replaces one of the same name;
COMMAND is a shell-style command line that accepts -c FILE -o OUT. Use
--pairs to limit the pairs, e.g.
--cc gcc='...' --pairs lcc:gcc,gcc:lcc,gcc:gcc

C++ units (gen.py writes them as .cc files) are built with each
compiler's C++ command: lcc's l++ and Unipro's clang by default, others
from --cxx NAME=COMMAND. They are linked with l++ and skipped for a pair
whose compiler has no C++ command.

With --remote the programs are copied to REMOTE_DIR on HOST (default
relcc2/compat in the remote home) and run there, at most --remote-jobs at
a time (default 4: the test machines are shared). The SSH key defaults to
secrets/id_ed25519 when it exists. -j still sets local compile jobs.
"""

import argparse
import concurrent.futures as cf
import itertools
import json
import os
import re
import shlex
import shutil
import subprocess
import sys
import tempfile
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
LCC_VERSION = "1.29.16"
UNIPRO = ROOT / "toolchains" / "unipro" / "bin" / "clang"
SSH_KEY = ROOT / "secrets" / "id_ed25519"

# Set by find_lcc().
LCC = None
SYSROOT = None
ENV = dict(os.environ)


def find_lcc(target):
    """Return (lcc binary, sysroot) for TARGET, e.g. v3 or v5.8c2."""
    opt = Path(f"/opt/mcst/lcc-{LCC_VERSION}.e2k-{target}.linux-6.1")
    if opt.is_dir():
        return opt / "bin" / "lcc", opt / "fs"
    local = ROOT / "toolchains" / f"lcc-{LCC_VERSION}-e2k-v5"
    if isa_version(target) == 5 and (local / "lcc").exists():
        found = sorted((local / "opt" / "mcst").glob("lcc-*/fs"))
        return local / "lcc", found[0] if found else None
    sys.exit(f"no lcc for target {target}: {opt} does not exist")


def isa_version(target):
    m = re.match(r"v(\d+)", target)
    if not m:
        sys.exit(f"bad target {target}: expected vN[.MODEL]")
    return int(m.group(1))


def default_compilers(target):
    compilers = {"lcc": f"{LCC} -std=gnu11 -O2"}
    if UNIPRO.exists():
        # Unipro's clang uses the host's headers unless given a sysroot.
        compilers["unipro"] = (
            f"{UNIPRO} --target=e2k64-linux "
            f"-march=elbrus-v{isa_version(target)} --sysroot={SYSROOT} "
            f"-Wno-bad-lcc -std=gnu11 -O2")
    return compilers


def default_cxx(target):
    compilers = {"lcc": f"{LCC.parent / 'l++'} -O2"}
    if UNIPRO.exists():
        compilers["unipro"] = default_compilers(target)["unipro"].replace(
            "-std=gnu11", "-std=gnu++17")
    return compilers


def default_runner(target):
    qemu = ROOT / "toolchains" / "qemu-mcst" / "bin" / "qemu-e2k"
    if not qemu.exists():
        qemu = "qemu-e2k"
    return f"{qemu} -cpu elbrus-v{isa_version(target)} -L {SYSROOT}"


def sh(cmd, timeout=None, stdin=None):
    r = subprocess.run(cmd, capture_output=True, text=True, env=ENV,
                       timeout=timeout, stdin=stdin)
    return r.returncode, r.stdout + r.stderr


class Local:
    """Run programs on this host under a runner such as qemu-e2k."""

    def __init__(self, runner):
        self.runner = shlex.split(runner)

    def upload(self, bindir):
        pass

    def close(self):
        pass

    def run(self, prog, args, timeout):
        """Return (exit status, output); status -1 means a timeout."""
        try:
            return sh(self.runner + [str(prog)] + args, timeout)
        except subprocess.TimeoutExpired:
            return -1, ""


class Remote:
    """Run programs on an Elbrus machine over SSH. One master connection
    is shared by all runs."""

    def __init__(self, host, key, remote_dir, outdir, port=None):
        self.host, self.dir, self.outdir = host, remote_dir, outdir
        # A socket path must be short (about 100 bytes), so it can't live
        # in OUTDIR.
        self.sockdir = tempfile.mkdtemp(prefix="relcc2-ssh-",
                                        dir=os.environ.get("XDG_RUNTIME_DIR"))
        self.ssh = ["ssh", "-o", "BatchMode=yes",
                    "-o", "ControlMaster=auto",
                    "-o", f"ControlPath={self.sockdir}/%C",
                    "-o", "ControlPersist=60"]
        if key:
            self.ssh += ["-i", str(key), "-o", "IdentitiesOnly=yes"]
        if port:
            self.ssh += ["-o", f"Port={port}"]

    def remote(self, command, timeout=None, stdin=None):
        rc, out = sh(self.ssh + [self.host, command], timeout, stdin)
        if rc == 255:
            sys.exit(f"ssh {self.host} failed:\n{out[-2000:]}")
        return rc, out

    def upload(self, bindir):
        d = shlex.quote(self.dir)
        tar = subprocess.Popen(["tar", "-c", "-C", str(bindir.parent),
                                bindir.name], stdout=subprocess.PIPE)
        rc, out = self.remote(f"rm -rf {d}/{bindir.name} && mkdir -p {d} && "
                              f"tar -x -C {d}", stdin=tar.stdout)
        tar.wait()
        if rc or tar.returncode:
            sys.exit(f"upload to {self.host} failed:\n{out[-2000:]}")

    def close(self):
        sh(self.ssh + ["-O", "exit", self.host])
        shutil.rmtree(self.sockdir, ignore_errors=True)

    def run(self, prog, args, timeout):
        rel = prog.relative_to(self.outdir)
        cmd = " ".join(["cd", shlex.quote(self.dir), "&&", "timeout", "-s",
                        "KILL", str(timeout), "./" + shlex.quote(str(rel))]
                       + [shlex.quote(a) for a in args])
        try:
            rc, out = self.remote(cmd, timeout + 30)
        except subprocess.TimeoutExpired:
            return -1, ""
        # timeout(1) exits with 128 + SIGKILL.
        return (-1 if rc == 137 else rc), out


def compile_one(cc_cmd, src, obj):
    obj.parent.mkdir(parents=True, exist_ok=True)
    rc, out = sh(shlex.split(cc_cmd) + ["-I", str(src.parent), "-c", str(src),
                                        "-o", str(obj)])
    return rc == 0, out


def load_known(path):
    known = []
    for line in path.read_text().splitlines():
        line = line.split("#", 1)[0].split()
        if line:
            cc, role, rx = line
            known.append((cc, role, re.compile(rx)))
    return known


def is_known(known, caller, callee, test):
    def match(cc, name):
        return name == cc or name.startswith(cc + "-")
    return any(rx.search(test) and
               (role == "caller" and match(cc, caller) or
                role == "callee" and match(cc, callee))
               for cc, role, rx in known)


def parse(out):
    fails = set()
    done = False
    for line in out.splitlines():
        if line.startswith("FAIL "):
            _, name, arg = line.split()
            fails.add((name, int(arg)))
        elif line.startswith("DONE "):
            done = True
    return fails, done


def run_prog(host, prog, names, timeout, test_timeout):
    """Return {test name: list of failures} where a failure is an argument
    index, -1/-2 for results, 'crash' or 'timeout'."""
    rc, out = host.run(prog, [], timeout)
    fails, done = parse(out)
    result = defaultdict(list)
    if done and rc == 0:
        for name, arg in fails:
            result[name].append(arg)
        return result
    # Rerun each test alone to find the ones that crash.
    for i, name in enumerate(names):
        rc, out = host.run(prog, [str(i)], test_timeout)
        fails, done = parse(out)
        for _, arg in fails:
            result[name].append(arg)
        if not done or rc != 0:
            result[name].append("timeout" if rc == -1 else "crash")
    return result


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("gendir", type=Path)
    ap.add_argument("-o", "--outdir", type=Path,
                    default=ROOT / "toolchains" / "compat")
    ap.add_argument("--target", default="v5.8c2",
                    help="lcc target directory suffix (default v5.8c2)")
    ap.add_argument("--cc", action="append", metavar="NAME=COMMAND")
    ap.add_argument("--cxx", action="append", metavar="NAME=COMMAND")
    where = ap.add_mutually_exclusive_group()
    where.add_argument("--runner", default=None)
    where.add_argument("--remote", metavar="[USER@]HOST")
    ap.add_argument("--ssh-key", type=Path,
                    default=SSH_KEY if SSH_KEY.exists() else None)
    ap.add_argument("--ssh-port", type=int)
    ap.add_argument("--remote-dir", default="relcc2/compat")
    ap.add_argument("--remote-jobs", type=int, default=4)
    ap.add_argument("--pairs", help="CALLER:CALLEE,... (default: all)")
    ap.add_argument("--known", type=Path,
                    default=Path(__file__).resolve().parent / "known.txt")
    ap.add_argument("--timeout", type=int, default=60,
                    help="seconds for a whole unit")
    ap.add_argument("--test-timeout", type=int, default=10,
                    help="seconds for one test when a unit is rerun")
    ap.add_argument("-j", "--jobs", type=int, default=os.cpu_count())
    args = ap.parse_args()

    global LCC, SYSROOT
    LCC, SYSROOT = find_lcc(args.target)
    # Unipro's clang runs "lcc" from PATH to find libraries; give it ours.
    ENV["PATH"] = f"{LCC.parent}:{ENV.get('PATH', '')}"
    compilers = default_compilers(args.target)
    compilers.update(c.split("=", 1) for c in args.cc or [])
    cxx = {name: cmd for name, cmd in default_cxx(args.target).items()
           if name in compilers}
    cxx.update(c.split("=", 1) for c in args.cxx or [])
    units = (args.gendir / "units").read_text().split()
    is_cxx = {u: (args.gendir / f"{u}_caller.cc").exists() for u in units}
    if args.pairs:
        pairs = [tuple(p.split(":")) for p in args.pairs.split(",")]
    else:
        pairs = list(itertools.product(compilers, repeat=2))
    out = args.outdir.resolve()
    out.mkdir(parents=True, exist_ok=True)
    if args.remote:
        host = Remote(args.remote, args.ssh_key, args.remote_dir, out,
                      args.ssh_port)
        run_jobs = args.remote_jobs
    else:
        host = Local(args.runner or default_runner(args.target))
        run_jobs = args.jobs

    with cf.ThreadPoolExecutor(args.jobs) as pool:
        # Compile.
        jobs = {}
        main_obj = out / "obj" / "main.o"
        jobs[pool.submit(compile_one, f"{LCC} -O2", args.gendir / "main.c",
                         main_obj)] = ("lcc", "main")
        for cc, unit, side in itertools.product(compilers, units,
                                                ("caller", "callee")):
            if is_cxx[unit] and cc not in cxx:
                continue
            src = args.gendir / f"{unit}_{side}.{'cc' if is_cxx[unit] else 'c'}"
            obj = out / "obj" / cc / f"{unit}_{side}.o"
            cmd = cxx[cc] if is_cxx[unit] else compilers[cc]
            jobs[pool.submit(compile_one, cmd, src, obj)] = (cc, f"{unit}_{side}")
        broken = set()
        for fut in cf.as_completed(jobs):
            ok, log = fut.result()
            if not ok:
                broken.add(jobs[fut])
                print(f"compile failed: {jobs[fut][0]} {jobs[fut][1]}\n{log[-2000:]}",
                      file=sys.stderr)
        if ("lcc", "main") in broken:
            sys.exit(1)

        # Link.
        def link(unit, caller, callee):
            if is_cxx[unit] and (caller not in cxx or callee not in cxx):
                return "skip"
            if (caller, f"{unit}_caller") in broken or \
                    (callee, f"{unit}_callee") in broken:
                return None
            prog = out / "bin" / f"{caller}--{callee}" / unit
            prog.parent.mkdir(parents=True, exist_ok=True)
            driver = LCC.parent / "l++" if is_cxx[unit] else LCC
            rc, log = sh([str(driver), str(main_obj),
                          str(out / "obj" / caller / f"{unit}_caller.o"),
                          str(out / "obj" / callee / f"{unit}_callee.o"),
                          "-o", str(prog)])
            if rc:
                print(f"link failed: {unit} {caller}->{callee}\n{log[-2000:]}",
                      file=sys.stderr)
                return None
            return prog

        links = {pool.submit(link, u, a, b): (u, a, b)
                 for u in units for a, b in pairs}
        progs = {links[fut]: fut.result() for fut in cf.as_completed(links)}

    # Run.
    def run(key, prog):
        names = (args.gendir / f"{key[0]}.tests").read_text().split()
        return len(names), run_prog(host, prog, names, args.timeout,
                                    args.test_timeout)

    results = {}
    try:
        host.upload(out / "bin")
        with cf.ThreadPoolExecutor(run_jobs) as pool:
            runs = {pool.submit(run, k, p): k for k, p in progs.items()
                if p and p != "skip"}
            for fut in cf.as_completed(runs):
                results[runs[fut]] = fut.result()
    finally:
        host.close()

    # Report.
    known = load_known(args.known) if args.known.exists() else []
    report = {}
    unexpected = 0
    pair_names = [f"{a}->{b}" for a, b in pairs]
    width = max(len(p) for p in pair_names) + 12
    print(f"{'unit':12}" + "".join(f"{p:>{width}}" for p in pair_names))
    for u in units:
        row = f"{u:12}"
        for (a, b), pn in zip(pairs, pair_names):
            r = results.get((u, a, b))
            if progs.get((u, a, b)) == "skip":
                row += f"{'skip':>{width}}"
                continue
            if r is None:
                row += f"{'error':>{width}}"
                unexpected += 1
                continue
            total, fails = r
            entry = report.setdefault(pn, {}).setdefault(
                u, {"total": total, "known": {}, "unexpected": {}})
            for name, what in sorted(fails.items()):
                kind = "known" if is_known(known, a, b, f"{u}/{name}") else "unexpected"
                entry[kind][name] = sorted(map(str, what))
            nk, nu = len(entry["known"]), len(entry["unexpected"])
            unexpected += nu
            cell = f"{total - nk - nu}/{total}" + (f" ({nk} known)" if nk else "")
            row += f"{cell:>{width}}"
        print(row)
    (out / "results.json").write_text(json.dumps(report, indent=1) + "\n")
    for pn in pair_names:
        bad = {u: e["unexpected"] for u, e in report.get(pn, {}).items()
               if e["unexpected"]}
        if not bad:
            continue
        print(f"\nunexpected, {pn}:")
        for u, fails in bad.items():
            for name, what in fails.items():
                print(f"  {u}/{name}: {' '.join(what)}")
    print(f"\n{unexpected} unexpected failures; full results: "
          f"{out / 'results.json'}")
    sys.exit(1 if unexpected else 0)


if __name__ == "__main__":
    main()
