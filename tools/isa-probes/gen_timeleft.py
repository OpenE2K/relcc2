# Read-modify-writes: 16 on 16 cache lines (as pocchk2.c t_atom_*), the
# lock-wait load (MAS 0x7), K empty cycles, the store with MAS M and
# rbranch back to the load.
def atom(name, k, smas, kind):
    body = wi("addd,0\t0x0, 0x5, %dr22") + nops(8) + wi("rrd,0\t%clkr, %dr28")
    for i in range(16):
        lbl = f".L{name}_{i}"
        off = f"{64 * i:#x}"
        body += f"{lbl}:\n" + wi(f"ldd,0\t%dr0, {off}, %dr20, mas=0x7") + nops(k)
        data = "%dr22"
        if kind == "add":
            body += wi("addd,0\t%dr20, 0x1, %dr21")
            data = "%dr21"
        body += wi(f"std,2\t%dr0, {off}, {data}, mas={smas}", f"rbranch\t{lbl}")
    body += wi("rrd,0\t%clkr, %dr29") + nops(2) + wi("subd,0\t%dr29, %dr28, %dr0")
    func(name, body, part="v6")
    cases["v6"].append(f"V6A ({name}, \"{kind} {smas} k{k}\", 16)\n")


