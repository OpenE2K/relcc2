"""Write fpenv.s, fpenv-v6.s and fpenv-ops.h for fpenv.c: ordinary
(non-80-bit) FP operations under every %pfpfr control setting, i.e. the
four rounding modes, flush to zero (bit 15, fz) and denormals are zero
(bit 6, daz) (spec/isa/semantics.md; check_fpenv.c recomputes every line
with SSE on an x86 host, whose MXCSR has %pfpfr's layout).

  python3 tools/isa-probes/gen_fpenv.py

Each function is  void fe_N(const u64 in[10], u64 out[2], u64 ctl): it
saves %pfpfr, loads the inputs (doubles in[0..2] into %dr3..%dr5,
floats in[3..5] into %dr9..%dr11, a 64-bit integer in[6] into %dr12, a
32-bit one in[7] into %dr13, packed singles in[8..9] into %dr14..%dr15),
presets %dr6 to 0x5555555555555555, writes ctl (masks, rounding, fz,
daz; no flags) to %pfpfr, runs the operation, and stores %dr6 in out[0]
and %pfpfr in out[1], then restores %pfpfr.
"""

from pathlib import Path

HERE = Path(__file__).resolve().parent

# name, operation text (destination %dr6 / %r6), result width, model
# key for check_fpenv.c, ISA (3 or 6).
OPS = [
    ("faddd", ["faddd,0\t%dr3, %dr4, %dr6"], 64),
    ("fsubd", ["fsubd,0\t%dr3, %dr4, %dr6"], 64),
    ("fmuld", ["fmuld,0\t%dr3, %dr4, %dr6"], 64),
    ("fdivd", ["fdivd,5\t%dr3, %dr4, %dr6"], 64),
    ("fsqrtd", ["fsqrtid,5\t%dr3, %dr7", "nop 7", "nop 7",
                "fsqrttd,5\t%dr3, %dr7, %dr6"], 64),
    ("fmaxd", ["fmaxd,0\t%dr3, %dr4, %dr6"], 64),
    ("fcmpltd", ["fcmpltd,0\t%dr3, %dr4, %dr6"], 64),
    ("fcmpeqd", ["fcmpeqd,0\t%dr3, %dr4, %dr6"], 64),
    ("fmul_addd", ["fmul_addd,0\t%dr3, %dr4, %dr5, %dr6"], 64),
    ("fadds", ["fadds,0\t%r9, %r10, %r6"], 32),
    ("fsubs", ["fsubs,0\t%r9, %r10, %r6"], 32),
    ("fmuls", ["fmuls,0\t%r9, %r10, %r6"], 32),
    ("fdivs", ["fdivs,5\t%r9, %r10, %r6"], 32),
    ("fsqrts", ["fsqrts,5\t%r9, %r6"], 32),
    ("fmul_adds", ["fmul_adds,0\t%r9, %r10, %r11, %r6"], 32),
    ("fdtois", ["fdtois,0\t%dr3, %r6"], 32),
    ("fdtoistr", ["fdtoistr,0\t%dr3, %r6"], 32),
    ("fstois", ["fstois,0\t%r9, %r6"], 32),
    ("fdtoid", ["fdtoid,0\t%dr3, %dr6"], 64),
    ("fstoid", ["fstoid,0\t%r9, %dr6"], 64),
    ("fdtofs", ["fdtofs,0\t%dr3, %r6"], 32),
    ("fstofd", ["fstofd,0\t%r9, %dr6"], 64),
    ("idtofd", ["idtofd,0\t%dr12, %dr6"], 64),
    ("idtofs", ["idtofs,0\t%dr12, %r6"], 32),
    ("istofs", ["istofs,0\t%r13, %r6"], 32),
    ("istofd", ["istofd,0\t%r13, %dr6"], 64),
    ("pfadds", ["pfadds,0\t%dr14, %dr15, %dr6"], 64),
    ("pfsubs", ["pfsubs,0\t%dr14, %dr15, %dr6"], 64),
    ("pfmuls", ["pfmuls,0\t%dr14, %dr15, %dr6"], 64),
    ("pfaddd", ["pfaddd,0\t%dr3, %dr4, %dr6"], 64),
    ("pfmuld", ["pfmuld,0\t%dr3, %dr4, %dr6"], 64),
]
OPS6 = [
    ("fmad", ["fmad,0\t%dr3, %dr4, %dr5, %dr6"], 64),
    ("fmas", ["fmas,0\t%r9, %r10, %r11, %r6"], 32),
]


def fn(i, ops):
    w = lambda *o: "\t{\n" + "".join(f"\t  {x}\n" for x in o) + "\t}\n"
    b = w("setwd\twsz = 0x8, nfx = 0x1, dbl = 0x0", "return\t%ctpr3")
    b += w("rrs,0\t%pfpfr, %r8")
    b += w("ldd,0\t%dr0, 0x0, %dr3", "ldd,2\t%dr0, 0x8, %dr4",
           "ldd,3\t%dr0, 0x10, %dr5", "ldd,5\t%dr0, 0x18, %dr9",
           "addd,1\t0x0, _f64,_lts0 0x5555555555555555, %dr6")
    b += w("ldd,0\t%dr0, 0x20, %dr10", "ldd,2\t%dr0, 0x28, %dr11",
           "ldd,3\t%dr0, 0x30, %dr12", "ldd,5\t%dr0, 0x38, %dr13")
    b += w("ldd,0\t%dr0, 0x40, %dr14", "ldd,2\t%dr0, 0x48, %dr15")
    b += w("rws,0\t%r2, %pfpfr")
    b += w("nop 7")
    b += "".join(w(o) for o in ops)
    b += w("nop 7") + w("nop 7")
    b += w("nop 2", "rrs,0\t%pfpfr, %r7")
    b += w("std,2\t%dr1, 0x0, %dr6", "stw,5\t%dr1, 0x8, %r7")
    b += w("rws,0\t%r8, %pfpfr") + w("nop 5") + w("ct\t%ctpr3")
    return (f"\n\t.global\tfe_{i}\n\t.type\tfe_{i}, #function\n"
            f"\t.align\t8\nfe_{i}:\n{b}\t.size\tfe_{i}, .-fe_{i}\n")


def main():
    head = ("! SPDX-License-Identifier: GPL-3.0-or-later\n"
            "! Generated by tools/isa-probes/gen_fpenv.py; see fpenv.c.\n"
            "\t.ignore\tld_st_style\n\t.text\n")
    (HERE / "fpenv.s").write_text(
        head + "".join(fn(i, o[1]) for i, o in enumerate(OPS)))
    (HERE / "fpenv-v6.s").write_text(
        head + "".join(fn(100 + i, o[1]) for i, o in enumerate(OPS6)))
    (HERE / "fpenv-ops.h").write_text(
        "/* SPDX-License-Identifier: GPL-3.0-or-later */\n"
        "/* Generated by tools/isa-probes/gen_fpenv.py.  */\n"
        + "".join(f'OP ({i}, "{o[0]}", {o[2]})\n' for i, o in enumerate(OPS))
        + "#ifdef FPENV_V6\n"
        + "".join(f'OP ({100 + i}, "{o[0]}", {o[2]})\n'
                  for i, o in enumerate(OPS6))
        + "#endif\n")
    print(len(OPS), "operations,", len(OPS6), "v6")


if __name__ == "__main__":
    main()
