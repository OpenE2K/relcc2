"""Write foldisa.s and foldisa-cases.h for foldisa.c: rechecks of the
proof-of-concept back end's finding I54 in docs/spec-poc-findings.md
(whether v5's getfz*, addcd/subcd and plog results reach integer
consumers as integer or as packed results), for spec/isa/timing.md and
operations-v5.md.  foldisa.s is v5 and later; foldisa-v3.s (with
foldisa-v3-cases.h, foldisa.c built with -DFOLDISA_V3) has the v3
producers only (addd, getfd, pandd, muld), for the 4C.

  python3 tools/isa-probes/gen_foldisa.py

Latency cases  long fi_lat_P__C_gG(long *mem, long a, long b): steps,
each a producer P (into register 8 or 10, alternately), G - 1 empty
cycles, and a consumer C of P's result in an instruction with nop 3 (so
a step is G + 4 cycles when C does not stall); setwd dbl = 0.  Every
step's inputs are constants (%dr2 = 8, %dr3 = 0, %dr4 = 0, %dr7 = 8,
%qpr12 = {8, 8}), so only P -> C can stall.  4 steps warm up, then 12
run between two %clkr reads; the return value is the difference (1 +
the 12 steps' cycles).  The method of pocchk4.c's lat section.

Write-back cases  fi_wb_P__X__C_dD: as a latency case with C D cycles
after P, and X in P's channel 2 cycles after P ("none": an empty
instruction there): whether packed results suffer the write-back
conflict of FP-side ones (timing.md, "Write-back conflicts").
"""

from pathlib import Path

HERE = Path(__file__).resolve().parent
HEADER = """! SPDX-License-Identifier: GPL-3.0-or-later
! Generated by tools/isa-probes/gen_foldisa.py; see foldisa.c.
	.ignore	ld_st_style
	.ignore	strict_delay
	.text
"""
cases, text = [], []
WARM, STEPS = 4, 12
V3 = False       # writing foldisa-v3.s: no v5 operation anywhere


def wi(*ops):
    return "\t{\n" + "".join(f"\t  {o}\n" for o in ops) + "\t}\n"


def nops(n):
    out = ""
    while n > 0:
        k = min(n, 8)
        out += wi(f"nop {k - 1}" if k > 1 else "nop")
        n -= k
    return out


def func(name, body):
    fn = f"fi_{name}"
    text.append(f"\n\t.global\t{fn}\n\t.type\t{fn}, #function\n\t.align\t8\n"
                f"{fn}:\n"
                + wi("setwd\twsz = 0x20, nfx = 0x1, dbl = 0x0") + body
                + wi("return\t%ctpr3") + nops(6) + wi("ct\t%ctpr3")
                + f"\t.size\t{fn}, .-{fn}\n")


SETUP = (wi("addd,0\t0x0, 0x8, %dr2", "addd,1\t0x0, 0x0, %dr3",
            "addd,2\t0x0, 0x0, %dr4", "addd,3\t0x0, 0x8, %dr7",
            "addd,4\t0x0, 0x0, %dr20", "addd,5\t0x0, 0x0, %dr21")
         + wi("addd,0\t0x0, 0x0, %dr8", "addd,1\t0x0, 0x0, %dr10",
              "cmpesb,3\t0x0, 0x0, %pred0")
         + nops(2))
QP_SETUP = wi("qppackdl,0\t%dr2, %dr2, %qpr12")


def timed(name, step):
    body = SETUP + ("" if V3 else QP_SETUP) + nops(8)
    for i in range(WARM):
        body += step(i)
    body += wi("rrd,0\t%clkr, %dr28")
    for i in range(WARM, WARM + STEPS):
        body += step(i)
    body += wi("rrd,0\t%clkr, %dr29") + nops(2)
    body += wi("subd,0\t%dr29, %dr28, %dr0")
    func(name, body)


# Producers: {D} the 64-bit destination, {d} its 32-bit view, {Q} the
# 128-bit one.  Every result is small and 8-aligned (a load index).
PROD = {
    "addd0": "addd,0\t%dr2, %dr3, {D}",
    "getfd0": "getfd,0\t%dr2, 0xc00, {D}",
    "pandd0": "pandd,0\t%dr2, %dr7, {D}",
    # (8 >> 3 & 0xfff) & ~0xf = 0: Lua's (i >> 7 & 0xff) * 16 (I53).
    "getfzd0": "getfzd,0\t%dr2, 0x8303, {D}",
    "getfzd3": "getfzd,3\t%dr2, 0x8303, {D}",
    "getfzs0": "getfzs,0\t%r2, 0x8303, {d}",
    "addcd1": "addcd,1\t%dr2, %dr3, %r4, {D}",
    "addcd_c1": "addcd_c,1\t%dr2, %dr3, %r4, {D}",
    "subcd4": "subcd,4\t%dr2, %dr3, %r4, {D}",
    "plog0": "plog_0x80,0\t%dr2, %dr2, %dr2, {D}",
    "plog3": "plog_0x80,3\t%dr2, %dr2, %dr2, {D}",
    "plog96_1": "plog_0x96,1\t%dr2, %dr3, %dr4, {D}",
    "qplog0": "qplog_0x80,0\t%qpr12, %qpr12, %qpr12, {Q}",
    # other 1-cycle v5 operations of timing.md's table
    "psrcd0": "psrcd,0\t%dr2, %dr3, {D}",
    "qppackdl0": "qppackdl,0\t%dr2, %dr2, {Q}",
    "qpswitchd0": "qpswitchd,0\t%qpr12, {Q}",
    # the write-back control (an FP-side producer: 6, 7 with a conflict)
    "muld0": "muld,0\t%dr2, %dr7, {D}",
}

# Consumers: {s} the producer's register as 32 bits, {S} as 64 bits,
# {o} a store offset that differs every step.
CONS = {
    **{f"addd{c}": f"addd,{c}\t{{S}}, 0x1, %dr20" for c in (0, 1, 3, 4)},
    "adds0": "adds,0\t{s}, 0x1, %r20",
    "adds3": "adds,3\t{s}, 0x1, %r20",
    "lddidx0": "ldd,0\t%dr0, {S}, %dr20",
    "std2": "std,2\t%dr0, {o}, {S}",
    "std5": "std,5\t%dr0, {o}, {S}",
    "faddd0": "faddd,0\t{S}, %dr2, %dr20",
    "pandd0": "pandd,0\t{S}, %dr2, %dr20",
    "plog0": "plog_0x80,0\t{S}, %dr2, %dr2, %dr20",
    "plog3": "plog_0x80,3\t{S}, %dr2, %dr2, %dr20",
    "getfzd0": "getfzd,0\t{S}, 0x8303, %dr20",
    "cmpedb0": "cmpedb,0\t{S}, 0x1, %pred2",
}
CORE = ["addd0", "addd3", "lddidx0", "std2", "std5", "faddd0", "plog0"]
LAT = {
    "addd0": ["addd0", "addd3", "plog0", "std2", "faddd0"],
    "getfd0": ["addd0", "lddidx0"],
    "pandd0": ["addd0", "addd3", "plog0", "std2"],
    "getfzd0": CORE + ["getfzd0"],
    "getfzd3": ["addd3", "addd0"],
    "getfzs0": ["adds0", "adds3", "addd0"],
    "addcd1": CORE,
    "addcd_c1": ["addd1", "addd0", "addd3"],
    "subcd4": ["addd4", "addd3", "addd0"],
    "plog0": CORE + ["pandd0", "cmpedb0", "getfzd0"],
    "plog3": ["addd3", "addd0", "plog3", "plog0"],
    "plog96_1": ["addd1", "addd0", "addd3"],
    "qplog0": ["addd0", "addd3", "plog0", "std2"],
    "psrcd0": ["addd0", "std2"],
    "qppackdl0": ["addd0", "std2"],
    "qpswitchd0": ["addd0", "std2"],
}
GAPS = range(1, 7)


def step_text(p, c, i, g):
    r = 8 if i % 2 == 0 else 10
    pop = PROD[p].format(D=f"%dr{r}", d=f"%r{r}", Q=f"%qpr{r}")
    cop = CONS[c].format(s=f"%r{r}", S=f"%dr{r}", o=f"{8 * (i % 64):#x}")
    return wi(pop) + nops(g - 1) + wi(cop, "nop 3")


LAT_V3 = {
    "addd0": ["addd0", "addd3", "std2", "faddd0"],
    "getfd0": ["addd0", "lddidx0"],
    "pandd0": ["addd0", "addd3", "lddidx0", "std2", "std5", "faddd0",
               "pandd0"],
}


# Write-back conflicts: X in ALC0 2 cycles after a producer in ALC0.
XOPS = {
    "addd0": "addd,0\t%dr2, %dr3, %dr21",
    "ldd0": "ldd,0\t%dr0, 0x0, %dr22",
}


def wb_text(p, x, c, i, d):
    r = 8 if i % 2 == 0 else 10
    pop = PROD[p].format(D=f"%dr{r}", d=f"%r{r}", Q=f"%qpr{r}")
    cop = CONS[c].format(s=f"%r{r}", S=f"%dr{r}", o=f"{8 * (i % 64):#x}")
    xs = [XOPS[x]] if x != "none" else ["nop"]
    return wi(pop) + nops(1) + wi(*xs) + nops(d - 3) + wi(cop, "nop 3")


def generate(lat, wbp):
    for p, cs in lat.items():
        for c in cs:
            for g in GAPS:
                name = f"lat_{p}__{c}_g{g}"
                timed(name, lambda i, p=p, c=c, g=g: step_text(p, c, i, g))
                cases.append(f"LAT ({name}, \"{p} -> {c}\", {g})\n")
    for p in wbp:
        for x in ["none"] + list(XOPS):
            for d in ((6, 7) if p == "muld0" else (4, 5)):
                name = f"wb_{p}__{x}__addd1_d{d}"
                timed(name,
                      lambda i, p=p, x=x, d=d: wb_text(p, x, "addd1", i, d))
                cases.append(f"WB ({name}, \"{p} + {x} -> addd1\", {d})\n")


def write(stem):
    (HERE / f"{stem}.s").write_text(HEADER + "".join(text))
    (HERE / f"{stem}-cases.h").write_text(
        "/* SPDX-License-Identifier: GPL-3.0-or-later */\n"
        "/* Generated by tools/isa-probes/gen_foldisa.py.  */\n"
        + "".join(cases))
    print(stem, len(cases), "functions")


if __name__ == "__main__":
    generate(LAT, ("plog0", "qplog0", "pandd0", "muld0"))
    write("foldisa")
    cases.clear()
    text.clear()
    V3 = True
    generate(LAT_V3, ("pandd0", "muld0"))
    write("foldisa-v3")
