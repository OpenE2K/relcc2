# 10. Does a stall between an FP-side producer and an integer operation
# planned 2 cycles after it in the same channel (timing.md, "Write-back
# conflicts") still delay the producer's result?  Four-instruction
# loops on fixed registers (%dr21 = 1.0, %dr2 = x): fmuld,1 in I1, its
# product read by faddd,3 in I3 of the same iteration, so the faddd
# waits for it in any case.
#   mid_*: a load in I0 used in I2 (one cycle early) stalls I2 for 4,
#          so I3 issues 6 cycles after the fmuld (the product is due);
#   own_*: nothing stalls before I3, whose faddd itself waits 4;
#   *_conf: addd,1 in I3 (2 cycles after the fmuld as written);
#   *_none: no addd,1; mid_i2: addd,1 in I2 (1 cycle after);
#   own_same: the product read by faddd,0 (the fmuld's cluster) instead.
def raw_case(name, instrs):
    fn = f"sb_{name}"
    body = wi("setwd\twsz = 0x10, nfx = 0x1, dbl = 0x0",
              "setbn\trsz = 0x3, rbs = 0x8, rcur = 0x0", "return\t%ctpr3")
    body += wi("ldd,0\t%dr1, 0x0, %dr2", "ldd,2\t%dr1, 0x8, %dr3",
               "ldd,3\t%dr1, 0x10, %dr4", f"disp\t%ctpr1, {fn}_loop")
    body += wi("addd,0\t0x0, _f64,_lts0 0x3ff0000000000000, %dr21",
               "addd,1\t0x0, 0x0, %dr26", "addd,3\t0x0, 0x0, %dr20",
               "addd,4\t0x0, 0x0, %dr23")
    body += wi("addd,0\t%dr0, 0x0, %dr9")
    body += wi(f"ord,0\t%dr9, _f64,_lts0 {VLC | LDOVL:#x}, %dr9")
    body += wi("rwd,0\t%dr9, %lsr")
    body += wi("nop 5")
    body += wi("rrd,0\t%clkr, %dr10")
    body += wi("ct\t%ctpr1")
    loop = ""
    for c, ops in enumerate(instrs):
        ctl = (["alc\talcf=1, alct=1", "ct\t%ctpr1 ? %NOT_LOOP_END"]
               if c == len(instrs) - 1 else [])
        loop += wi(*ctl, *ops) if (ctl or ops) else wi("nop")
    body += f"\t.balign\t1024\n{fn}_loop:\n" + loop
    body += wi("rrd,0\t%clkr, %dr11")
    body += wi("subd,0\t%dr11, %dr10, %dr0")
    body += wi("ct\t%ctpr3")
    text.append(f"\n\t.balign\t1024\n\t.global\t{fn}\n\t.type\t{fn}, "
                f"#function\n{fn}:\n{body}\t.size\t{fn}, .-{fn}\n")
    cases.append((name, 0, 0, 8))


