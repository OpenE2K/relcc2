def w_call(n, kind):
    """The prepare (or none), then a call to cl_leaf (a cold function of
    its own page in modes 1-3), then N divides and disp + ct to T."""
    def w(t):
        back = ".L" + t[3:-2] + "_back"
        first = {"late": [T0], "pref": [T0, f"pref\t%ipr0, {t}"],
                 "disp": [T0, f"disp\t%ctpr3, {t}"]}[kind]
        return (wi(*first) + wi("disp\t%ctpr1, cl_leaf") + nops(4)
                + wi("call\t%ctpr1, wbs = 0x1c")
                + wi(f"disp\t%ctpr2, {back}")
                + "".join(wi(DIV) for _ in range(n))
                + wi(f"disp\t%ctpr1, {t}") + nops(4) + wi("ct\t%ctpr1"))
    return w


