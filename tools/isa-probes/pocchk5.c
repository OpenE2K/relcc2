#define NDS (sizeof dspec / sizeof dspec[0])
#define NSS (sizeof sspec / sizeof sspec[0])
#define NRAND 200

static u64 dval[NDS + NRAND];
static u32 sval[NSS + NRAND];

static void
make_values (void)
{
  memcpy (dval, dspec, sizeof dspec);
  memcpy (sval, sspec, sizeof sspec);
  for (int i = 0; i < NRAND; i++)
    {
      /* exponents -3 .. 60 (double), -3 .. 28 (single), both signs */
      u64 s = (u64) (lcg () & 1) << 63;
      u64 e = 1023 - 3 + lcg () % 64;
      u64 m = ((u64) lcg () << 31 ^ lcg ()) & ((1UL << 52) - 1);
      dval[NDS + i] = s | e << 52 | m;
      u32 ss = (lcg () & 1) << 31, es = 127 - 3 + lcg () % 32;
      sval[NSS + i] = ss | es << 23 | (lcg () & ((1u << 23) - 1));
    }
}

static int
flags (void)
{
  return fetestexcept (FL);
}

/* Expected flags of an fdtoifd-style rounding with immediate IMM.  */
static int
want_flags (int imm, int inx, int inv)
{
  return (inv ? FE_INVALID : 0) | (inx && !(imm & 8) ? FE_INEXACT : 0);
}

static int
imm_mode (int imm, int cur)
{
  return imm & 4 ? cur : imm & 3;
}

static int nshown;
static void
show (const char *what, int imm, u64 x, u64 got, int gfl, u64 want, int wfl)
{
  if (nshown++ < 12)
    printf ("    %s imm %#x x %016lx: %016lx fl %#x, want %016lx fl %#x\n",
            what, imm, x, got, gfl, want, wfl);
}

/* The hardware forms in mode M.  */
static void
round_hw (int m)
{
  fesetround (modes[m]);
  long n = 0, bad = 0;
  nshown = 0;
  for (int imm = 0; imm < 16; imm++)
    {
      int r = imm_mode (imm, m);
      for (unsigned i = 0; i < NDS + NRAND; i++)
        {
          int inx, inv;
          u64 w = model (dval[i], 64, r, &inx, &inv);
          feclearexcept (FL);
          u64 g = p5_rnd_d (imm, dval[i]);
          int f = flags (), wf = want_flags (imm, inx, inv);
          n++;
          if (g != w || f != wf)
            bad++, show ("fdtoifd", imm, dval[i], g, f, w, wf);
        }
      for (unsigned i = 0; i < NSS + NRAND; i++)
        {
          int inx, inv;
          u64 w = model (sval[i], 32, r, &inx, &inv);
          feclearexcept (FL);
          u64 g = p5_rnd_s (imm, sval[i]) & 0xffffffff;
          int f = flags (), wf = want_flags (imm, inx, inv);
          n++;
          if (g != w || f != wf)
            bad++, show ("fstoifs", imm, sval[i], g, f, w, wf);
        }
      for (unsigned i = 0; i < NSS + NRAND; i++)
        {
          int inx0, inv0, inx1, inv1;
          u32 lo = sval[i], hi = sval[(i * 7 + 3) % (NSS + NRAND)];
          u64 x = (u64) hi << 32 | lo;
          u64 w = model (hi, 32, r, &inx1, &inv1) << 32
                  | model (lo, 32, r, &inx0, &inv0);
          feclearexcept (FL);
          u64 g = p5_rnd_ps (imm, x);
          int f = flags ();
          int wf = want_flags (imm, inx0, inv0) | want_flags (imm, inx1, inv1);
          n++;
          if (g != w || f != wf)
            bad++, show ("pfstoifs", imm, x, g, f, w, wf);
        }
    }
  printf ("round hw %-7s: %ld cases, %ld differ from the model\n",
          mname[m], n, bad);
}

typedef double (*dfn) (double);
typedef float (*sfn) (float);
static struct
{
  const char *name;
  dfn d;
  sfn s;
  int r;                        /* model rounding, -1: the current mode */
} lib[] = {
  { "floor", floor, floorf, 1 }, { "ceil", ceil, ceilf, 2 },
  { "trunc", trunc, truncf, 3 }, { "roundeven", roundeven, roundevenf, 0 },
  { "round", round, roundf, 4 }, { "rint", rint, rintf, -1 },
  { "nearbyint", nearbyint, nearbyintf, -1 },
};
#define NLIB (sizeof lib / sizeof lib[0])

/* glibc's function K in mode M, called with the flags clear, or with
   every flag set when PRESET (values only: MCST's libm computes some of
   these with speculative FP operations, which give diagnostic values
   when a flag they would raise is clear).  */
static fexcept_t all_set;
static int preset;

static void
before_call (void)
{
  feclearexcept (FL);
  if (preset)
    fesetexceptflag (&all_set, FL);
}

static void
round_lib (int k, int m)
{
  fesetround (modes[m]);
  int r = lib[k].r < 0 ? m : lib[k].r;
  long n = 0, bad = 0, nonint = 0, inexact = 0, badfl = 0;
  dfn volatile fd = lib[k].d;
  sfn volatile fs = lib[k].s;
  nshown = 0;
  for (unsigned i = 0; i < NDS + NRAND; i++)
    {
      int inx, inv;
      u64 w = model (dval[i], 64, r, &inx, &inv), g;
      double x, y;
      memcpy (&x, &dval[i], 8);
      before_call ();
      y = fd (x);
      int f = flags ();
      memcpy (&g, &y, 8);
      n++;
      nonint += inx;
      inexact += inx && (f & FE_INEXACT);
      int wf = (inv ? FE_INVALID : 0);
      if (g != w)
        bad++, show (lib[k].name, -1, dval[i], g, f, w, wf);
      if (!preset && ((f & ~FE_INEXACT) != wf || (!inx && (f & FE_INEXACT))))
        badfl++, show (lib[k].name, -2, dval[i], g, f, w, wf);
    }
  for (unsigned i = 0; i < NSS + NRAND; i++)
    {
      int inx, inv;
      u64 w = model (sval[i], 32, r, &inx, &inv);
      u32 g;
      float x, y;
      memcpy (&x, &sval[i], 4);
      before_call ();
      y = fs (x);
      int f = flags ();
      memcpy (&g, &y, 4);
      n++;
      nonint += inx;
      inexact += inx && (f & FE_INEXACT);
      int wf = (inv ? FE_INVALID : 0);
      if (g != w)
        bad++, show (lib[k].name, -3, sval[i], g, f, w, wf);
      if (!preset && ((f & ~FE_INEXACT) != wf || (!inx && (f & FE_INEXACT))))
        badfl++, show (lib[k].name, -4, sval[i], g, f, w, wf);
    }
  if (preset)
    printf ("round lib %-9s %-7s, flags set: %ld cases, %ld values differ\n",
            lib[k].name, mname[m], n, bad);
  else
    printf ("round lib %-9s %-7s: %ld cases, %ld values and %ld other flags"
            " differ; inexact on %ld of %ld non-integral\n",
            lib[k].name, mname[m], n, bad, badfl, inexact, nonint);
}

static void
child (void (*f) (int, int), int a, int b, const char *what)
{
  fflush (stdout);
  pid_t p = fork ();
  if (p == 0)
    {
      f (a, b);
      fflush (stdout);
      _exit (0);
    }
  int st;
  waitpid (p, &st, 0);
  if (WIFSIGNALED (st))
    printf ("%s: killed by signal %d\n", what, WTERMSIG (st));
}

static void
round_hw2 (int m, int unused)
{
  (void) unused;
  round_hw (m);
}

static void
round_lib2 (int k, int m)
{
  round_lib (k, m);
}

static void
section_round (void)
{
  for (int m = 0; m < 4; m++)
    child (round_hw2, m, 0, "round hw");
  feraiseexcept (FL);
  fegetexceptflag (&all_set, FL);
  feclearexcept (FL);
  for (preset = 0; preset < 2; preset++)
    for (unsigned k = 0; k < NLIB; k++)
      for (int m = 0; m < 4; m++)
        {
          char what[64];
          snprintf (what, sizeof what, "round lib %s %s%s", lib[k].name,
                    mname[m], preset ? ", flags set" : "");
          child (round_lib2, k, m, what);
        }
  fesetexceptflag (&all_set, FL);
}

/* Square roots.  */
static void
sqrt_mode (int m, int unused)
{
  (void) unused;
  fesetround (modes[m]);
  long n = 0, bad = 0, badinv = 0;
  dfn volatile fd = sqrt;
  sfn volatile fs = sqrtf;
  nshown = 0;
  for (unsigned i = 0; i < NDS + NRAND + 64; i++)
    {
      u64 x = i < NDS + NRAND ? dval[i]
              : (u64) (lcg () & 1) << 63 | (u64) (lcg () % 2046 + 1) << 52
                | (((u64) lcg () << 31 ^ lcg ()) & ((1UL << 52) - 1));
      double xd, yd;
      u64 g, w;
      memcpy (&xd, &x, 8);
      feclearexcept (FL);
      g = p5_sqrt_d (x);
      int f = flags ();
      int nan = (x & 0x7ff0000000000000) == 0x7ff0000000000000
                && (x & 0xfffffffffffff);
      int neg = (x >> 63) && (x << 1) != 0 && !nan;
      int snan = nan && !(x & 0x8000000000000);
      int winv = neg || snan;
      feraiseexcept (FL);
      yd = fd (xd);
      memcpy (&w, &yd, 8);
      n++;
      if (g != w)
        bad++, show ("sqrt", -1, x, g, f, w, 0);
      if (!!(f & FE_INVALID) != winv)
        badinv++, show ("sqrt inv", -1, x, g, f, w, winv);
    }
  for (unsigned i = 0; i < NSS + NRAND + 64; i++)
    {
      u32 x = i < NSS + NRAND ? sval[i]
              : (lcg () & 1) << 31 | (lcg () % 254 + 1) << 23
                | (lcg () & ((1u << 23) - 1));
      float xf, yf;
      u32 g, w;
      memcpy (&xf, &x, 4);
      feclearexcept (FL);
      g = p5_sqrt_s (x) & 0xffffffff;
      int f = flags ();
      int nan = (x & 0x7f800000) == 0x7f800000 && (x & 0x7fffff);
      int neg = (x >> 31) && (x << 1) != 0 && !nan;
      int snan = nan && !(x & 0x400000);
      int winv = neg || snan;
      feraiseexcept (FL);
      yf = fs (xf);
      memcpy (&w, &yf, 4);
      n++;
      if (g != w)
        bad++, show ("sqrtf", -1, x, g, f, w, 0);
      if (!!(f & FE_INVALID) != winv)
        badinv++, show ("sqrtf inv", -1, x, g, f, w, winv);
    }
  printf ("sqrt %-7s: %ld cases, %ld results differ from glibc's, "
          "%ld invalid flags differ from negative-or-sNaN\n",
          mname[m], n, bad, badinv);
}

static void
section_sqrt (void)
{
  for (int m = 0; m < 4; m++)
    child (sqrt_mode, m, 0, "sqrt");
}

