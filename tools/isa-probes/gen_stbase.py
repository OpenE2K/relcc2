"""Write stbase.s and stbase-cases.h for stbase.c: pipelined daxpy
kernels (y[i] += a * x[i], four elements an iteration, II 4) that differ
in one thing at a time, for the proof-of-concept back end's finding I35
(docs/spec-poc-findings.md): the same kernel ran 4.78 or 6.13 cycles an
iteration on the 8C2 depending on which instance of the y pointer its
stores read.

  python3 tools/isa-probes/gen_stbase.py

Every function is  long sb_NAME (long n, long *p)  with p[0] = x,
p[1] = y, p[2] = the bits of a.  It runs n iterations of the kernel
(plus the pipeline's fill) and returns the %clkr cycles of the loop.

A kernel is a modulo schedule written as a table: each operation has
an issue time t counted from its iteration's start (kernel instruction
t % 4, stage t // 4) and a channel.  The generator gives every value a
set of rotating registers (an instance read r iterations after it was
written is %b[base + 2r]; loops.md, "Rotation"), initialises the
pointer instances the first iterations read, and computes each memory
offset from the pointer instance it reads: a pointer instance written
by iteration h holds ARRAY + bias + 32 (h + 1), so an access of
iteration g to element j through the instance of iteration g - d has
offset 8j + 32 (d - 1) - bias (d is the "age" of the instance, negative
for an instance a later iteration wrote).

The base schedules are the two kernels of I35, as read from the
finding's description and the proof-of-concept's assembly (the same
operations, times and channels; register numbers are this generator's):

  plain    stores through the y pointer written 4 iterations earlier
           (std %b[..], -32 ...)
  rebased  stores through the instance written 1 iteration earlier
           (I1, offsets -128, -120) or in the same iteration (I3,
           -144, -136), and the bundler's other channels: fmuld 0 in
           ALC1 (plain ALC4), faddd 2 in ALC3 (ALC1), faddd 3 in ALC4
           (ALC3), the y pointer's addd in ALC4 (ALC1), the x
           pointer's addd in ALC1 (ALC4).

The other kernels change one thing at a time (the groups below): the
store bases' age, offsets and register kind, the number of stores,
loop_mode, ,sm, and the channels.  What they showed (4C, 8C2; the l5_
kernels on the 2C3 too): only the channels matter.  In the rebased
kernel the x pointer's addd in ALC1 comes 2 cycles after fmuld 2 in
ALC1, whose product faddd 2 reads in ALC3 exactly 6 cycles later: the
write-back conflict of timing.md, which stalls every other iteration.
The wb_ kernels (groups 10 and 11) show that the conflict follows the
schedule as written (nops count), not the cycles a stall adds, also
with a load as the integer-side operation.
"""

import copy
from pathlib import Path

HERE = Path(__file__).resolve().parent
II = 4
HEADER = """! SPDX-License-Identifier: GPL-3.0-or-later
! Generated by tools/isa-probes/gen_stbase.py; see stbase.c.
	.ignore	ld_st_style
	.ignore	strict_delay
	.text
"""
RBS = 8                      # the ring starts at %dr16
FIXED_PTR = {"px": "%dr12", "py": "%dr13", "ps": "%dr14"}
ARR = {"x": "%dr2", "y": "%dr3"}
A_REG = "%dr4"
VLC = 1 << 37
LDOVL = 0xff << 40

text, cases = [], []


def wi(*ops):
    return "\t{\n" + "".join(f"\t  {o}\n" for o in ops if o) + "\t}\n"


def base_plain():
    return {
        # element j's x load, y load, multiply, add and store
        "ldx": [dict(t=0, ch=c, ptr="px", d=2) for c in (5, 3, 0, 2)],
        "ldy": [dict(t=2, ch=c, ptr="py", d=0) for c in (0, 2, 3, 5)],
        "mul": [dict(t=t, ch=c) for t, c in zip((4, 5, 5, 5), (4, 0, 1, 3))],
        "add": [dict(t=t, ch=c) for t, c in zip((10, 11, 11, 11), (1, 0, 1, 3))],
        "st": [dict(t=t, ch=c, ptr="py", d=0)
               for t, c in zip((17, 17, 19, 19), (2, 5, 2, 5))],
        # pointer chains: addd p + 32 at time t (stage 0), reading the
        # previous iteration's instance
        "ptr": {"px": dict(t=3, ch=4, arr="x", bias=0, rot=True),
                "py": dict(t=0, ch=1, arr="y", bias=0, rot=True)},
        "lm": False,         # loop_mode (stores suppressed while pcnt > 0)
        "sm": True,          # ,sm on loads, FP operations and addd
        "check": True,       # the kernel computes the whole of y
    }


def base_rebased():
    k = base_plain()
    for j, c in enumerate((1, 0, 1, 3)):
        k["mul"][j]["ch"] = c
    for j, c in enumerate((1, 0, 3, 4)):
        k["add"][j]["ch"] = c
    k["ptr"]["py"]["ch"] = 4
    k["ptr"]["px"]["ch"] = 1
    for j, d in enumerate((-3, -3, -4, -4)):
        k["st"][j]["d"] = d
    return k


class Kernel:
    def __init__(self, name, k):
        self.name, self.k = name, k
        self.ops = []        # (t, ch, kind, mem, dst, [(src, d)])
        self.prod = {}       # value -> producer time
        self.rot = {}        # value -> rotating?
        k = self.k
        for p, pd in k["ptr"].items():
            assert 0 <= pd["t"] < II, "pointer updates must be in stage 0"
            self.prod[p] = pd["t"]
            self.rot[p] = pd["rot"]
            self.ops.append((pd["t"], pd["ch"], "addp", None, p, [(p, 1)]))
        for j, o in enumerate(k["ldx"]):
            self._val(f"x{j}", o["t"])
            self.ops.append((o["t"], o["ch"], "ld", ("x", j, o["ptr"], o["d"]),
                             f"x{j}", [(o["ptr"], o["d"])]))
        for j, o in enumerate(k["ldy"]):
            self._val(f"y{j}", o["t"])
            self.ops.append((o["t"], o["ch"], "ld", ("y", j, o["ptr"], o["d"]),
                             f"y{j}", [(o["ptr"], o["d"])]))
        for j, o in enumerate(k["mul"]):
            self._val(f"m{j}", o["t"])
            self.ops.append((o["t"], o["ch"], "mul", None, f"m{j}", [(f"x{j}", 0)]))
        for j, o in enumerate(k["add"]):
            self._val(f"s{j}", o["t"])
            self.ops.append((o["t"], o["ch"], "add", None, f"s{j}",
                             [(f"y{j}", 0), (f"m{j}", 0)]))
        for j, o in enumerate(k["st"]):
            if o is None:
                continue
            self.ops.append((o["t"], o["ch"], "st", ("y", j, o["ptr"], o["d"]),
                             None, [(o["ptr"], o["d"]), (f"s{j}", 0)]))
        self.stages = max(t for t, *_ in self.ops) // II + 1
        sts = [o["t"] for o in k["st"] if o is not None]
        self.s_st = max(sts) // II if sts else self.stages - 1
        self._alloc()

    def _val(self, v, t):
        self.prod[v] = t
        self.rot[v] = True

    def dist(self, v, d, t):
        """Rotations between V's instance of iteration g - d being
        written and its read at time T of iteration g."""
        tp = self.prod[v]
        r = d + t // II - tp // II
        assert r >= 0, (self.name, v, d, t)
        if r == 0:
            assert t % II > tp % II, (self.name, v, d, t, "read before write")
        return r

    def eff_d(self, p, t):
        """The instance age a read of non-rotating pointer P at time T
        sees: the latest write before T's kernel instruction."""
        ta = self.prod[p]
        s = t // II
        return -s if t % II > ta % II else 1 - s

    def _alloc(self):
        reach = {v: 0 for v in self.prod if self.rot[v]}
        for t, ch, kind, mem, dst, srcs in self.ops:
            for v, d in srcs:
                if self.rot[v]:
                    reach[v] = max(reach[v], self.dist(v, d, t))
        used, self.base = set(), {}
        # pointers first (they have the longest reach)
        for v in sorted(reach, key=lambda v: (-reach[v], v)):
            b = 0
            while any(b + 2 * e in used for e in range(reach[v] + 1)):
                b += 1
            self.base[v] = b
            used |= {b + 2 * e for e in range(reach[v] + 1)}
        self.reach = reach
        n = max(used) + 1
        self.ring = n + (n % 2)

    def reg(self, v, d, t):
        if not self.rot[v]:
            return FIXED_PTR[v]
        return f"%b[{self.base[v] + 2 * self.dist(v, d, t)}]"

    def dname(self, v):
        """The register an operation writes V to."""
        return FIXED_PTR[v] if not self.rot[v] else f"%b[{self.base[v]}]"

    def offset(self, arr, j, p, d, t):
        if not self.rot[p]:
            d = self.eff_d(p, t)
        return 8 * j + 32 * (d - 1) - self.k["ptr"][p]["bias"]

    def text(self):
        k, sm = self.k, (",sm" if self.k["sm"] else "")
        instrs = [[] for _ in range(II)]
        for t, ch, kind, mem, dst, srcs in sorted(self.ops, key=lambda o: (o[0], o[1])):
            c = t % II
            if kind == "addp":
                src = self.reg(dst, 1, t)
                op = f"addd,{ch}{sm}\t{src}, 0x20, {self.dname(dst)}"
            elif kind == "ld":
                arr, j, p, d = mem
                op = (f"ldd,{ch}{sm}\t{self.reg(p, d, t)}, "
                      f"{self.offset(arr, j, p, d, t)}, {self.dname(dst)}")
            elif kind == "mul":
                op = (f"fmuld,{ch}{sm}\t{A_REG}, {self.reg(srcs[0][0], 0, t)}, "
                      f"{self.dname(dst)}")
            elif kind == "add":
                op = (f"faddd,{ch}{sm}\t{self.reg(srcs[0][0], 0, t)}, "
                      f"{self.reg(srcs[1][0], 0, t)}, {self.dname(dst)}")
            else:
                arr, j, p, d = mem
                op = (f"std,{ch}\t{self.reg(p, d, t)}, "
                      f"{self.offset(arr, j, p, d, t)}, {self.reg(srcs[1][0], 0, t)}")
            instrs[c].append((ch, op))
        for c in range(II):
            chans = [ch for ch, _ in instrs[c]]
            assert len(chans) == len(set(chans)), (self.name, c, chans)
        out = []
        for c in range(II):
            ops = [op for _, op in sorted(instrs[c], key=lambda x: x[0])]
            ctl = ["loop_mode"] if k["lm"] else []
            if c == II - 1:
                ctl += ["alc\talcf=1, alct=1", "abn\tabnf=1, abnt=1",
                        "ct\t%ctpr1 ? %NOT_LOOP_END"]
            out.append(wi(*ctl, *ops))
        return out

    def emit(self):
        k, name = self.k, f"sb_{self.name}"
        rsz = self.ring // 2 - 1
        wsz = RBS + self.ring // 2 + 1
        assert wsz <= 0x40
        body = wi(f"setwd\twsz = {wsz:#x}, nfx = 0x1, dbl = 0x0",
                  f"setbn\trsz = {rsz:#x}, rbs = {RBS:#x}, rcur = 0x0",
                  "return\t%ctpr3")
        body += wi("ldd,0\t%dr1, 0x0, %dr2", "ldd,2\t%dr1, 0x8, %dr3",
                   "ldd,3\t%dr1, 0x10, %dr4", f"disp\t%ctpr1, {name}_loop")
        zero = [f"%b[{i}]" for i in range(self.ring)]
        for i in range(0, len(zero), 6):
            body += wi(*(f"addd,{c}\t0x0, 0x0, {r}"
                         for c, r in enumerate(zero[i:i + 6])))
        # pointer instances of iterations -1 .. -reach (rotating), or
        # the instance of iteration -1 (non-rotating)
        inits = []
        for p, pd in k["ptr"].items():
            arr = ARR[pd["arr"]]
            if pd["rot"]:
                for e in range(1, self.reach[p] + 1):
                    inits.append(f"{arr}, {pd['bias'] + 32 * (1 - e)}, "
                                 f"%b[{self.base[p] + 2 * e}]")
            else:
                inits.append(f"{arr}, {pd['bias']}, {FIXED_PTR[p]}")
        for i in range(0, len(inits), 6):
            body += wi(*(f"addd,{c}\t{x}" for c, x in enumerate(inits[i:i + 6])))
        lsr = VLC | LDOVL
        if k["lm"]:
            lsr |= (self.s_st << 48) | (127 << 53)
        body += wi(f"addd,0\t%dr0, {self.s_st}, %dr9")
        body += wi(f"ord,0\t%dr9, _f64,_lts0 {lsr:#x}, %dr9")
        body += wi("rwd,0\t%dr9, %lsr")
        body += wi("nop 5")
        body += wi("rrd,0\t%clkr, %dr10")
        body += wi("ct\t%ctpr1")
        body += f"\t.balign\t1024\n{name}_loop:\n" + "".join(self.text())
        body += wi("rrd,0\t%clkr, %dr11")
        body += wi("subd,0\t%dr11, %dr10, %dr0")
        body += wi("ct\t%ctpr3")
        text.append(f"\n\t.balign\t1024\n\t.global\t{name}\n\t.type\t{name}, "
                    f"#function\n{name}:\n{body}\t.size\t{name}, .-{name}\n")
        nst = sum(1 for o in k["st"] if o is not None)
        cases.append((self.name, nst, int(k["check"]), self.ring))


def case(name, base, **ch):
    k = copy.deepcopy(base)
    for key, val in ch.items():
        if key in ("mul_ch", "add_ch", "ldx_ch", "ldy_ch", "st_ch"):
            for j, c in enumerate(val):
                if k[key[:-3]][j] is not None:
                    k[key[:-3]][j]["ch"] = c
        elif key in ("st_d", "ldx_d", "ldy_d"):
            for j, d in enumerate(val):
                if k[key[:-2]][j] is not None:
                    k[key[:-2]][j]["d"] = d
        elif key in ("mul_t", "add_t", "st_t", "ldx_t", "ldy_t"):
            for j, t in enumerate(val):
                if k[key[:-2]][j] is not None:
                    k[key[:-2]][j]["t"] = t
        elif key == "ptr_ch":
            for p, c in val.items():
                k["ptr"][p]["ch"] = c
        elif key == "ptr_t":
            for p, t in val.items():
                k["ptr"][p]["t"] = t
        elif key == "bias":
            for p, b in val.items():
                k["ptr"][p]["bias"] = b
        elif key == "fixed":
            for p in val:
                k["ptr"][p]["rot"] = False
        elif key == "st_keep":
            k["st"] = [o if j in val else None for j, o in enumerate(k["st"])]
            k["check"] = False
        elif key == "st_ptr":
            # stores through a separate pointer on y: (t, ch) of its addd
            t, c = val
            k["ptr"]["ps"] = dict(t=t, ch=c, arr="y", bias=0, rot=True)
            for o in k["st"]:
                if o is not None:
                    o["ptr"] = "ps"
        elif key == "shift":
            # later stages for the multiplies, adds and stores (v6's
            # 5-cycle loads)
            for kind in ("mul", "add", "st"):
                for o in k[kind]:
                    if o is not None:
                        o["t"] += val
        elif key in ("lm", "sm", "check"):
            k[key] = val
        else:
            raise KeyError(key)
    Kernel(name, k).emit()


