"""Write sem6.s and sem6-ops.h: every ALU operation new in v6, for
sem6.c, which runs them over fixed inputs on hardware or under qemu so
the two can be compared (spec/isa/semantics.md).

  python3 tools/isa-probes/gen_sem6.py

As gen_sem5.py: each function is  void v6_N(const u128 in[3], u128
out[2]); it loads in[0..2] into %qpr2..%qpr4, clears the %pfpfr flags,
presets %qpr5 to 0x5555... in both halves, runs the operation with
sources from %qpr2..4 (as %drK or %rK for 64- and 32-bit operands) into
%qpr5 / %dr5 / %r5 and stores all 128 bits of %qpr5 in out[0] and
%pfpfr in out[1].  A compare into a predicate (`*op`, `*ap`) stores 1 or
0; the merges by a predicate (`pmrgp`, `qpmrgp`) run twice, with the
predicate false (_f) and true (_t).  Operations are taken from
binutils-ops.yaml: those whose first ISA version is 6, except the
register branches and calls (ibranchd, icalld; ctl6.c).
"""

from pathlib import Path

import yaml

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]

HEADER = """! SPDX-License-Identifier: GPL-3.0-or-later
! Generated by tools/isa-probes/gen_sem6.py; see sem6.c.
	.ignore	ld_st_style
	.text
"""

SKIP = ("ibranchd", "icalld")
REG = {"p": "%qpr", "d": "%dr", "s": "%r"}


def ops():
    data = yaml.safe_load((ROOT / "spec/isa/binutils-ops.yaml").read_text())
    first = {}
    for e in data["alu_ops"]:
        if e.get("isets"):
            first.setdefault(e["name"], []).append(e)
    out = []
    for name, es in sorted(first.items()):
        if min(min(e["isets"]) for e in es) != 6 or name in SKIP:
            continue
        e = next(e for e in es if 6 in e["isets"])
        a = (name, e["args"], e["channels"][0], e["alopf"])
        if e["alopf"].endswith("_MERGE"):
            out += [(f"{name}_f", *a, 0), (f"{name}_t", *a, 1)]
        else:
            out.append((name, *a, None))
    return out


def body(name, args, ch, alopf, pred):
    srcs = [f"{REG[a]}{2 + k}" for k, a in enumerate(args[:-1])]
    dst = f"{REG[args[-1]]}5"
    pre, post = [], []
    if alopf == "ALOPF17":              # two sources -> predicate
        srcs = [f"{REG[a]}{2 + k}" for k, a in enumerate(args)]
        op = f"{name},{ch}\t{', '.join(srcs)}, %pred1"
        post = ["addd,0\t0x0, 0x0, %dr5", "addd,0\t0x0, 0x1, %dr5 ? %pred1"]
    elif alopf.endswith("_MERGE"):
        pre = [f"cmpesb,0\t0x0, {0 if pred else 1:#x}, %pred1"]
        op = f"{name},{ch}\t{', '.join(srcs)}, {dst}, %pred1"
    elif alopf in ("ALOPF2", "ALOPF12"):
        op = f"{name},{ch}\t{REG[args[0]]}2, {dst}"
    else:
        op = f"{name},{ch}\t{', '.join(srcs)}, {dst}"
    return pre, op, post


def fn(i, label, name, args, ch, alopf, pred):
    pre, op, post = body(name, args, ch, alopf, pred)
    w = lambda *o: "\t{\n" + "".join(f"\t  {x}\n" for x in o) + "\t}\n"
    b = w("setwd\twsz = 0x8, nfx = 0x1, dbl = 0x0", "return\t%ctpr3",
          "rrs,0\t%pfpfr, %r8")
    b += w("ldqp,0\t%dr0, 0x0, %qpr2", "ldqp,2\t%dr0, 0x10, %qpr3",
           "ldqp,3\t%dr0, 0x20, %qpr4",
           "addd,1\t0x0, _f64,_lts0 0x5555555555555555, %dr6")
    b += w("qppackdl,1\t%dr6, %dr6, %qpr5", "ands,0\t%r8, 0xffffffc0, %r9")
    b += w("rws,0\t%r9, %pfpfr")
    b += "".join(w(p) for p in pre)
    b += w("nop 7")
    b += w(op)
    b += w("nop 7") + w("nop 7")
    b += "".join(w(p) for p in post)
    b += w("nop 2", "rrs,0\t%pfpfr, %r9")
    b += w("stqp,2\t%dr1, 0x0, %qpr5", "stw,5\t%dr1, 0x10, %r9")
    b += w("rws,0\t%r8, %pfpfr") + w("nop 5") + w("ct\t%ctpr3")
    return (f"\n\t.global\tv6_{i}\n\t.type\tv6_{i}, #function\n"
            f"\t.align\t8\nv6_{i}:\n{b}\t.size\tv6_{i}, .-v6_{i}\n")


def main():
    ls = ops()
    (HERE / "sem6.s").write_text(
        HEADER + "".join(fn(i, *o) for i, o in enumerate(ls)))
    (HERE / "sem6-ops.h").write_text(
        "/* SPDX-License-Identifier: GPL-3.0-or-later */\n"
        "/* Generated by tools/isa-probes/gen_sem6.py.  */\n"
        + "".join(f'OP ({i}, "{o[0]}")\n' for i, o in enumerate(ls)))
    print(len(ls), "cases")


if __name__ == "__main__":
    main()
