"""Write damlist.s and damlist-cases.h for damlist.c: why the
proof-of-concept back end's finding I45 (docs/spec-poc-findings.md)
lost time on the 8C2 when a pipelined list reversal (CoreMark's
core_list_reverse) put its lock load and check in one wide instruction.
For spec/isa/speculation.md and timing.md.

  python3 tools/isa-probes/gen_damlist.py

List cases (dl_*)  long dl_NAME(long head, long *aux): reverse the list
that starts at HEAD and ends at the sentinel node aux[0] (whose next
points to itself) and return the new head.  aux[1] gets the number of
compensation-code runs, aux[2] is a dummy address for the clean-up,
aux[3] the step between nodes (the "arith" cases), aux[4] a scratch
address (the "scratch" store cases).  A node's next pointer is its
first doubleword.  Logical iteration j (nodes n_0 .. n_{K-1}, n_K the
sentinel) is

  L_j  lock load  n_{j+1} = n_j->next           (ldd,LCH,sm .. mas=0x4)
  C_j  check      n_{j+1} = n_j->next           (ldd,CCH .. mas=0x3, rbranch)
  S_j  store      n_j->next = n_{j-1}           (std,SCH)

with L_j at cycle II*j + LSLOT (a pointer chase at the load latency
when II is 3), C_j DC cycles and S_j DS cycles after L_j: L_j moves
above S_{j-1} (and S_{j-2}), so C_j must follow S_{j-1} and precede S_j
(DS - II < DC < DS).  The kernel is II wide instructions with the
loop's ct (and abn, abp) in the last one; a compare against the
sentinel (cmpedb, CMPCH) in slot TCMP feeds the next iteration's ct
through a rotated predicate.  L_j writes %b[0]; R(j - a), the value
L_{j-a} loaded, is %b[2(s + a)] for an operation in stage s.  The
peeled prologue runs the first stages under the names their values
have when the kernel starts, as lcc does; the epilogue relocks and
checks every ring register (instead of lcc's mmurw %dam_inv) so no
entry outlives the call.  Compensation code counts and returns with
ibranch: the probe's lists never alias, so a failed check (after an
interrupt) reloads the value the early load gave.  Variants: every
placement of the check and the store (p_*), channels (ch_*), no
rbranch, no check, plain loads instead of lock and check, the store to
another word, addresses by addition instead of a chase, other ring
sizes (v_*), and II 5 for the 2C3's 5-cycle loads (v6_*; v6_d1 puts
the store 1 cycle before the next lock).

Store-then-load cases (dt_*), what the list cases pointed to: a store,
a load D cycles later at another offset or width, the loaded value used
U cycles after the load (see tgen below); the y_ cases tried to break
the rule this gave (a store under a false or a true predicate, wider
and narrower loads, the line's last byte).

Each function is aligned to 1 KiB and its loop sits in the first 0x1c0
bytes (the list cases enter through an ibranch), so gas's
CODE_PLACEMENT padding never lands inside a loop; check with objdump.
"""

from pathlib import Path

HERE = Path(__file__).resolve().parent
HEADER = """! SPDX-License-Identifier: GPL-3.0-or-later
! Generated by tools/isa-probes/gen_damlist.py; see damlist.c.
	.ignore	ld_st_style
	.ignore	strict_delay
	.text
"""
cases, text = [], []


def wi(*ops):
    ops = [o for o in ops if o]
    if not ops:
        ops = ["nop"]
    return "\t{\n" + "".join(f"\t  {o}\n" for o in ops) + "\t}\n"


def nops(n):
    out = ""
    while n > 0:
        k = min(n, 8)
        out += wi(f"nop {k - 1}" if k > 1 else "nop")
        n -= k
    return out


class Case:
    def __init__(self, name, dc, ds, lslot=0, ii=3, lch=0, cch=2, sch=2,
                 cmpch=1, tcmp=None, rb=True, lock="dam", check="dam",
                 store="list", chase=True, rsz=4, desc=""):
        self.__dict__.update(locals())
        del self.__dict__["self"]
        if self.tcmp is None:
            self.tcmp = ii - 1


def gen(c):
    II = c.ii
    fn = f"dl_{c.name}"
    lab = f".Ldl_{c.name}"
    tL = c.lslot
    sL, slotL = divmod(tL, II)
    sS, slotS = divmod(tL + c.ds, II)
    assert sL == 0 and sS >= 2, c.name
    hasC = c.check != "none"
    if hasC:
        assert c.ds - II < c.dc < c.ds, c.name
        sC, slotC = divmod(tL + c.dc, II)
        if c.rb and c.check == "dam":
            assert slotC != II - 1, c.name  # rbranch and ct: both SS
    rsz = max(c.rsz, sS + 2)
    ring = 2 * (rsz + 1)
    k0 = sS
    wsz = max(0x10, 8 + rsz + 1)

    def R(s, a, delta):          # R(j - a) for an op in stage s
        return f"%b[{(2 * (s + a + delta)) % ring}]"

    def B(s, a, delta):          # B(j - a): node address (arith cases)
        return f"%b[{(2 * (s + a + delta) + 1) % ring}]"

    def addr(s, delta):          # n_j for an op of iteration j
        return B(s, 0, delta) if not c.chase else R(s, 1, delta)

    ncomp = [0]
    comp = []

    def ops_for(stage_ok, delta):
        """Ops of one kernel (or prologue) iteration by slot.  STAGE_OK
        says which stages run; DELTA renames (prologue)."""
        slots = [[] for _ in range(II)]
        rbs = [None] * II
        # Lock.
        if stage_ok(sL):
            mas = ", mas=0x4" if c.lock == "dam" else ""
            slots[slotL].append(
                f"ldd,{c.lch},sm\t{addr(sL, delta)}, 0x0, "
                f"{R(sL, 0, delta)}{mas}")
            if not c.chase:      # B(j + 1) = B(j) + step
                slots[slotL].append(
                    f"addd,{4 if c.cmpch == 1 else 1}\t{B(sL, 0, delta)}, "
                    f"%dr3, {B(sL, -1, delta)}")
        # Check.
        if hasC and stage_ok(sC):
            if c.check == "dam":
                slots[slotC].append(
                    f"ldd,{c.cch}\t{addr(sC, delta)}, 0x0, "
                    f"{R(sC, 0, delta)}, mas=0x3")
                if c.rb:
                    rbs[slotC] = True
            else:                # plain load of the same word, dead result
                slots[slotC].append(
                    f"ldd,{c.cch}\t{addr(sC, delta)}, 0x0, %dr7")
        # Store.
        if stage_ok(sS):
            data = R(sS, 2, delta)
            if c.store == "list":
                slots[slotS].append(
                    f"std,{c.sch}\t{addr(sS, delta)}, 0x0, {data}")
            elif c.store == "info":
                slots[slotS].append(
                    f"std,{c.sch}\t{addr(sS, delta)}, 0x8, {data}")
            elif c.store == "scratch":
                slots[slotS].append(f"std,{c.sch}\t%dr9, 0x0, {data}")
        return slots, rbs

    def emit(slots, rbs):
        out = ""
        for i in range(II):
            ops = list(slots[i])
            tail = ""
            if rbs[i]:
                n = ncomp[0]
                ncomp[0] += 1
                ops.append(f"rbranch\t{lab}_c{n}")
                tail = f"{lab}_r{n}:\n"
                comp.append(f"{lab}_c{n}:\n"
                            + wi(f"ibranch\t{lab}_r{n}",
                                 "addd,0\t%dr6, 0x1, %dr6"))
            out += wi(*ops) + tail
        return out

    # Entry: window, then jump over the kernel to the set-up.
    body = wi(f"setwd\twsz = {wsz:#x}, nfx = 0x1, dbl = 0x0",
              f"setbn\trsz = {rsz:#x}, rbs = 0x8, rcur = 0x0",
              "setbp\tpsz = 0x1")
    body += wi(f"ibranch\t{lab}_pro")
    # Kernel.
    kslots, krbs = ops_for(lambda s: True, 0)
    kslots[c.tcmp].append(
        f"cmpedb,{c.cmpch}\t{R(0, sS - 1, 0)}, %dr4, %pred0")
    kslots[II - 1] += ["ct\t%ctpr1 ? ~%pred1", "abn\tabnf=1, abnt=1",
                       "abp\tabpf=1, abpt=1"]
    body += f"{lab}_loop:\n" + emit(kslots, krbs)
    # Epilogue: the new head is R(K - 2), then clean the DAM.
    body += wi(f"addd,0\t0x0, %b[{(2 * (sS + 2)) % ring}], %dr0")
    regs = [f"%b[{2 * i}]" for i in range(rsz + 1)]
    for i in range(0, len(regs), 2):
        body += wi(*[f"ldd,{ch},sm\t%dr5, 0x0, {r}, mas=0x4"
                     for ch, r in zip((0, 3), regs[i:i + 2])])
    for i in range(0, len(regs), 2):
        body += wi(*[f"ldd,{ch}\t%dr5, 0x0, {r}, mas=0x3"
                     for ch, r in zip((2, 5), regs[i:i + 2])])
    body += wi("std,2\t%dr1, 0x8, %dr6") + nops(2) + wi("ct\t%ctpr3")
    # Set-up and prologue.
    body += f"{lab}_pro:\n"
    body += wi("return\t%ctpr3", "ldd,0\t%dr1, 0x0, %dr4",
               "ldd,2\t%dr1, 0x10, %dr5", "ldd,3\t%dr1, 0x18, %dr3",
               "ldd,5\t%dr1, 0x20, %dr9", "addd,1\t0x0, 0x0, %dr6",
               "addd,4\t0x0, 0x0, %dr7")
    body += wi(f"disp\t%ctpr1, {lab}_loop")
    body += wi(f"disp\t%ctpr2, {lab}_loop")  # v6: keep every CTPR valid
    body += nops(2)
    init = [f"addd,0\t0x0, %dr0, {R(0, 1, k0)}",
            f"addd,1\t0x0, %dr4, {R(0, 2, k0)}"]
    if not c.chase:
        init.append(f"addd,3\t0x0, %dr0, {B(0, 0, k0)}")
    body += wi(*init) + nops(1)   # no cluster crossing into the first lock
    for k in range(k0):
        pslots, prbs = ops_for(lambda s, k=k: s <= k, k0 - k)
        if k == k0 - 1:
            pslots[c.tcmp].append(
                f"cmpedb,{c.cmpch}\t{R(0, sS - 1, 1)}, %dr4, %pred1")
        body += emit(pslots, prbs)
    body += wi(f"ibranch\t{lab}_loop")
    body += "".join(comp)
    text.append(f"\n\t.global\t{fn}\n\t.type\t{fn}, #function\n"
                f"\t.align\t1024\n{fn}:\n{body}\t.size\t{fn}, .-{fn}\n")
    rev = 1 if c.store == "list" else 0
    arith = 0 if c.chase else 1
    cases.append(f'K ({c.name}, {rev}, {arith}, {II}, "{c.desc}")\n')


def empty():
    text.append("\n\t.global\tdl_empty\n\t.type\tdl_empty, #function\n"
                "\t.align\t1024\ndl_empty:\n"
                + wi("setwd\twsz = 0x10, nfx = 0x1, dbl = 0x0",
                     "return\t%ctpr3")
                + nops(3) + wi("ct\t%ctpr3")
                + "\t.size\tdl_empty, .-dl_empty\n")


empty()

# --------------------------------------------------------------------
# Placements, II 3 (v3, v5): every (DC, DS) with the store in stage 2
# or 3, the lock in each slot; lock ALC0, check ALC2, store ALC2 (as the
# proof-of-concept back end's kernels).
#   PoC slow (I45):  lslot 0, dc 6, ds 7   {L, C, rb} {S} {cmp, ct}
#   PoC fast:        lslot 0, dc 7, ds 8   {L} {C, rb} {S, cmp, ct}
#   hand-edited:     lslot 0, dc 6, ds 8   {L, C, rb, nop 1} {S, cmp, ct}
#   lcc's:           lslot 1, dc 6, ds 7   {} {L, C, rb} {S, cmp, ct}
for ds in (6, 7, 8, 9, 10, 11):
    for dc in range(ds - 2, ds):
        for ls in (0, 1, 2):
            sS = (ls + ds) // 3
            if sS < 2 or (ls + dc) % 3 == 2:
                continue
            gen(Case(f"p_l{ls}_c{dc}_s{ds}", dc, ds, lslot=ls,
                     desc=f"lock slot {ls}, check +{dc}, store +{ds}"))

# Channels for the PoC's three kernels and lcc's.
for tag, ls, dc, ds in (("slow", 0, 6, 7), ("fast", 0, 7, 8),
                        ("hand", 0, 6, 8), ("lcc", 1, 6, 7)):
    for lch in (0, 3):
        for cch in (2, 5):
            for sch in (2, 5):
                # gas: no store in ALC2 with a load in ALC3, nor ALC5
                # with ALC0, in one instruction; one op per channel.
                same_LS = (ls + ds) % 3 == ls % 3
                same_CS = (ls + ds) % 3 == (ls + dc) % 3
                if same_CS and cch == sch:
                    continue
                if same_LS and ((sch == 2 and lch == 3)
                                or (sch == 5 and lch == 0)):
                    continue
                if same_CS and ((sch == 2 and cch == 3)
                                or (sch == 5 and cch == 0)):
                    continue
                gen(Case(f"ch_{tag}_l{lch}c{cch}s{sch}", dc, ds, lslot=ls,
                         lch=lch, cch=cch, sch=sch,
                         desc=f"{tag}: lock ALC{lch}, check ALC{cch}, "
                              f"store ALC{sch}"))

# What the stall needs: the DAM (plain loads instead), the check, the
# rbranch, the store's address, the chase.
for tag, ls, dc, ds in (("slow", 0, 6, 7), ("fast", 0, 7, 8),
                        ("lcc", 1, 6, 7)):
    kw = dict(lslot=ls)
    if tag == "lcc":
        kw.update(lch=3, cch=5, sch=5, cmpch=4)
    gen(Case(f"v_{tag}_norb", dc, ds, rb=False, **kw,
             desc=f"{tag} without rbranch"))
    gen(Case(f"v_{tag}_nocheck", dc, ds, check="none", **kw,
             desc=f"{tag}, lock but no check"))
    gen(Case(f"v_{tag}_plainchk", dc, ds, check="plain", **kw,
             desc=f"{tag}, lock, plain load of the word for the check"))
    gen(Case(f"v_{tag}_plain", dc, ds, lock="plain", check="plain", **kw,
             desc=f"{tag}, plain ldd,sm and plain load: no DAM"))
    gen(Case(f"v_{tag}_plainnochk", dc, ds, lock="plain", check="none",
             **kw, desc=f"{tag}, plain ldd,sm, no check: no DAM"))
    gen(Case(f"v_{tag}_stinfo", dc, ds, store="info", **kw,
             desc=f"{tag}, store to the node's second doubleword"))
    gen(Case(f"v_{tag}_stscr", dc, ds, store="scratch", **kw,
             desc=f"{tag}, store to a fixed scratch word"))
    gen(Case(f"v_{tag}_arith", dc, ds, chase=False, **kw,
             desc=f"{tag}, addresses by addition (no chase)"))
    gen(Case(f"v_{tag}_ring16", dc, ds, rsz=7, **kw,
             desc=f"{tag}, rotating ring of 16 registers"))
    gen(Case(f"v_{tag}_ring12", dc, ds, rsz=5, **kw,
             desc=f"{tag}, rotating ring of 12 registers"))

# II 5 for the 2C3 (5-cycle loads): the same shapes, scaled, and one
# with the store 1 cycle before the next lock (d1).
for tag, ls, dc, ds in (("slow", 0, 10, 11), ("fast", 0, 11, 13),
                        ("hand", 0, 10, 13), ("lcc", 1, 10, 11),
                        ("d1", 0, 12, 14)):
    gen(Case(f"v6_{tag}", dc, ds, lslot=ls, ii=5,
             desc=f"II 5: {tag} shape, check +{dc}, store +{ds}"))

# --------------------------------------------------------------------
# Store, then load, in a loop: the rule the list cases point to.  Each
# step stores the chain value to [b + 64k + SO] (ALC SCH), loads
# [b + 64k + LO] (ALC LCH) D cycles later, and ORs the loaded value into
# the chain U cycles after the load (its latency: 3 on v3 and v5, 5 on
# v6), so a late load result delays the next step.  Four steps an
# iteration at 64-byte strides, the base moving 256 bytes an iteration
# (MOVE) or staying (fixed addresses); a step takes D + U + 1 cycles
# without a penalty.  long dt_NAME(long buf, long *aux): aux[5] holds
# the iteration count.
tcases = []


def tgen(name, d, off, u=3, so=0, sch=2, lch=0, move=True, steps=4,
         sop="std", lop="ldd", spred=None, desc=""):
    fn = f"dt_{name}"
    lab = f".Ldt_{name}"
    lo = so + off
    body = wi("setwd\twsz = 0x10, nfx = 0x1, dbl = 0x0",
              "return\t%ctpr3")
    # SPRED "f" / "t": the store under %pred1 = false / ~%pred1 = true.
    body += wi("ldd,0\t%dr1, 0x28, %dr12", "addd,1\t0x0, %dr0, %dr13",
               "addd,3\t0x0, 0x0, %dr10",
               "cmpbdb,4\t%dr0, %dr0, %pred1" if spred else None)
    cond = {None: "", "f": " ? %pred1", "t": " ? ~%pred1"}[spred]
    body += wi(f"disp\t%ctpr1, {lab}_loop")
    body += wi(f"disp\t%ctpr2, {lab}_loop") + nops(3)
    # Instructions of one iteration, by cycle.
    plen = steps * (d + u + 1)
    slots = [[] for _ in range(plen)]
    for k in range(steps):
        t0 = k * (d + u + 1)
        sa, la = 64 * k + so, 64 * k + lo
        sreg = "%dr10" if sop == "std" else "%r10"
        lreg = "%dr11" if lop == "ldd" else "%r11"
        slots[t0].append(f"{sop},{sch}\t%dr13, {sa:#x}, {sreg}{cond}")
        slots[t0 + d].append(f"{lop},{lch}\t%dr13, {la:#x}, {lreg}")
        slots[t0 + d + u].append("ord,1\t%dr10, %dr11, %dr10")
    slots[0].append("subd,4\t%dr12, 0x1, %dr12")
    slots[1].append("cmpedb,4\t%dr12, 0x0, %pred0")
    slots[plen - 1].append("ct\t%ctpr1 ? ~%pred0")
    if move:
        slots[plen - 1].append(f"addd,0\t%dr13, {64 * steps:#x}, %dr13")
    body += f"{lab}_loop:\n"
    i = 0
    while i < plen:
        if slots[i]:
            body += wi(*slots[i])
            i += 1
        else:
            j = i
            while j < plen and not slots[j]:
                j += 1
            body += nops(j - i)
            i = j
    body += wi("addd,0\t0x0, %dr10, %dr0") + nops(2) + wi("ct\t%ctpr3")
    text.append(f"\n\t.global\t{fn}\n\t.type\t{fn}, #function\n"
                f"\t.align\t1024\n{fn}:\n{body}\t.size\t{fn}, .-{fn}\n")
    tcases.append(f'T ({name}, {steps}, {d + u + 1}, "{desc}")\n')


# Distance D (store to load) by offset LO - SO, use at the latency.
for u in (3, 5):
    for d in range(0, 9):
        for off in (0, 8, 16, 24, -8, 32, 64, 4096):
            nm = f"u{u}_d{d}_o{off}".replace("-", "m")
            tgen(nm, d, off, u=u, sch=2, lch=0,
                 desc=f"store, load {d} later at {off:+d}, use {u} later")
# Where in the block, for D 2: store at each doubleword, load at each.
for so in (0, 8, 16, 24):
    for lo in (0, 8, 16, 24, 32, 56):
        if so == 0 and lo in (0, 8, 16, 24, 32):
            continue
        tgen(f"u3_d2_s{so}_l{lo}", 2, lo - so, so=so,
             desc=f"D 2, store at +{so}, load at +{lo} of a 64-byte line")
# Channels, D 2, offset 8.
for sch in (2, 5):
    for lch in (0, 2, 3, 5):
        tgen(f"u3_d2_o8_s{sch}l{lch}", 2, 8, sch=sch, lch=lch,
             desc=f"D 2, offset 8, store ALC{sch}, load ALC{lch}")
# Fixed addresses (no move).
for d in (1, 2, 3):
    for off in (0, 8, 64):
        tgen(f"u3_d{d}_o{off}_fixed", d, off, move=False,
             desc=f"D {d}, offset {off}, the same addresses every iteration")
# Access widths: word and byte stores and loads, a doubleword store and
# a narrower load, a word store and a wider load; the use 5 cycles
# after the load (the v6 latency), so the 4C's 9-cycle L2 reads +4.
for d in range(1, 9):
    for tag, sop, lop, off in (
            ("w0", "stw", "ldw", 0), ("w4", "stw", "ldw", 4),
            ("w8", "stw", "ldw", 8), ("b1", "stb", "ldb", 1),
            ("b8", "stb", "ldb", 8), ("dw4", "std", "ldw", 4),
            ("dw8", "std", "ldw", 8), ("wd8", "stw", "ldd", 8)):
        tgen(f"x_d{d}_{tag}", d, off, u=5, sop=sop, lop=lop,
             desc=f"D {d}: {sop} at +0, {lop} at +{off}, use 5 later")

# Attempts to break the rule (the verification run): the store under a
# false predicate (does the load still pay?) and a true one (control),
# a load wider than the store that holds the stored bytes, a narrower
# load at the start of the stored doubleword, the line's last byte and
# the next line's first.  The use 5 cycles after the load.
for tag, d, off, sop, lop, sp in (
        ("pf_d2_o8", 2, 8, "std", "ldd", "f"),
        ("pt_d2_o8", 2, 8, "std", "ldd", "t"),
        ("pf_d1_o0", 1, 0, "std", "ldd", "f"),
        ("pt_d1_o0", 1, 0, "std", "ldd", "t"),
        ("pf_d4_w4", 4, 4, "stw", "ldw", "f"),
        ("pt_d4_w4", 4, 4, "stw", "ldw", "t"),
        ("wd0_d1", 1, 0, "stw", "ldd", None),
        ("wd0_d2", 2, 0, "stw", "ldd", None),
        ("wd0_d4", 4, 0, "stw", "ldd", None),
        ("dw0_d2", 2, 0, "std", "ldw", None),
        ("dw0_d4", 4, 0, "std", "ldw", None),
        ("b31_d2", 2, 31, "std", "ldb", None),
        ("b32_d2", 2, 32, "std", "ldb", None)):
    tgen(f"y_{tag}", d, off, u=5, sop=sop, lop=lop, spred=sp,
         desc=f"D {d}: {sop} at +0{' under a ' + ('false' if sp == 'f' else 'true') + ' predicate' if sp else ''}, {lop} at +{off}, use 5 later")

# When the value comes: the use 3 to 15 cycles after the load.
for d, off in ((0, 0), (0, 8), (1, 0), (1, 8), (2, 0), (2, 8), (3, 8),
               (4, 8), (2, 64)):
    for u in range(3, 16):
        tgen(f"w{u}_d{d}_o{off}", d, off, u=u,
             desc=f"D {d}, offset {off}, use {u} after the load")

(HERE / "damlist.s").write_text(HEADER + "".join(text))
(HERE / "damlist-cases.h").write_text(
    "/* SPDX-License-Identifier: GPL-3.0-or-later */\n"
    "/* Generated by tools/isa-probes/gen_damlist.py.  */\n"
    + "".join(cases) + "".join(tcases))
