/* Which 32-bit operations does WD.dbl zero-extend into the full register?
   (spec/abi/registers.md, "dbl").  dbl.s and dbl-ops.h are generated by
   gen_dbl.py.

     LCC=/opt/mcst/lcc-1.29.16.e2k-v3.4c.linux-6.1/bin/lcc
     $LCC -O3 tools/abi/probes/dbl.c tools/abi/probes/dbl.s -o dbl && ./dbl

   Each case loads 0x2222222222222222 into the destination (%r3, or the
   global %g20 for *_g), writes a 32-bit result with one operation under
   setwd dbl = 0 and dbl = 1, and prints the whole 64-bit register:
   "kept" if the upper half is still 0x22222222, "zero" if it is 0,
   "full" if the operation wrote all 64 bits itself.  */

#include <stdio.h>

#define OP(n) void p_##n##_0 (long *, int *, int); \
  void p_##n##_1 (long *, int *, int);
#include "dbl-ops.h"
#undef OP

static const char *
kind (unsigned long v)
{
  if ((v >> 32) == 0x22222222)
    return "kept";
  if ((v >> 32) == 0)
    return "zero";
  return "full";
}

int
main (void)
{
  int src = 0x12345678;
  long out0, out1;
#define OP(n) \
  out0 = out1 = 0x2222222222222222L; \
  p_##n##_0 (&out0, &src, 0x12345678); \
  p_##n##_1 (&out1, &src, 0x12345678); \
  printf ("%-10s dbl=0 %016lx %-4s  dbl=1 %016lx %s\n", #n, out0, \
          kind (out0), out1, kind (out1));
#include "dbl-ops.h"
#undef OP
  return 0;
}
