/* Loop mode on hardware (spec/isa/loops.md).  loops.s and loops-cases.h
   are generated by gen_loops.py.

     LCC=/opt/mcst/lcc-1.29.16.e2k-v3.linux-6.1/bin/lcc
     $LCC -O1 tools/isa-probes/loops.c tools/isa-probes/loops.s -o loops
     ./loops

   Each line: case, the %lsr written (decoded), then what the loop did:
   iterations, counts of operations under %pcnt0 / %pcnt1 / %lcntex,
   %lsr and %ilcr after the write and after the loop, the stores that
   reached memory (iteration numbers), the rotating registers, cycles.  */

#include <setjmp.h>
#include <signal.h>
#include <stdio.h>
#include <string.h>
#include <sys/mman.h>
#include <unistd.h>

#define CASE(n) long loop_##n (unsigned long *, unsigned long, long *);
#include "loops-cases.h"
#undef CASE

static sigjmp_buf env;

static void
handler (int sig)
{
  siglongjmp (env, sig);
}

/* A full %lsr with the load controls too.  */
static unsigned long
lsrl (unsigned lcnt, unsigned ecnt, int ldmc, unsigned ldovl)
{
  return (unsigned long) lcnt | (unsigned long) (ecnt & 0x1f) << 32
         | 1UL << 37 | (unsigned long) !!ldmc << 39
         | (unsigned long) (ldovl & 0xff) << 40;
}

static unsigned long
lsr (unsigned lcnt, unsigned ecnt, int vlc, unsigned pcnt, unsigned strmd,
     int semc)
{
  return (unsigned long) lcnt | (unsigned long) (ecnt & 0x1f) << 32
         | (unsigned long) !!vlc << 37 | (unsigned long) (pcnt & 0x1f) << 48
         | (unsigned long) (strmd & 0x7f) << 53 | (unsigned long) !!semc << 60;
}

static void
fields (const char *what, unsigned long v)
{
  printf (" %s[lcnt %lu ecnt %lu vlc %lu over %lu pcnt %lu strmd %lu]", what,
          v & 0xffffffff, v >> 32 & 0x1f, v >> 37 & 1, v >> 38 & 1,
          v >> 48 & 0x1f, v >> 53 & 0x7f);
}

static void
run (const char *name, long (*f) (unsigned long *, unsigned long, long *),
     unsigned long l, int show_regs)
{
  unsigned long out[16];
  long buf[64];
  memset (out, 0, sizeof out);
  memset (buf, 0, sizeof buf);
  long cycles = f (out, l, buf);
  printf ("%-12s", name);
  fields ("set", l);
  printf ("\n             iterations %lu  pcnt0 %lu pcnt1 %lu lcntex %lu",
          out[0], out[1], out[2], out[3]);
  fields ("lsr", out[4]);
  fields ("ilcr", out[5]);
  printf ("\n            ");
  fields ("lsr after", out[6]);
  fields ("ilcr after", out[7]);
  printf ("\n             stores:");
  for (int i = 0; i < 64; i++)
    if (buf[i])
      printf (" [%d]=%ld", i, buf[i]);
  if (show_regs)
    {
      printf ("\n             %%dr16..23:");
      for (int i = 8; i < 16; i++)
        printf (" %lx", out[i]);
    }
  printf ("\n             %ld cycles\n", cycles);
}

static void
run_loads (unsigned long l)
{
  long pg = sysconf (_SC_PAGESIZE);
  char *m = mmap (NULL, 2 * pg, PROT_READ | PROT_WRITE,
                  MAP_PRIVATE | MAP_ANONYMOUS, -1, 0);
  munmap (m + pg, pg);
  long *buf = (long *) (m + pg - 6 * 8);
  unsigned long out[16];
  int sig;
  printf ("%-12s", "loads");
  fields ("set", l);
  printf (" ldmc %lu ldovl %lu: ", l >> 39 & 1, l >> 40 & 0xff);
  if ((sig = sigsetjmp (env, 1)) == 0)
    {
      loop_loads (out, l, buf);
      printf ("no fault, %lu iterations\n", out[0]);
    }
  else
    printf ("signal %d\n", sig);
  munmap (m, pg);
}

int
main (void)
{
  setvbuf (stdout, NULL, _IOLBF, 0);
  signal (SIGSEGV, handler);
  signal (SIGBUS, handler);
  /* Iteration counts.  */
  run ("count", loop_count, lsr (5, 0, 1, 0, 0, 0), 0);
  run ("count", loop_count, lsr (1, 0, 1, 0, 0, 0), 0);
  run ("count", loop_count, lsr (0, 0, 1, 0, 0, 0), 0);
  /* vlc = 0: %LOOP_END never comes, the loop runs until killed.  */
  run ("count", loop_count, lsr (5, 2, 1, 0, 0, 0), 0);
  run ("count", loop_count, lsr (5, 0, 1, 3, 0, 0), 0);
  run ("count", loop_count, lsr (5, 2, 1, 3, 0, 0), 0);
  /* Prologue and loop-end predicates.  */
  run ("preds", loop_preds, lsr (5, 2, 1, 3, 0, 0), 0);
  run ("preds", loop_preds, lsr (5, 0, 1, 0, 0, 0), 0);
  /* Stores under loop_mode.  */
  run ("stores", loop_stores, lsr (5, 0, 1, 0, 0, 0), 0);
  run ("stores", loop_stores, lsr (5, 2, 1, 3, 0, 0), 0);
  run ("stores", loop_stores, lsr (5, 2, 1, 3, 1, 0), 0);
  run ("stores", loop_stores, lsr (5, 2, 1, 3, 0, 1), 0);
  run ("stores2", loop_stores2, lsr (5, 2, 1, 3, 0, 0), 0);
  run ("stores2", loop_stores2, lsr (5, 2, 1, 3, 1, 0), 0);
  run ("stores2", loop_stores2, lsr (5, 2, 1, 3, 2, 0), 0);
  run ("stores_nolm", loop_stores_nolm, lsr (5, 2, 1, 3, 0, 0), 0);
  /* Rotation.  */
  run ("rotate", loop_rotate, lsr (5, 0, 1, 0, 0, 0), 1);
  run ("rotate", loop_rotate, lsr (3, 0, 1, 0, 0, 0), 1);
  run ("rotate_pred", loop_rotate_pred, lsr (5, 0, 1, 0, 0, 0), 1);
  run ("rotate_pred", loop_rotate_pred, lsr (6, 0, 1, 0, 0, 0), 1);
  run ("early1", loop_early1, lsr (5, 0, 1, 0, 0, 0), 0);
  run ("early2", loop_early2, lsr (5, 0, 1, 0, 0, 0), 0);
  run ("early3", loop_early3, lsr (5, 0, 1, 0, 0, 0), 0);
  run ("early4", loop_early4, lsr (5, 0, 1, 0, 0, 0), 0);
  run ("early5", loop_early5, lsr (5, 0, 1, 0, 0, 0), 0);
  run ("early6", loop_early6, lsr (5, 0, 1, 0, 0, 0), 0);
  run ("lcntex_after", loop_lcntex_after, lsr (5, 2, 1, 0, 0, 0), 0);
  /* Loads beyond the array in epilogue iterations.  */
  run_loads (lsrl (5, 0, 0, 0));
  run_loads (lsrl (5, 2, 0, 0));
  run_loads (lsrl (5, 2, 0, 255));
  run_loads (lsrl (5, 2, 1, 0));
  run_loads (lsrl (5, 2, 1, 255));
  run_loads (lsrl (5, 2, 0, 1));
  run_loads (lsrl (5, 2, 0, 2));
  /* Throughput.  */
  run ("one", loop_one, lsr (1000, 0, 1, 0, 0, 0), 0);
  run ("count", loop_count, lsr (1000, 0, 1, 0, 0, 0), 0);
  return 0;
}
