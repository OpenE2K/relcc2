"""Write semantics.s: one small function per E2K operation, called from
semantics.c to observe what the operation computes on hardware.

  python3 tools/isa-probes/gen_semantics.py     # rewrites semantics.s
"""

from pathlib import Path

HERE = Path(__file__).resolve().parent

HEADER = """! SPDX-License-Identifier: GPL-3.0-or-later
! Generated by tools/isa-probes/gen_semantics.py; see semantics.c.
	.ignore	ld_st_style
	.text
"""


def fn(name, groups, wsz=4):
    """A function whose body is GROUPS (lists of operations, one wide
    instruction each), returning %dr0 after enough cycles for any result."""
    body = "".join("\t{\n" + "".join(f"\t  {op}\n" for op in g) + "\t}\n"
                   for g in groups)
    return f"""
	.global	{name}
	.type	{name}, #function
	.align	8
{name}:
	{{
	  setwd	wsz = 0x{wsz:x}, nfx = 0x1, dbl = 0x0
	  return	%ctpr3
	}}
{body}	{{
	  nop 7
	}}
	{{
	  nop 7
	}}
	{{
	  ct	%ctpr3
	}}
	.size	{name}, .-{name}
"""


def main():
    out = [HEADER]
    # long f(long a, long b) for 64-bit binary operations.
    for op in ["addd", "subd", "andnd", "ornd", "xornd", "shld", "shrd",
               "sard", "scld", "scrd", "udivd", "sdivd", "smulhd", "umulhd",
               "fmaxd", "fmind"]:
        out.append(fn(f"s_{op}", [[f"{op} %dr0, %dr1, %dr0"]]))
    # 32-bit binary operations on the low halves.
    for op in ["shls", "shrs", "sars", "scls", "scrs", "udivs", "sdivs"]:
        out.append(fn(f"s_{op}", [[f"{op} %r0, %r1, %r0"]]))
    # Unary operations.
    for op in ["popcntd", "lzcntd", "bitrevd", "popcnts", "lzcnts", "bitrevs"]:
        r = "%dr" if op.endswith("d") else "%r"
        out.append(fn(f"s_{op}", [[f"{op} {r}0, {r}0"]]))
    # sxt with each value of src1.
    for n in range(8):
        out.append(fn(f"s_sxt{n}", [[f"sxt {n:#x}, %dr0, %dr0"]]))
    # long merged(a, b, c): %pred0 = (c == 1).
    out.append(fn("s_merged", [["cmpedb,0 %dr2, 0x1, %pred0"], ["nop 2"],
                               ["merged %dr0, %dr1, %dr0, %pred0"]]))
    # Integer compares: 1 if the predicate is true (a predicated add, so
    # the result does not depend on merge's operand order).
    for c in ["o", "b", "e", "be", "s", "p", "l", "le"]:
        out.append(fn(f"s_cmp{c}db", [
            [f"cmp{c}db,0 %dr0, %dr1, %pred0", "addd,1 0x0, 0x0, %dr2"],
            ["nop 2"], ["addd,0 0x0, 0x1, %dr2 ? %pred0"],
            ["addd,0 0x0, %dr2, %dr0"]]))
    # FP compares into a predicate: (pred << 8) | %pfpfr flags raised.
    for c in ["eq", "lt", "le", "uod", "neq", "nlt", "nle", "od"]:
        out.append(fn(f"s_fcmp{c}db", [
            ["rrs,0 %pfpfr, %r8"], ["nop 5"],
            ["ands,0 %r8, 0xffffffc0, %r9"], ["rws,0 %r9, %pfpfr"], ["nop 5"],
            [f"fcmp{c}db,0 %dr0, %dr1, %pred0", "addd,1 0x0, 0x0, %dr2"],
            ["nop 2"], ["addd,0 0x0, 0x100, %dr2 ? %pred0"], ["nop 5"],
            ["rrs,0 %pfpfr, %r10"], ["nop 5"],
            ["ands,0 %r10, 0x3f, %r10"], ["rws,0 %r8, %pfpfr"],
            ["ord,0 %dr2, %dr10, %dr0"]], wsz=8))
    # double fmul_addd(a, b, c): fused or two roundings?
    out.append(fn("s_fmul_addd", [["fmul_addd %dr0, %dr1, %dr2, %dr0"]]))
    (HERE / "semantics.s").write_text("".join(out))


if __name__ == "__main__":
    main()
