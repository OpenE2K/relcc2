def timed(name, step, n=STEPS, dbl=0, warm=WARM, part=""):
    """WARM steps, then N between two %clkr reads (STEP(i) gives step
    i's text)."""
    body = "\ttl_setup\n" if part == "" else SETUP + nops(8)
    for i in range(warm):
        body += step(i)
    body += wi("rrd,0\t%clkr, %dr28")
    for i in range(warm, warm + n):
        body += step(i)
    body += wi("rrd,0\t%clkr, %dr29") + nops(2)
    body += wi("subd,0\t%dr29, %dr28, %dr0")
    func(name, body, dbl, part=part)


