/* Control-transfer leftovers on hardware (spec/isa/control-transfer.md,
   predicates.md, loops.md, spec/abi/atomics.md): what vfrpsz checks and
   which wbs a system call may use, ctcond type 9 (%MLOCK || %cmpN /
   %clpN), branches into code that is not in the instruction cache (disp
   distance, ipd, pref) and straight-line fetch of 8- to 64-byte wide
   instructions, and on v6 qpcheck*, abgc/rbgc and fillr/fillc.
   ctlleft.s, ctlleft6.s and ctlleft-cases.h are generated by
   gen_ctlleft.py.

     python3 tools/isa-probes/gen_ctlleft.py
     LCC=/opt/mcst/lcc-1.29.16.e2k-v3.4c.linux-6.1/bin/lcc    # or v5.8c2
     $LCC -O2 tools/isa-probes/ctlleft.c tools/isa-probes/ctlleft.s \
         -o ctlleft -lpthread
     LCC6=/opt/mcst/lcc-1.29.16.e2k-v6.2c3.linux-6.1/bin/lcc
     $LCC6 -O2 -DCTL_V6 tools/isa-probes/ctlleft.c tools/isa-probes/ctlleft.s \
         tools/isa-probes/ctlleft6.s -o ctlleft6 -lpthread
     ./ctlleft [vfrpsz] [t9] [spin[=A,B]] [fetch[=SUBSTR]] [straight] [v6]
                                                     # on hardware
                                     # fetch=SUBSTR: only cases named *SUBSTR*
     # 4C (four NUMA nodes): keep code and data on the node that runs it
     numactl --cpunodebind=0 --membind=0 cp ctlleft ctlleft-n0
     numactl --physcpubind=2 --membind=0 ./ctlleft-n0 fetch straight

   Every value case runs in a child process of its own and prints the
   value or the signal and si_code.  Timing cases print the cycles of one
   block, (T(32 blocks) - T(16)) / 16, best of 200 runs.  Fetch cases
   print the cycles from the window's first instruction to the clock read
   at the target, min and median of 15 runs, for four states: 0 all
   cached, 1 after 256 KiB of other code, 2 after 512 KiB, 3 after a
   64 MiB data stream and 512 KiB of code.  */

