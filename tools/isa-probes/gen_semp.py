"""Write semp.s and semp-ops.h: every packed operation of v3 (64-bit
packed integer and packed FP, p*, except the combined pf*_* ones, which
fcomb.c covers, and the tag operations puttc/puttst), for semp.c, which
runs them over fixed inputs on hardware or under qemu so the two can be
compared (spec/isa/semantics.md, "Packed operations").

  python3 tools/isa-probes/gen_semp.py

Each function is  void sp_N(const u64 in[3], u64 out[2]): it loads in[0..2]
into %dr2..%dr4, clears the %pfpfr flags, presets %dr5 to
0x5555555555555555, runs the operation (sources from %dr2.., or %r2.. for
32-bit operands; an 8-bit immediate where the format has one) into %dr5
or %r5, and stores the whole %dr5 in out[0] and %pfpfr in out[1].
"""

from pathlib import Path

import yaml

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]

HEADER = """! SPDX-License-Identifier: GPL-3.0-or-later
! Generated by tools/isa-probes/gen_semp.py; see semp.c.
	.ignore	ld_st_style
	.text
"""
REG = {"d": "%dr", "s": "%r"}
IMMS = (0x00, 0x01, 0x05, 0x1b, 0x4e, 0x7f)


def ops():
    data = yaml.safe_load((ROOT / "spec/isa/binutils-ops.yaml").read_text())
    out = {}
    for e in data["alu_ops"]:
        n = e["name"]
        if (not n.startswith("p") or n.startswith(("pass", "puttc", "puttst"))
                or "_" in n or not e.get("isets") or 3 not in e["isets"]
                or min(e["isets"]) > 3):
            continue
        out.setdefault(n, (e["args"], e["channels"][0], e["alopf"]))
    res = []
    for n, (args, ch, alopf) in sorted(out.items()):
        if "LIT8" in alopf or "PSHUFH" in alopf:
            for imm in IMMS:
                res.append((f"{n}_{imm:02x}", n, args, ch, alopf, imm))
        else:
            res.append((n, n, args, ch, alopf, None))
    return res


def fn(i, label, name, args, ch, alopf, imm):
    srcs = [f"{REG[a]}{2 + k}" for k, a in enumerate(args[:-1])]
    if imm is not None:
        if "PSHUFH" in alopf:          # pshufh src, imm, dst
            srcs = [srcs[0], f"{imm:#x}"]
        else:                          # op src1, src2, imm, dst
            srcs = srcs[:2] + [f"{imm:#x}"]
    dst = f"{REG[args[-1]]}5"
    return f"""
	.global	sp_{i}
	.type	sp_{i}, #function
	.align	8
sp_{i}:
	{{
	  setwd	wsz = 0x8, nfx = 0x1, dbl = 0x0
	  return	%ctpr3
	}}
	{{
	  rrs,0	%pfpfr, %r8
	}}
	{{
	  ldd,0	%dr0, 0x0, %dr2
	  ldd,2	%dr0, 0x8, %dr3
	  ldd,3	%dr0, 0x10, %dr4
	  addd,1	0x0, _f64,_lts0 0x5555555555555555, %dr5
	}}
	{{
	  ands,0	%r8, 0xffffffc0, %r9
	}}
	{{
	  rws,0	%r9, %pfpfr
	}}
	{{
	  nop 7
	}}
	{{
	  {name},{ch}	{", ".join(srcs + [dst])}
	}}
	{{
	  nop 7
	}}
	{{
	  nop 7
	  rrs,0	%pfpfr, %r9
	}}
	{{
	  std,2	%dr1, 0x0, %dr5
	  stw,5	%dr1, 0x8, %r9
	}}
	{{
	  rws,0	%r8, %pfpfr
	}}
	{{
	  nop 5
	}}
	{{
	  ct	%ctpr3
	}}
	.size	sp_{i}, .-sp_{i}
"""


def main():
    ls = ops()
    (HERE / "semp.s").write_text(
        HEADER + "".join(fn(i, *o) for i, o in enumerate(ls)))
    (HERE / "semp-ops.h").write_text(
        "/* SPDX-License-Identifier: GPL-3.0-or-later */\n"
        "/* Generated by tools/isa-probes/gen_semp.py.  */\n"
        + "".join(f'OP ({i}, "{o[0]}")\n' for i, o in enumerate(ls)))


if __name__ == "__main__":
    main()
