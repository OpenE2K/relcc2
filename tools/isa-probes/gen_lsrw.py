"""Write lsrw.s and lsrw-v5.s: how soon writes of the loop registers
take effect, for lsrw.c (spec/isa/loops.md, timing.md).

  python3 tools/isa-probes/gen_lsrw.py   # rewrites lsrw*.s, lsrw*-cases.h

Every case is  long lsrw_NAME(unsigned long *out, unsigned long a,
unsigned long b, unsigned long c)  with a, b, c in %dr1..%dr3.

Read-back cases (rb_W_R_D): the setup writes the registers it needs
and waits; then out[0] = R read the instruction before the write of W,
out[1] = R read D cycles after the write, out[2] = R read 8 cycles
later.  Loop cases (lp_*): the setup writes its registers and waits,
then a sequence of writes with given distances, then a one-instruction
loop (alc, ct ? %NOT_LOOP_END) whose iterations are counted in
another channel; out[0] = iterations, out[1] = %lsr after the loop,
out[2] = cycles from before the sequence to after the loop, out[3] =
%lsr on entry (what the caller left).

Each loop case starts on a 512-byte boundary, which keeps its loop
label (under 0xc0 bytes in) out of page offsets 0x1c0-0x1ff of each
1 KiB block.  gas moves any jump target out of those offsets by
inserting an empty wide instruction before it (the CODE_PLACEMENT
workaround, spec/isa/hwbugs.md), which runs and would make the loop
start a cycle later than its distance says.
"""

from pathlib import Path

HERE = Path(__file__).resolve().parent
HEADER = """! SPDX-License-Identifier: GPL-3.0-or-later
! Generated by tools/isa-probes/gen_lsrw.py; see lsrw.c.
\t.ignore\tld_st_style
\t.text
"""
VLC = 1 << 37


def lsr(lcnt):
    return VLC | lcnt


class Case:
    def __init__(self, name):
        self.name, self.out = name, []

    def wi(self, *ops):
        self.out.append("\t{\n" + "".join(f"\t  {o}\n" for o in ops)
                        + "\t}\n")

    def head(self, align=8):
        n = self.name
        self.out.append(f"\n\t.global\tlsrw_{n}\n\t.type\tlsrw_{n}, #function\n"
                        f"\t.align\t{align}\nlsrw_{n}:\n")
        self.wi("setwd\twsz = 0x10, nfx = 0x1, dbl = 0x0", "return\t%ctpr3")

    def write(self, src, reg, gap):
        """rwd SRC, REG; the next instruction comes GAP cycles later."""
        self.wi(f"rwd,0\t{src}, {reg}", *([f"nop {gap - 1}"] if gap > 1 else []))

    def text(self):
        self.wi("ct\t%ctpr3")
        return "".join(self.out) + f"\t.size\tlsrw_{self.name}, .-lsrw_{self.name}\n"


def rb(name, pre, w, r, d):
    """PRE: (src, reg) writes long before; W = (src, reg) written D cycles
    before R is read."""
    c = Case(name)
    c.head()
    for src, reg in pre:
        c.write(src, reg, 8)
    c.wi(f"rrd,0\t{r}, %dr6")
    c.wi("nop 7")
    c.write(*w, d)
    c.wi(f"rrd,0\t{r}, %dr4")
    c.wi("nop 7")
    c.wi(f"rrd,0\t{r}, %dr5")
    c.wi("nop 5")
    c.wi("std,2\t%dr0, 0x0, %dr6", "std,5\t%dr0, 0x8, %dr4")
    c.wi("std,2\t%dr0, 0x10, %dr5")
    return c


def lp(name, pre, seq):
    """PRE: (src, reg) writes long before; SEQ: (src, reg, gap) writes,
    the last one GAP cycles before the loop's first (only) instruction."""
    c = Case(name)
    c.head(512)
    c.wi("addd,1\t0x0, 0x0, %dr10", f"disp\t%ctpr1, .L{name}_loop",
         "rrd,0\t%lsr, %dr7")
    for src, reg in pre:
        c.write(src, reg, 8)
    c.wi("nop 7")
    c.wi("rrd,0\t%clkr, %dr8")
    for src, reg, gap in seq:
        c.write(src, reg, gap)
    c.out.append(f".L{name}_loop:\n")
    c.wi("addd,3\t%dr10, 0x1, %dr10", "loop_mode", "alc\talcf=1, alct=1",
         "ct\t%ctpr1 ? %NOT_LOOP_END")
    c.wi("rrd,0\t%clkr, %dr9")
    c.wi("rrd,0\t%lsr, %dr4")
    c.wi("subd,0\t%dr9, %dr8, %dr5", "nop 5")
    c.wi("std,2\t%dr0, 0x0, %dr10", "std,5\t%dr0, 0x8, %dr4")
    c.wi("std,2\t%dr0, 0x10, %dr5", "std,5\t%dr0, 0x18, %dr7")
    return c


def main():
    v3, v5 = [], []         # (case, kind, d, a, b, c)
    D = range(1, 7)
    # v3+: %lsr read back (the known 4 cycles, as a check) and %ilcr
    # after a %lsr write; a loop D cycles after a %lsr write.
    for d in D:
        v3.append((rb(f"rb_lsr_lsr_{d}", [("%dr1", "%lsr")], ("%dr2", "%lsr"),
                      "%lsr", d), 0, d, lsr(5), lsr(9), 0))
        v3.append((rb(f"rb_lsr_ilcr_{d}", [("%dr1", "%lsr")], ("%dr2", "%lsr"),
                      "%ilcr", d), 0, d, lsr(5), lsr(9), 0))
    # The old %lsr: lcnt 3, a finished loop (lcnt 0, over), no vlc,
    # lcnt 1, 2, ecnt 2; cur_: whatever the caller left (as loops.c's
    # early cases).
    for tag, old in (("", lsr(3)), ("fin_", VLC | 1 << 38), ("novlc_", 3),
                     ("l1_", lsr(1)), ("l2_", lsr(2)), ("e2_", lsr(0) | 2 << 32),
                     ("cur_", None)):
        for d in D:
            v3.append((lp(f"lp_lsr_{tag}{d}", [("%dr3", "%lsr")] if old is not None else [],
                          [("%dr1", "%lsr", d)]), 1, d, lsr(5), 0, old or 0))
    # Can user code write %ilcr at all (ilcr_w: read back 8 cycles
    # later, and %lsr after it)?  The driver runs the rest only if so.
    v3.append((rb("ilcr_w", [("%dr1", "%lsr")], ("%dr2", "%ilcr"), "%ilcr", 8),
               2, 8, lsr(5), 9, 0))
    v3.append((rb("ilcr_w_lsr", [("%dr1", "%lsr")], ("%dr2", "%ilcr"), "%lsr", 8),
               3, 8, lsr(5), 9, 0))
    for d in D:
        v3.append((rb(f"rb_ilcr_ilcr_{d}", [("%dr1", "%lsr")], ("%dr2", "%ilcr"),
                      "%ilcr", d), 3, d, lsr(5), 9, 0))
    # v5+: %lsr1 (the 64-bit count) read back as itself, %lsr (lcnt),
    # %ilcr1 and %ilcr; %lsr1 after a %lsr write (which resets it).
    big = (1 << 32) + 7
    for r in ("%lsr1", "%lsr", "%ilcr1", "%ilcr"):
        for d in D:
            v5.append((rb(f"rb_lsr1_{r[1:]}_{d}", [("%dr1", "%lsr")],
                          ("%dr2", "%lsr1"), r, d), 0, d, lsr(5), big, 0))
    for d in D:
        v5.append((rb(f"rb_lsr_lsr1_{d}", [("%dr1", "%lsr"), ("%dr3", "%lsr1")],
                      ("%dr2", "%lsr"), "%lsr1", d), 0, d, lsr(5), lsr(9), big))
    # A loop D cycles after a %lsr1 write (%lsr: lcnt 5 long before,
    # %lsr1: 7); lcc's order (%lsr, then %lsr1 one cycle later, the loop
    # D cycles after that); the two writes G cycles apart in either
    # order, the loop 8 cycles after the second (%lsr lcnt 3 before).
    for d in D:
        v5.append((lp(f"lp_lsr1_{d}", [("%dr1", "%lsr")],
                      [("%dr2", "%lsr1", d)]), 1, d, lsr(5), 7, 0))
    for d in D:
        v5.append((lp(f"lp_lcc_{d}", [("%dr3", "%lsr")],
                      [("%dr1", "%lsr", 1), ("%dr2", "%lsr1", d)]),
                   1, d, lsr(5), 7, lsr(3)))
    for g in range(1, 6):
        v5.append((lp(f"lp_lsr_lsr1_g{g}", [("%dr3", "%lsr")],
                      [("%dr1", "%lsr", g), ("%dr2", "%lsr1", 8)]),
                   1, g, lsr(5), 7, lsr(3)))
        v5.append((lp(f"lp_lsr1_lsr_g{g}", [("%dr3", "%lsr")],
                      [("%dr2", "%lsr1", g), ("%dr1", "%lsr", 8)]),
                   1, g, lsr(5), 7, lsr(3)))
    for path, cs in (("lsrw", v3), ("lsrw-v5", v5)):
        (HERE / f"{path}.s").write_text(HEADER + "".join(c.text() for c, *_ in cs))
        (HERE / f"{path}-cases.h").write_text(
            "/* SPDX-License-Identifier: GPL-3.0-or-later */\n"
            "/* Generated by tools/isa-probes/gen_lsrw.py.  */\n"
            + "".join(f"CASE ({c.name}, {k}, {d}, {a:#x}UL, {b:#x}UL, {x:#x}UL)\n"
                      for c, k, d, a, b, x in cs))


if __name__ == "__main__":
    main()
