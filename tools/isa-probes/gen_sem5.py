"""Write sem5.s and sem5-ops.h: every ALU operation new in v5, for
sem5.c, which runs them over fixed inputs on hardware or under qemu so
the two can be compared (spec/isa/semantics.md).

  python3 tools/isa-probes/gen_sem5.py

Each function is  void v5_N(const u128 in[3], u128 out[2])  (N an index;
sem5-ops.h names them).  It loads in[0..2] into %qpr2..%qpr4, clears the
%pfpfr flags and %qpr5, runs the operation with sources from %qpr2..4
(as %drK or %rK for 64- and 32-bit operands) into %qpr5 / %dr5 / %r5,
and stores all 128 bits of %qpr5 in out[0] and %pfpfr in out[1].
Operations are taken from binutils-ops.yaml: those whose first ISA
version is 5, except loads, stores and protected-mode operations.
"""

from pathlib import Path

import yaml

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]

HEADER = """! SPDX-License-Identifier: GPL-3.0-or-later
! Generated by tools/isa-probes/gen_sem5.py; see sem5.c.
	.ignore	ld_st_style
	.text
"""

SKIP = ("ld", "st", "apto", "getva", "puttag")
REG = {"p": "%qpr", "d": "%dr", "s": "%r"}


def ops():
    data = yaml.safe_load((ROOT / "spec/isa/binutils-ops.yaml").read_text())
    first = {}
    for e in data["alu_ops"]:
        i = e.get("isets") or []
        if not i:
            continue
        first.setdefault(e["name"], []).append(e)
    out = []
    for name, es in sorted(first.items()):
        if min(min(e["isets"]) for e in es) != 5 or name.startswith(SKIP):
            continue
        e = next(e for e in es if 5 in e["isets"])
        args = e["args"]
        if name.startswith("qplog"):
            args = "pppp"
        out.append((name, args, e["channels"][0]))
    return out


def fn(i, name, args, ch):
    srcs = [f"{REG[a]}{2 + k}" for k, a in enumerate(args[:-1])]
    dst = f"{REG[args[-1]]}5"
    return f"""
	.global	v5_{i}
	.type	v5_{i}, #function
	.align	8
v5_{i}:
	{{
	  setwd	wsz = 0x8, nfx = 0x1, dbl = 0x0
	  return	%ctpr3
	  rrs,0	%pfpfr, %r8
	}}
	{{
	  ldqp,0	%dr0, 0x0, %qpr2
	  ldqp,2	%dr0, 0x10, %qpr3
	  ldqp,3	%dr0, 0x20, %qpr4
	  qppackdl,1	0x0, 0x0, %qpr5
	  nop 1
	}}
	{{
	  ands,0	%r8, 0xffffffc0, %r9
	}}
	{{
	  rws,0	%r9, %pfpfr
	  nop 7
	}}
	{{
	  nop 7
	}}
	{{
	  {name},{ch}	{", ".join(srcs + [dst])}
	}}
	{{
	  nop 7
	}}
	{{
	  nop 7
	  rrs,0	%pfpfr, %r9
	}}
	{{
	  stqp,2	%dr1, 0x0, %qpr5
	  stw,5	%dr1, 0x10, %r9
	}}
	{{
	  rws,0	%r8, %pfpfr
	}}
	{{
	  nop 5
	}}
	{{
	  ct	%ctpr3
	}}
	.size	v5_{i}, .-v5_{i}
"""


def main():
    ls = ops()
    (HERE / "sem5.s").write_text(
        HEADER + "".join(fn(i, *o) for i, o in enumerate(ls)))
    (HERE / "sem5-ops.h").write_text(
        "/* SPDX-License-Identifier: GPL-3.0-or-later */\n"
        "/* Generated by tools/isa-probes/gen_sem5.py.  */\n"
        + "".join(f'OP ({i}, "{n}", "{a}")\n' for i, (n, a, _) in
                  enumerate(ls)))


if __name__ == "__main__":
    main()
