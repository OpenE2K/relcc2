"""Write apb-stream.s and apb-stream-cases.h: streaming loops through one
array prefetch area, one per area size (asz) and cache control (dcd), for
apb-stream.c (spec/isa/apb.md, "Timing").

  python3 tools/isa-probes/gen_apb_stream.py

Each function is  long stream_NAME(const long *a, unsigned long lsr,
long *cycles): a one-instruction loop_mode loop counted by %lsr that
reads one element per iteration through movad (am = 1) into %b[0] and
adds it into %dr9 six iterations later (as %b[12]), past the mova's
latency of 5, so the loop can run an iteration per cycle; it returns
the sum of the first lcnt - 6 elements.  *cycles is the %clkr
difference across the loop.  STEP elements per iteration (AAINCR1)
spread the reads over more cache lines.

The multi_* functions stream K arrays at once, K areas of ASZ, one movad
each per iteration: area j reads a + j * SPAN bytes (APLS disp), areas
0 and 1 in the left half (channels 0, 1), 2 and 3 in the right (2, 3).
Only area 0 is summed; the others go to scratch registers.
"""

from pathlib import Path

HERE = Path(__file__).resolve().parent


def fn(name, asz, dcd, step, k=1, span=0):
    return f"""
	.global	stream_{name}
	.type	stream_{name}, #function
	.align	8
stream_{name}:
	{{
	  setwd	wsz = 0x10, nfx = 0x1, dbl = 0x0
	  setbn	rsz = 0x7, rbs = 0x8, rcur = 0x0
	  return	%ctpr3
	}}
	{{
	  addd,0	0x0, 0x0, %b[0]
	  addd,1	0x0, 0x0, %b[2]
	  addd,2	0x0, 0x0, %b[4]
	  addd,3	0x0, 0x0, %b[6]
	  addd,4	0x0, 0x0, %b[8]
	  addd,5	0x0, 0x0, %b[10]
	}}
	{{
	  addd,0	0x0, 0x0, %b[12]
	  addd,1	0x0, 0x0, %b[14]
	}}
	{{
	  ldisp	%ctpr2, .L{name}_prog
	  aaurwd,2	%dr0, %aad0
	  addd,1	0x0, 0x0, %dr8
	  addd,3	0x0, 0x0, %dr9
	  addd,4	0x0, {step:#x}, %dr10
	}}
	{{
	  aaurw,2	%r10, %aaincr1
	  disp	%ctpr1, .L{name}_loop
	  rwd,0	%dr1, %lsr
	}}
	{{
	  nop 7
	  bap
	}}
	{{
	  nop 7
	}}
	{{
	  nop 7
	  rrd,0	%clkr, %dr4
	}}
.L{name}_loop:
	{{
	  loop_mode
	  alc	alcf=1, alct=1
	  abn	abnf=1, abnt=1
	  ct	%ctpr1 ? %NOT_LOOP_END
	  movad,0	area=0, ind=0, am=1, be=0, %b[0]
	  addd,0	%dr9, %b[12], %dr9{extra_movas(k)}
	}}
	{{
	  rrd,0	%clkr, %dr5
	}}
	{{
	  nop 7
	  disp	%ctpr2, disp=0x0
	}}
	{{
	  addd,0	%dr9, 0x0, %dr0
	  subd,1	%dr5, %dr4, %dr6
	}}
	{{
	  std,2	%dr2, 0x0, %dr6
	}}
	{{
	  ct	%ctpr3
	}}
	.align	8
.L{name}_prog:
{program(k, asz, dcd, span)}	.size	stream_{name}, .-stream_{name}
"""


def extra_movas(k):
    # Area j: left half for j < 2 (instruction j), right half for j >= 2
    # (instruction j - 2), channel j.
    return "".join(f"\n\t  movad,{j}\tarea={j % 2}, ind=0, am=1, be=0, %dr{10 + j}"
                   for j in range(1, k))


def program(k, asz, dcd, span):
    def half(j, flag):
        return (f"fapb\t{flag}, dcd={dcd}, fmt=4, mrng=8, d=0, incr=1, "
                f"ind=0, asz={asz}, abs={(j % 2) * (2 ** asz)}, "
                f"disp={j * span:#x}")
    rows = []
    n = 2 if k > 1 else 1
    for i in range(n):
        last = i == n - 1
        ops = [half(i, f"ct={int(last)}")]
        if i + 2 < k:
            ops.append(half(i + 2, "dpl=0"))
        rows.append("\t{\n" + "".join(f"\t  {o}\n" for o in ops) + "\t}\n")
    return "".join(rows)


def main():
    cases = []
    for step in (1, 8):
        for dcd in (0, 1, 2, 3):
            for asz in range(6):
                cases.append((f"s{step}_d{dcd}_a{asz}", asz, dcd, step, 1, 0))
    # Several arrays at once, 64 MiB apart (the C side keeps them in
    # one 512 MiB block): 1, 2 and 4 areas of 1 KiB, and 4 of 512 B.
    for step in (1, 8):
        for k, asz in ((1, 4), (2, 4), (4, 4), (2, 3), (4, 3)):
            cases.append((f"multi{k}_s{step}_a{asz}", asz, 0, step, k,
                          64 << 20))
    (HERE / "apb-stream.s").write_text(
        "! SPDX-License-Identifier: GPL-3.0-or-later\n"
        "! Generated by tools/isa-probes/gen_apb_stream.py; see "
        "apb-stream.c.\n\t.ignore\tld_st_style\n\t.text\n"
        + "".join(fn(*c) for c in cases))
    (HERE / "apb-stream-cases.h").write_text(
        "/* SPDX-License-Identifier: GPL-3.0-or-later */\n"
        "/* Generated by tools/isa-probes/gen_apb_stream.py.  */\n"
        + "".join(f"CASE ({n}, {a}, {d}, {s}, {k})\n"
                  for n, a, d, s, k, _ in cases))


if __name__ == "__main__":
    main()
